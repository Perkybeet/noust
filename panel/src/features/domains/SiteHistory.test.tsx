import { screen, waitFor, within } from "@testing-library/react";
import { beforeEach, describe, expect, it, vi } from "vitest";

import { expectNoAxeViolations } from "../../test/axe";
import { renderConsole } from "../../test/console";
import { fakeBackend, json, signedInRoutes } from "../../test/fakes";
import type { RouteHandler } from "../../test/fakes";
import { SMALL_CONFIG } from "./siteTestFixtures";

beforeEach(() => {
  vi.stubGlobal("matchMedia", (query: string) => ({
    matches: true,
    media: query,
    onchange: null,
    addEventListener: () => undefined,
    removeEventListener: () => undefined,
    addListener: () => undefined,
    removeListener: () => undefined,
    dispatchEvent: () => false,
  }));
});

const SITE = "shop.example.com";
const PATH = `/etc/nginx/sites-available/${SITE}`;
const OLDER = "# Generated by Noust\nserver { listen 80; }\n";

const VERSIONS = {
  site: SITE,
  webserver: "nginx",
  edited_outside: false,
  pending_reload: false,
  versions: [
    { version: 3, sha256: "c", size: 2048, source: "edit", actor: "ana", created_at: "2026-10-16T10:00:00+00:00", current: true },
    { version: 2, sha256: "b", size: 1900, source: "found", actor: null, created_at: "2026-10-15T10:00:00+00:00", current: false },
    { version: 1, sha256: "a", size: 1800, source: "generated", actor: null, created_at: "2026-10-14T10:00:00+00:00", current: false },
  ],
};

function page(info: Record<string, unknown> = {}, extra: Record<string, RouteHandler> = {}) {
  const backend = fakeBackend({
    ...signedInRoutes(),
    [`GET /api/sites/${SITE}`]: () =>
      json(200, { name: SITE, webserver: "nginx", enabled: true, config_path: PATH, has_ssl: true, server_names: [SITE], pending_reload: false, edited_outside: false, ...info }),
    [`GET /api/sites/${SITE}/config`]: () => json(200, { site: SITE, webserver: "nginx", config: SMALL_CONFIG, path: PATH }),
    [`GET /api/sites/${SITE}/config/versions`]: () => json(200, VERSIONS),
    [`GET /api/sites/${SITE}/config/versions/1`]: () => json(200, { ...VERSIONS.versions[2], site: SITE, webserver: "nginx", config: OLDER, diff: "--- version 1\n+++ now\n@@ -1 +1 @@\n-server { listen 80; }\n+server { listen 81; }\n" }),
    [`GET /api/sites/${SITE}/structure`]: () => json(200, { site: SITE, webserver: "nginx", path: PATH, structure: null, error: null }),
    ...extra,
  });
  return { ...renderConsole(`/domains/sites/${SITE}`), backend };
}

describe("a site's history", { timeout: 20_000 }, () => {
  it("lists the versions, says how each came to be, and shows what changed", async () => {
    const { user } = page();

    await user.click(await screen.findByRole("button", { name: "History" }));
    const dialog = await screen.findByRole("dialog", { name: `History of ${SITE}` });
    const list = await within(dialog).findByRole("list", { name: `Versions of ${SITE}` });
    expect(within(list).getByText("Saved by a person")).toBeInTheDocument();
    expect(within(list).getByText("Found on disk")).toBeInTheDocument();
    expect(within(list).getByText("Rendered by Noust")).toBeInTheDocument();
    expect(within(list).getByText("Now")).toBeInTheDocument();
    expect(within(list).getByText("ana")).toBeInTheDocument();
    await expectNoAxeViolations(dialog);

    const row = within(list).getByText("Version 1").closest("li");
    if (row === null) throw new Error("no row");
    await user.click(within(row).getByRole("button", { name: "Show changes" }));
    expect(await within(row).findByText(/-server \{ listen 80; \}/)).toBeInTheDocument();
    expect(within(row).getByText(/\+server \{ listen 81; \}/)).toBeInTheDocument();
  });

  it("puts a version back through the server's restore, and the editor reads the file again", async () => {
    let text = SMALL_CONFIG;
    const { user, backend } = page(
      {},
      {
        [`GET /api/sites/${SITE}/config`]: () => json(200, { site: SITE, webserver: "nginx", config: text, path: PATH }),
        [`POST /api/sites/${SITE}/config/versions/1/restore`]: () => {
          text = OLDER;
          return json(200, { success: true, message: `Version 1 of ${SITE} is back. Reload nginx to apply it.`, site: SITE });
        },
      },
    );

    await user.click(await screen.findByRole("button", { name: "History" }));
    const dialog = await screen.findByRole("dialog", { name: `History of ${SITE}` });
    const list = await within(dialog).findByRole("list", { name: `Versions of ${SITE}` });
    const row = within(list).getByText("Version 1").closest("li");
    if (row === null) throw new Error("no row");
    // The version that is the file now has nothing to use.
    expect(within(within(list).getByText("Version 3").closest("li") as HTMLElement).queryByRole("button", { name: "Use this version" })).not.toBeInTheDocument();
    await user.click(within(row).getByRole("button", { name: "Use this version" }));

    await waitFor(() => expect(screen.queryByRole("dialog", { name: `History of ${SITE}` })).not.toBeInTheDocument());
    // The server's own restore, not a draft made of the version's text: the file is the version and nothing is waiting to be saved.
    expect(backend.callsTo(`POST /api/sites/${SITE}/config/versions/1/restore`)).toHaveLength(1);
    expect(backend.callsTo(`PUT /api/sites/${SITE}/config`)).toHaveLength(0);
    await waitFor(() => expect(screen.getByRole("textbox", { name: `Configuration of ${SITE}` })).toHaveValue(OLDER));
    expect(screen.queryByText(/^\d+ unsaved changes?$/)).not.toBeInTheDocument();
    expect(await screen.findByText("Version 1 is back. Reload nginx to apply it.")).toBeInTheDocument();
  });

  it("says why the web server refused a version, in its own words, and leaves the file as it was", async () => {
    const { user } = page(
      {},
      {
        [`POST /api/sites/${SITE}/config/versions/1/restore`]: () =>
          json(400, { error: "validation_error", detail: "nginx refused this text, so nothing was changed", output: "nginx: [emerg] unknown directive in /etc/nginx/sites-available/shop.example.com:1", hint: null, fields: null }),
      },
    );

    await user.click(await screen.findByRole("button", { name: "History" }));
    const dialog = await screen.findByRole("dialog", { name: `History of ${SITE}` });
    const list = await within(dialog).findByRole("list", { name: `Versions of ${SITE}` });
    const row = within(list).getByText("Version 1").closest("li");
    if (row === null) throw new Error("no row");
    await user.click(within(row).getByRole("button", { name: "Use this version" }));

    expect(await within(dialog).findByText("Version 1 was not put back")).toBeInTheDocument();
    expect(within(dialog).getByText(/unknown directive/)).toBeInTheDocument();
    expect(screen.getByRole("textbox", { name: `Configuration of ${SITE}`, hidden: true })).toHaveValue(SMALL_CONFIG);
  });

  it("asks once before it replaces what the editor holds, then restores", async () => {
    const { user, backend } = page({}, { [`POST /api/sites/${SITE}/config/versions/1/restore`]: () => json(200, { success: true, message: "back", site: SITE }) });

    await user.type(await screen.findByRole("textbox", { name: `Configuration of ${SITE}` }), " # mine");
    await user.click(await screen.findByRole("button", { name: "History" }));
    const dialog = await screen.findByRole("dialog", { name: `History of ${SITE}` });
    const list = await within(dialog).findByRole("list", { name: `Versions of ${SITE}` });
    const row = within(list).getByText("Version 1").closest("li");
    if (row === null) throw new Error("no row");

    await user.click(within(row).getByRole("button", { name: "Use this version" }));
    expect(await within(dialog).findByText(/replaces the unsaved changes in the editor/)).toBeInTheDocument();
    expect(backend.callsTo(`POST /api/sites/${SITE}/config/versions/1/restore`)).toHaveLength(0);

    await user.click(within(row).getByRole("button", { name: "Use this version" }));
    await waitFor(() => expect(backend.callsTo(`POST /api/sites/${SITE}/config/versions/1/restore`)).toHaveLength(1));
  });

  it("says when the file was changed outside Noust", async () => {
    const { user } = page({ edited_outside: true });

    expect(await screen.findByText("Changed outside Noust")).toBeInTheDocument();
    const [, inNotice] = screen.getAllByRole("button", { name: "History" });
    if (inNotice === undefined) throw new Error("the notice has no History button");
    await user.click(inNotice);
    expect(await screen.findByRole("dialog", { name: `History of ${SITE}` })).toBeInTheDocument();
  });

  it("says when the web server has not loaded the file, and reloads it", async () => {
    const { user, backend } = page(
      { pending_reload: true },
      { "POST /api/sites/reload": () => json(200, { success: true, message: "nginx reloaded", webserver: "nginx" }) },
    );

    expect(await screen.findByText("nginx has not loaded this file")).toBeInTheDocument();
    const notice = screen.getByText("nginx has not loaded this file").closest<HTMLElement>("[data-tone]");
    if (notice === null) throw new Error("no notice");
    await user.click(within(notice).getByRole("button", { name: /Reload nginx/ }));

    await waitFor(() => expect(backend.callsTo("POST /api/sites/reload")).toHaveLength(1));
  });

  it("is quiet when nothing has drifted", async () => {
    page();

    await screen.findByRole("button", { name: "History" });
    expect(screen.queryByText("Changed outside Noust")).not.toBeInTheDocument();
    expect(screen.queryByText("nginx has not loaded this file")).not.toBeInTheDocument();
  });
});
