"""
Write ``src/noust/core/rdap_bootstrap_data.py`` from IANA's RDAP bootstrap file for domain names.

RDAP (RFC 7480 and following) is how a registry publishes what it knows of a domain, the date its
registration expires among it. Which server answers for which top-level domain is IANA's list
(RFC 9224, https://data.iana.org/rdap/dns.json), and it ships inside Noust as data, written here,
so that an installation never asks IANA anything: the monitor's only request is the one to the
registry of a domain the operator serves, and only when the operator turned that on
(``monitor.domain_expiry``, docs/PRIVACY.md).

This runs by hand, with a network, when a release is made (the file is committed and the release
carries it); no installation and no test runs it. ``--input`` renders a file already downloaded.
A service that has no https address is left out: Noust does not ask a registry over plain http.

Usage:
    scripts/generate_rdap_bootstrap.py                  Download the list and write the module.
    scripts/generate_rdap_bootstrap.py --input FILE     Render a downloaded copy of the list.
"""

from __future__ import annotations

import argparse
import json
import sys
import textwrap
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "noust" / "core" / "rdap_bootstrap_data.py"
SOURCE = "https://data.iana.org/rdap/dns.json"

#: How wide the lines of top-level domains are wrapped.
WIDTH = 84

HEADER = '''# Copyright (c) 2024-2026 Yago López Prado
# SPDX-License-Identifier: AGPL-3.0-or-later

"""
Which RDAP server answers for each top-level domain: IANA's bootstrap file, as data.

Generated by ``scripts/generate_rdap_bootstrap.py`` from {source}
(published {publication}); never edited by hand. It is written when a release is made and ships
with Noust, so an installation never asks IANA: :mod:`noust.core.rdap` reads it. {services}
services, {tlds} top-level domains; a service with no https address is left out ({plain} of them),
and so is a top-level domain IANA lists no server for: Noust says that registry does not publish
the expiry, and does not try it again every day.
"""

from __future__ import annotations

#: When IANA published the list this was written from.
PUBLICATION = "{publication}"

#: ``(base address of the registry's RDAP service, its top-level domains separated by spaces)``.
SERVICES: tuple[tuple[str, str], ...] = (
'''


def render(data: dict[str, Any]) -> str:
    """
    Write the module for a bootstrap file.

    Args:
        data: IANA's file, parsed: ``publication`` and ``services``, each a list of top-level
            domains and a list of addresses.

    Returns:
        The text of ``rdap_bootstrap_data.py``: services in the order of their first top-level
        domain, and the top-level domains in each in order, so that the same list always gives
        the same file.
    """
    services: list[tuple[str, list[str]]] = []
    plain = 0
    for tlds, urls in data["services"]:
        https = [url for url in urls if url.lower().startswith("https://")]
        if not https:
            plain += 1
            continue
        base = https[0] if https[0].endswith("/") else https[0] + "/"
        names = sorted({tld.strip().lower() for tld in tlds if tld.strip()})
        if names:
            services.append((base, names))
    services.sort(key=lambda item: item[1][0])
    count = sum(len(names) for _, names in services)
    lines = [
        HEADER.format(
            source=SOURCE,
            publication=data.get("publication", ""),
            services=len(services),
            tlds=count,
            plain=plain,
        ).rstrip("\n")
    ]
    for base, names in services:
        wrapped = textwrap.wrap(
            " ".join(names), WIDTH, break_long_words=False, break_on_hyphens=False
        )
        one_line = f'    ("{base}", "{wrapped[0]}"),'
        if len(wrapped) == 1 and len(one_line) <= 100:
            lines.append(one_line)
            continue
        lines.append("    (")
        lines.append(f'        "{base}",')
        for index, chunk in enumerate(wrapped):
            tail = " " if index < len(wrapped) - 1 else ""
            comma = "," if index == len(wrapped) - 1 else ""
            lines.append(f'        "{chunk}{tail}"{comma}')
        lines.append("    ),")
    lines.append(")")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """
    Args:
        argv: The arguments; ``sys.argv`` by default.

    Returns:
        0 when the module was written.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, help="Render this downloaded copy of the list.")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="Where to write.")
    args = parser.parse_args(argv)
    if args.input:
        data = json.loads(args.input.read_text(encoding="utf-8"))
    else:
        request = urllib.request.Request(SOURCE, headers={"User-Agent": "noust-release/1"})
        with urllib.request.urlopen(request, timeout=30) as response:
            data = json.loads(response.read().decode("utf-8"))
    args.output.write_text(render(data), encoding="utf-8")
    print(f"wrote {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
