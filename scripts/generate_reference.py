"""
Generate the reference pages of the documentation from the code (checklist N-22).

Three pages that cannot be allowed to drift from what the product does are written, never edited:

- ``docs/reference-cli.md``: every command and option, from the Click tree. It is the tree the
  manual page and the shell completions are generated from too (``scripts/generate_man.py``,
  ``scripts/generate_completions.py``), so the three cannot disagree.
- ``docs/reference-api.md``: every operation of the HTTP API with the permission it needs and
  whether it asks for sudo mode or a second person, from ``panel/openapi.json`` (the schema the
  console's types are generated from).
- ``docs/reference-config.md``: every configuration key with its default, from
  ``noust.core.config.DEFAULT_CONFIG``.

None of them carries a version or a date: a release must not change them unless the product
changed, so CI can fail on a stale file.

Usage:
    scripts/generate_reference.py            Write the three pages.
    scripts/generate_reference.py --check    Fail if any is out of date. CI runs this.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import click

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

CLI_PAGE = ROOT / "docs" / "reference-cli.md"
API_PAGE = ROOT / "docs" / "reference-api.md"
CONFIG_PAGE = ROOT / "docs" / "reference-config.md"
OPENAPI = ROOT / "panel" / "openapi.json"

NOTICE = (
    "<!-- Generated by scripts/generate_reference.py from {source}. Do not edit by hand: "
    "change the code, then run the script. -->\n"
)

METHODS = ("get", "post", "put", "patch", "delete")


def cell(text: object) -> str:
    """
    Make text safe inside a Markdown table cell.

    Args:
        text: Anything printable.

    Returns:
        One line, pipes escaped.
    """
    return " ".join(str(text).split()).replace("|", "\\|")


# -- the command line


def has_default(option: click.Option) -> bool:
    """
    Report whether an option has a default worth printing.

    Args:
        option: The option.

    Returns:
        True for a real, non-flag default.
    """
    unset = getattr(click.core, "UNSET", None)
    default = option.default
    if option.is_flag or default is None or default is False:
        return False
    return unset is None or default is not unset


def walk(
    command: click.Command, path: tuple[str, ...]
) -> Iterator[tuple[tuple[str, ...], click.Command]]:
    """
    Visit a command and everything under it, in the tree's order.

    Args:
        command: The command.
        path: Names leading to it.

    Yields:
        ``(path, command)`` for the command and then each descendant.
    """
    from noust.cli.app import documented_commands

    yield path, command
    if isinstance(command, click.Group):
        context = click.Context(command)
        for name, child in documented_commands(command, context):
            if not child.hidden:
                yield from walk(child, (*path, name))


def anchor_of(path: tuple[str, ...]) -> str:
    """
    Args:
        path: A command path.

    Returns:
        The heading anchor GitHub gives ``### noust a b``.
    """
    return "-".join(path)


def command_section(path: tuple[str, ...], command: click.Command) -> list[str]:
    """
    Write one command's section.

    Args:
        path: Names leading to it, ``noust`` first.
        command: The command.

    Returns:
        Markdown lines.
    """
    context = click.Context(command, info_name=" ".join(path))
    text = (command.help or command.short_help or "").strip()
    lines = [f"### {' '.join(path)}", ""]
    if text:
        # Whitespace collapsed, as cell() does: a docstring keeps its indentation before Python
        # 3.13 and loses it from 3.13 on, and the page must read the same from either.
        lines += [" ".join(text.split("\n\n")[0].split()), ""]
    lines += ["```", command.get_usage(context).removeprefix("Usage: "), "```", ""]
    arguments = [p for p in command.params if isinstance(p, click.Argument)]
    options = [p for p in command.params if isinstance(p, click.Option) and p.name != "help"]
    if arguments:
        lines += ["Arguments: " + ", ".join(f"`{p.name}`" for p in arguments), ""]
    if options:
        lines += ["| Option | What it does | Default |", "|---|---|---|"]
        for option in options:
            flags = ", ".join(f"`{o}`" for o in (*option.opts, *option.secondary_opts))
            default = f"`{option.default}`" if has_default(option) else ""
            lines.append(f"| {flags} | {cell(option.help or '')} | {default} |")
        lines.append("")
    if isinstance(command, click.Group):
        from noust.cli.app import documented_commands

        context = click.Context(command)
        names = [n for n, c in documented_commands(command, context) if not c.hidden]
        if names:
            lines += [
                "Subcommands: " + ", ".join(f"[`{n}`](#{anchor_of((*path, n))})" for n in names),
                "",
            ]
    return lines


def cli_page() -> str:
    """Returns: The command-line reference page."""
    from noust.cli.app import cli

    lines = [
        "# Command reference",
        "",
        NOTICE.format(source="the Click command tree").rstrip(),
        "",
        "Every command of `noust`, with its options. Global options (`--verbose`, `--dry-run`, "
        "`--json`, `--no-color`, `--reason`) go before or after the command name. "
        "`noust COMMAND --help` "
        "prints the same text, and `man noust` is generated from the same tree.",
        "",
    ]
    commands = list(walk(cli, ("noust",)))
    top = [p for p, _c in commands if len(p) == 2]
    lines += ["Commands: " + ", ".join(f"[`{p[1]}`](#{anchor_of(p)})" for p in top), ""]
    for path, command in commands[1:]:
        lines += command_section(path, command)
    return "\n".join(lines).rstrip() + "\n"


# -- the HTTP API


def api_page(openapi: Path = OPENAPI) -> str:
    """
    Args:
        openapi: The exported schema.

    Returns:
        The API reference page.
    """
    data = json.loads(openapi.read_text(encoding="utf-8"))
    prefix = data["info"].get("x-noust-api-prefix", "/api/v1")
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, item in data["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if op is None:
                continue
            tag = (op.get("tags") or ["Other"])[0]
            groups.setdefault(tag, []).append((method.upper(), path, op))
    lines = [
        "# API reference",
        "",
        NOTICE.format(source="panel/openapi.json").rstrip(),
        "",
        f"Every operation of the HTTP API. Each is served at `/api/...` and, the same, at `{prefix}/...`. "
        "**Permission** is what a principal needs ([roles and permissions](security.md)); "
        "**Sudo** marks an operation that asks for a recent confirmation of the signed-in person, "
        "and **Approval** one that can ask for a second person. How to authenticate, the error "
        "contract, events and WebSockets are in [the API guide](api.md).",
        "",
        f"{sum(len(v) for v in groups.values())} operations.",
        "",
    ]
    for tag in sorted(groups):
        rows = sorted(groups[tag], key=lambda r: (r[1], METHODS.index(r[0].lower())))
        lines += [
            f"## {tag}",
            "",
            "| Method | Path | What it does | Permission | Sudo | Approval |",
            "|---|---|---|---|---|---|",
        ]
        for method, path, op in rows:
            lines.append(
                "| {m} | `{p}` | {s} | {perm} | {sudo} | {appr} |".format(
                    m=method,
                    p=path,
                    s=cell(op.get("summary", "")),
                    perm=f"`{op['x-noust-permission']}`" if op.get("x-noust-permission") else "",
                    sudo="yes" if op.get("x-noust-requires-elevation") else "",
                    appr="yes" if op.get("x-noust-requires-approval") else "",
                )
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# -- configuration


def flatten(tree: dict[str, Any], prefix: str = "") -> Iterator[tuple[str, Any]]:
    """
    Flatten nested settings into dotted keys.

    Args:
        tree: The settings.
        prefix: The dotted path so far.

    Yields:
        ``(key, default)`` for every leaf; an empty mapping is a leaf.
    """
    for name, value in tree.items():
        key = f"{prefix}{name}"
        if isinstance(value, dict) and value:
            yield from flatten(value, f"{key}.")
        else:
            yield key, value


def config_page() -> str:
    """Returns: The configuration reference page."""
    from noust.core.config import DEFAULT_CONFIG

    lines = [
        "# Configuration keys",
        "",
        NOTICE.format(source="noust.core.config.DEFAULT_CONFIG").rstrip(),
        "",
        "Every configuration key and the value it has until you change it. Set one with "
        "`noust config set KEY VALUE`, read it with `noust config get KEY`; the file is "
        "`/etc/noust/config.yaml`. What each setting does, and the ones that are obsolete, is "
        "in [the configuration guide](CONFIG.md). A key that holds a secret is shown as empty here "
        "and masked everywhere Noust prints it.",
        "",
        "| Key | Default |",
        "|---|---|",
    ]
    for key, value in sorted(flatten(DEFAULT_CONFIG)):
        shown = json.dumps(value, ensure_ascii=False) if value != "" else '`""`'
        lines.append(
            f"| `{key}` | {cell(shown) if shown.startswith('`') else '`' + cell(shown) + '`'} |"
        )
    return "\n".join(lines).rstrip() + "\n"


PAGES = {CLI_PAGE: cli_page, API_PAGE: api_page, CONFIG_PAGE: config_page}


def main(argv: list[str] | None = None) -> int:
    """
    Command line entry point.

    Args:
        argv: Arguments, defaulting to ``sys.argv``.

    Returns:
        0 when written or current, 1 when ``--check`` finds a stale page.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--check", action="store_true", help="fail if a page is out of date")
    args = parser.parse_args(argv)
    stale = []
    for page, make in PAGES.items():
        content = make()
        if args.check:
            if not page.exists() or page.read_text(encoding="utf-8") != content:
                stale.append(page)
        else:
            page.write_text(content, encoding="utf-8")
    if args.check:
        if stale:
            print("These pages are out of date. Run scripts/generate_reference.py:")
            for page in stale:
                print(f"  {page.relative_to(ROOT)}")
            return 1
        print("The reference pages match the code")
        return 0
    print("Wrote " + ", ".join(str(p.relative_to(ROOT)) for p in PAGES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
