"""
Generate the Python client of the API from ``panel/openapi.json`` (checklist J-18).

``panel/openapi.json`` is what the console's types are generated from; this turns the very same
document into a typed Python client, ``sdk/python/noust_sdk``, so a script that automates Noust
(a pipeline, a provisioning tool, a test) calls ``client.applications.list_apps()`` and gets
completion and a type checker instead of building URLs and guessing JSON.

Two files are written and never edited:

- ``_models.py``: one ``TypedDict`` for every schema of the API, so the shape of a request and of an
  answer is checked by mypy and shown by the editor. They are dictionaries at run time, which is what
  the API sends.
- ``_operations.py``: one method for every operation, grouped by the tag the console groups them by.
  A method's docstring carries the verb and path, what the route does, the permission it needs and
  whether it asks for sudo mode or a second person. ``OPERATIONS`` lists them all as data.

Everything else in the package (the transport, the errors, waiting for a job) is written by hand and
imports nothing but the standard library.

Usage:
    scripts/generate_sdk.py            Write the two files.
    scripts/generate_sdk.py --check    Fail if they are out of date. CI runs this.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "panel" / "openapi.json"
PACKAGE = ROOT / "sdk" / "python" / "noust_sdk"
MODELS = PACKAGE / "_models.py"
OPERATIONS = PACKAGE / "_operations.py"

HTTP_METHODS = ("get", "post", "put", "patch", "delete")

HEADER = """# Copyright (c) 2024-2026 Yago Lopez Prado
# SPDX-License-Identifier: AGPL-3.0-or-later
#
# Generated by scripts/generate_sdk.py from panel/openapi.json. Do not edit: change the API and
# generate it again (`python scripts/generate_sdk.py`); CI fails when this file is out of date.
"""


def identifier(text: str) -> str:
    """
    Args:
        text: A name from the schema: a tag, a schema, a parameter.

    Returns:
        A valid Python name, lower case, that is not a keyword or a name this client uses.
    """
    name = re.sub(r"\W+", "_", text).strip("_") or "x"
    if name[0].isdigit():
        name = f"_{name}"
    if keyword.iskeyword(name) or name in {"self", "body", "query", "timeout"}:
        name += "_"
    return name


def snake(text: str) -> str:
    """
    Args:
        text: A tag or a function name.

    Returns:
        It in snake case.
    """
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", text)
    return identifier(spaced).lower()


def class_name(text: str) -> str:
    """
    Args:
        text: A schema or a tag name.

    Returns:
        A CamelCase class name.
    """
    parts = [part for part in re.split(r"\W+|_", text) if part]
    joined = "".join(part[:1].upper() + part[1:] for part in parts) or "Model"
    return joined if not joined[0].isdigit() else f"M{joined}"


def split_top_level(text: str) -> list[str]:
    """
    Args:
        text: The inside of a bracket: ``str, list[int], None``.

    Returns:
        Its members, split at the commas that are not inside another bracket.
    """
    members, depth, start = [], 0, 0
    for index, char in enumerate(text):
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
        elif char == "," and depth == 0:
            members.append(text[start:index].strip())
            start = index + 1
    members.append(text[start:].strip())
    return members


def union(members: list[str]) -> str:
    """
    A union written with ``Union[...]``: a member may be a quoted forward reference, and
    ``"A" | None`` cannot be evaluated where a TypedDict is created.

    Args:
        members: Python type expressions.

    Returns:
        One expression for any of them.
    """
    flat: list[str] = []
    for member in members:
        if member.startswith("Union["):
            flat += split_top_level(member[len("Union[") : -1])
        else:
            flat.append(member)
    unique = list(dict.fromkeys(flat))
    return unique[0] if len(unique) == 1 else f"Union[{', '.join(unique)}]"


def optional(kind: str) -> str:
    """
    Args:
        kind: A Python type expression.

    Returns:
        The same, accepting ``None`` as well.
    """
    return union([kind, "None"])


class Models:
    """
    The schemas of the API as Python types.

    Args:
        schemas: ``components.schemas`` of the document.
    """

    def __init__(self, schemas: dict[str, Any]) -> None:
        self.schemas = schemas
        self.names: dict[str, str] = {}
        taken: set[str] = set()
        for original in sorted(schemas):
            name = class_name(original)
            while name in taken:
                name += "_"
            taken.add(name)
            self.names[original] = name

    def ref(self, reference: str) -> str:
        """
        Args:
            reference: ``#/components/schemas/Name``.

        Returns:
            The class that stands for it, quoted (they are defined in any order).
        """
        return f'"{self.names[reference.rsplit("/", 1)[-1]]}"'

    def type_of(self, schema: dict[str, Any]) -> str:
        """
        Args:
            schema: A JSON Schema as FastAPI writes it.

        Returns:
            A Python type expression for it.
        """
        if "$ref" in schema:
            return self.ref(schema["$ref"])
        if "enum" in schema:
            values = ", ".join(json.dumps(value) for value in schema["enum"])
            return f"Literal[{values}]"
        if "const" in schema:
            return f"Literal[{json.dumps(schema['const'])}]"
        for combine in ("anyOf", "oneOf"):
            if combine in schema:
                return union([self.type_of(member) for member in schema[combine]])
        if "allOf" in schema:
            members = [self.type_of(member) for member in schema["allOf"]]
            return members[0] if len(members) == 1 else "dict[str, Any]"
        kind = schema.get("type")
        if isinstance(kind, list):
            return union([self.type_of({**schema, "type": k}) for k in kind])
        scalars = {
            "string": "str",
            "integer": "int",
            "number": "float",
            "boolean": "bool",
            "null": "None",
        }
        if kind in scalars:
            return scalars[kind]
        if kind == "array":
            return f"list[{self.type_of(schema.get('items') or {})}]"
        if kind == "object" or "properties" in schema or "additionalProperties" in schema:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and not schema.get("properties"):
                return f"dict[str, {self.type_of(extra)}]"
            return "dict[str, Any]"
        return "Any"

    def render(self) -> str:
        """
        Returns:
            The text of ``_models.py``.
        """
        lines = [
            HEADER,
            '"""The shapes of the API\'s requests and answers, as typed dictionaries."""',
            "",
            "from __future__ import annotations",
            "",
            "from typing import Any, Literal, NotRequired, Required, TypeAlias, TypedDict, Union",
            "",
        ]
        for original in sorted(self.schemas):
            schema = self.schemas[original]
            name = self.names[original]
            if schema.get("type") == "object" or "properties" in schema:
                required = set(schema.get("required", []))
                fields = []
                for key, member in (schema.get("properties") or {}).items():
                    wrapper = "Required" if key in required else "NotRequired"
                    fields.append(f"    {json.dumps(key)}: {wrapper}[{self.type_of(member)}],")
                if fields:
                    lines.append(f'{name} = TypedDict("{name}", {{')
                    lines.extend(fields)
                    lines.append("})")
                else:
                    lines.append(f"{name} = dict[str, Any]")
            else:
                lines.append(f"{name}: TypeAlias = {self.type_of(schema)}")
            lines.append("")
        return "\n".join(lines).rstrip("\n") + "\n"


def success_schema(operation: dict[str, Any]) -> dict[str, Any] | None:
    """
    Args:
        operation: One operation of the document.

    Returns:
        The schema of its first successful JSON answer, or None.
    """
    for code in sorted(operation.get("responses", {})):
        if code.startswith("2"):
            content = operation["responses"][code].get("content") or {}
            if "application/json" in content:
                return content["application/json"].get("schema")  # type: ignore[no-any-return]
    return None


def is_binary(operation: dict[str, Any]) -> bool:
    """
    Args:
        operation: One operation of the document.

    Returns:
        Whether its successful answer is not JSON (a file, a CSV, an image).
    """
    for code, response in operation.get("responses", {}).items():
        if code.startswith("2"):
            content = response.get("content") or {}
            if content and "application/json" not in content:
                return True
    return False


def method_name(operation: dict[str, Any], path: str, verb: str) -> str:
    """
    Args:
        operation: One operation of the document.
        path: Its path.
        verb: Its HTTP method, lower case.

    Returns:
        The name of the function it was written as: FastAPI appends the path and the verb to it.
    """
    operation_id = operation.get("operationId", "")
    suffix = re.sub(r"\W", "_", path) + "_" + verb
    if operation_id.endswith(suffix) and len(operation_id) > len(suffix):
        return snake(operation_id[: -len(suffix)])
    return snake(operation_id or f"{verb}_{path}")


def docstring(operation: dict[str, Any], path: str, verb: str) -> str:
    """
    Args:
        operation: One operation of the document.
        path: Its path.
        verb: Its HTTP method.

    Returns:
        The method's docstring.
    """
    summary = (operation.get("summary") or "").strip()
    needs = (
        [f"permission `{operation['x-noust-permission']}`"]
        if "x-noust-permission" in operation
        else []
    )
    if operation.get("x-noust-requires-elevation"):
        needs.append("sudo mode")
    if operation.get("x-noust-requires-approval"):
        needs.append("a second person's approval can be required")
    first = f"{verb.upper()} {path}"
    body = [first]
    if summary:
        body.append(summary)
    if needs:
        body.append("Needs: " + ", ".join(needs) + ".")
    if operation.get("deprecated"):
        body.append("Deprecated: see the API changelog.")
    return "\n\n        ".join(body).replace('"""', "'''")


def render_operations(document: dict[str, Any], models: Models) -> str:
    """
    Args:
        document: The OpenAPI document.
        models: Its schemas as Python types.

    Returns:
        The text of ``_operations.py``.
    """
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path in sorted(document["paths"]):
        for verb in HTTP_METHODS:
            operation = document["paths"][path].get(verb)
            if operation is None:
                continue
            tag = (operation.get("tags") or ["Other"])[0]
            groups.setdefault(tag, []).append((path, verb, operation))

    table: list[str] = []
    classes: list[str] = []
    attributes: list[tuple[str, str]] = []
    for tag in sorted(groups):
        group = snake(tag)
        cls = class_name(tag)
        attributes.append((group, cls))
        lines = [f"class {cls}:", f'    """{tag}: {len(groups[tag])} operations."""', ""]
        lines += ["    def __init__(self, call: Call) -> None:", "        self._call = call", ""]
        used: set[str] = {"__init__"}
        for path, verb, operation in groups[tag]:
            name = method_name(operation, path, verb)
            if name in used:
                name = f"{name}_{verb}"
            while name in used:
                name += "_"
            used.add(name)
            parameters = operation.get("parameters", [])
            path_params = [p for p in parameters if p["in"] == "path"]
            query_params = [p for p in parameters if p["in"] == "query"]
            body = operation.get("requestBody")
            body_required = bool(body and body.get("required"))
            body_schema = None
            if body:
                body_schema = (body.get("content") or {}).get("application/json", {}).get("schema")
            returns = "bytes" if is_binary(operation) else "Any"
            answer = success_schema(operation)
            if answer is not None:
                returns = models.type_of(answer)
            signature = ["self"]
            names: dict[str, str] = {}
            for parameter in path_params:
                local = identifier(parameter["name"])
                names[parameter["name"]] = local
                kind = models.type_of(parameter.get("schema") or {})
                signature.append(f"{local}: {'int | str' if kind == 'int' else kind}")
            if body_schema is not None and body_required:
                signature.append(f"body: {models.type_of(body_schema)}")
            keyword_only: list[str] = []
            for parameter in query_params:
                local = identifier(parameter["name"])
                names[parameter["name"]] = local
                kind = models.type_of(parameter.get("schema") or {})
                if parameter.get("required"):
                    keyword_only.insert(0, f"{local}: {kind}")
                else:
                    keyword_only.append(f"{local}: {optional(kind)} = None")
            if body_schema is not None and not body_required:
                keyword_only.append(f"body: {optional(models.type_of(body_schema))} = None")
            if keyword_only:
                signature += ["*", *keyword_only]
            url = path
            for parameter in path_params:
                url = url.replace(
                    "{" + parameter["name"] + "}",
                    "{quote(str(" + names[parameter["name"]] + "), safe='')}",
                )
            literal = f'f"{url}"' if path_params else f'"{url}"'
            query = (
                "{" + ", ".join(f'"{p["name"]}": {names[p["name"]]}' for p in query_params) + "}"
                if query_params
                else "None"
            )
            lines.append(f"    def {name}({', '.join(signature)}) -> {returns}:")
            lines.append(f'        """{docstring(operation, path, verb)}"""')
            lines.append(
                f'        return self._call("{verb.upper()}", {literal}, query={query}, '
                f"body={'body' if body_schema is not None else 'None'}"
                f"{', binary=True' if is_binary(operation) else ''})"
            )
            lines.append("")
            table.append(
                f'    ("{group}", "{name}"): ("{verb.upper()}", "{path}", '
                f"{json.dumps(operation.get('x-noust-permission'))}, "
                f"{bool(operation.get('x-noust-requires-elevation'))}),"
            )
        classes.append("\n".join(lines))

    head = [
        HEADER,
        '"""One method for every operation of the API, grouped by the area the console groups them in."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, Protocol, Union",
        "from urllib.parse import quote",
        "",
        "from noust_sdk._models import *  # noqa: F403",
        "",
        "",
        "class Call(Protocol):",
        '    """What a group needs of the client: to make one request."""',
        "",
        "    def __call__(",
        "        self,",
        "        method: str,",
        "        path: str,",
        "        *,",
        "        query: dict[str, Any] | None = None,",
        "        body: Any = None,",
        "        binary: bool = False,",
        "    ) -> Any: ...",
        "",
        "",
        f"API_VERSION = {json.dumps(document['info'].get('version'))}",
        "",
        "#: ``(group, method)`` to ``(HTTP method, path, permission, needs sudo mode)``.",
        "OPERATIONS: dict[tuple[str, str], tuple[str, str, str | None, bool]] = {",
        *table,
        "}",
        "",
        "",
    ]
    tail = [
        "",
        "",
        "class Api:",
        '    """Every group of operations, as attributes of the client."""',
        "",
    ]
    tail += [f"    {group}: {cls}" for group, cls in attributes]
    tail += ["", "    def __init__(self, call: Call) -> None:"]
    tail += [f"        self.{group} = {cls}(call)" for group, cls in attributes]
    return "\n".join(head) + "\n\n\n".join(classes) + "\n".join(tail) + "\n"


def generate() -> dict[Path, str]:
    """
    Returns:
        The text of each generated file, by path.
    """
    document = json.loads(SCHEMA.read_text(encoding="utf-8"))
    models = Models(document["components"]["schemas"])
    return {MODELS: models.render(), OPERATIONS: render_operations(document, models)}


def main(argv: list[str] | None = None) -> int:
    """
    Args:
        argv: Arguments; the process's by default.

    Returns:
        0, or 1 under ``--check`` when a file is out of date.
    """
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="Fail if a file is out of date.")
    args = parser.parse_args(argv)
    stale = []
    for path, text in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        names = ", ".join(str(path) for path in stale)
        print(f"{names} out of date: run python scripts/generate_sdk.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
