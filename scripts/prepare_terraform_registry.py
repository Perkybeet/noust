"""
Stage the Terraform provider as the repository the Terraform Registry needs (checklist J-14).

The registry publishes only a public GitHub repository named ``terraform-provider-<name>``, whose releases
carry a zip per platform, a SHA256SUMS file and its detached GPG signature. The provider's source lives in
``terraform-provider-noust/`` of this repository, so publishing means copying it into a repository of its
own. This script does the copying and the checking, and nothing else:

- it writes a directory on this machine (``build/terraform-registry/terraform-provider-noust`` by default);
- it creates no repository, pushes nothing, tags nothing, and touches no key and no secret.

The repository, the signing key and the registry account are the owner's; ``docs/terraform-registry.md``
says what to do with the directory this leaves, and the last thing this prints is the same list.

    python scripts/prepare_terraform_registry.py
    python scripts/prepare_terraform_registry.py --owner SomeOrg --out /tmp/stage
    python scripts/prepare_terraform_registry.py --check      # only verify that the provider is ready
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from collections.abc import Sequence
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "terraform-provider-noust"
DEFAULT_OUT = REPO / "build" / "terraform-registry"

#: The GitHub account the provider's module path and registry address are written for.
DEFAULT_OWNER = "Perkybeet"
PROVIDER_NAME = "noust"
REPOSITORY = f"terraform-provider-{PROVIDER_NAME}"

#: Where the Noust repository's own documents are, for the links that leave the provider's directory.
DOCS_BASE = "https://github.com/Perkybeet/noust/blob/main/"

#: What the registry cannot publish without.
REQUIRED = (
    "main.go",
    "go.mod",
    "go.sum",
    "LICENSE",
    "README.md",
    ".goreleaser.yml",
    "terraform-registry-manifest.json",
    ".github/workflows/release.yml",
    "docs/index.md",
    "examples/provider/provider.tf",
)

#: What a staged repository does not carry: the end-to-end test drives the Noust repository's harness, and
#: nothing generated by a local Terraform belongs in git.
EXCLUDED_DIRECTORIES = {"e2e", ".terraform", "dist", "__pycache__"}
EXCLUDED_SUFFIXES = (".tfstate", ".tfstate.backup", ".plan")


class NotReady(Exception):
    """The provider is missing something the registry needs."""


def missing(root: Path) -> list[str]:
    """
    Args:
        root: A provider directory, the source or a staged copy.

    Returns:
        What the registry needs that is not there: the required files, and the documentation pages
        ``tfplugindocs`` writes for the resources and the data sources (``go generate ./...``). CI
        regenerates them and fails on a difference, so that they are there is all this has to look for.
    """
    found = [name for name in REQUIRED if not (root / name).is_file()]
    for kind in ("resources", "data-sources"):
        directory = root / "docs" / kind
        if not directory.is_dir() or not any(directory.glob("*.md")):
            found.append(f"docs/{kind}/*.md")
    return found


def stage(destination: Path, *, owner: str = DEFAULT_OWNER, source: Path = SOURCE) -> list[Path]:
    """
    Copy the provider into ``destination`` as the repository the registry publishes.

    Args:
        destination: The directory to write, replaced if it exists.
        owner: The GitHub account that will own the repository. The module path and the registry address
            are rewritten for it when it is not the default.
        source: The provider's directory.

    Returns:
        The files written, relative to the destination.

    Raises:
        NotReady: The provider lacks something the registry needs.
    """
    absent = missing(source)
    if absent:
        raise NotReady("the provider is not ready to publish, it lacks: " + ", ".join(absent))
    if destination.exists():
        shutil.rmtree(destination)
    written: list[Path] = []
    for path in sorted(source.rglob("*")):
        relative = path.relative_to(source)
        if (
            path.is_dir()
            or EXCLUDED_DIRECTORIES & set(relative.parts)
            or path.name.endswith(EXCLUDED_SUFFIXES)
        ):
            continue
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if (
            path.suffix in {".go", ".md", ".mod", ".tf", ".yml", ".yaml", ".json", ".sh"}
            or path.name == "go.mod"
        ):
            text = path.read_text(encoding="utf-8")
            target.write_text(_adapt(text, relative, owner), encoding="utf-8")
            target.chmod(path.stat().st_mode)
        else:
            shutil.copy2(path, target)
        written.append(relative)
    (destination / ".gitignore").write_text(
        "dist/\n.terraform/\n.terraform.lock.hcl\n*.tfstate\n*.tfstate.backup\n*.plan\n",
        encoding="utf-8",
    )
    written.append(Path(".gitignore"))
    return written


def _adapt(text: str, relative: Path, owner: str) -> str:
    """
    Make a file of the monorepo true in a repository of its own.

    Args:
        text: The file.
        relative: Its path in the provider.
        owner: The GitHub account that will own the repository.

    Returns:
        The file with the links that left the directory made absolute, and the owner's name where it is
        written.
    """
    if relative.suffix == ".md":
        # [..](../docs/terraform.md) is a document of the Noust repository.
        text = re.sub(r"\]\(\.\./", f"]({DOCS_BASE}", text)
    if owner != DEFAULT_OWNER:
        text = text.replace(
            f"github.com/{DEFAULT_OWNER}/{REPOSITORY}", f"github.com/{owner}/{REPOSITORY}"
        )
        text = text.replace(
            f"{DEFAULT_OWNER.lower()}/{PROVIDER_NAME}", f"{owner.lower()}/{PROVIDER_NAME}"
        )
    return text


def next_steps(destination: Path, owner: str) -> str:
    """
    Returns:
        What the owner does with the staged directory, as commands. Nothing here is run.
    """
    return f"""\
Staged: {destination}

Nothing was created and nothing was pushed. To publish (docs/terraform-registry.md has the reasons):

  1. Make the repository public and empty, named exactly {REPOSITORY}, under {owner}:
       gh repo create {owner}/{REPOSITORY} --public --description "Terraform and OpenTofu provider for Noust"
  2. Make a signing key (RSA 4096) and give the registry its public half and the repository its private half:
       gpg --full-generate-key
       gpg --armor --export <KEY-ID>                       > the registry (Settings, Signing Keys)
       gpg --armor --export-secret-keys <KEY-ID>           > the repository secret GPG_PRIVATE_KEY
       the key's passphrase                                > the repository secret PASSPHRASE
  3. Push the staged directory as the repository's first commit:
       cd {destination}
       git init -b main && git add -A && git commit -m "terraform-provider-noust 0.1.0"
       git remote add origin git@github.com:{owner}/{REPOSITORY}.git && git push -u origin main
  4. Publish it at registry.terraform.io (Publish, Provider, the repository), then tag the release:
       git tag v0.1.0 && git push origin v0.1.0
"""


def main(argv: Sequence[str] | None = None) -> int:
    """
    Stage the provider, or check it.

    Args:
        argv: Arguments, defaulting to ``sys.argv[1:]``.

    Returns:
        0 on success, 1 when the provider is not ready.
    """
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_OUT / REPOSITORY, help="the directory to write"
    )
    parser.add_argument(
        "--owner", default=DEFAULT_OWNER, help="the GitHub account that will own the repository"
    )
    parser.add_argument(
        "--check", action="store_true", help="only check that the provider is ready to publish"
    )
    args = parser.parse_args(argv)
    if args.check:
        absent = missing(SOURCE)
        if absent:
            print("not ready, lacks: " + ", ".join(absent), file=sys.stderr)
            return 1
        print("ready")
        return 0
    try:
        written = stage(args.out, owner=args.owner)
    except NotReady as error:
        print(error, file=sys.stderr)
        return 1
    print(f"{len(written)} files")
    print(next_steps(args.out, args.owner))
    return 0


if __name__ == "__main__":
    sys.exit(main())
