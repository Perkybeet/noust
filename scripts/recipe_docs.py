"""
Write the catalogue's table into docs/recipes.md, from the recipes themselves.

The list of what ships was typed by hand while the catalogue was fifty recipes; at a hundred and
more it is generated, so that the count, the versions and what each recipe runs on cannot drift
from the files. The part between the two markers of "What ships, and what does not" is this tool's;
the table of the recipes that are listed but not installable, and the prose around, are written by
a person.

Usage:
    scripts/recipe_docs.py            Rewrite the generated part of docs/recipes.md.
    scripts/recipe_docs.py --check    Fail if it is out of date (CI and the tests run this).
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from noust.recipes import list_recipes  # noqa: E402
from noust.recipes.model import Recipe  # noqa: E402

DOCS = ROOT / "docs" / "recipes.md"
RECIPES = ROOT / "src" / "noust" / "recipes"
START = "<!-- recipes:start (generated by scripts/recipe_docs.py; do not edit) -->"
END = "<!-- recipes:end -->"

#: What a database or store image is called in the table, by repository (first match wins).
SERVICES: tuple[tuple[str, str], ...] = (
    ("pgvector/pgvector", "PostgreSQL with pgvector"),
    ("immich-app/postgres", "PostgreSQL with VectorChord"),
    ("postgres", "PostgreSQL"),
    ("mysql", "MySQL"),
    ("mariadb", "MariaDB"),
    ("mongo", "MongoDB"),
    ("clickhouse/clickhouse-server", "ClickHouse"),
    ("valkey/valkey", "Valkey"),
    ("redis", "Redis"),
    ("getmeili/meilisearch", "Meilisearch"),
    ("karakeep-app/karakeep-chrome", "headless Chrome"),
)

#: The native deployers' names in the table.
RUNTIMES = {
    "nodejs": "Node.js",
    "php-fpm": "PHP-FPM",
    "python": "Python",
    "nextjs": "Node.js",
}

#: What a person adds to a row that the files do not say.
NOTES = {
    "mailpit": "SMTP on 127.0.0.1",
    "ollama": "no authentication of its own",
    "searxng": "a dated build, the project has no releases",
    "rabbitmq": "AMQP on 127.0.0.1",
    "home-assistant": "no discovery on the local network: devices by address",
}


def services_of(recipe: Recipe) -> list[str]:
    """
    Name the databases and stores a Compose recipe runs beside its application.

    Args:
        recipe: A Compose recipe.

    Returns:
        Their names in the order the document lists them, each once, and never the application
        itself (Meilisearch's own recipe does not list Meilisearch).
    """
    found: list[str] = []
    for image in recipe.images:
        repository = image.repository
        if repository.endswith(f"/{recipe.name}") or repository == recipe.name:
            continue
        for prefix, label in SERVICES:
            if repository == prefix or repository.endswith(f"/{prefix}"):
                if label not in found:
                    found.append(label)
                break
    return found


def runs(recipe: Recipe) -> str:
    """
    Say what a recipe runs on, for its row.

    Args:
        recipe: An installable recipe.

    Returns:
        ``Docker; PostgreSQL, Valkey; opens 2222 tcp``, or the language runtime and the engines a
        native recipe asks the server for.
    """
    if recipe.kind == "compose":
        head, stores = "Docker", services_of(recipe)
    else:
        head = RUNTIMES.get(recipe.app_type, recipe.app_type)
        engines = {"postgres": "PostgreSQL", "mysql": "MySQL", "mariadb": "MariaDB"}
        stores = [engines.get(need, need.capitalize()) for need in recipe.requires if need != "s3"]
        if recipe.database_choices:
            stores = ["MySQL/MariaDB"]
    extras: list[str] = []
    if recipe.entrypoints:
        extras.append(
            "answers on "
            + " and ".join(f"a second address ({entry.name})" for entry in recipe.entrypoints)
        )
    opened: dict[int, list[str]] = {}
    for port in recipe.public_ports:
        opened.setdefault(port.port, []).append(port.protocol)
    extras.extend(f"opens {number} {' and '.join(kinds)}" for number, kinds in opened.items())
    if recipe.name in NOTES:
        extras.append(NOTES[recipe.name])
    return "; ".join([head, *([", ".join(stores)] if stores else []), *extras])


def provenance(recipe: Recipe) -> str:
    """
    Say where a recipe comes from, from the comment that heads its file.

    Args:
        recipe: A recipe of the package.

    Returns:
        ``coolify`` when its header credits a Coolify template, else ``project``.
    """
    head = (RECIPES / f"{recipe.name}.yaml").read_text(encoding="utf-8").split("schema:", 1)[0]
    return "coolify" if re.search(r"Coolify'?s? (service )?template", head) else "project"


def generate() -> str:
    """
    Build the generated part of the page.

    Returns:
        The text between the markers, markers included.
    """
    recipes = sorted(list_recipes(), key=lambda recipe: recipe.title.lower())
    installable = [recipe for recipe in recipes if recipe.available]
    listed = [recipe for recipe in recipes if not recipe.available]
    kinds = Counter(recipe.kind for recipe in installable)
    sources = Counter(provenance(recipe) for recipe in installable)
    lines = [
        START,
        "",
        f"The catalogue has {len(installable)} recipes you can install and {len(listed)} that are "
        "listed with the reason.",
        "",
        f"Of the {len(installable)} you can install, {kinds['compose']} run in Docker and "
        f"{kinds['native']} are native (a pinned source built by one of Noust's deployers). "
        f"{sources['project']} were written from the project's own documentation, and "
        f"{sources['coolify']} took part of their wiring from Coolify's service templates "
        "(Apache-2.0), credited in the header of their file. Every image is pinned by tag and by "
        "digest and every recipe starts closed. `scripts/recipe_smoke.py` starts a recipe in "
        "Docker and asks its health check: run it for a recipe you add or change.",
        "",
        "| Recipe | Version | Kind | Runs |",
        "|---|---|---|---|",
    ]
    for recipe in installable:
        lines.append(f"| {recipe.title} | {recipe.version} | {recipe.kind} | {runs(recipe)} |")
    lines.extend(["", END])
    return "\n".join(lines)


def current() -> str:
    """
    Read the generated part as the page holds it.

    Returns:
        The text between the markers, markers included.

    Raises:
        SystemExit: The page has no markers.
    """
    text = DOCS.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{DOCS} has no {START!r} ... {END!r} block")
    return START + text.split(START, 1)[1].split(END, 1)[0] + END


def main(argv: Sequence[str] | None = None) -> int:
    """
    Run the tool.

    Args:
        argv: The arguments; ``sys.argv`` when None.

    Returns:
        0 when the page is (or has been made) current, 1 under ``--check`` when it is not.
    """
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args(argv)
    wanted, found = generate(), current()
    if wanted == found:
        print("docs/recipes.md is current.")
        return 0
    if args.check:
        print("docs/recipes.md is out of date: run scripts/recipe_docs.py", file=sys.stderr)
        return 1
    DOCS.write_text(DOCS.read_text(encoding="utf-8").replace(found, wanted, 1), encoding="utf-8")
    print("docs/recipes.md updated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
