#: The release in which every entry below stops being accepted unless it says otherwise.
#: Dropping one is a decision per entry, made when the major version changes.
NEXT_MAJOR = "5.0"


@dataclass(frozen=True)
class LegacyName:
    """
    One name that is still accepted, with the reason and the date.

    Attributes:
        key: What it is called here.
        old: The name from before 4.0.
        new: The name Noust writes now; empty when the thing has no name any more.
        handling: What is done with the old name: ``read`` (accepted as input), ``renamed``
            (Noust holds it and renames it on next use), ``kept`` (while something that is
            not Noust's names it) or ``ignored`` (not read, expired where it can be).
        reason: Why the old name is still met.
        until: When it stops being accepted.
    """

    key: str
    old: str
    new: str
    handling: str
    reason: str
    until: str


# -- Console sign-in ----------------------------------------------------------------------

#: A browser signed in before the update holds these. They are not read: the console asks
#: to sign in once, and the sign-in and the sign-out expire them so they do not linger.
SESSION_COOKIE = "wasm_session"
CSRF_COOKIE = "wasm_csrf"

#: Scripts that sign in with a cookie jar and then call the API hard-code the header;
#: nothing but its name differs, so it is accepted beside ``X-Noust-CSRF``.
CSRF_HEADER = "X-WASM-CSRF"

#: Integrations that open a stream with the token in the subprotocol.
WS_SUBPROTOCOL = "wasm.auth"
WS_TOKEN_PREFIX = "wasm.token."  # noqa: S105 - subprotocol prefix, not a credential

#: API tokens issued before 3.0 are stored hashed and live in scripts and CI secrets of
#: people Noust cannot reach: they work until revoked or expired.
API_TOKEN_PREFIX = "wasm_tok_"  # noqa: S105 - a prefix, not a credential

# -- Files in the operator's repositories, parameters of their scripts ----------------------

NGINX_OVERRIDE_FILES: tuple[str, ...] = ("wasm.nginx.yaml", "wasm.nginx.yml")
ONLY_PARAMETER = "wasm_only"

# -- What Noust generates and others may name -----------------------------------------------

#: Prefix of the upstream blocks Noust generates for blue/green and for a Compose relay.
#: A site the operator wrote may name one (``proxy_pass http://<prefix><app>``); it is never
#: rewritten, so the application keeps generating the old name while such a site exists.
UPSTREAM_PREFIX = "wasm_bg_"

#: First line a site or a unit file carried when it was written before the rename and
#: nothing regenerated it since: rewritten once, in that line only, by the name migration.
GENERATED_MARKER = "Generated by WASM"

# -- What Noust holds and renames when it is next used ---------------------------------------

#: The accounts the read-only console signs in as (``<prefix><database>``), and Redis's.
READ_ONLY_PREFIX = "wasm_ro_"

#: What Noust keeps in an application's tree.
TREE_ENV_DIR = ".wasm"
TREE_RUNTIME_STAMP = ".wasm-runtime.json"
TREE_PHP_SETTINGS = ".wasm-php.json"
TREE_PHP_TMP = ".wasm-php-tmp"

FOLLOW_BRANCH_KEY = "wasm.branch"
PREVIOUS_IMAGE_TAG = "wasm-previous"

#: The folder backups went to by default; the ones already there stay listed until their
#: retention removes them. ``CURRENT_BACKUP_FOLDER`` is the one that replaces it.
BACKUP_FOLDER = "wasm-backups"
CURRENT_BACKUP_FOLDER = "noust-backups"

#: The prefix application units had before 0.14.1. A unit that still has it keeps working
#: and is renamed by that application's next deployment, which restarts it anyway.
UNIT_PREFIX = "wasm-"

# -- Data that never expires ---------------------------------------------------------------

#: A backup archive holds its payload under this directory; the reader is
#: :mod:`noust.core.legacy_archive`, and archives are written under ``noust-backup`` now.
ARCHIVE_PAYLOAD_DIR = "wasm-backup"

#: The string a backup's origin fingerprint is derived from, for the archives of both
#: spellings. Not a name anyone sees: changing it would make every backup this server wrote
#: look as if another server had made it.
ARCHIVE_ORIGIN_SALT = "wasm-backup-origin"

#: An application export document says ``"format": "wasm-app"`` and ``"wasm_version"``.
EXPORT_FORMAT = "wasm-app"
EXPORT_VERSION_KEY = "wasm_version"


