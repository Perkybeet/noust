"""
Every name from before 4.0 that Noust still accepts, each with why and until when.

The product's names are Noust's everywhere it writes. What lives where Noust does not
control is a different matter: a script that sends a header, a token stored in a CI
secret, a file in a customer's repository, a site an operator wrote by hand, a backup
that was made years ago. Those keep the name they were made with, so a server that
updates does not break the things around it, and this is the one module that spells
them. Code elsewhere asks for ``legacy_names.X`` where it must still recognise the old
spelling, and writes the new one.

The rule for every entry is the same: **accept the old name on input, emit the new one**.
Where Noust itself holds the old name (an account, a unit, a file in an application's
tree, a tag, a folder) it is renamed the next time that thing is used anyway, never
in a step that restarts something outside a deployment; :mod:`noust.core.name_migration`
lists what is left.

:data:`REGISTRY` is the same list as data, for ``noust setup doctor``, the documentation
and the test that holds each entry to a reason and a date.
"""

