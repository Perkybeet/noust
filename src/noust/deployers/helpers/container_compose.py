"""
The Compose project Noust writes for a container application.

A container application runs through the same machinery as a Compose stack
(its unit, its health gate, its site): what differs is who wrote the compose
file. Here nothing in it comes from a repository. It is generated, from the
settings the store keeps and the release being activated, and has one service
with one image, published on 127.0.0.1 only: the web server in front is the
only way in.

The image is always one that Noust already has on the host, named
``noust-<app>:<release>`` (see :func:`image_tag`), with ``pull_policy: never``.
Building it, or pulling it from a registry, happens before, behind the
deployer's steps and with the registry account it needs; a restart of the unit
must never fetch anything, and going back to a release is writing this file
again with that release's tag.

This module only decides what the file says. :mod:`noust.deployers.container`
writes it, through the filesystem seam.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

import yaml

from noust.core.container_store import ContainerSettings
from noust.core.exceptions import ValidationError
from noust.managers.service_manager import ResourceLimits
from noust.validators.container import METHOD_IMAGE, METHOD_RAILPACK

#: The generated file, beside the application's own files. Named apart from
#: ``compose.yaml`` so a repository that has one for development is left alone.
COMPOSE_FILE = "compose.noust.yaml"

#: The one service of the project.
SERVICE = "app"

#: What the first line of the file says, and the marker the rest of Noust
#: recognises its own files by.
GENERATED_MARKER = (
    "Generated by Noust. Do not edit: change the settings with `noust app container set`."
)

#: Every image a container application runs is named after it.
IMAGE_PREFIX = "noust-"

#: The release part of a tag: the ids ``ReleaseManager`` hands out.
_RELEASE = re.compile(r"^\d{8}-\d{6}-(?:[0-9a-f]{7}|nogit)(?:-[1-9][0-9]*)?$")

#: What a volume's name may hold in a compose file.
_VOLUME_NAME = re.compile(r"[^a-z0-9]+")


@dataclass(frozen=True)
class ContainerPlan:
    """
    Everything the compose file of one release is made from.

    Attributes:
        app_name: The application's name (``domain_to_app_name``).
        domain: Its domain, for the labels.
        release_id: The release the image belongs to.
        host_port: The port on 127.0.0.1 the web server proxies to.
        settings: How the application is built and run.
        limits: The application's memory, CPU and task limits.
        bind_mounts: Files and paths of the server bound into the container, as
            ``(source on the server, target in the container, read_only)``.
    """

    app_name: str
    domain: str
    release_id: str
    host_port: int
    settings: ContainerSettings
    limits: ResourceLimits
    bind_mounts: tuple[tuple[str, str, bool], ...] = ()


def image_repository(app_name: str) -> str:
    """
    Name the repository every image of an application is kept under.

    Args:
        app_name: The application's name.

    Returns:
        ``noust-<app>``.
    """
    return f"{IMAGE_PREFIX}{app_name}"


def image_tag(app_name: str, release_id: str) -> str:
    """
    Name the image of one release.

    Args:
        app_name: The application's name.
        release_id: The release's id.

    Returns:
        ``noust-<app>:<release>``.
    """
    return f"{image_repository(app_name)}:{release_id}"


def release_of_tag(app_name: str, tag: str) -> str | None:
    """
    Read the release an application's image tag names.

    Args:
        app_name: The application's name.
        tag: An image reference as Docker lists it.

    Returns:
        The release id, or None when the tag is not one of this application's
        release images.
    """
    repository, _, release = tag.partition(":")
    if repository != image_repository(app_name) or _RELEASE.fullmatch(release) is None:
        return None
    return release


def _volume_names(paths: tuple[str, ...]) -> list[str]:
    """
    Give each volume a name of its own.

    Args:
        paths: The container paths.

    Returns:
        One name per path: its slug, with a number after it when another path
        has the same slug.
    """
    names: list[str] = []
    for path in paths:
        slug = _VOLUME_NAME.sub("-", path.lower()).strip("-") or "data"
        candidate, number = slug, 1
        while candidate in names:
            number += 1
            candidate = f"{slug}-{number}"
        names.append(candidate)
    return names


def _literal(words: tuple[str, ...]) -> list[str]:
    """
    Write words so Compose hands them to the container as they are.

    Compose interpolates ``$NAME`` in every string of the file, and a command is the
    operator's literal text: a ``$`` they typed reaches the process, not the host's environment.

    Args:
        words: The command's words.

    Returns:
        The words with every ``$`` doubled.
    """
    return [word.replace("$", "$$") for word in words]


def build_document(plan: ContainerPlan) -> dict[str, Any]:
    """
    Build the compose file of one release, as a document.

    Args:
        plan: What it is made from.

    Returns:
        The document, ready to dump.

    Raises:
        ValidationError: The host port is not a port.
    """
    if isinstance(plan.host_port, bool) or not 1 <= plan.host_port <= 65535:
        raise ValidationError(
            f"{plan.host_port!r} is not a port the web server can proxy to",
            details="The port on 127.0.0.1 is chosen when the application is created.",
            field="port",
        )
    settings = plan.settings
    port = settings.effective_port
    labels = {
        "io.noust.managed": "true",
        "io.noust.app": plan.domain,
        "io.noust.release": plan.release_id,
    }
    if settings.method == METHOD_IMAGE and settings.image:
        labels["io.noust.source"] = settings.image
    service: dict[str, Any] = {
        "image": image_tag(plan.app_name, plan.release_id),
        "pull_policy": "never",
        "restart": settings.restart_policy,
        "env_file": [".env"],
        # The host side is 127.0.0.1: the container is reached through the web
        # server, never from the network.
        "ports": [f"127.0.0.1:{plan.host_port}:{port}"],
        "labels": labels,
    }
    if settings.method == METHOD_RAILPACK:
        # What Railpack's images are documented to listen on.
        service["environment"] = {"PORT": str(port)}
    # What replaces the image's own program and arguments; an argument vector, never a shell.
    if settings.entrypoint is not None:
        service["entrypoint"] = _literal(settings.entrypoint)
    if settings.command is not None:
        service["command"] = _literal(settings.command)
    document: dict[str, Any] = {"services": {SERVICE: service}}

    if settings.volumes:
        names = _volume_names(settings.volumes)
        service["volumes"] = [
            f"{name}:{path}" for name, path in zip(names, settings.volumes, strict=True)
        ]
        document["volumes"] = {name: {} for name in names}
    if plan.bind_mounts:
        # A file or a path of the server, bound where the operator said: read-only
        # unless they asked otherwise (noust.managers.app_mounts validated it).
        service.setdefault("volumes", []).extend(
            f"{source}:{target}:{'ro' if read_only else 'rw'}"
            for source, target, read_only in plan.bind_mounts
        )

    limits: dict[str, str] = {}
    if plan.limits.memory_max_mb is not None:
        limits["memory"] = f"{plan.limits.memory_max_mb}M"
    if plan.limits.cpu_quota_percent is not None:
        limits["cpus"] = f"{plan.limits.cpu_quota_percent / 100:.2f}"
    if limits:
        service["deploy"] = {"resources": {"limits": limits}}
    if plan.limits.tasks_max is not None:
        service["pids_limit"] = plan.limits.tasks_max
    return document


def render_compose(plan: ContainerPlan) -> str:
    """
    Write the compose file of one release.

    Args:
        plan: What it is made from.

    Returns:
        The file's text: deterministic, so the same plan is the same bytes.

    Raises:
        ValidationError: See :func:`build_document`.
    """
    body = yaml.safe_dump(build_document(plan), sort_keys=False, default_flow_style=False)
    return f"# {GENERATED_MARKER}\n{body}"
