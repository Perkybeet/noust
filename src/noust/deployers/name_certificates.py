_APPLY_ERRORS = (NoustError, OSError)


@dataclass(frozen=True)
class NameCertificateChange:
    """
    What a change of a name's certificate did.

    Attributes:
        app: The application's primary domain.
        name: The name.
        certificate: ``shared`` or ``own`` afterwards.
        changed: Whether the choice differs from before (a retry of the same choice is not).
        tls: Whether the site serves TLS. Without it only the choice is kept, and the first
            certificate (``noust cert create``) orders the name's own.
        ordered: Whether a certificate was ordered for the name.
        shared_reduced: Whether the shared certificate was ordered again without the name.
        lineage_removed: Whether the certificate the name held on its own was deleted.
        operator_site: Whether the site is the operator's, and so was not written.
        lineage: The lineage that presents the name now (the name's own, or the shared one).
        warnings: What did not work after the site was already right, in certbot's own words
            where there are any.
    """

    app: str
    name: str
    certificate: str
    changed: bool
    tls: bool
    ordered: bool = False
    shared_reduced: bool = False
    lineage_removed: bool = False
    operator_site: bool = False
    lineage: str | None = None
    warnings: tuple[str, ...] = ()


@dataclass(frozen=True)
class NameBinding:
    """
    Which certificate serves one name of an application.

    Attributes:
        app: The application's primary domain.
        name: The name.
        kind: ``primary``, ``alias`` or ``redirect``.
        enabled: Whether the name is served.
        certificate: ``shared`` or ``own``, as recorded.
        served_by: The certificate that presents the name: a lineage certbot keeps, or an
            uploaded certificate. For a name with a certificate of its own that has not been
            ordered yet, the shared one, because that is what the site presents meanwhile.
        source: ``acme``, ``custom`` (uploaded) or ``lineage`` (another application's, a
            wildcard).
        pending: Whether the name asked for a certificate of its own that is not on disk yet.
        challenge: How the certificate is renewed: ``http-01``, ``dns-01``, or empty for an
            uploaded one.
    """

    app: str
    name: str
    kind: str
    enabled: bool
    certificate: str
    served_by: str | None
    source: str
    pending: bool = False
    challenge: str = ""


def set_certificate(
    app_domain: str,
    name: str,
    certificate: str,
    *,
    challenge: str | None = None,
    dns_provider: str | None = None,
    logger: Logger | None = None,
    verbose: bool = False,
) -> NameCertificateChange:
    """
    Make a name hold a certificate of its own, or go back to the application's.

    Args:
        app_domain: The application's primary domain.
        name: An alias or a redirect of the application.
        certificate: ``own`` or ``shared``.
        challenge: How the name's own certificate is proven, ``http-01`` or ``dns-01``; what
            it already had, else the application's own way. Changing it orders the certificate
            again once, because certbot keeps the way in the lineage's renewal configuration.
        dns_provider: The DNS account that answers ``dns-01``.
        logger: Where progress goes.
        verbose: Verbosity of the managers.

    Returns:
        What was done.

    Raises:
        NoustError: The application is unknown.
        DomainError: The name is not the application's, is its primary (which is the lineage
            everything hangs from), or belongs to the canonical pair, which is served together.
        ValidationError: The application's type orders one certificate for names only its
            deploy knows, a wildcard is asked to be proven over HTTP, the DNS account does not
            exist, or the web server refuses the new site (the choice is put back).
        CertificateError: The order was refused. certbot's output is carried verbatim and the
            certificate that served keeps serving.
        AppBusyError: Another operation is running on the application.
    """
    require_server_role("Certificates")
    mode = check_mode(certificate)
    if challenge is not None:
        check_choice(challenge, dns_provider)
    with app_lock(validate_domain(app_domain), "certificate change"):
        log = logger or Logger(verbose=verbose)
        app = domains.application(app_domain)
        host = validate_server_name(name)
        record = _record(app, host)
        deployer = domains.site_deployer(app, verbose=verbose)
        if mode == OWN:
            return _take_own(app, record, deployer, challenge, dns_provider, log)
        return _give_back(app, record, deployer, log)


def _record(app: App, name: str) -> DomainRecord:
    """
    Find the row of a name of the application.

    Args:
        app: The application.
        name: The name.

    Returns:
        Its row.

    Raises:
        DomainError: It is not one of the application's.
    """
    found = {record.domain: record for record in get_store().list_domains(app.domain)}.get(name)
    if found is None:
        raise DomainError(
            f"{name} is not a domain of {app.domain}",
            details=f"See the domains it answers on with: noust domain list {app.domain}",
        )
    return found


def _take_own(
    app: App,
    record: DomainRecord,
    deployer: ServesDomains,
    challenge: str | None,
    dns_provider: str | None,
    log: Logger,
) -> NameCertificateChange:
    """:func:`set_certificate` for ``own``, under the application's lock."""
    name = record.domain
    _check_can_hold(app, record)
    store, certificates = get_store(), CertificateStore()
    already = record.certificate == OWN
    before = certificates.get_settings(name)
    wanted = certificates.settings_for_name(
        app.domain, name, challenge=challenge, dns_provider=dns_provider, updated_by=_actor()
    )
    if wanted.challenge == CHALLENGE_DNS:
        check_choice(wanted.challenge, wanted.dns_provider)
    elif is_wildcard(name):
        raise ValidationError(
            f"{name} can only be proven with the DNS challenge",
            details=f"Choose the DNS account that manages it: noust domain certificate "
            f"{app.domain} {name} --own --dns NAME",
            field="challenge",
        )
    method_changed = already and (before.challenge, before.dns_provider) != (
        wanted.challenge,
        wanted.dns_provider,
    )

    tls = domains.serves_tls(app, deployer)
    manager = deployer.webserver_manager()
    operator = is_operator_site(manager, app.domain)
    lineage = lineage_name(name)
    existed = _on_disk(lineage)

    # 1. The certificate first, while the site goes on serving the name as it did. The settings
    #    are what the order reads; a refusal puts them back and nothing has changed.
    certificates.set_settings(wanted)
    ordered = False
    if tls:
        try:
            deployer.cert_manager.obtain_name(
                name,
                nginx=manager.backend.name == "nginx",
                apache=manager.backend.name == "apache",
                force=method_changed,
            )
        except _APPLY_ERRORS:
            certificates.set_settings(before)
            raise
        ordered = not existed or method_changed

    # 2. The site, with a block of its own for the name. The web server tests it before it
    #    reloads; a refusal puts the choice back.
    store.set_domain_certificate(app.domain, name, OWN)
    try:
        deployer.refresh_site(with_ssl=tls)
    except _APPLY_ERRORS:
        store.set_domain_certificate(app.domain, name, record.certificate)
        certificates.set_settings(before)
        raise

    audit.record(
        "domains.certificate",
        target=f"app:{app.domain}",
        details={
            "name": name,
            "certificate": OWN,
            "challenge": wanted.challenge,
            "dns_provider": wanted.dns_provider,
            "ordered": ordered,
            "tls": tls,
        },
    )
    log.success(
        f"{name} has a certificate of its own"
        if tls
        else f"{name} will have a certificate of its own with the first one: "
        f"noust cert create -d {app.domain}"
    )

    # 3. The shared lineage stops naming it. Housekeeping: the site is already right.
    warnings: list[str] = []
    reduced = False
    if tls and not operator and not already:
        reduced, error = domains.try_reduce(deployer, log)
        if error:
            warnings.append(
                f"The shared certificate still names {name}: {error}\n"
                f"Retry with: noust domain certificate {app.domain} --reduce"
            )
    if operator:
        warnings.append(_operator_words(app, name, lineage))
    return NameCertificateChange(
        app=app.domain,
        name=name,
        certificate=OWN,
        changed=not already,
        tls=tls,
        ordered=ordered,
        shared_reduced=reduced,
        operator_site=operator,
        lineage=lineage if tls and _on_disk(lineage) else None,
        warnings=tuple(warnings),
    )


def _give_back(
    app: App, record: DomainRecord, deployer: ServesDomains, log: Logger
) -> NameCertificateChange:
    """:func:`set_certificate` for ``shared``, under the application's lock."""
    name = record.domain
    if record.certificate == SHARED:
        return NameCertificateChange(
            app=app.domain,
            name=name,
            certificate=SHARED,
            changed=False,
            tls=domains.serves_tls(app, deployer),
            lineage=app.domain,
        )
    store = get_store()
    tls = domains.serves_tls(app, deployer)
    manager = deployer.webserver_manager()
    operator = is_operator_site(manager, app.domain)

    # 1. The shared certificate learns the name before the site stops presenting the name's own;
    #    the record is what tells it, so it is changed first and put back on a refusal. Only the
    #    shared lineage is ordered: another name's trouble is not this change's.
    store.set_domain_certificate(app.domain, name, SHARED)
    try:
        if tls:
            deployer.cert_manager.obtain(
                app.domain,
                nginx=manager.backend.name == "nginx",
                apache=manager.backend.name == "apache",
                include_own=False,
            )
        # 2. The site, with the name back in the shared block.
        deployer.refresh_site(with_ssl=tls)
    except _APPLY_ERRORS:
        store.set_domain_certificate(app.domain, name, OWN)
        raise

    audit.record(
        "domains.certificate",
        target=f"app:{app.domain}",
        details={"name": name, "certificate": SHARED, "tls": tls},
    )
    log.success(f"{name} is covered by the certificate of {app.domain} again")

    # 3. The lineage the name held is no longer presented by anything: it goes, unrevoked.
    warnings: list[str] = []
    removed = False
    if not operator:
        removed, words = domains.release_certificate_of(deployer, name, log)
        if words is not None:
            warnings.append(
                f"The certificate {name} held on its own was not deleted: {words}\n"
                f"It stays and renews until: noust cert delete {name}"
            )
    else:
        warnings.append(
            f"{app.domain} has a site Noust did not write, so it still presents whatever you "
            f"pointed it at for {name}. Point it at the shared certificate, then: "
            f"noust cert delete {name}"
        )
    return NameCertificateChange(
        app=app.domain,
        name=name,
        certificate=SHARED,
        changed=True,
        tls=tls,
        lineage_removed=removed,
        operator_site=operator,
        lineage=app.domain,
        warnings=tuple(warnings),
    )


def _check_can_hold(app: App, record: DomainRecord) -> None:
    """
    Refuse a name that cannot hold a certificate of its own, before anything is ordered.

    The store refuses the same at the moment it is recorded; this is earlier, so that no
    order is spent on a choice that would be refused after it.

    Args:
        app: The application.
        record: The name's row.

    Raises:
        ValidationError: The application's type orders one certificate for names only its
            deploy knows.
        DomainError: The name is the primary, or one of the canonical pair.
    """
    if app.app_type in TYPES_WITHOUT_OWN_CERTIFICATE:
        raise ValidationError(
            f"A {app.app_type} has one certificate for all its names",
            details="Its workspaces' subdomains are named by its deploy, which orders the "
            f"certificate: noust update {app.domain}",
            field="certificate",
        )
    if record.kind == DomainKind.PRIMARY.value:
        raise DomainError(
            f"{record.domain} is the primary domain, and the shared certificate is the one "
            "kept under it",
            details="Give the other names a certificate of their own and the shared one "
            f"covers {record.domain} alone.",
        )
    canonical = SitePolicyManager().get(app.domain).canonical
    if canonical:
        host = canonical_host(app.domain, canonical)
        if record.domain in (host, counterpart(host)):
            raise DomainError(
                f"{record.domain} belongs to the canonical pair {app.domain} is served on",
                details="The pair is served together, with one certificate. Serve both as "
                f"recorded first: noust domain canonical {app.domain} none",
            )


def _operator_words(app: App, name: str, lineage: str) -> str:
    """
    Say what the operator's own site has to present, since Noust did not write it.

    Args:
        app: The application.
        name: The name.
        lineage: Its lineage.

    Returns:
        The sentence.
    """
    live = CertManager.LETSENCRYPT_DIR / "live" / lineage
    return (
        f"{app.domain} has a site Noust did not write, so it is kept as it is. For {name} it "
        f"has to present {live / 'fullchain.pem'} with the key {live / 'privkey.pem'}."
    )


def _on_disk(lineage: str) -> bool:
    """
    Args:
        lineage: A lineage name.

    Returns:
        Whether certbot's live directory holds its certificate.
    """
    return (CertManager.LETSENCRYPT_DIR / "live" / lineage / "fullchain.pem").is_file()


def _actor() -> str | None:
    """
    Returns:
        A label for who is acting, for the records' ``updated_by``.
    """
    actor = audit.current_actor()
    return None if actor is None else str(actor.name or actor.id or actor.kind)


def bindings(app_domain: str, *, include_disabled: bool = True) -> list[NameBinding]:
    """
    Say, for each name of an application, which certificate serves it.

    Reads the store and the files certbot keeps; runs nothing. A name with a certificate of its
    own that is not on disk yet is reported as served by the shared one, with ``pending`` set,
    because that is what the site presents until the order succeeds.

    Args:
        app_domain: The application's primary domain.
        include_disabled: Also the names that are switched off.

    Returns:
        One entry per name, the primary first, then the aliases, then the redirects.
    """
    store = get_store()
    certificates = CertificateStore()
    settings = certificates.get_settings(app_domain)
    shared_by, source = _shared_certificate(app_domain, settings)
    found = []
    for record in store.list_domains(app_domain, include_disabled=include_disabled):
        if record.certificate == OWN:
            lineage = lineage_name(record.domain)
            if _on_disk(lineage):
                own = certificates.get_settings(record.domain)
                found.append(
                    NameBinding(
                        app=app_domain,
                        name=record.domain,
                        kind=record.kind,
                        enabled=record.enabled,
                        certificate=OWN,
                        served_by=lineage,
                        source=SOURCE_ACME,
                        challenge=own.challenge,
                    )
                )
                continue
        found.append(
            NameBinding(
                app=app_domain,
                name=record.domain,
                kind=record.kind,
                enabled=record.enabled,
                certificate=record.certificate,
                served_by=shared_by,
                source=source,
                pending=record.certificate == OWN,
                challenge="" if source == SOURCE_CUSTOM else settings.challenge,
            )
        )
    return found


def _shared_certificate(app_domain: str, settings: CertificateSettings) -> tuple[str, str]:
    """
    Name the certificate that covers the application's shared names.

    Args:
        app_domain: The application's primary domain.
        settings: Its certificate settings.

    Returns:
        ``(certificate, source)``: the upload or another lineage it was assigned, else the
        lineage under its primary domain.
    """
    if settings.source in (SOURCE_CUSTOM, SOURCE_LINEAGE) and settings.name:
        return settings.name, settings.source
    return app_domain, SOURCE_ACME


def all_bindings() -> list[NameBinding]:
    """
    Say which certificate serves every name of every application.

    Returns:
        One entry per name, application by application.
    """
    found: list[NameBinding] = []
    for app in get_store().list_apps():
        found.extend(bindings(app.domain))
    return found


def names_served_by_certificate() -> dict[str, list[str]]:
    """
    Say which names each certificate serves, across every application.

    Returns:
        For each lineage or uploaded certificate that serves something, the names it serves
        (switched-off ones left out, and a name still waiting for its own certificate counted
        against the shared one that serves it meanwhile).
    """
    served: dict[str, list[str]] = {}
    for binding in all_bindings():
        if binding.served_by is not None and binding.enabled:
            served.setdefault(binding.served_by, []).append(binding.name)
    return served
