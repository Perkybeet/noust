"""
A central that servers dial in to: the account they log in as, the invitation, the key.

Some servers cannot be reached by SSH at all: behind NAT, behind a carrier's
CGNAT, in a house. Those servers reach the central instead. ``noust fleet link``
(run on the server, :mod:`noust.fleet.link.node`) keeps an ``ssh -R`` open to
this central, and the central drives the server's console through the port the
forward leaves on its loopback, exactly as it does through ``ssh -L`` for any
other (:meth:`~noust.fleet.tunnels.TunnelManager.endpoint`). Nothing about the
model changes: the central never gets a shell on a server, and the server gets
no shell here either.

What a central needs for that:

1. ``noust node link setup``: the unprivileged account servers dial in as,
   ``noust-link`` (no home, ``nologin``, a password nothing matches), restricted
   in sshd itself by a Noust ``Match User noust-link`` block - remote
   forwarding of a loopback port and nothing else; no command, no terminal, no
   local forward, no Unix socket, no agent - reading its keys from a root-owned
   file it cannot edit. This is the same restriction ``noust-tunnel`` gets on a
   node, turned the other way round (:mod:`noust.fleet.authorize`).
2. ``noust node link invite NAME --host H``: an invitation. It gives the server
   a loopback port on this machine that only it will listen on, and prints the
   command to run there. The command carries this central's SSH host key, which
   the server pins: it never trusts whatever answers the first connection.
3. ``noust node link add NAME``: the server's link code. Its key is installed
   as ``restrict,port-forwarding,permitopen="127.0.0.1:1",permitlisten=
   "127.0.0.1:<its port>",command="/usr/bin/false"`` - it may listen on its one
   port and on no other, so one server cannot take another's - and the server
   is registered like any node (:meth:`~noust.fleet.nodes.NodeManager.add_linked`).

The port is a promise the central keeps too: before it sends a token anywhere
it checks that the listener on the port belongs to the link account
(:mod:`noust.fleet.link.listener`).
"""

