#: The comment that marks a linked node's line in the link account's key file.
LINK_COMMENT_PREFIX = "noust-link:"

#: Noust's sshd fragment for the link account. ``00-`` for the same reason the
#: tunnel account's is: the first value sshd reads for an account wins.
LINK_DROPIN_NAME = "00-noust-link.conf"

#: Marks the block when sshd_config includes no fragment directory.
LINK_POLICY_BEGIN = "# BEGIN Noust fleet link account (generated by Noust; do not edit)"
LINK_POLICY_END = "# END Noust fleet link account"

#: How long an invitation can be answered.
INVITE_TTL = timedelta(hours=24)

#: The one local forward the link key may ask for: a port nothing listens on
#: (see :data:`noust.fleet.authorize.NO_LISTEN` for why it is not "none").
NO_OPEN = "127.0.0.1:1"

#: What the fragment says about itself.
LINK_HEADER = (
    "# Generated by Noust: the account servers behind NAT dial in as.\n"
    "# 'noust node link setup' writes this file; changes made here are replaced.\n"
)

#: Longest wait for a server's link to come up when its code is accepted.
DEFAULT_WAIT = 30.0


def link_policy_block(user: str, keys_dir: Path = TUNNEL_KEYS_DIR) -> str:
    """
    Spell the ``Match User`` block that restricts the link account in sshd itself.

    Args:
        user: The link account.
        keys_dir: Where its key file is.

    Returns:
        The block, ending with a newline.
    """
    lines = [
        f"Match User {user}",
        f"    AuthorizedKeysFile {keys_dir}/%u.keys",
        "    PubkeyAuthentication yes",
        "    AuthenticationMethods publickey",
        "    DisableForwarding no",
        "    AllowTcpForwarding remote",
        "    AllowStreamLocalForwarding no",
        "    PermitOpen none",
        "    PermitListen 127.0.0.1:*",
        "    GatewayPorts no",
        "    PermitTunnel no",
        "    PermitTTY no",
        "    X11Forwarding no",
        "    AllowAgentForwarding no",
        "    PermitUserRC no",
        f"    ForceCommand {FORCED_COMMAND}",
    ]
    return "\n".join(lines) + "\n"


def link_policy_problems(settings: SshdSettings, keys_dir: Path) -> builtins.list[str]:
    """
    Compare what sshd applies to the link account with what Noust's block asks for.

    Args:
        settings: ``sshd -T -C user=<link account>``.
        keys_dir: Where the account's key file is.

    Returns:
        One sentence per setting sshd applies differently: an earlier ``Match``
        block or file set it first.
    """
    expected: builtins.list[tuple[str, object, object]] = [
        ("AllowTcpForwarding", settings.allow_tcp_forwarding, "remote"),
        ("DisableForwarding", "yes" if settings.disable_forwarding else "no", "no"),
        ("AllowStreamLocalForwarding", settings.allow_stream_local_forwarding, "no"),
        ("PermitOpen", " ".join(settings.permit_open), "none"),
        ("PermitListen", " ".join(settings.permit_listen), "127.0.0.1:*"),
        ("PermitTTY", settings.permit_tty, "no"),
        ("X11Forwarding", settings.x11_forwarding, "no"),
        ("AllowAgentForwarding", settings.allow_agent_forwarding, "no"),
        ("ForceCommand", settings.force_command or "none", FORCED_COMMAND),
        ("AuthorizedKeysFile", " ".join(settings.authorized_keys_files), f"{keys_dir}/%u.keys"),
    ]
    return [
        f"sshd applies '{name} {actual}' to the link account, not '{name} {wanted}': "
        "another Match block or configuration file sets it first."
        for name, actual, wanted in expected
        if actual != wanted
    ]


def link_account_policy(user: str = LINK_USER, keys_dir: Path = TUNNEL_KEYS_DIR) -> AccountPolicy:
    """
    Describe the restrictions of the link account.

    Args:
        user: The link account.
        keys_dir: Where its key file is.

    Returns:
        The policy.
    """
    return AccountPolicy(
        user=user,
        block=link_policy_block(user, keys_dir),
        dropin_name=LINK_DROPIN_NAME,
        begin=LINK_POLICY_BEGIN,
        end=LINK_POLICY_END,
        header=LINK_HEADER,
        problems=lambda settings: link_policy_problems(settings, keys_dir),
        retry="run 'noust node link setup' again",
    )


def authorized_link_line(node: str, key: PublicKey, port: int) -> str:
    """
    Spell a linked server's restricted ``authorized_keys`` line.

    Args:
        node: The server's name.
        key: The key it dials in with.
        port: The one loopback port it may listen on.

    Returns:
        The line, without a newline.
    """
    options = (
        f'restrict,port-forwarding,permitopen="{NO_OPEN}",'
        f'permitlisten="127.0.0.1:{int(port)}",command="{FORCED_COMMAND}"'
    )
    return f"{options} {key.bare} {LINK_COMMENT_PREFIX}{validate_node_name(node)}"


@dataclass
class Invite:
    """
    What the operator needs to link a server.

    Attributes:
        node: The server's name.
        central: This central's name, as the server will call it.
        host: The address the server dials.
        ssh_port: The SSH port it dials.
        port: The loopback port its link listens on, here.
        nonce: The invitation's nonce.
        host_key: This central's SSH host key, ``ssh-ed25519 AAAA...``.
        host_key_fingerprint: Its fingerprint, to compare by eye.
        expires_at: When the invitation stops being answerable, ISO 8601 UTC.
        command: What to run on the server, as root.
    """

    node: str
    central: str
    host: str
    ssh_port: int
    port: int
    nonce: str
    host_key: str
    host_key_fingerprint: str
    expires_at: str
    command: str

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The invitation as plain data.
        """
        return {
            "node": self.node,
            "central": self.central,
            "host": self.host,
            "ssh_port": self.ssh_port,
            "port": self.port,
            "host_key_fingerprint": self.host_key_fingerprint,
            "expires_at": self.expires_at,
            "command": self.command,
        }


def invite_command(
    *, node: str, central: str, host: str, ssh_port: int, host_key: str, port: int, nonce: str
) -> str:
    """
    Spell the command the operator runs on the server to link it.

    Every value is validated before it gets here (names, host, ports, key,
    nonce) and none holds a character the shell reads, but the key is quoted
    all the same.

    Args:
        node: The server's name.
        central: This central's name.
        host: The address to dial.
        ssh_port: The SSH port.
        host_key: This central's host key.
        port: The loopback port.
        nonce: The invitation's nonce.

    Returns:
        ``noust fleet link ...``.
    """
    return (
        f"noust fleet link --name {central} --as {node} --host {host} --ssh-port {ssh_port} "
        f"--host-key '{host_key}' --remote-port {port} --invite {nonce}"
    )


@dataclass
class LinkStatus:
    """
    Whether this central can take servers that dial in.

    Attributes:
        ready: A server can be invited now.
        problems: What stops it, one actionable sentence each.
        account: The link account exists.
        ssh_port: sshd's port.
        host_key_fingerprint: This central's host key, when it has one.
        links: Every server that dials in or was invited.
        setup_command: What prepares this central.
    """

    ready: bool
    problems: builtins.list[str] = field(default_factory=builtins.list)
    account: bool = False
    ssh_port: int = 22
    host_key_fingerprint: str | None = None
    links: builtins.list[dict[str, Any]] = field(default_factory=builtins.list)
    setup_command: str = "noust node link setup"

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The status as plain data.
        """
        return {
            "ready": self.ready,
            "problems": self.problems,
            "account": self.account,
            "ssh_port": self.ssh_port,
            "host_key_fingerprint": self.host_key_fingerprint,
            "links": self.links,
            "setup_command": self.setup_command,
        }


@dataclass
class SetupResult:
    """
    What ``noust node link setup`` did.

    Attributes:
        account: The account.
        account_created: Whether it was created now.
        sshd_policy: The file holding its ``Match`` block.
        keys_file: Where its keys are.
        ssh_port: sshd's port.
        host_key_fingerprint: This central's host key.
        changed: Whether the sshd file changed.
    """

    account: str
    account_created: bool
    sshd_policy: str
    keys_file: str
    ssh_port: int
    host_key_fingerprint: str
    changed: bool

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The result as plain data.
        """
        return dict(self.__dict__)


class LinkManager:
    """
    Prepare a central for servers that dial in, invite them and accept them.

    Args:
        store: The store; the process-wide one by default.
        runner: The runner ``sshd``, ``useradd`` and ``systemctl`` go through.
        fs: The filesystem seam.
        sshd_config: sshd's main configuration.
        dropin_dir: sshd's fragment directory.
        keys_dir: Where the link account's key file is.
        host_key_file: This central's ed25519 host key.
        passwd: Account lookup.
        proc_net: ``/proc/net``, for the free-port check.
        clock: The current time.
    """

    def __init__(
        self,
        *,
        store: NoustStore | None = None,
        runner: CommandRunner | None = None,
        fs: FileSystem | None = None,
        sshd_config: Path = SSHD_CONFIG,
        dropin_dir: Path = SSHD_DROPIN_DIR,
        keys_dir: Path = TUNNEL_KEYS_DIR,
        host_key_file: Path = HOST_KEY_FILE,
        passwd: Callable[[str], pwd.struct_passwd] = pwd.getpwnam,
        proc_net: Path | None = None,
        clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc),
    ) -> None:
        self._store = store
        self._runner = runner
        self._fs = fs
        self._sshd_config = sshd_config
        self._dropin_dir = dropin_dir
        self._keys_dir = keys_dir
        self._host_key_file = host_key_file
        self._passwd = passwd
        self._proc_net = proc_net
        self._clock = clock

    @property
    def runner(self) -> CommandRunner:
        """The runner."""
        return self._runner or get_runner()

    @property
    def fs(self) -> FileSystem:
        """The filesystem seam."""
        return self._fs or get_fs()

    @property
    def records(self) -> LinkRecords:
        """The links."""
        return LinkRecords(self._store)

    def keys_file(self) -> AuthorizedKeys:
        """
        Returns:
            The editor of the link account's key file.
        """
        return tunnel_keys_file(
            LINK_USER,
            keys_dir=self._keys_dir,
            fs=self._fs,
            runner=self._runner,
            comment_prefix=LINK_COMMENT_PREFIX,
        )

    # -- Preparing the central -------------------------------------------------------

    def host_key(self) -> PublicKey:
        """
        Read this central's SSH host key: what a server pins.

        Returns:
            The key.

        Raises:
            NodeError: When there is none.
        """
        try:
            return parse_public_key(
                self._host_key_file.read_text(encoding="utf-8"),
                what="SSH host key of this central",
            )
        except FileNotFoundError as exc:
            raise NodeError(
                f"This central has no ed25519 SSH host key ({self._host_key_file})",
                details="Install OpenSSH's server, generate the host keys with 'ssh-keygen -A', "
                "and reload sshd. A server pins this key; without it nothing can dial in safely.",
            ) from exc

    def setup(self, *, dry_run: bool = False, actor: str | None = None) -> SetupResult:
        """
        Make this central accept servers that dial in: the account and its sshd block.

        Every check runs before anything changes, and an sshd block that does
        not apply is put back as it was.

        Args:
            dry_run: Rehearse: nothing is created, written or reloaded.
            actor: Who sets it up, for the audit trail.

        Returns:
            What was done (or would be).

        Raises:
            NodeError: When this central has no SSH host key, sshd would refuse
                the account, the account exists and can log in, or sshd does not
                apply the block.
        """
        host_key = self.host_key()
        try:
            existing: pwd.struct_passwd | None = self._passwd(LINK_USER)
        except KeyError:
            existing = None
        settings = read_sshd_settings(self.runner, self._sshd_config, user=LINK_USER)
        blockers = sshd_blockers(
            settings,
            LINK_USER,
            groups_of(existing) if existing is not None else (LINK_USER,),
            tunnel=True,
            again="run 'noust node link setup' again",
        )
        if blockers:
            raise NodeError(
                "sshd would refuse the account servers dial in as", details="\n".join(blockers)
            )
        _, created = ensure_tunnel_account(
            LINK_USER, runner=self.runner, passwd=self._passwd, dry_run=dry_run
        )
        policy = apply_account_policy(
            link_account_policy(LINK_USER, self._keys_dir),
            runner=self.runner,
            fs=self.fs,
            sshd_config=self._sshd_config,
            dropin_dir=self._dropin_dir,
            dry_run=dry_run,
        )
        if not dry_run:
            audit.record(
                "fleet.link.setup",
                target=f"account:{LINK_USER}",
                details={"created": created, "policy": str(policy.path), "by": actor},
            )
        return SetupResult(
            account=LINK_USER,
            account_created=created,
            sshd_policy=str(policy.path),
            keys_file=str(self.keys_file().path),
            ssh_port=settings.port,
            host_key_fingerprint=host_key.fingerprint,
            changed=policy.changed,
        )

    def planned_policy(self) -> SshdPolicy:
        """
        Returns:
            Where the link account's block goes and what the file becomes; nothing is written.
        """
        return plan_account_policy(
            link_account_policy(LINK_USER, self._keys_dir),
            sshd_config=self._sshd_config,
            dropin_dir=self._dropin_dir,
        )

    def status(self) -> LinkStatus:
        """
        Say whether this central can take servers that dial in, and which do.

        Read-only: ``sshd -T`` and a look at the account.

        Returns:
            The status; ``problems`` says what stops it, with the command that fixes it.
        """
        problems: builtins.list[str] = []
        fingerprint: str | None = None
        try:
            fingerprint = self.host_key().fingerprint
        except NodeError as exc:
            problems.append(f"{exc.message}. {exc.details}".strip())
        try:
            account: pwd.struct_passwd | None = self._passwd(LINK_USER)
        except KeyError:
            account = None
        settings = read_sshd_settings(self.runner, self._sshd_config, user=LINK_USER)
        if account is None:
            problems.append(
                f"The account {LINK_USER} does not exist yet: run 'noust node link setup' "
                "as root to create it and restrict it in sshd."
            )
        else:
            problems.extend(
                link_policy_problems(settings, self._keys_dir)
                + sshd_blockers(
                    settings,
                    LINK_USER,
                    groups_of(account),
                    tunnel=True,
                    again="run 'noust node link setup' again",
                )
            )
        return LinkStatus(
            ready=not problems,
            problems=problems,
            account=account is not None,
            ssh_port=settings.port,
            host_key_fingerprint=fingerprint,
            links=[record.to_dict() for record in self.records.list()],
        )

    # -- Inviting ---------------------------------------------------------------------

    def _free_port(self, taken: set[int]) -> int:
        """
        Pick a loopback port no link holds and nothing listens on.

        Args:
            taken: The ports links hold.

        Returns:
            The port.

        Raises:
            NodeError: When every port of the range is used.
        """
        for candidate in range(PORT_FIRST, PORT_LAST + 1):
            if candidate not in taken and not self._listening(candidate):
                return candidate
        raise NodeError(
            "No link port is free",
            details=f"Ports {PORT_FIRST} to {PORT_LAST} are all held. Remove a server that "
            "dials in, or pass --port.",
        )

    def _listening(self, port: int) -> bool:
        """
        Report whether anything listens on a loopback port.

        Args:
            port: The port.

        Returns:
            True when something does.
        """
        if self._proc_net is None:
            return bool(listener_uids(port))
        return bool(listener_uids(port, self._proc_net))

    def invite(
        self,
        node: str,
        *,
        host: str,
        ssh_port: int | None = None,
        port: int | None = None,
        actor: str | None = None,
    ) -> Invite:
        """
        Invite a server to dial in: give it a port and the command to run there.

        Args:
            node: The server's name on this central.
            host: The address the server will dial (a name or an IP address).
            ssh_port: The SSH port it dials; sshd's by default.
            port: The loopback port its link listens on here; one is chosen.
            actor: Who invites it.

        Returns:
            The invitation.

        Raises:
            NodeError: When this central is not ready for links (the problems
                are the details), the name is registered or the invitation is
                answered already, the host or a port is invalid, or no port is free.
        """
        from noust.core.store import get_store

        name = validate_node_name(node)
        store = self._store or get_store()
        if store.get_node(name) is not None:
            raise NodeError(
                f"A node named {name} is already registered",
                details=f"Pick another name, or remove it first: noust node remove {name}",
                field="name",
            )
        status = self.status()
        if not status.ready:
            raise NodeError(
                "This central is not ready for servers that dial in",
                details="\n".join(status.problems),
            )
        address = validate_host(host.strip().strip("[]"))
        chosen_ssh = (
            validate_port(ssh_port, "SSH port") if ssh_port is not None else status.ssh_port
        )
        records = self.records
        taken = records.used_ports()
        previous = records.get(name)
        if previous is not None:
            # Inviting again replaces an invitation nobody answered: its port is free again.
            taken.discard(previous.port)
        if port is not None:
            chosen = validate_port(port, "link port")
            if chosen < 1024:
                raise NodeError(
                    f"The link port {chosen} is a privileged port",
                    details="sshd only lets an unprivileged account listen above 1023.",
                    field="port",
                )
            if chosen in taken or self._listening(chosen):
                raise NodeError(
                    f"The port {chosen} is taken",
                    details="Another server's link holds it, or something listens on it. "
                    "Leave --port out to be given a free one.",
                    field="port",
                )
        else:
            chosen = self._free_port(taken)
        key = self.host_key()
        nonce = pysecrets.token_hex(16)
        central = central_name()
        record = records.invite(
            name,
            port=chosen,
            nonce=nonce,
            central_host=address,
            central_port=chosen_ssh,
            actor=actor,
            created_at=self._clock().isoformat(timespec="seconds"),
        )
        expires = datetime.fromisoformat(record.created_at) + INVITE_TTL
        audit.record(
            "fleet.link.invite",
            target=f"node:{name}",
            details={"host": address, "ssh_port": chosen_ssh, "port": chosen, "by": actor},
        )
        return Invite(
            node=name,
            central=central,
            host=address,
            ssh_port=chosen_ssh,
            port=chosen,
            nonce=nonce,
            host_key=key.bare,
            host_key_fingerprint=key.fingerprint,
            expires_at=expires.isoformat(timespec="seconds"),
            command=invite_command(
                node=name,
                central=central,
                host=address,
                ssh_port=chosen_ssh,
                host_key=key.bare,
                port=chosen,
                nonce=nonce,
            ),
        )

    def cancel(self, name: str, *, actor: str | None = None) -> None:
        """
        Cancel an invitation nobody answered: its port is free again.

        Args:
            name: The server's name.
            actor: Who cancels it, for the audit trail.

        Raises:
            NodeError: When there is no invitation for the name, or the server
                already dials in (remove it instead: it has a key and a token).
        """
        name = validate_node_name(name)
        record = self.records.get(name)
        if record is None:
            raise NodeError(f"{name} has no invitation to cancel", field="name")
        if record.state != INVITED:
            raise NodeError(
                f"{name} already dials in to this central",
                details=f"Remove it instead: noust node remove {name}",
                field="name",
            )
        self.records.delete(name)
        audit.record("fleet.link.cancel", target=f"node:{name}", details={"by": actor})

    # -- Accepting --------------------------------------------------------------------

    def check_code(self, name: str, text: str) -> tuple[LinkCode, LinkRecord]:
        """
        Read a link code and check it answers the invitation of this server.

        Args:
            name: The server's name on this central.
            text: The code the server printed.

        Returns:
            The code and the invitation's record.

        Raises:
            NodeError: When the code is malformed, there is no invitation for
                the name (or it was answered), the code is for another
                invitation, another central or another name, or the invitation
                has expired.
        """
        name = validate_node_name(name)
        code = LinkCode.decode(text)
        record = self.records.get(name)
        if record is None:
            raise NodeError(
                f"{name} was never invited to dial in",
                details=f"Invite it first: noust node link invite {name} --host <this central's "
                "address>",
                field="name",
            )
        if record.state != INVITED:
            raise NodeError(
                f"{name} already dials in to this central",
                details=f"Remove it first to link it again: noust node remove {name}",
                field="name",
            )
        if not NONCE.fullmatch(record.nonce) or not pysecrets.compare_digest(
            code.nonce, record.nonce
        ):
            raise NodeError(
                "This link code answers another invitation",
                details=f"Invite {name} again and run the command it prints on the server; "
                "the code that prints is the one to paste.",
                field="link_code",
            )
        if code.node_name != name:
            raise NodeError(
                f"This link code is for a server called {code.node_name}, not {name}",
                details="Invite the server under the name the code carries, or link it again "
                f"with '--as {name}'.",
                field="name",
            )
        if code.central != central_name():
            raise NodeError(
                f"This link code was made for the central {code.central}, not {central_name()}",
                details="It was printed after an invitation from another central.",
                field="link_code",
            )
        created = datetime.fromisoformat(record.created_at)
        if self._clock() - created > INVITE_TTL:
            raise NodeError(
                f"The invitation of {name} expired",
                details=f"Invitations last {int(INVITE_TTL.total_seconds() // 3600)} hours. "
                f"Invite {name} again.",
            )
        return code, record

    def install_key(self, name: str, code: LinkCode, record: LinkRecord) -> bool:
        """
        Let a server's key listen on its port, and activate its link.

        Args:
            name: The server's name.
            code: Its link code.
            record: Its invitation.

        Returns:
            True when the key file changed.
        """
        key = parse_public_key(code.link_key, what="the server's link key")
        changed = self.keys_file().install(authorized_link_line(name, key, record.port), name)
        self.records.activate(name, key.bare)
        return changed

    def uninstall_key(self, name: str) -> int:
        """
        Take a server's key out of the link account's key file.

        Args:
            name: The server's name.

        Returns:
            How many lines were removed.
        """
        return self.keys_file().remove(name)

    def forget(self, name: str) -> builtins.list[str]:
        """
        Forget a server's link: its key line and its record.

        Args:
            name: The server's name.

        Returns:
            Warnings for the operator; empty when nothing went wrong or there was no link.
        """
        if self.records.get(name) is None:
            return []
        warnings: builtins.list[str] = []
        try:
            self.uninstall_key(name)
        except (NodeError, OSError) as exc:
            warnings.append(
                f"The key of {name} could not be taken out of {self.keys_file().path} "
                f"({exc}); remove its line by hand."
            )
        self.records.delete(name)
        return warnings
