"""
SSL certificates, driven through certbot.

Certificate data crosses two module boundaries: ``certbot certificates`` is
parsed here and read by the CLI and by ``noust health``. It travels as a
:class:`CertificateInfo`, so the field names are stated once instead of being
guessed at each end - ``noust health`` spent several releases looking for an
``expires`` key that this module never wrote, and a plain dict answered that
with ``None`` forever. Asking one of these records for a field it does not have
is now a :class:`KeyError`, not a silent miss.

The other thing this module has to get right is idempotence. Issuance is a rate
limited network operation against Let's Encrypt, so "run it again" must be
cheap and safe:

- A certificate that already covers every requested domain is left alone.
- A failure to *read* the current state is an error, never a licence to issue.
  ``certbot certificates`` returning non-zero used to be parsed as "there is no
  certificate", so every run of a broken-but-installed certbot placed a fresh
  order for a domain that was already served.
- One that covers some of them is expanded, never issued a second time under a
  new lineage name. That is why every command passes ``--cert-name``: without
  it certbot invents ``example.com-0001`` as soon as the domain set changes, and
  the renewal timer then keeps two half-right certificates alive.
- ``www`` is handled here rather than at each call site, because the rule for
  when a bare domain deserves a ``www`` alias is a property of the domain.

How a certificate comes to be is a property of the application, kept in the store
(:mod:`noust.core.certificate_store`) and read here, in the one place that orders:

- **HTTP-01** (the default): certbot proves control over the application's own port 80.
- **DNS-01**: a record in the domain's DNS zone, answered through a DNS account
  (:mod:`noust.managers.dns`). It needs no open port, reaches hosts nobody can browse
  to, and is the only way to a wildcard (``*.example.com``). A Cloudflare account is
  answered by Noust's own hooks; any other by certbot's plugin.
- **An uploaded certificate** (:mod:`noust.managers.custom_certificates`): nothing is
  ordered, renewed or revoked; the files are served as they are.
- **A lineage that already covers the name**: an application one label under a
  wildcard certificate is given that one instead of an order of its own, which is
  what keeps a preview per pull request from spending the authority's rate limit.
- **A name with a certificate of its own** (:mod:`noust.core.domain_certificates`): a lineage
  named after the name and holding only it, ordered the way the name's own settings say and
  renewed with the application's. The lineage under the primary domain never names it
  (:meth:`CertManager.certificate_domains`), and every order that covers an application covers
  those names after it (:meth:`CertManager.obtain`).

Which authority orders and as whom is :mod:`noust.managers.acme`'s.
"""

