#: The drop-in's file name: after the distribution's (``10-*``) and before an operator's own.
DROPIN_NAME = "90-noust-limits.conf"

#: The first line of the drop-in, which says whose it is.
MARKER = "# Generated by Noust"

#: The limits, by the name the interfaces use, and the directive each one is.
DIRECTIVES: dict[str, str] = {
    "memory_mb": "MemoryMax",
    "cpus": "CPUQuota",
    "swap_mb": "MemorySwapMax",
    "tasks": "TasksMax",
}

#: The fewest tasks (processes and threads) an engine is given: below this PostgreSQL cannot
#: start a connection, nor MongoDB its threads.
MIN_TASKS = 256

#: The most tasks a limit may name; the kernel's own ceiling is far above any engine's needs.
MAX_TASKS = 4_194_304

#: Memory an engine needs when its catalog entry does not say, in megabytes.
FALLBACK_MINIMUM_MB = 256

#: Seconds Noust waits for the engine to answer after a limit changed.
WAIT_SECONDS = 30

#: Lines of the engine's journal an error carries.
JOURNAL_LINES = 50

MB = 1024 * 1024

_SPAN = re.compile(r"(\d+(?:\.\d+)?)\s*(us|ms|s|min|h)")
_UNIT_SECONDS = {"us": 1e-6, "ms": 1e-3, "s": 1.0, "min": 60.0, "h": 3600.0}


def _sleep(seconds: float) -> None:
    """
    Wait; a test replaces this so the engine's wait takes no time.

    Args:
        seconds: How long.
    """
    time.sleep(seconds)


@dataclass(frozen=True)
class LimitValues:
    """
    The four limits, each ``None`` for none.

    Attributes:
        memory_mb: ``MemoryMax``, in megabytes.
        cpus: ``CPUQuota``, in processors (``1.5`` is 150%).
        swap_mb: ``MemorySwapMax``, in megabytes; ``0`` is no swap at all.
        tasks: ``TasksMax``.
    """

    memory_mb: int | None = None
    cpus: float | None = None
    swap_mb: int | None = None
    tasks: int | None = None

    def get(self, key: str) -> int | float | None:
        """
        Args:
            key: One of :data:`DIRECTIVES`.

        Returns:
            Its value.
        """
        values: dict[str, int | float | None] = {
            "memory_mb": self.memory_mb,
            "cpus": self.cpus,
            "swap_mb": self.swap_mb,
            "tasks": self.tasks,
        }
        return values[key]

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The limits as JSON-serialisable values.
        """
        return {key: self.get(key) for key in DIRECTIVES}

    def without(self, keys: Sequence[str]) -> LimitValues:
        """
        Args:
            keys: Limits to drop.

        Returns:
            A copy with those unset.
        """
        kept = self
        for key in keys:
            kept = kept.with_limit(key, None)
        return kept

    def with_limit(self, key: str, value: int | float | None) -> LimitValues:
        """
        Args:
            key: One of :data:`DIRECTIVES`.
            value: Its new value, None for none.

        Returns:
            A copy with that limit changed.
        """
        values = self.to_dict()
        values[key] = value
        return LimitValues(**values)


@dataclass(frozen=True)
class LimitsStatus:
    """
    What an engine's limits are, and whether they hold.

    Attributes:
        engine: The engine.
        display_name: Its name for a person.
        unit: The systemd unit the limits are on.
        file: The drop-in Noust writes.
        configured: What Noust's drop-in sets.
        effective: What systemd holds for the unit, from every source.
        enforced: Per limit, whether the kernel's cgroup holds it: ``True``, ``False`` (systemd
            has it and the kernel does not), or ``None`` when it cannot be read (not running, a
            cgroup layout without the file).
        memory_in_use_mb: What the engine's cgroup holds now, when known.
        server_memory_mb: This server's memory.
        cpus: This server's processors.
        minimum_memory_mb: The least memory the engine runs in.
        elsewhere: Limits another drop-in or the unit itself sets, which Noust's drop-in replaces
            when it names the same one.
    """

    engine: str
    display_name: str
    unit: str
    file: str
    configured: LimitValues
    effective: LimitValues
    enforced: dict[str, bool | None]
    memory_in_use_mb: int | None
    server_memory_mb: int
    cpus: int
    minimum_memory_mb: int
    elsewhere: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The status as JSON-serialisable values.
        """
        return {
            "engine": self.engine,
            "display_name": self.display_name,
            "unit": self.unit,
            "file": self.file,
            "configured": self.configured.to_dict(),
            "effective": self.effective.to_dict(),
            "enforced": dict(self.enforced),
            "memory_in_use_mb": self.memory_in_use_mb,
            "server_memory_mb": self.server_memory_mb,
            "cpus": self.cpus,
            "minimum_memory_mb": self.minimum_memory_mb,
            "elsewhere": list(self.elsewhere),
        }


@dataclass(frozen=True)
class LimitsOutcome:
    """
    What a change of limits did.

    Attributes:
        engine: The engine.
        display_name: Its name for a person.
        file: The drop-in.
        changed: The limits that changed.
        configured: What Noust's drop-in sets now.
        warnings: What the operator should know, in English: a limit the kernel does not enforce.
    """

    engine: str
    display_name: str
    file: str
    changed: list[str]
    configured: LimitValues
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The outcome as JSON-serialisable values.
        """
        return {
            "engine": self.engine,
            "display_name": self.display_name,
            "file": self.file,
            "changed": list(self.changed),
            "configured": self.configured.to_dict(),
            "warnings": list(self.warnings),
        }


def check_tasks(value: object) -> int:
    """
    Accept a limit of tasks.

    Args:
        value: A whole number.

    Returns:
        The number.

    Raises:
        ValidationError: Not a whole number from :data:`MIN_TASKS` to :data:`MAX_TASKS`.
    """
    if isinstance(value, bool) or not isinstance(value, (int, str)):
        number = -1
    else:
        try:
            number = int(str(value).strip())
        except ValueError:
            number = -1
    if not MIN_TASKS <= number <= MAX_TASKS:
        raise ValidationError(
            f"{value!r} is not a limit of tasks",
            details=f"Use a whole number from {MIN_TASKS} to {MAX_TASKS}. A task is a process or a "
            "thread; an engine with many connections needs thousands.",
            field="tasks",
        )
    return number


def parse_span_seconds(text: str) -> float | None:
    """
    Read a time span as systemd prints it.

    Args:
        text: ``1s``, ``1.500s``, ``100ms``, ``1min 30s`` or ``infinity``.

    Returns:
        Seconds; None for ``infinity`` or for text that is not a span.
    """
    found = _SPAN.findall(text)
    if not found or not _SPAN.sub("", text).strip() == "":
        return None
    return sum(float(number) * _UNIT_SECONDS[unit] for number, unit in found)


def _bytes_to_mb(text: str) -> int | None:
    """
    Args:
        text: A number of bytes as systemd or the kernel prints it, or ``infinity`` / ``max``.

    Returns:
        Whole megabytes (rounded down); None for no limit or for text that is not a number.
    """
    if not text.strip().isdigit():
        return None
    return int(text.strip()) // MB


class HostLimits:
    """The resource limits of one host engine: read them, change them, prove them."""

    def __init__(self, manager: BaseDatabaseManager, resources: Resources | None = None) -> None:
        """
        Args:
            manager: The engine's manager, on this host.
            resources: This server; measured when None.

        Raises:
            DatabaseEngineError: When the manager drives a container, or Noust offers the engine
                no settings (and so no unit to find).
        """
        manager.refuse_in_container("limit")
        self.manager = manager
        self.resources = resources or server_resources()
        self.settings: EngineSettings = settings_for(manager, self.resources)

    # -- where --------------------------------------------------------------------

    def unit(self) -> str:
        """
        Returns:
            The unit whose cgroup holds the engine: the cluster's own for PostgreSQL.
        """
        return self.settings.unit()

    def dropin(self) -> Path:
        """
        Returns:
            Noust's drop-in for the unit.
        """
        unit = self.unit()
        name = unit if unit.endswith(".service") else f"{unit}.service"
        return flavours.HOST.at(f"/etc/systemd/system/{name}.d/{DROPIN_NAME}")

    def minimum_memory_mb(self) -> int:
        """
        Returns:
            The least memory the engine runs in, from the catalog of what Noust runs itself.
        """
        try:
            return spec_for(self.manager.ENGINE_NAME).min_memory_mb
        except ValidationError:
            return FALLBACK_MINIMUM_MB

    # -- reading ------------------------------------------------------------------

    def configured(self) -> LimitValues:
        """
        Read what Noust's drop-in sets.

        Returns:
            The limits, None for those it does not name.

        Raises:
            DatabaseEngineError: When the drop-in cannot be read or is a link.
        """
        text = read_config_file(self.dropin())
        found: dict[str, str] = {}
        for line in (text or "").splitlines():
            name, separator, value = line.partition("=")
            if separator and name.strip() in DIRECTIVES.values():
                found[name.strip()] = value.strip()
        return LimitValues(
            memory_mb=_megabytes(found.get("MemoryMax")),
            cpus=_cpus(found.get("CPUQuota")),
            swap_mb=_megabytes(found.get("MemorySwapMax")),
            tasks=_whole(found.get("TasksMax")),
        )

    def _show(self) -> dict[str, str]:
        """
        Ask systemd what it holds for the unit.

        Returns:
            Property to value, empty when systemd does not answer.
        """
        properties = (
            "MemoryMax",
            "MemorySwapMax",
            "CPUQuotaPerSecUSec",
            "TasksMax",
            "MemoryCurrent",
            "ControlGroup",
        )
        result = self.manager._exec(
            ["systemctl", "show", self.unit(), *[f"--property={name}" for name in properties]],
            timeout=SERVICE_TIMEOUT,
        )
        if not result.success:
            return {}
        values: dict[str, str] = {}
        for line in result.stdout.splitlines():
            name, separator, value = line.partition("=")
            if separator:
                values[name.strip()] = value.strip()
        return values

    def _default_tasks(self) -> int | None:
        """
        Ask systemd for the task limit it gives every service that sets none.

        Returns:
            ``DefaultTasksMax`` (a share of the kernel's process limit, so a number on every
            current systemd); None when systemd does not say. Without it a service's own
            ``TasksMax`` would always look like a limit somebody set.
        """
        result = self.manager._exec(
            ["systemctl", "show", "--property=DefaultTasksMax"], timeout=SERVICE_TIMEOUT
        )
        if not result.success:
            return None
        for line in result.stdout.splitlines():
            name, separator, value = line.partition("=")
            if separator and name.strip() == "DefaultTasksMax":
                return _whole(value)
        return None

    @staticmethod
    def _effective(shown: Mapping[str, str]) -> LimitValues:
        """
        Args:
            shown: What :meth:`_show` returned.

        Returns:
            The limits systemd holds.
        """
        seconds = parse_span_seconds(shown.get("CPUQuotaPerSecUSec", ""))
        return LimitValues(
            memory_mb=_bytes_to_mb(shown.get("MemoryMax", "")),
            cpus=round(seconds, 2) if seconds else None,
            swap_mb=_bytes_to_mb(shown.get("MemorySwapMax", "")),
            tasks=_whole(shown.get("TasksMax")),
        )

    def _kernel(self, shown: Mapping[str, str]) -> dict[str, str] | None:
        """
        Read the limits the kernel holds for the unit's cgroup.

        Args:
            shown: What :meth:`_show` returned.

        Returns:
            The cgroup files' content by name, None when the unit has no cgroup (not running) or
            the host does not use the unified hierarchy.
        """
        group = shown.get("ControlGroup", "")
        if not group.startswith("/"):
            return None
        folder = flavours.HOST.at(f"/sys/fs/cgroup{group}")
        files: dict[str, str] = {}
        for name in ("memory.max", "memory.swap.max", "cpu.max", "pids.max", "memory.current"):
            try:
                files[name] = (folder / name).read_text().strip()
            except OSError:
                continue
        return files or None

    def _proof(self, shown: Mapping[str, str]) -> tuple[dict[str, bool | None], int | None]:
        """
        Check that the kernel holds what systemd says it set.

        Args:
            shown: What :meth:`_show` returned.

        Returns:
            Per limit whether the kernel's cgroup holds the value systemd reports (None when it
            cannot be read), and the memory the cgroup holds now, in megabytes.
        """
        kernel = self._kernel(shown)
        in_use = None
        if shown.get("MemoryCurrent", "").isdigit():
            in_use = int(shown["MemoryCurrent"]) // MB
        enforced: dict[str, bool | None] = dict.fromkeys(DIRECTIVES)
        if kernel is None:
            return enforced, in_use
        if in_use is None and "memory.current" in kernel:
            in_use = _bytes_to_mb(kernel["memory.current"])
        enforced["memory_mb"] = _held(kernel.get("memory.max"), shown.get("MemoryMax"))
        enforced["swap_mb"] = _held(kernel.get("memory.swap.max"), shown.get("MemorySwapMax"))
        enforced["tasks"] = _held(kernel.get("pids.max"), shown.get("TasksMax"))
        quota = kernel.get("cpu.max")
        if quota is not None:
            first, _, period = quota.partition(" ")
            wanted = parse_span_seconds(shown.get("CPUQuotaPerSecUSec", ""))
            if wanted is None:
                enforced["cpus"] = first == "max"
            elif first.isdigit() and period.isdigit() and int(period) > 0:
                enforced["cpus"] = abs(int(first) / int(period) - wanted) < 0.01
            else:
                enforced["cpus"] = False
        return enforced, in_use

    def status(self) -> LimitsStatus:
        """
        Report the engine's limits and whether the kernel holds them.

        Returns:
            What Noust sets, what systemd holds, what the kernel enforces.

        Raises:
            DatabaseEngineError: When the drop-in cannot be read.
        """
        configured = self.configured()
        shown = self._show()
        effective = self._effective(shown)
        enforced, in_use = self._proof(shown)
        default_tasks = self._default_tasks()
        elsewhere = [
            DIRECTIVES[key]
            for key in DIRECTIVES
            if effective.get(key) is not None
            and configured.get(key) is None
            # Systemd gives every service a task limit of its own; that one is nobody's setting.
            and not (key == "tasks" and effective.get(key) == default_tasks)
        ]
        return LimitsStatus(
            engine=self.manager.ENGINE_NAME,
            display_name=self.manager.DISPLAY_NAME,
            unit=self.unit(),
            file=str(self.dropin()),
            configured=configured,
            effective=effective,
            enforced=enforced,
            memory_in_use_mb=in_use,
            server_memory_mb=self.resources.memory_bytes // MB,
            cpus=self.resources.cpus,
            minimum_memory_mb=self.minimum_memory_mb(),
            elsewhere=elsewhere,
        )

    # -- checking -----------------------------------------------------------------

    @staticmethod
    def known(key: str) -> str:
        """
        Args:
            key: A limit's name.

        Returns:
            The name.

        Raises:
            ValidationError: When it is not one of :data:`DIRECTIVES`.
        """
        if key not in DIRECTIVES:
            raise ValidationError(
                f"{key!r} is not a limit Noust sets",
                details=f"Choose one of: {', '.join(DIRECTIVES)}.",
                field=key,
            )
        return key

    def check(self, key: str, value: object) -> int | float:
        """
        Accept one limit.

        Args:
            key: One of :data:`DIRECTIVES`.
            value: What was asked, as the interfaces take it.

        Returns:
            The value, normalised.

        Raises:
            ValidationError: When it is below what the engine needs or above what the server
                has, or is not a number.
        """
        server_mb = self.resources.memory_bytes // MB
        if key == "memory_mb":
            megabytes = parse_memory(value)
            minimum = self.minimum_memory_mb()
            if megabytes < minimum:
                raise ValidationError(
                    f"{megabytes} MB is too little memory for {self.manager.DISPLAY_NAME}",
                    details=f"It needs at least {minimum} MB to start and answer.",
                    field="memory_mb",
                )
            if server_mb and megabytes > server_mb:
                raise ValidationError(
                    f"{megabytes} MB is more memory than this server has",
                    details=f"It has {server_mb} MB. A limit above that limits nothing.",
                    field="memory_mb",
                )
            return megabytes
        if key == "cpus":
            cpus = check_cpus(value)
            if cpus > self.resources.cpus:
                raise ValidationError(
                    f"{cpus:g} processors is more than this server has",
                    details=f"It has {self.resources.cpus}. A quota above that limits nothing.",
                    field="cpus",
                )
            return cpus
        if key == "swap_mb":
            # The command line hands over text; the validator takes the number.
            return check_swap(
                int(value) if isinstance(value, str) and value.strip().isdigit() else value
            )
        if key == "tasks":
            return check_tasks(value)
        raise AssertionError(self.known(key))

    # -- changing -----------------------------------------------------------------

    def apply(
        self,
        changes: Mapping[str, object] | None = None,
        *,
        clear: Sequence[str] = (),
        confirm: bool = False,
    ) -> LimitsOutcome:
        """
        Set, change or remove limits, proving them, or leave the engine as it was.

        Args:
            changes: Limits to set, by name (``memory_mb``, ``cpus``, ``swap_mb``, ``tasks``).
            clear: Limits to remove.
            confirm: The operator accepts what a limit below the engine's current use costs.

        Returns:
            What changed.

        Raises:
            ValidationError: For a limit that is not valid, or named both to set and to clear.
            ConfirmationRequired: When the memory limit is below what the engine uses now and was
                not confirmed; nothing changed.
            DatabaseEngineError: When the engine is not running, systemd did not take the limits
                or did not hold them, or the engine stopped answering (the previous limits are
                back).
        """
        changes = changes or {}
        for key in (*changes, *clear):
            self.known(key)
        both = sorted(set(changes) & set(clear))
        if both:
            raise ValidationError(
                f"{', '.join(both)} cannot be set and removed in one change",
                details="Name each limit once.",
            )
        checked = {key: self.check(key, value) for key, value in changes.items()}
        with self.settings._locked():
            before = self.configured()
            wanted = before.without(clear)
            for key, value in checked.items():
                wanted = wanted.with_limit(key, value)
            changed = [key for key in DIRECTIVES if wanted.get(key) != before.get(key)]
            if not changed:
                return LimitsOutcome(
                    self.manager.ENGINE_NAME,
                    self.manager.DISPLAY_NAME,
                    str(self.dropin()),
                    [],
                    before,
                )
            self._confirm(wanted, changed, confirm)
            return self._write_and_prove(before, wanted, changed)

    def _confirm(self, wanted: LimitValues, changed: Sequence[str], confirm: bool) -> None:
        """
        Ask for confirmation of a memory limit the engine already exceeds.

        Args:
            wanted: The limits that would be set.
            changed: Which of them change.
            confirm: Whether the operator already accepted.

        Raises:
            ConfirmationRequired: When one is needed and was not given.
        """
        if "memory_mb" not in changed or wanted.memory_mb is None or confirm:
            return
        in_use = self._proof(self._show())[1]
        if in_use is not None and in_use > wanted.memory_mb:
            raise ConfirmationRequired(
                [
                    f"{self.manager.DISPLAY_NAME} uses {in_use} MB now, more than the "
                    f"{wanted.memory_mb} MB limit. The kernel will reclaim what it can and, when "
                    "that is not enough, kill the engine's process: for a database that is a "
                    "crash and a recovery."
                ]
            )

    def _write_and_prove(
        self, before: LimitValues, wanted: LimitValues, changed: Sequence[str]
    ) -> LimitsOutcome:
        """
        Write the drop-in, have systemd apply it, prove it, and undo it if anything fails.

        Args:
            before: The limits Noust's drop-in set.
            wanted: The limits to set.
            changed: Which of them change.

        Returns:
            What changed.

        Raises:
            DatabaseEngineError: As :meth:`apply`.
        """
        path = self.dropin()
        previous = read_config_file(path)
        text = _render(wanted)
        try:
            self._put(path, text)
            self._reload_systemd()
            warnings = self._prove(wanted)
            if not self.settings._wait():
                raise DatabaseEngineError(
                    f"{self.manager.DISPLAY_NAME} stopped answering under the new limits"
                )
        except DatabaseEngineError as failure:
            raise self._put_back(path, previous, failure) from failure
        except (KeyboardInterrupt, SystemExit):
            # An interruption: the engine's limits are not left half changed either.
            self._put_back(path, previous, DatabaseEngineError("The change was interrupted"))
            raise
        return LimitsOutcome(
            self.manager.ENGINE_NAME,
            self.manager.DISPLAY_NAME,
            str(path),
            list(changed),
            wanted,
            warnings,
        )

    def _put(self, path: Path, text: str | None) -> None:
        """
        Write the drop-in, or remove it when no limit is left.

        Args:
            path: The drop-in.
            text: Its content; None removes it.

        Raises:
            DatabaseEngineError: When it cannot be written or removed.
        """
        if text is None:
            try:
                self.manager.fs.remove(path)
            except OSError as exc:
                raise DatabaseEngineError(f"Could not remove {path}", details=str(exc)) from exc
            return
        write_config_file(self.manager.fs, path, text, preserve=False)

    def _reload_systemd(self) -> None:
        """
        Have systemd read the drop-in, which applies it to the running service.

        Raises:
            DatabaseEngineError: When systemd refuses.
        """
        result = self.manager._exec(["systemctl", "daemon-reload"], timeout=SERVICE_TIMEOUT)
        if not result.success:
            raise DatabaseEngineError(
                "systemd did not take the new limits",
                output=(result.stderr or result.stdout).strip() or None,
            )

    def _prove(self, wanted: LimitValues) -> list[str]:
        """
        Check that systemd holds the limits, and that the kernel enforces them.

        Args:
            wanted: The limits that should be in force.

        Returns:
            What the operator should know: a limit systemd holds and the kernel does not.

        Raises:
            DatabaseEngineError: When systemd holds something other than what was written.
        """
        if is_rehearsal():
            return []
        shown = self._show()
        effective = self._effective(shown)
        # What the operator asked for. A limit just removed may still be held by the unit itself
        # or by another drop-in, which is not this change's to judge.
        wrong = [
            DIRECTIVES[key]
            for key in DIRECTIVES
            if wanted.get(key) is not None and not _same(key, wanted.get(key), effective.get(key))
        ]
        if wrong:
            raise DatabaseEngineError(
                f"systemd does not hold {', '.join(wrong)} as written",
                details="Another drop-in of the unit may set it later; see: "
                f"systemctl cat {self.unit()}",
            )
        enforced, _ = self._proof(shown)
        return [
            f"systemd holds {DIRECTIVES[key]} and the kernel does not enforce it "
            "(a cgroup v1 host, or memory accounting off): the limit is on paper only."
            for key, held in enforced.items()
            if held is False and wanted.get(key) is not None
        ]

    def _put_back(
        self, path: Path, previous: str | None, failure: DatabaseEngineError
    ) -> DatabaseEngineError:
        """
        Restore the previous drop-in and have systemd read it again.

        Args:
            path: The drop-in.
            previous: What it held, None when it did not exist.
            failure: Why the change failed.

        Returns:
            The error to raise: the failure with the engine's journal and what was put back.
        """
        notes: list[str] = []
        try:
            self._put(path, previous)
            self._reload_systemd()
            notes.append("The previous limits were put back.")
        except DatabaseEngineError as again:
            notes.append(f"The previous limits could not be put back: {again.message}")
        journal = self.journal()
        details = "\n".join(part for part in (failure.details, *notes) if part)
        return DatabaseEngineError(
            failure.message,
            details=details,
            output="\n".join(part for part in (failure.output, journal) if part) or None,
        )

    def journal(self) -> str:
        """
        Read the end of the engine's journal.

        Returns:
            journalctl's output verbatim, or its error.
        """
        result = self.manager._exec(
            ["journalctl", "-u", self.unit(), "-n", str(JOURNAL_LINES), "--no-pager"],
            timeout=SERVICE_TIMEOUT,
        )
        return (result.stdout if result.success else result.stderr).strip()


def _render(values: LimitValues) -> str | None:
    """
    Write the drop-in.

    Args:
        values: The limits to set.

    Returns:
        Its text; None when no limit is set, so the file is removed.
    """
    lines = []
    if values.memory_mb is not None:
        lines.append(f"MemoryMax={values.memory_mb}M")
    if values.cpus is not None:
        lines.append(f"CPUQuota={round(values.cpus * 100)}%")
    if values.swap_mb is not None:
        lines.append(f"MemorySwapMax={values.swap_mb}M")
    if values.tasks is not None:
        lines.append(f"TasksMax={values.tasks}")
    if not lines:
        return None
    return "\n".join([MARKER, "# Change it with: noust db limits", "[Service]", *lines]) + "\n"


def _megabytes(text: str | None) -> int | None:
    """
    Args:
        text: ``2048M`` as the drop-in holds it.

    Returns:
        The megabytes; None when absent or not in that form.
    """
    if text is None or not text.endswith("M") or not text[:-1].isdigit():
        return None
    return int(text[:-1])


def _cpus(text: str | None) -> float | None:
    """
    Args:
        text: ``150%`` as the drop-in holds it.

    Returns:
        The processors (``1.5``); None when absent or not in that form.
    """
    if text is None or not text.endswith("%") or not text[:-1].isdigit():
        return None
    return int(text[:-1]) / 100


def _whole(text: str | None) -> int | None:
    """
    Args:
        text: A whole number, or ``infinity``.

    Returns:
        The number; None for no limit.
    """
    if text is None or not text.strip().isdigit():
        return None
    return int(text.strip())


def _held(kernel: str | None, systemd: str | None) -> bool | None:
    """
    Args:
        kernel: What the cgroup file holds, None when it could not be read.
        systemd: What systemd reports for the same limit (``infinity`` for none).

    Returns:
        Whether the kernel holds what systemd set; None when either cannot be read.
    """
    if kernel is None or systemd is None:
        return None
    return kernel == ("max" if systemd == "infinity" else systemd)


def _same(key: str, wanted: int | float | None, held: int | float | None) -> bool:
    """
    Args:
        key: The limit.
        wanted: What was written.
        held: What systemd reports.

    Returns:
        Whether they agree; a quota is compared to a hundredth of a processor.
    """
    if wanted is None or held is None:
        return wanted is None and held is None
    if key == "cpus":
        return abs(float(wanted) - float(held)) < 0.01
    return int(wanted) == int(held)
