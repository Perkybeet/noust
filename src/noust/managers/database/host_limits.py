"""
Resource limits for an engine that runs on the host: its memory, processors, swap and tasks.

An application has limits behind the health gate and an instance (a container) has them from the
day it is made (``noust db instance limits``). The engine the distribution installed on the host
had only its cache settings, so one runaway query on a shared server could take the memory of
every application beside it. This is the same limit for that engine.

**Where it is written.** A systemd drop-in of Noust's own beside the engine's unit
(``/etc/systemd/system/<unit>.service.d/90-noust-limits.conf``), never the distribution's unit
file: ``MemoryMax=``, ``CPUQuota=``, ``MemorySwapMax=``, ``TasksMax=``. Nothing outside those four
is written.

**How it is applied.** Without a restart: ``systemctl daemon-reload`` makes systemd write the new
limits into the running service's cgroup, so no connection is dropped. A limit is then **proved**
rather than assumed, twice: systemd is asked what it holds for the unit, and the kernel's cgroup
files are read for what it will enforce (a limit systemd accepts and the kernel ignores, as on a
cgroup v1 host or one with memory accounting off, is reported, not hidden). Then the engine must
still answer. When any of that fails, the previous drop-in is put back, systemd reloaded again,
and the error carries the engine's journal verbatim, as the settings and the health gate do.

**What it costs.** A memory limit is a promise to the kernel, which kills the engine's process when
it is exceeded: for a database that is a crash, not a slowdown. A limit below what the engine
uses now is therefore asked for twice (:class:`~noust.core.exceptions.ConfirmationRequired`), and
the console and the documentation say to set it well above the engine's cache.

An engine in a container has its own limits (:mod:`noust.managers.database.instance_tuning`); this
module refuses it.
"""

