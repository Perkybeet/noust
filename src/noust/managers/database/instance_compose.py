"""
The Compose project, the environment and the configuration of a database instance.

Everything an instance's container is started from is decided here, from one
row of the store (:class:`~noust.core.db_instance_store.InstanceRecord`), and
nothing here touches the machine: the manager writes what these functions
return, through the filesystem seam. The same row is always the same bytes, so
an upgrade or a repair is writing the file again.

What the file says, and why:

- **The image is pinned by tag and digest** and Compose may pull it when it is
  missing: a restart after a ``docker image prune`` fetches exactly the bytes
  the instance was made with.
- **One port, on 127.0.0.1 only.** Docker publishes a port on every interface
  unless told otherwise and bypasses the host's firewall when it does, so the
  host side is always the loopback; the public way in is ``noust db public``.
- **A memory limit, always**, on the container (the kernel enforces it) and in
  the engine (so the engine sizes its caches to it and is not killed for
  growing past it): PostgreSQL's ``shared_buffers``, InnoDB's buffer pool,
  Redis's ``maxmemory`` and MongoDB's WiredTiger cache.
- **The superuser's password is in no argument.** It is in the container's
  environment, from a 0600 file; Redis and Valkey cannot read it from there, so
  it is also in their configuration file, which the container reads and nobody
  on the host can (it sits in the instance's 0700 directory). A command line is
  visible in ``ps`` to every local user, a container's included.
- **A literal ``$`` is written ``$$``**, which is how Compose is told not to
  interpolate it: the health checks run in the container's shell.

The file carries the "Generated by Noust" marker, and the unit that runs it is
the one the Compose applications use (``docker-compose.service.j2``).
"""

from __future__ import annotations

from typing import Any

import yaml

from noust.core.db_instance_store import TLS_OFF, TLS_REQUIRED, InstanceRecord
from noust.core.exceptions import ValidationError
from noust.managers.database import instance_layout as layout
from noust.managers.database.instance_catalog import EngineSpec, spec_for

#: Where each engine's configuration file is mounted in the image, for the engines
#: that read their password from one.
_CONFIG_MOUNTS: dict[str, str] = {
    "redis": "/usr/local/etc/redis/redis.conf",
    "valkey": "/usr/local/etc/valkey/valkey.conf",
}

#: How long Docker waits for the engine to stop on its own before killing it.
#: A database flushing a large buffer pool needs more than the default ten seconds.
STOP_GRACE = "60s"

#: The share of the limit the engine's own cache gets, in percent. The rest is
#: connections, sorts, the operating system's page cache for the container and
#: the engine's background work.
_POSTGRES_SHARE = 25
_INNODB_SHARE = 50
_REDIS_SHARE = 75
_MONGO_SHARE = 50

#: The environment variable each flavour's password is in, which is also where
#: Noust's own client finds it (``instances.PASSWORD_SOURCES``).
PASSWORD_VARIABLES: dict[str, str] = {
    "postgresql": "POSTGRES_PASSWORD",
    "mysql": "MYSQL_ROOT_PASSWORD",
    "mariadb": "MARIADB_ROOT_PASSWORD",
    "redis": "REDIS_PASSWORD",
    "valkey": "VALKEY_PASSWORD",
    "mongodb": "MONGO_INITDB_ROOT_PASSWORD",
}

#: MongoDB's administrator. Noust's own name for it, as on the host's MongoDB.
MONGO_ADMIN = "noust_admin"

#: Where an instance's certificate, key and authority are mounted in its container.
TLS_MOUNT = "/etc/noust-tls"

#: The group the images' engines run as (``postgres``, ``mysql``, ``mongodb``: 999
#: in every one of the Debian, Oracle Linux and Ubuntu images Noust pins). The key
#: file is root's, readable by this group and no other, which is what PostgreSQL
#: accepts of a key it does not own.
ENGINE_GID = 999

#: The first MariaDB release that can refuse a plaintext connection for the whole server.
_MARIADB_REQUIRED_FROM = (11, 4)


def _share(memory_mb: int, percent: int, *, floor: int) -> int:
    """
    Args:
        memory_mb: The instance's limit.
        percent: The share of it.
        floor: The least the setting may be.

    Returns:
        That share, in whole megabytes, never below the floor.
    """
    return max(memory_mb * percent // 100, floor)


def _version_tuple(version: str) -> tuple[int, ...]:
    """
    Args:
        version: ``11.4``, ``17``.

    Returns:
        Its numbers.
    """
    return tuple(int(part) for part in version.split(".") if part.isdigit())


def tls_supported(flavour: str, version: str, mode: str) -> str | None:
    """
    Say why an engine cannot serve TLS in a mode, or None when it can.

    PostgreSQL and MySQL/MariaDB can refuse a plaintext connection while Noust's own
    client, which uses their local socket, goes on working. MongoDB can serve TLS
    to those who ask (``preferTLS``) but not refuse the rest: its health check and
    Noust's client inside the container connect without it. Redis and Valkey need
    their own client changed to speak TLS, which Noust does not do yet.

    Args:
        flavour: The flavour.
        version: Its version.
        mode: ``off``, ``optional`` or ``required``.

    Returns:
        A sentence saying why not, or None.
    """
    if mode == TLS_OFF:
        return None
    if flavour in ("redis", "valkey"):
        return (
            "Noust's client for Redis and Valkey inside the container does not speak TLS yet, "
            "so an instance of either cannot serve it"
        )
    if mode == TLS_REQUIRED and flavour == "mongodb":
        return (
            "MongoDB's health check and Noust's own client inside the container connect "
            "without TLS, so MongoDB can serve TLS to those who ask (optional) but not refuse "
            "the rest"
        )
    if (
        mode == TLS_REQUIRED
        and flavour == "mariadb"
        and _version_tuple(version) < _MARIADB_REQUIRED_FROM
    ):
        return (
            f"MariaDB {version} cannot refuse a plaintext connection for the whole server "
            "(it can from 11.4): serve TLS as optional, or move to a newer MariaDB"
        )
    return None


def tls_command(flavour: str, mode: str) -> list[str]:
    """
    Say what the engine is started with to serve TLS.

    Args:
        flavour: The flavour.
        mode: ``optional`` or ``required``.

    Returns:
        The arguments to add after the engine's program.
    """
    cert = f"{TLS_MOUNT}/server.crt"
    key = f"{TLS_MOUNT}/server.key"
    authority = f"{TLS_MOUNT}/ca.crt"
    if flavour == "postgresql":
        arguments = [
            "-c",
            "ssl=on",
            "-c",
            f"ssl_cert_file={cert}",
            "-c",
            f"ssl_key_file={key}",
            "-c",
            f"ssl_ca_file={authority}",
        ]
        if mode == TLS_REQUIRED:
            arguments += ["-c", f"hba_file={TLS_MOUNT}/pg_hba.conf"]
        return arguments
    if flavour in ("mysql", "mariadb"):
        arguments = [f"--ssl-ca={authority}", f"--ssl-cert={cert}", f"--ssl-key={key}"]
        if mode == TLS_REQUIRED:
            arguments.append("--require-secure-transport=ON")
        return arguments
    if flavour == "mongodb":
        return [
            "--tlsMode",
            "preferTLS",
            "--tlsCertificateKeyFile",
            f"{TLS_MOUNT}/server.pem",
            "--tlsCAFile",
            authority,
        ]
    return []


def render_pg_hba(mode: str) -> str:
    """
    Write the ``pg_hba.conf`` of a PostgreSQL instance that refuses plaintext.

    The image's own file, with its last line made TLS-only: the engine's local
    socket and its own loopback stay as they were (that is how Noust's client and
    the health check reach it), and every connection from outside the container
    must use TLS.

    Args:
        mode: ``required`` (the only mode that needs the file).

    Returns:
        The file's text.
    """
    if mode != TLS_REQUIRED:
        raise ValidationError(
            "Only a required TLS mode changes pg_hba.conf",
            details="An optional one leaves the image's own file in place.",
        )
    return (
        f"# {layout.GENERATED_MARKER}\n"
        "local all all trust\n"
        "host all all 127.0.0.1/32 trust\n"
        "host all all ::1/128 trust\n"
        "hostssl all all all scram-sha-256\n"
        "host all all all reject\n"
    )


def engine_command(flavour: str, memory_mb: int, *, tls: str = TLS_OFF) -> list[str] | None:
    """
    Say how the engine is started so that it sizes itself to its memory limit.

    Args:
        flavour: The flavour.
        memory_mb: The instance's limit.
        tls: ``off``, ``optional`` or ``required``: whether it serves TLS.

    Returns:
        The container's command, or None to leave the image's own.
    """
    serving = tls_command(flavour, tls) if tls != TLS_OFF else []
    if flavour == "postgresql":
        buffers = _share(memory_mb, _POSTGRES_SHARE, floor=32)
        return ["postgres", "-c", f"shared_buffers={buffers}MB", *serving]
    if flavour in ("mysql", "mariadb"):
        pool = _share(memory_mb, _INNODB_SHARE, floor=64)
        program = "mysqld" if flavour == "mysql" else "mariadbd"
        return [program, f"--innodb-buffer-pool-size={pool}M", *serving]
    if flavour in ("redis", "valkey"):
        program = "redis-server" if flavour == "redis" else "valkey-server"
        return [program, _CONFIG_MOUNTS[flavour]]
    if flavour == "mongodb":
        cache = max(memory_mb * _MONGO_SHARE / 100 / 1024, 0.25)
        return ["mongod", "--wiredTigerCacheSizeGB", f"{cache:.2f}", *serving]
    return None


def health_check(flavour: str, spec: EngineSpec) -> dict[str, Any]:
    """
    Say how Docker can tell the engine is up and accepting connections.

    Every check goes over TCP on the container's own loopback, which is what
    tells the engine from the temporary server its image runs while it
    initialises (that one listens on a socket only).

    Args:
        flavour: The flavour.
        spec: Its spec.

    Returns:
        The service's ``healthcheck``.
    """
    port = spec.container_port
    tests: dict[str, list[str]] = {
        "postgresql": ["CMD-SHELL", f"pg_isready -h 127.0.0.1 -p {port} -U postgres"],
        "mysql": ["CMD-SHELL", f"mysqladmin ping -h 127.0.0.1 -P {port} --silent"],
        "mariadb": ["CMD-SHELL", f"mariadb-admin ping -h 127.0.0.1 -P {port} --silent"],
        "redis": ["CMD-SHELL", 'REDISCLI_AUTH="$$REDIS_PASSWORD" redis-cli ping | grep -q PONG'],
        "valkey": [
            "CMD-SHELL",
            'REDISCLI_AUTH="$$VALKEY_PASSWORD" valkey-cli ping | grep -q PONG',
        ],
        "mongodb": [
            "CMD",
            "mongosh",
            "--quiet",
            "--eval",
            "quit(db.adminCommand('ping').ok === 1 ? 0 : 1)",
        ],
    }
    return {
        "test": tests[flavour],
        "interval": "10s",
        "timeout": "5s",
        "retries": 12,
        "start_period": "30s",
    }


def build_document(record: InstanceRecord) -> dict[str, Any]:
    """
    Build the Compose file of an instance, as a document.

    Args:
        record: The instance's row.

    Returns:
        The document, ready to dump.

    Raises:
        ValidationError: The flavour is not one Noust runs.
    """
    spec = spec_for(record.flavour)
    name = record.name
    labels = {
        layout.MANAGED_LABEL: "true",
        layout.INSTANCE_LABEL: name,
        "io.noust.db-flavour": record.flavour,
    }
    volumes = [f"{layout.data_volume(name)}:{spec.data_path(record.version)}"]
    named: dict[str, Any] = {
        layout.data_volume(name): {"name": layout.data_volume(name), "labels": dict(labels)}
    }
    for path in spec.extra_volumes:
        volume = layout.config_volume(name)
        volumes.append(f"{volume}:{path}")
        named[volume] = {"name": volume, "labels": dict(labels)}
    mount = _CONFIG_MOUNTS.get(record.flavour)
    if mount is not None:
        volumes.append(f"./{layout.CONFIG_FILE}:{mount}:ro")
    if record.tls_mode != TLS_OFF:
        volumes.append(f"./{layout.TLS_DIRECTORY}:{TLS_MOUNT}:ro")

    service: dict[str, Any] = {
        "image": record.reference,
        "container_name": layout.container_name(name),
        "restart": "unless-stopped",
        "env_file": [layout.ENV_FILE],
        "ports": [f"127.0.0.1:{record.host_port}:{spec.container_port}"],
        "volumes": volumes,
        "labels": labels,
        "healthcheck": health_check(record.flavour, spec),
        "deploy": {"resources": {"limits": {"memory": f"{record.memory_limit_mb}M"}}},
        "stop_grace_period": STOP_GRACE,
        "logging": {"driver": "json-file", "options": {"max-size": "10m", "max-file": "3"}},
    }
    command = engine_command(record.flavour, record.memory_limit_mb, tls=record.tls_mode)
    if command is not None:
        service["command"] = command
    return {"services": {layout.SERVICE: service}, "volumes": named}


def render_compose(record: InstanceRecord) -> str:
    """
    Write the Compose file of an instance.

    Args:
        record: The instance's row.

    Returns:
        The file's text: deterministic, so the same row is the same bytes.

    Raises:
        ValidationError: See :func:`build_document`.
    """
    body = yaml.safe_dump(build_document(record), sort_keys=False, default_flow_style=False)
    return f"# {layout.GENERATED_MARKER}\n{body}"


def render_env(flavour: str, password: str) -> str:
    """
    Write the environment file an instance's container reads.

    The file holds the superuser's password and is written 0600. What each image
    reads from it is the image's own documented variable, which is also where
    Noust's client inside the container looks for it.

    Args:
        flavour: The flavour.
        password: The superuser's password, letters and digits only (nothing
            that Compose's env-file grammar would read differently).

    Returns:
        The file's text.

    Raises:
        ValueError: The password has a character an env file would not keep.
    """
    if not password.isalnum():
        raise ValueError("an instance's password is letters and digits only")
    lines = [f"# {layout.GENERATED_MARKER}", f"{PASSWORD_VARIABLES[flavour]}={password}"]
    if flavour == "mongodb":
        lines.insert(1, f"MONGO_INITDB_ROOT_USERNAME={MONGO_ADMIN}")
    return "\n".join(lines) + "\n"


def render_engine_config(record: InstanceRecord, password: str) -> str | None:
    """
    Write the configuration file of an engine that reads its password from one.

    Redis and Valkey have no variable for it, and a ``--requirepass`` argument
    would be in ``ps`` for every local user.

    Args:
        record: The instance's row.
        password: The superuser's password.

    Returns:
        The file's text, or None for an engine that has none.

    Raises:
        ValueError: The password has a character a configuration file would not keep.
    """
    if record.flavour not in _CONFIG_MOUNTS:
        return None
    if not password.isalnum():
        raise ValueError("an instance's password is letters and digits only")
    limit = _share(record.memory_limit_mb, _REDIS_SHARE, floor=16)
    return (
        f"# {layout.GENERATED_MARKER}\n"
        f"requirepass {password}\n"
        "appendonly yes\n"
        f"maxmemory {limit}mb\n"
        "maxmemory-policy noeviction\n"
    )
