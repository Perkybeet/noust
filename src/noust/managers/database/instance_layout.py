"""
Where each part of a database instance lives, derived from its name.

An instance is a Compose project Noust writes (one service, ``db``), a systemd
unit that runs it, a directory with the files that project reads, and Docker
volumes for its data. Nothing of that is a column of the store: every name is
built here from the instance's name, so a row can never name a unit or a volume
it was not made with, and a test can say what a name is once.

Everything a name could break is checked by
:func:`noust.validators.db_instance.check_instance_name` first; the helpers here
assume a name that passed it and do not repeat the check.
"""

from __future__ import annotations

from pathlib import Path

from noust.core import paths

#: The label every container of an instance carries, naming the instance. The
#: store's row is the authority on what is Noust's; the label is how discovery
#: finds the container of a row.
INSTANCE_LABEL = "io.noust.db-instance"

#: The label every container and volume Noust makes carries.
MANAGED_LABEL = "io.noust.managed"

#: The label that says what engine a container Noust made runs. Discovery trusts it, with the two
#: above, for an image whose name it does not know: an operator's own image has any name.
FLAVOUR_LABEL = "io.noust.db-flavour"

#: The one service of an instance's Compose project.
SERVICE = "db"

#: What the files of an instance are called, in its directory.
COMPOSE_FILE = "compose.yaml"
ENV_FILE = "instance.env"

#: Where the engine's own configuration file is kept, for the engines that cannot
#: take a password any other way than a file (Redis, Valkey).
CONFIG_FILE = "engine.conf"

#: The directory of an instance's certificate, key and authority, mounted read-only
#: in its container when it serves TLS.
TLS_DIRECTORY = "tls"

#: The directory of the SQL scripts an engine runs the first time it starts, mounted
#: read-only where the official images look for them.
INIT_DIRECTORY = "initdb"

#: The first line of a file Noust wrote, and the marker everything of Noust's
#: is recognised by.
GENERATED_MARKER = "Generated by Noust. Do not edit: change the instance with `noust db instance`."

#: The directory every instance's own directory is under.
DIRECTORY_NAME = "db-instances"


def instances_dir() -> Path:
    """
    Returns:
        The directory the instances' directories are in, under Noust's state
        directory.
    """
    return paths.state_dir() / DIRECTORY_NAME


def directory(name: str) -> Path:
    """
    Args:
        name: The instance's name.

    Returns:
        Its directory, ``<state>/db-instances/<name>``.
    """
    return instances_dir() / name


def init_directory(name: str) -> Path:
    """
    Args:
        name: The instance's name.

    Returns:
        Where its initialisation scripts are written, ``<directory>/initdb``.
    """
    return directory(name) / INIT_DIRECTORY


def compose_path(name: str) -> Path:
    """
    Args:
        name: The instance's name.

    Returns:
        The Compose file the unit runs.
    """
    return directory(name) / COMPOSE_FILE


def env_path(name: str) -> Path:
    """
    Args:
        name: The instance's name.

    Returns:
        The 0600 file the container's environment, and with it the superuser's
        password, is read from.
    """
    return directory(name) / ENV_FILE


def config_path(name: str) -> Path:
    """
    Args:
        name: The instance's name.

    Returns:
        The engine's configuration file, where it has one.
    """
    return directory(name) / CONFIG_FILE


def tls_directory(name: str) -> Path:
    """
    Args:
        name: The instance's name.

    Returns:
        Where its certificate, key and authority are kept.
    """
    return directory(name) / TLS_DIRECTORY


def unit_name(name: str) -> str:
    """
    Args:
        name: The instance's name.

    Returns:
        The systemd unit that runs it, without the ``.service`` suffix.
    """
    return f"{paths.DB_INSTANCE_UNIT_PREFIX}{name}"


def project_name(name: str) -> str:
    """
    Args:
        name: The instance's name.

    Returns:
        Its Compose project (passed as ``-p`` everywhere, so the project never
        depends on the directory's name).
    """
    return unit_name(name)


def container_name(name: str) -> str:
    """
    Args:
        name: The instance's name.

    Returns:
        Its container's name, fixed so ``docker exec`` and ``docker logs`` always
        find it.
    """
    return unit_name(name)


def data_volume(name: str) -> str:
    """
    Args:
        name: The instance's name.

    Returns:
        The Docker volume that holds its data.
    """
    return f"{unit_name(name)}-data"


def config_volume(name: str) -> str:
    """
    Args:
        name: The instance's name.

    Returns:
        The Docker volume of an engine's second declared volume (MongoDB's
        ``/data/configdb``), named so Docker never leaves an anonymous one
        behind each time the container is recreated.
    """
    return f"{unit_name(name)}-config"
