"""
Where Noust writes the settings it gives MySQL and MariaDB, and the text of those files.

MySQL and MariaDB read ``[mysqld]`` settings from the files of an include directory, in the
order of their names. Noust never edits the files the packages ship: it adds files of its own, with
a name that sorts after theirs so its settings win, and takes them away to put the settings back.

- ``98-noust-tls.cnf``: the certificate the server presents (:mod:`.host_tls`).
- ``99-noust-replication.cnf``: what a primary needs for its replicas
  (:mod:`.replication_mysql`): binary logging, GTIDs, the address it listens on.
- ``99-noust-replica.cnf``: what a replica needs: its own ``server_id``, read-only.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from pathlib import Path

from noust.core.exceptions import DatabaseEngineError
from noust.managers.database import flavours

__all__ = ["include_directory", "parse_include", "render_include"]

#: The marker every file of Noust's carries.
MARKER = "# Generated by Noust"

_SETTING = re.compile(r"\s*(?P<key>[A-Za-z_][A-Za-z0-9_-]*)\s*=\s*(?P<value>.*?)\s*")


def include_directory(mariadb: bool) -> Path:
    """
    Name the directory the server includes settings files from.

    Args:
        mariadb: Whether the server is MariaDB (its directory differs from MySQL's on Debian).

    Returns:
        The first of the directories the flavours' packages use that exists on this server.

    Raises:
        DatabaseEngineError: When there is none.
    """
    for candidate in (
        "/etc/mysql/mariadb.conf.d" if mariadb else "/etc/mysql/mysql.conf.d",
        "/etc/my.cnf.d",
    ):
        folder = flavours.HOST.at(candidate)
        if folder.is_dir():
            return folder
    raise DatabaseEngineError(
        "Noust has nowhere to write settings for this MySQL or MariaDB",
        details="It writes into /etc/mysql/mysql.conf.d, /etc/mysql/mariadb.conf.d or "
        "/etc/my.cnf.d, whichever the server includes.",
    )


def render_include(purpose: str, settings: Mapping[str, str]) -> str:
    """
    Write a settings file.

    Args:
        purpose: One line saying what the file is for.
        settings: The ``[mysqld]`` settings, in the order they are written.

    Returns:
        The file's text.
    """
    body = "".join(f"{key} = {value}\n" for key, value in settings.items())
    return f"{MARKER}: {purpose} (see: noust db replica status)\n[mysqld]\n{body}"


def parse_include(text: str) -> dict[str, str]:
    """
    Read the settings of a file :func:`render_include` wrote.

    Args:
        text: The file.

    Returns:
        Its settings, in order.
    """
    settings: dict[str, str] = {}
    for line in text.splitlines():
        match = _SETTING.fullmatch(line)
        if match is not None and not line.lstrip().startswith(("#", "[")):
            settings[match.group("key")] = match.group("value")
    return settings
