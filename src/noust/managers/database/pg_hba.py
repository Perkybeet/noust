"""
The one block Noust ever puts in ``pg_hba.conf``: an account that must use TLS.

PostgreSQL decides who may connect, from where and how, in ``pg_hba.conf``, a
file the distribution owns and Noust has never edited. A database made
reachable from the network gets an account of its own (see
:mod:`noust.managers.database.public_access`), and the only way to make
PostgreSQL refuse that account when it does not use TLS is a line for it::

    hostnossl <database> <account> all reject

``pg_hba.conf`` is read top to bottom and the first line that matches decides,
so the block goes above every other connection line; it matches that one
account on that one database and nothing else, and TLS connections fall
through to the lines that were already there. The block is marked, so removing
it, and only it, is exact.

Pure text in, text out: reading, writing, checking and reloading are the
manager's (:meth:`~noust.managers.database.postgres.PostgresManager.set_remote_tls`).
"""

from __future__ import annotations

import re

#: What a database or an account may be called here. The names reach the file
#: unquoted, so only what needs no quoting is accepted.
_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,62}")

#: What every block of this module opens with, whoever it is for.
_BLOCK_OPENING = "# BEGIN noust remote access:"


def _checked(value: str, what: str) -> str:
    """
    Check a name that is about to be written, unquoted, into ``pg_hba.conf``.

    Args:
        value: The database or the account.
        what: Which one, for the message.

    Returns:
        The name.

    Raises:
        ValueError: When it needs quoting, which Noust does not write.
    """
    if not _NAME.fullmatch(value):
        raise ValueError(f"The {what} {value!r} cannot be written into pg_hba.conf unquoted")
    return value


def _markers(account: str) -> tuple[str, str]:
    """
    Name the lines that fence an account's block.

    Args:
        account: The account.

    Returns:
        The line that opens the block and the line that closes it.
    """
    return (
        f"{_BLOCK_OPENING} {account}",
        f"# END noust remote access: {account}",
    )


def block(database: str, account: str) -> str:
    """
    Write the block that makes an account use TLS.

    Args:
        database: The database the account is for.
        account: The account.

    Returns:
        The block, newline-terminated.

    Raises:
        ValueError: When a name cannot be written unquoted.
    """
    begin, end = _markers(_checked(account, "account"))
    return (
        f"{begin}\n"
        "# Generated by Noust: this account is for a database reachable from the network and "
        "must use TLS.\n"
        f"hostnossl {_checked(database, 'database')} {account} all reject\n"
        f"{end}\n"
    )


def has_block(text: str, account: str) -> bool:
    """
    Tell whether the file holds an account's block.

    Args:
        text: The file.
        account: The account.

    Returns:
        True when the opening marker is there.
    """
    begin, _ = _markers(account)
    return any(line.strip() == begin for line in text.splitlines())


def without_block(text: str, account: str) -> str:
    """
    Take an account's block out of the file, and nothing else.

    Args:
        text: The file.
        account: The account.

    Returns:
        The file without the block; unchanged when it holds none. A block
        that was opened and never closed is left alone: a half block is not
        guessed at.
    """
    begin, end = _markers(account)
    lines = text.splitlines(keepends=True)
    kept: list[str] = []
    index = 0
    while index < len(lines):
        if lines[index].strip() == begin:
            closing = next(
                (at for at in range(index + 1, len(lines)) if lines[at].strip() == end), None
            )
            if closing is None:
                return text
            index = closing + 1
            continue
        kept.append(lines[index])
        index += 1
    return "".join(kept)


def with_block(text: str, database: str, account: str) -> str:
    """
    Put an account's block above every connection line of the file.

    A block the file already holds for the account is replaced, not repeated.

    Args:
        text: The file.
        database: The database the account is for.
        account: The account.

    Returns:
        The file with the block after its leading comments.

    Raises:
        ValueError: When a name cannot be written unquoted.
    """
    cleaned = without_block(text, account)
    lines = cleaned.splitlines(keepends=True)
    at = 0
    # After the leading comments, and above the first connection line or the
    # first block of another account, never inside one.
    while (
        at < len(lines)
        and not lines[at].strip().startswith(_BLOCK_OPENING)
        and (not lines[at].strip() or lines[at].lstrip().startswith("#"))
    ):
        at += 1
    new = block(database, account)
    head = "".join(lines[:at])
    if head and not head.endswith("\n"):
        head += "\n"
    return head + new + "".join(lines[at:])
