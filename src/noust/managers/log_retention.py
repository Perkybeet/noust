"""
How long the logs are kept (checklist G-13: "with a retention you can set").

The logs of an application live in the journal, so how long they are searchable is how
long ``systemd-journald`` keeps them: by default until they use a tenth of the disk,
which on a busy server can be a week and on a quiet one a year, and *nothing* after a
reboot when the journal is volatile (no ``/var/log/journal``). This writes the two
settings that make it a number you chose, in a drop-in of journald's own configuration
(``/etc/systemd/journald.conf.d/50-noust-retention.conf``):

``MaxRetentionSec``
    Entries older than this are dropped, whatever room is left.
``SystemMaxUse``
    The most disk the journal may use; the oldest go first when it is reached.

A drop-in somebody else wrote is never overwritten (the file starts with Noust's marker
or it is not touched), and removing the retention removes the file and nothing else.
Journald is restarted to read it; it keeps what it has.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from noust.core.exceptions import ServiceError, ValidationError
from noust.core.fs import FileSystem, get_fs
from noust.core.runner import CommandRunner, get_runner

#: Where the drop-in goes, and what marks it as Noust's.
DROPIN = Path("/etc/systemd/journald.conf.d/50-noust-retention.conf")
MARKER = "# Generated by Noust (noust log retention)"

#: The journal's directory: when it is missing, journald is volatile.
JOURNAL_DIR = Path("/var/log/journal")

#: Bounds of what may be asked for.
MIN_DAYS, MAX_DAYS = 1, 3_650
MIN_MB, MAX_MB = 16, 1_048_576

#: Deadline of the commands this runs.
COMMAND_TIMEOUT = 30

_SETTING = re.compile(r"^\s*(MaxRetentionSec|SystemMaxUse|Storage)\s*=\s*(\S+)\s*$", re.MULTILINE)
_SECONDS = re.compile(
    r"(\d+)\s*(s|sec|m|min|h|hour|d|day|days|w|week|month|y|year)?", re.IGNORECASE
)
_SIZE = re.compile(r"(\d+(?:\.\d+)?)\s*([KMGT])?", re.IGNORECASE)


@dataclass
class RetentionStatus:
    """
    How long the logs are kept, and by what.

    Attributes:
        days: The age past which entries are dropped; None for the default.
        max_use_mb: The most disk the journal may use; None for the default.
        persistent: The drop-in asks for ``Storage=persistent``.
        journal_on_disk: ``/var/log/journal`` exists, so the journal survives a reboot.
        disk_usage: What ``journalctl --disk-usage`` says, verbatim.
        configured: A Noust drop-in is in place.
        foreign: A drop-in of that name exists that Noust did not write: it is left alone.
        notes: What an operator should know.
    """

    days: int | None = None
    max_use_mb: int | None = None
    persistent: bool = False
    journal_on_disk: bool = False
    disk_usage: str = ""
    configured: bool = False
    foreign: bool = False
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The status as the API and the CLI show it.
        """
        return {
            "days": self.days,
            "max_use_mb": self.max_use_mb,
            "persistent": self.persistent,
            "journal_on_disk": self.journal_on_disk,
            "disk_usage": self.disk_usage,
            "configured": self.configured,
            "foreign": self.foreign,
            "notes": list(self.notes),
        }


def _days_of(text: str) -> int | None:
    """
    Args:
        text: A ``MaxRetentionSec`` value as journald reads it (``30day``, ``2592000``).

    Returns:
        Whole days, or None when it is not one this module wrote.
    """
    match = _SECONDS.fullmatch(text.strip())
    if match is None:
        return None
    number, unit = int(match.group(1)), (match.group(2) or "s").lower()
    seconds = {
        "s": 1,
        "sec": 1,
        "m": 60,
        "min": 60,
        "h": 3_600,
        "hour": 3_600,
        "d": 86_400,
        "day": 86_400,
        "days": 86_400,
        "w": 604_800,
        "week": 604_800,
        "month": 2_629_800,
        "y": 31_557_600,
        "year": 31_557_600,
    }[unit]
    return max(1, round(number * seconds / 86_400))


def _mb_of(text: str) -> int | None:
    """
    Args:
        text: A ``SystemMaxUse`` value (``2G``, ``500M``).

    Returns:
        Megabytes, or None when it is not a size.
    """
    match = _SIZE.fullmatch(text.strip())
    if match is None:
        return None
    factor = {"K": 1 / 1024, "M": 1, "G": 1024, "T": 1024 * 1024, None: 1 / (1024 * 1024)}[
        (match.group(2) or "").upper() or None
    ]
    return max(1, round(float(match.group(1)) * factor))


class LogRetention:
    """
    Reads and sets the journal's retention.

    Args:
        runner: Runs ``journalctl`` and ``systemctl``; the process-wide one by default.
        fs: Writes the drop-in; the process-wide one by default (so ``--dry-run`` is honoured).
        dropin: The drop-in's path (tests).
        journal_dir: Where a persistent journal lives (tests).
    """

    def __init__(
        self,
        runner: CommandRunner | None = None,
        fs: FileSystem | None = None,
        *,
        dropin: Path = DROPIN,
        journal_dir: Path = JOURNAL_DIR,
    ) -> None:
        self._runner = runner
        self._fs = fs
        self._dropin = dropin
        self._journal_dir = journal_dir

    @property
    def runner(self) -> CommandRunner:
        """The command runner."""
        return self._runner or get_runner()

    @property
    def fs(self) -> FileSystem:
        """The filesystem the drop-in is written through."""
        return self._fs or get_fs()

    def status(self) -> RetentionStatus:
        """
        Returns:
            What the drop-in sets, whether the journal is kept across reboots,
            and how much disk it takes now.
        """
        found = RetentionStatus(journal_on_disk=self._journal_dir.is_dir())
        text = self._read()
        if text is not None:
            if text.lstrip().startswith(MARKER):
                found.configured = True
                settings = dict(_SETTING.findall(text))
                if "MaxRetentionSec" in settings:
                    found.days = _days_of(settings["MaxRetentionSec"])
                if "SystemMaxUse" in settings:
                    found.max_use_mb = _mb_of(settings["SystemMaxUse"])
                found.persistent = settings.get("Storage") == "persistent"
            else:
                found.foreign = True
                found.notes.append(
                    f"{self._dropin} exists and Noust did not write it, so it is left alone."
                )
        if not found.journal_on_disk and not found.persistent:
            found.notes.append(
                "The journal is kept in memory and lost at every reboot. Add --persistent to keep it."
            )
        done = self.runner.run(["journalctl", "--disk-usage"], timeout=COMMAND_TIMEOUT)
        if done.success:
            found.disk_usage = done.stdout.strip()
        return found

    def set(
        self,
        *,
        days: int | None = None,
        max_use_mb: int | None = None,
        persistent: bool | None = None,
    ) -> RetentionStatus:
        """
        Keep the logs this long, using at most this much disk.

        What is not named is kept as it is.

        Args:
            days: Drop entries older than this many days.
            max_use_mb: Use at most this many megabytes.
            persistent: Keep the journal across reboots.

        Returns:
            The status after journald was told to reread its configuration.

        Raises:
            ValidationError: A number out of range, or nothing to set.
            ServiceError: A drop-in that Noust did not write is in the way.
        """
        before = self.status()
        if before.foreign:
            raise ServiceError(
                f"{self._dropin} was not written by Noust",
                details="Move it aside, or set the retention in that file yourself.",
            )
        new_days = days if days is not None else before.days
        new_mb = max_use_mb if max_use_mb is not None else before.max_use_mb
        new_persistent = before.persistent if persistent is None else persistent
        if days is None and max_use_mb is None and persistent is None:
            raise ValidationError(
                "Name what to keep: --days, --max-use or --persistent", field="days"
            )
        if new_days is not None and not MIN_DAYS <= new_days <= MAX_DAYS:
            raise ValidationError(f"days is a number from {MIN_DAYS} to {MAX_DAYS}", field="days")
        if new_mb is not None and not MIN_MB <= new_mb <= MAX_MB:
            raise ValidationError(
                f"The most disk is a number of megabytes from {MIN_MB} to {MAX_MB}",
                field="max_use_mb",
            )
        lines = [MARKER, "[Journal]"]
        if new_persistent:
            lines.append("Storage=persistent")
        if new_days is not None:
            lines.append(f"MaxRetentionSec={new_days}day")
        if new_mb is not None:
            lines.append(f"SystemMaxUse={new_mb}M")
        self.fs.make_dir(self._dropin.parent, mode=0o755)
        self.fs.write_text(self._dropin, "\n".join(lines) + "\n", mode=0o644)
        self._apply()
        return self.status()

    def clear(self) -> RetentionStatus:
        """
        Remove the drop-in: journald goes back to its own defaults.

        Returns:
            The status afterwards.

        Raises:
            ServiceError: A drop-in that Noust did not write is in the way.
        """
        before = self.status()
        if before.foreign:
            raise ServiceError(
                f"{self._dropin} was not written by Noust", details="It is left as it is."
            )
        if before.configured:
            self.fs.remove(self._dropin, missing_ok=True)
            self._apply()
        return self.status()

    def _read(self) -> str | None:
        """
        Returns:
            The drop-in's text, or None when there is none.
        """
        try:
            return self._dropin.read_text(encoding="utf-8")
        except (FileNotFoundError, NotADirectoryError):
            return None
        except (OSError, UnicodeDecodeError) as exc:
            raise ServiceError(f"{self._dropin} could not be read", details=str(exc)) from exc

    def _apply(self) -> None:
        """Tell journald to reread its configuration; it keeps what it has."""
        done = self.runner.run(
            ["systemctl", "restart", "systemd-journald"], timeout=COMMAND_TIMEOUT
        )
        if not done.success:
            raise ServiceError(
                "The retention was written but journald could not be restarted",
                details=(done.stderr or done.stdout).strip(),
            )
