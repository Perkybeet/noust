_logger = logging.getLogger(__name__)

#: The first bytes of a file are where the marker is; nothing Noust writes puts it later.
_MARKER_WINDOW = 2000

#: Files bigger than this are not Noust's to rewrite.
_MAX_BYTES = 1024 * 1024

#: A docker command that only lists or names an image.
_DOCKER_TIMEOUT = 60

#: The directories whose files carry the marker, and the extensions that count in each.
_MARKED_PLACES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("/etc/nginx/sites-available", ()),
    ("/etc/nginx/sites-enabled", ()),
    ("/etc/nginx/conf.d", (".conf",)),
    ("/etc/nginx/noust-upstreams", (".conf",)),
    ("/etc/apache2/sites-available", (".conf",)),
    ("/etc/apache2/conf-available", (".conf",)),
    ("/etc/systemd/system", (".service", ".timer")),
    ("/etc/ssh/sshd_config.d", (".conf",)),
    ("/etc/fail2ban/jail.d", (".conf", ".local")),
    ("/etc/fail2ban/filter.d", (".conf",)),
)


@dataclass(frozen=True)
class Finding:
    """
    One thing that still has a name from before 4.0.

    Attributes:
        kind: ``upstream``, ``token``, ``repository file``, ``unit``, ``tree``, ``marker`` or ``folder``.
        subject: What it is about (an application, a token, a file).
        text: What was found, as a sentence.
        fix: What to do, when there is something to do.
        waits_for_operator: Whether something somebody else wrote keeps it (never rewritten).
        notes: More lines under it, such as the exact line of an operator's site.
    """

    kind: str
    subject: str
    text: str
    fix: str | None = None
    waits_for_operator: bool = False
    notes: tuple[str, ...] = ()


@dataclass
class StepOutcome:
    """
    What one step of :class:`NameMigration` did.

    Attributes:
        step: Its name.
        changed: What was renamed.
        kept: What was left on purpose, with the reason.
        failed: What could not be done, with what the system said.
    """

    step: str
    changed: list[str] = field(default_factory=list)
    kept: list[str] = field(default_factory=list)
    failed: list[str] = field(default_factory=list)


# -- the marker ------------------------------------------------------------------------------


def marker_files(roots: Sequence[tuple[Path, tuple[str, ...]]] | None = None) -> list[Path]:
    """
    List the files that still start with the marker of before 3.0.

    Args:
        roots: Directories and the extensions that count in them; the places Noust writes by
            default.

    Returns:
        The regular files (never links) that carry it in their first lines.
    """
    places = roots if roots is not None else [(Path(p), ext) for p, ext in _MARKED_PLACES]
    found: list[Path] = []
    for directory, extensions in places:
        try:
            entries = sorted(directory.iterdir())
        except OSError:
            continue
        for entry in entries:
            if entry.is_symlink() or not entry.is_file():
                continue
            if extensions and entry.suffix not in extensions:
                continue
            try:
                if entry.stat().st_size > _MAX_BYTES:
                    continue
                head = entry.read_text(encoding="utf-8", errors="replace")[:_MARKER_WINDOW]
            except OSError:
                continue
            if legacy_names.GENERATED_MARKER in head:
                found.append(entry)
    return found


def rewrite_markers(
    *,
    fs: FileSystem | None = None,
    roots: Sequence[tuple[Path, tuple[str, ...]]] | None = None,
    backup_to: Path | None = None,
) -> list[Path]:
    """
    Put the current marker in the files that still have the one of before 3.0.

    Only the marker changes, in the first place it stands; the rest of each file is as it was.
    A copy of the original goes under ``backup_to`` first, with the file's own path below it, so
    nothing is lost if a file turns out not to have been Noust's.

    Args:
        fs: The filesystem the changes go through.
        roots: Where to look; the places Noust writes by default.
        backup_to: Where the copies go; ``<backups>/names-4.0`` by default.

    Returns:
        The files rewritten.
    """
    fs = fs or get_fs()
    copies = backup_to if backup_to is not None else paths.backup_dir() / "names-4.0"
    done: list[Path] = []
    for path in marker_files(roots):
        try:
            text = path.read_text(encoding="utf-8")
            mode = path.stat().st_mode & 0o7777
            copy = copies / str(path).lstrip("/")
            fs.make_dir(copy.parent, mode=0o700, parents=True)
            fs.write_text(copy, text, mode=0o600)
            updated = text.replace(legacy_names.GENERATED_MARKER, paths.UNIT_MARKER, 1)
            fs.write_text(path, updated, mode=mode)
        except (OSError, UnicodeDecodeError) as exc:
            _logger.warning("Could not bring the marker of %s up to date: %s", path, exc)
            continue
        done.append(path)
    return done


def _state_file() -> Path:
    """The record that says the marker rewrite has been looked at on this server."""
    return paths.state_dir() / "name-migration.json"


def run_automatically(argv: list[str], announce: Callable[[str], None]) -> list[Path] | None:
    """
    Rewrite the markers on the first privileged run after the update, once.

    Not for a process systemd started (the console's own unit), a rehearsal, or shell
    completion. Every failure is contained: the command the operator asked for runs either way.

    Args:
        argv: The command line after the program name.
        announce: Receives one line when something was rewritten.

    Returns:
        The files rewritten, or None when nothing was looked at.
    """
    environ = os.environ
    if os.geteuid() != 0 or environ.get("INVOCATION_ID") or "--dry-run" in argv:
        return None
    if any(key in environ for key in ("_NOUST_COMPLETE", "_WASM_COMPLETE")):
        return None
    record = _state_file()
    if record.is_file():
        return None
    try:
        rewritten = rewrite_markers()
        fs = get_fs()
        fs.make_dir(record.parent, mode=0o755, parents=True)
        fs.write_text(
            record,
            json.dumps({"markers": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}) + "\n",
            mode=0o644,
        )
    except (NoustError, OSError) as exc:
        _logger.warning("The names from before 4.0 were not brought up to date: %s", exc)
        return None
    if rewritten:
        announce(
            f"{len(rewritten)} file(s) Noust wrote before 3.0 now say who wrote them "
            f"(copies in {paths.backup_dir() / 'names-4.0'})"
        )
    return rewritten


# -- what remains ------------------------------------------------------------------------------


def _unit_files(unit_dir: Path) -> list[Path]:
    """
    List the units of applications that still have the prefix of before 0.14.1.

    Args:
        unit_dir: The directory of the units.

    Returns:
        The unit files with the prefix.
    """
    try:
        entries = sorted(unit_dir.glob(f"{legacy_names.UNIT_PREFIX}*.service"))
    except OSError:
        return []
    return [entry for entry in entries if entry.is_file() and not entry.is_symlink()]


class NameMigration:
    """
    The renaming of what Noust holds, finished on request.

    Every collaborator can be given, so a test (or a rehearsal) drives it over its own tree.

    Args:
        store: Where the applications are read.
        fs: The filesystem every change goes through.
        runner: Runs docker and git.
        web: The web server manager, for the upstream names.
        unit_dir: Where application units live.
    """

    def __init__(
        self,
        *,
        store: NoustStore | None = None,
        fs: FileSystem | None = None,
        runner: CommandRunner | None = None,
        web: object | None = None,
        unit_dir: Path | None = None,
        marker_roots: Sequence[tuple[Path, tuple[str, ...]]] | None = None,
        backup_to: Path | None = None,
    ) -> None:
        self._store = store
        self._fs = fs
        self._runner = runner
        self._web = web
        self.unit_dir = unit_dir or SYSTEMD_DIR
        self.marker_roots = marker_roots
        self.backup_to = backup_to

    @property
    def store(self) -> NoustStore:
        """The store applications are read from."""
        return self._store or get_store()

    @property
    def fs(self) -> FileSystem:
        """The filesystem every change goes through."""
        return self._fs or get_fs()

    @property
    def runner(self) -> CommandRunner:
        """The runner docker and git go through."""
        return self._runner or get_runner()

    def web(self) -> object:
        """The nginx manager, built when first needed."""
        if self._web is None:
            from noust.managers.nginx_manager import NginxManager

            self._web = NginxManager(fs=self.fs, runner=self.runner)
        return self._web

    def apps(self) -> list[tuple[str, Path]]:
        """
        List the applications and the directory their running code is in.

        Returns:
            Each application's domain and code path; empty when the store cannot be read.
        """
        try:
            return [
                (app.domain, code_path_for(app)) for app in self.store.list_apps() if app.app_path
            ]
        except (NoustError, sqlite3.Error) as exc:
            _logger.warning("Could not read the applications: %s", exc)
            return []

    # -- the steps ----------------------------------------------------------------------------

    def run(self, steps: Iterable[str] | None = None) -> list[StepOutcome]:
        """
        Do every step that can be done without restarting anything.

        Args:
            steps: The steps to run, by name; all of them by default.

        Returns:
            One outcome per step, in order.
        """
        available: dict[str, Callable[[], StepOutcome]] = {
            "markers": self.markers,
            "trees": self.trees,
            "upstreams": self.upstreams,
            "branches": self.branches,
            "accounts": self.accounts,
            "images": self.images,
        }
        wanted = list(steps) if steps is not None else list(available)
        return [available[name]() for name in wanted if name in available]

    def markers(self) -> StepOutcome:
        """The first line of the sites and units written before 3.0."""
        outcome = StepOutcome("markers")
        outcome.changed = [
            str(path)
            for path in rewrite_markers(
                fs=self.fs, roots=self.marker_roots, backup_to=self.backup_to
            )
        ]
        return outcome

    def trees(self) -> StepOutcome:
        """The files Noust keeps in each application's tree."""
        outcome = StepOutcome("trees")
        for domain, code in self.apps():
            root = code.parent if code.name == "current" else code
            outcome.changed.extend(str(path) for path in tree_names.sweep(root, fs=self.fs))
            if domain and not root.exists():
                outcome.kept.append(f"{domain}: {root} is not there")
        return outcome

    def upstreams(self) -> StepOutcome:
        """The upstream names of blue/green and of the Compose relay."""
        from noust.managers import upstream_names

        outcome = StepOutcome("upstreams")
        try:
            results = upstream_names.rename(self.web())  # type: ignore[arg-type]
        except NoustError as exc:
            outcome.failed.append(str(exc))
            return outcome
        for result in results:
            if result.status in {"renamed", "rehearsed"}:
                outcome.changed.append(f"{result.name} -> {result.new_name}")
            elif result.status == "aliased":
                where = ", ".join(f"{ref.path}:{ref.line}" for ref in result.references[:3])
                outcome.kept.append(
                    f"{result.name} stays defined beside {result.new_name}: {where} names it"
                )
            else:
                outcome.failed.append(f"{result.name}: {result.detail}")
        return outcome

    def branches(self) -> StepOutcome:
        """The branch each detached checkout remembers."""
        from noust.managers.source_manager import SourceManager

        outcome = StepOutcome("branches")
        manager = SourceManager(runner=self.runner)
        for domain, code in self.apps():
            if manager.adopt_branch_key(code):
                outcome.changed.append(domain)
        return outcome

    def accounts(self) -> StepOutcome:
        """The read-only account of each database of every engine that is running."""
        from noust.managers.database.service import DatabaseService

        outcome = StepOutcome("accounts")
        try:
            managers = DatabaseService().all_managers()
        except NoustError as exc:
            outcome.failed.append(str(exc))
            return outcome
        for manager in managers:
            try:
                if not manager.is_installed() or not manager.is_running():
                    continue
                for database in manager.list_databases():
                    if manager.drop_legacy_read_only_account(database.name):
                        outcome.changed.append(f"{manager.ENGINE_NAME}/{database.name}")
            except NoustError as exc:
                outcome.failed.append(f"{manager.ENGINE_NAME}: {exc}")
        return outcome

    def images(self) -> StepOutcome:
        """The image tags Compose updates kept their way back under."""
        from noust.deployers.helpers import compose_retention

        outcome = StepOutcome("images")
        if not self.runner.exists("docker"):
            return outcome
        listed = self.runner.run(
            [
                "docker",
                "image",
                "ls",
                "--filter",
                f"reference=*:{compose_retention.LEGACY_PREVIOUS_TAG}",
                "--format",
                "{{.Repository}}\t{{.ID}}",
            ],
            timeout=_DOCKER_TIMEOUT,
        )
        if not listed.success:
            outcome.failed.append((listed.stderr or listed.stdout).strip())
            return outcome
        for line in listed.stdout.splitlines():
            repository, _, image_id = line.partition("\t")
            if not repository or not image_id:
                continue
            old = f"{repository}:{compose_retention.LEGACY_PREVIOUS_TAG}"
            new = f"{repository}:{compose_retention.PREVIOUS_TAG}"
            present = self.runner.run(
                ["docker", "image", "ls", "--filter", f"reference={new}", "--format", "{{.ID}}"],
                timeout=_DOCKER_TIMEOUT,
            )
            if not present.stdout.strip():
                tagged = self.runner.run(
                    ["docker", "image", "tag", image_id, new], timeout=_DOCKER_TIMEOUT
                )
                if not tagged.success:
                    outcome.failed.append(f"{old}: {tagged.stderr.strip()}")
                    continue
            removed = self.runner.run(["docker", "image", "rm", old], timeout=_DOCKER_TIMEOUT)
            if removed.success:
                outcome.changed.append(f"{old} -> {new}")
            else:
                outcome.failed.append(f"{old}: {removed.stderr.strip()}")
        return outcome

    # -- the findings -------------------------------------------------------------------------

    def findings(self) -> list[Finding]:
        """
        List what still has a name from before 4.0.

        Reads files and the store only, never a database engine or docker, so the health report
        can ask on every request.

        Returns:
            The findings, those that wait for the operator first.
        """
        found: list[Finding] = []
        found.extend(self._upstream_findings())
        found.extend(self._token_findings())
        found.extend(self._repository_findings())
        found.extend(self._unit_findings())
        found.extend(self._tree_findings())
        found.extend(self._marker_findings())
        found.extend(self._folder_findings())
        return sorted(found, key=lambda finding: not finding.waits_for_operator)

    def _upstream_findings(self) -> list[Finding]:
        from noust.managers import upstream_names

        try:
            verdicts = upstream_names.scan(self.web())  # type: ignore[arg-type]
        except (NoustError, OSError) as exc:
            _logger.debug("The upstream names were not read: %s", exc)
            return []
        found = []
        for verdict in verdicts:
            if verdict.free:
                found.append(
                    Finding(
                        "upstream",
                        verdict.name,
                        f"The upstream {verdict.name} still has the name of before 4.0",
                        fix="Run: noust setup rename",
                    )
                )
                continue
            lines = tuple(
                f"{ref.path}:{ref.line}  {ref.text}  ->  change {verdict.name} to {verdict.new_name}"
                for ref in verdict.references
            )
            found.append(
                Finding(
                    "upstream",
                    verdict.name,
                    f"A site somebody else wrote names the upstream {verdict.name}: it works as it "
                    f"is, because Noust keeps that name defined beside {verdict.new_name}, and "
                    "never edits the site",
                    fix=f"Change the line to {verdict.new_name} (either name works until then), "
                    "then run: noust setup rename, which takes the old name away",
                    waits_for_operator=True,
                    notes=lines,
                )
            )
        return found

    def _token_findings(self) -> list[Finding]:
        try:
            from noust.web.auth import SecurityConfig, TokenManager, get_global_token_manager

            manager = get_global_token_manager() or TokenManager(SecurityConfig())
            in_use = manager.legacy_prefix_tokens_in_use()
        except (ImportError, NoustError, OSError, sqlite3.Error) as exc:
            _logger.debug("The tokens were not read: %s", exc)
            return []
        return [
            Finding(
                "token",
                str(token["name"]),
                f"The API token {token['name']} signed in with the prefix of before 3.0 "
                f"({time.strftime('%Y-%m-%d', time.localtime(float(token['legacy_prefix_used_at'])))})",
                fix=f"Make a new token with: noust token create {token['name']}-new --scope "
                f"{token['scope']}; give it to whatever uses the old one; then revoke the old "
                f"with: noust token revoke {token['id']}",
                waits_for_operator=True,
            )
            for token in in_use
        ]

    def _repository_findings(self) -> list[Finding]:
        found = []
        for domain, code in self.apps():
            for name in legacy_names.NGINX_OVERRIDE_FILES:
                path = code / name
                if path.is_file() and not path.is_symlink():
                    current = name.replace(name.split(".", 1)[0], "noust", 1)
                    found.append(
                        Finding(
                            "repository file",
                            domain,
                            f"The repository of {domain} has {name}, named after the old product",
                            fix=f"In the repository: git mv {name} {current}",
                            waits_for_operator=True,
                        )
                    )
        return found

    def _unit_findings(self) -> list[Finding]:
        domains = {domain_to_app_name(domain): domain for domain, _ in self.apps()}
        found = []
        for path in _unit_files(self.unit_dir):
            base = path.stem.removeprefix(legacy_names.UNIT_PREFIX)
            command = f"noust update {domains[base]}" if base in domains else "noust update <it>"
            found.append(
                Finding(
                    "unit",
                    path.stem,
                    f"The unit {path.stem} has the prefix units had before 0.14.1",
                    fix=f"The application's next update renames it: {command}",
                )
            )
        return found

    def _tree_findings(self) -> list[Finding]:
        found = []
        for domain, code in self.apps():
            root = code.parent if code.name == "current" else code
            leftovers = len(tree_names.pending(root))
            if leftovers:
                found.append(
                    Finding(
                        "tree",
                        domain,
                        f"{leftovers} file(s) in the tree of {domain} have the names of before 4.0",
                        fix="Run: noust setup rename",
                    )
                )
        return found

    def _marker_findings(self) -> list[Finding]:
        files = marker_files(self.marker_roots)
        if not files:
            return []
        return [
            Finding(
                "marker",
                f"{len(files)} file(s)",
                f"{len(files)} site or unit file(s) still say the old product wrote them",
                fix="Run: noust setup rename",
                notes=tuple(str(path) for path in files[:5]),
            )
        ]

    def _folder_findings(self) -> list[Finding]:
        try:
            destinations = self.store.list_backup_destinations()
        except (NoustError, sqlite3.Error):
            return []
        return [
            Finding(
                "folder",
                destination.name,
                f"The backup destination {destination.name} also reads the folder it used to send "
                "to, until what is in it has expired",
            )
            for destination in destinations
            if destination.settings.get("legacy_path")
        ]


def findings() -> list[Finding]:
    """
    List what this server still carries from before 4.0, as the health report and the doctor ask.

    Returns:
        The findings of :meth:`NameMigration.findings` over the running machine.
    """
    return NameMigration().findings()


def finding_lines(items: Iterable[Finding]) -> list[str]:
    """
    Turn findings into the lines a report prints.

    Args:
        items: The findings.

    Returns:
        One line per finding, with its fix after it.
    """
    lines = []
    for item in items:
        line = item.text
        if item.fix:
            line += f" ({item.fix})"
        lines.append(re.sub(r"\s+", " ", line))
    return lines
