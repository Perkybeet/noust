"""
What a server still carries from before 4.0, and the command that finishes the renaming.

Updating to 4.0 renames nothing by itself that could stop something: an application's unit
is renamed by its next update (it restarts anyway), a read-only account by the next read of its
database, a backup folder by the next backup. This module is the rest. :func:`findings` lists
what still has the old name and why (a file somebody else wrote names it; it is waiting for the
next deployment; it waits for ``noust setup rename``), for ``noust health`` and ``noust setup
doctor``. :class:`NameMigration` does what can be done at once without restarting anything:
``noust setup rename``. Each step is idempotent and can be repeated; one that fails leaves the
rest to be done, and the next run starts where this one stopped.

The one step that runs without being asked is the rewrite of the "Generated by" marker that
sites and units written before 3.0 still carry (:func:`rewrite_markers`): the first line of a
file is what says Noust wrote it, and a Noust that stopped recognising the old line would stop
managing those files without a word. It changes that line only, with a copy of the file kept
beside the server's backups.
"""

