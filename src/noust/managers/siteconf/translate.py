"""
Translate a site file from nginx to Apache, or from Apache to nginx.

This is what moving an application to the other web server (backlog item 105) is made of, and like
the rest of the package it is pure: text in, text out, and a list of what did not come across.

- :func:`translate` reads the site with :func:`~noust.managers.siteconf.parse`, collects what it
  says into the records of :mod:`~noust.managers.siteconf.translate_model` and writes them in the
  other dialect. A line the reader cannot place is a :class:`Finding`; a file the web server would
  not read at all is a blocking finding and yields no text.
- The result starts with Noust's marker, so the site that comes out is one Noust wrote: a deploy
  rewrites it from its own templates like any other, and keeps what it replaced in the site's
  history.

The text is **not** tested here. Whether the new server accepts it is a question for that server
(:meth:`~noust.managers.webserver.WebServerManager.test_config_text`), which the move asks before it
touches anything.
"""

from __future__ import annotations

from noust.core.exceptions import SiteError
from noust.core.templates import text_environment
from noust.managers.siteconf.apache import parse_apache
from noust.managers.siteconf.nginx import parse_nginx
from noust.managers.siteconf.translate_from_apache import ApacheReader
from noust.managers.siteconf.translate_from_nginx import NginxReader
from noust.managers.siteconf.translate_model import (
    DISPLAY,
    Finding,
    Findings,
    Translation,
)
from noust.managers.siteconf.translate_to_apache import ApacheWriter
from noust.managers.siteconf.translate_to_nginx import NginxWriter
from noust.managers.siteconf.tree import Kind, ParseError

__all__ = ["Finding", "Translation", "translate"]

#: What the first comments of a translated site say; the second line is Noust's marker.
_HEADER = "# {target} site for {domain}, translated from {source} by Noust\n# Generated by Noust\n"


def _canonical_log(target: Kind, domain: str) -> dict[str, str]:
    """
    Read the log format Noust's own template writes for a site, in the target's words.

    The traffic page reads these logs by their format, so a translated site writes the format its
    server's template does, not an equivalent worked out from the old server's variables.

    Args:
        target: The dialect written.
        domain: The site's domain.

    Returns:
        ``{format name: its definition}``; empty when the template is not there.
    """
    try:
        environment = text_environment(f"templates/{target}")
        return {f"noust_{domain}": environment.get_template("_log_format.j2").render(domain=domain)}
    except (ValueError, ImportError, SiteError) as exc:
        # A package installed without its data files: the format is then translated generally.
        del exc
        return {}


def translate(text: str, *, source: Kind, target: Kind, domain: str) -> Translation:
    """
    Translate a site.

    Args:
        text: The site as the old web server reads it.
        source: Its dialect, ``nginx`` or ``apache``.
        target: The dialect to write; not the same as ``source``.
        domain: The site's domain, which names its log format.

    Returns:
        The new site and everything that did not come across. When the old file does not parse the
        text is empty and one finding blocks.

    Raises:
        ValueError: ``source`` and ``target`` are the same, or not a dialect this package knows.
    """
    if source == target:
        raise ValueError("A site is translated to the other web server, not to its own")
    if {source, target} != {"nginx", "apache"}:
        raise ValueError(f"Cannot translate {source!r} to {target!r}")
    findings = Findings(source, target)
    try:
        tree = parse_nginx(text) if source == "nginx" else parse_apache(text)
    except ParseError as exc:
        findings.unreadable(exc.line, exc.message)
        return Translation("", source, target, tuple(findings.items))

    log = _canonical_log(target, domain)
    names: list[str]
    modules: tuple[str, ...] = ()
    if source == "nginx":
        model = NginxReader(tree, findings, domain).read()
        apache = ApacheWriter(model, findings, domain, lambda name: log.get(name))
        body = apache.write()
        modules = tuple(sorted(apache.modules))
        names = apache.names
    else:
        model = ApacheReader(tree, findings, domain).read()
        nginx = NginxWriter(model, findings, domain, lambda name: log.get(name))
        body = nginx.write()
        names = nginx.names
    header = _HEADER.format(
        target=DISPLAY[target].capitalize(), domain=domain, source=DISPLAY[source]
    )
    return Translation(
        header + "\n" + body, source, target, tuple(findings.items), modules, tuple(names)
    )


def kind_of(webserver: str) -> Kind:
    """
    Args:
        webserver: A web server as the store records it, ``nginx`` or ``apache``.

    Returns:
        The same as the dialect the siteconf package calls it.

    Raises:
        ValueError: It is neither.
    """
    if webserver == "nginx":
        return "nginx"
    if webserver == "apache":
        return "apache"
    raise ValueError(f"Unknown web server: {webserver!r}")
