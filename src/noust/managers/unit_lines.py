"""
Take lines of Noust's own out of a unit, whether or not the unit still says it is Noust's.

``ServiceManager`` refuses to write a body that lacks the ``# Generated by Noust`` line, and rightly:
that line is what an operator removes to make a unit theirs, and what Noust never rewrites after that.
But a unit made theirs can still carry a line Noust put there before (the check that a Compose stack
runs before it starts), and removing Noust must not leave that line behind, because a unit that cannot
start is the one thing leaving was promised not to cause. The only thing this module can do to such a
unit is delete the lines its caller names, so that "never rewrite what is not ours" still holds for
everything else in the file.
"""

from __future__ import annotations

import errno
import os
import stat
from collections.abc import Callable

from noust.managers.service_manager import ServiceManager


def drop_lines(services: ServiceManager, name: str, drop: Callable[[str], bool]) -> bool:
    """
    Delete from an application's unit the lines ``drop`` names, and tell systemd.

    The rest of the file is kept byte for byte, with the mode it has: a unit its operator edited is
    theirs, and what changes in it is only what Noust wrote.

    Args:
        services: The unit manager (a dry run's, when the command is one).
        name: The application's unit name.
        drop: Says of one line (without its newline) whether it is Noust's to delete.

    Returns:
        Whether the file changed. A unit that does not exist, or that no application of the store owns,
        is not changed.

    Raises:
        OSError: The unit is a link or not a plain file (it is left as it is), or cannot be read or
            written.
        ValidationError: ``name`` is not a safe unit name.
    """
    info = services.inspect_unit(name, serving=False)
    if not info.exists or not info.managed:
        return False
    path = info.path
    if path.is_symlink() or not path.is_file():
        raise OSError(errno.EINVAL, "not a plain file, left as it is", str(path))
    before = path.read_text()
    after = "\n".join(line for line in before.split("\n") if not drop(line))
    if after == before:
        return False
    services.fs.write_text(path, after, mode=stat.S_IMODE(os.stat(path).st_mode))
    services.daemon_reload()
    return True
