"""
The post-receive hook of a push repository, and the file it reads its settings from.

When a branch moves, git runs ``hooks/post-receive`` as the push account. The hook tells the
console, the way a code host would: a GitHub-shaped ``push`` event signed with the application's
webhook secret (HMAC-SHA256) to ``/hooks/deploy/<domain>`` on the console's loopback address.
So a push is accepted, filtered (the branch the application tracks, ``[skip ci]``, watch paths),
logged in the application's delivery log and queued behind the same deploy queue as every other
door, by the code that already does all of that (rule 3), and the hook itself decides nothing.

The hook is a script of the standard library alone, written by Noust, owned by root and not
writable by the push account, so a push cannot change it. The settings (the URL, the secret, the
branch) are in ``noust-push.json`` beside it, readable by the push account's group only. The
hook never fails a push: whatever goes wrong it says so on the pusher's terminal and exits 0,
because the code is stored and ``noust update`` deploys it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

#: The hook's name in the repository's ``hooks`` directory.
HOOK_NAME = "post-receive"

#: Where its settings are, beside it.
CONFIG_NAME = "noust-push.json"

#: The hook. Written with ``{python}`` replaced by the interpreter. It is a module with a
#: ``main`` so that a test can run it with a fake git and a fake console.
_SCRIPT = '''#!{python}
# Generated by Noust: the post-receive hook of a push repository. Changes made here are replaced
# (noust push refresh). It reads noust-push.json beside it and never fails a push.
"""Tell Noust that a branch moved, so the application is updated."""

import hashlib
import hmac
import json
import os
import ssl
import subprocess
import sys
import urllib.error
import urllib.request
import uuid

CONFIG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "noust-push.json")
MAX_COMMITS = 20
NOTIFY_TIMEOUT = 20


def say(text):
    print(text)


def git(*args):
    try:
        done = subprocess.run(["git", *args], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return ""
    return done.stdout if done.returncode == 0 else ""


def files(sha):
    added, modified, removed = [], [], []
    for line in git("diff-tree", "--no-commit-id", "--name-status", "-r", "-m", "--root", sha).splitlines():
        status, _, rest = line.partition("\\t")
        paths = rest.split("\\t")
        if status.startswith("D"):
            removed += paths[:1]
        elif status.startswith("A"):
            added += paths[-1:]
        elif status.startswith(("R", "C")):
            if status.startswith("R"):
                removed += paths[:1]
            added += paths[-1:]
        elif paths and paths[0]:
            modified += paths[:1]
    return {{"added": added, "modified": modified, "removed": removed}}


def commits(old, new):
    reach = new if set(old) <= {{"0"}} else old + ".." + new
    listing = git("log", "-n", str(MAX_COMMITS), "--format=%H%x1f%B%x1e", reach)
    found = []
    for record in listing.split("\\x1e"):
        sha, _, message = record.strip("\\n").partition("\\x1f")
        sha = sha.strip()
        if sha:
            found.append({{"id": sha, "message": message.strip(), **files(sha)}})
    total = git("rev-list", "--count", reach).strip()
    return found, int(total) if total.isdigit() else len(found)


def payload(config, ref, old, new):
    found, total = commits(old, new)
    return {{
        "ref": ref,
        "before": old,
        "after": new,
        "total_commits_count": total,
        "repository": {{"full_name": config["domain"], "name": config["domain"]}},
        "commits": found,
        "head_commit": found[0] if found else None,
    }}


def deliver(config, body):
    signature = hmac.new(config["secret"].encode(), body, hashlib.sha256).hexdigest()
    request = urllib.request.Request(
        config["url"],
        data=body,
        method="POST",
        headers={{
            "Content-Type": "application/json",
            "User-Agent": "noust-push-hook",
            "X-GitHub-Event": "push",
            "X-GitHub-Delivery": str(uuid.uuid4()),
            "X-Hub-Signature-256": "sha256=" + signature,
        }},
    )
    context = None
    if config["url"].startswith("https:"):
        # The console's own certificate on the loopback address; the signature is what proves it.
        context = ssl.create_default_context()
        context.check_hostname = False
        context.verify_mode = ssl.CERT_NONE
    try:
        with urllib.request.urlopen(request, timeout=NOTIFY_TIMEOUT, context=context) as answer:
            return answer.status, json.loads(answer.read(65536) or b"{{}}")
    except urllib.error.HTTPError as exc:
        try:
            return exc.code, json.loads(exc.read(65536) or b"{{}}")
        except ValueError:
            return exc.code, {{}}
    except (OSError, ValueError) as exc:
        return None, {{"error": str(exc)}}


def report(config, status, answer):
    domain = config["domain"]
    if status == 202:
        job = answer.get("job_id")
        say("queued the update of %s (job %s). Follow it with: noust deploy queue %s" % (domain, job, domain))
    elif status == 200:
        reason = answer.get("reason") or answer.get("status") or "nothing to do"
        detail = answer.get("detail")
        say("nothing was deployed: %s%s" % (reason, " (%s)" % detail if detail else ""))
    elif status == 429:
        say("the deploy queue is full. Push again in a moment, or deploy it on the server: noust update %s" % domain)
    elif status in (401, 404):
        say("the console did not accept the notification (HTTP %s). On the server: noust push refresh %s" % (status, domain))
    elif status is None:
        say("the console is not reachable (%s). The code is stored; deploy it on the server: noust update %s" % (answer.get("error", "no answer"), domain))
    else:
        say("the console answered HTTP %s. The code is stored; deploy it on the server: noust update %s" % (status, domain))


def main(lines=None, config_path=CONFIG):
    try:
        with open(config_path, encoding="utf-8") as handle:
            config = json.load(handle)
        config["url"], config["secret"], config["branch"], config["domain"]
    except (OSError, ValueError, KeyError, TypeError):
        say("this repository's settings cannot be read, so nothing was deployed. On the server: noust push refresh")
        return 0
    for line in sys.stdin if lines is None else lines:
        parts = line.split()
        if len(parts) != 3 or not parts[2].startswith("refs/heads/"):
            continue
        old, new, ref = parts
        branch = ref[len("refs/heads/"):]
        if set(new) <= {{"0"}}:
            continue
        if branch != config["branch"]:
            say("%s was stored; %s deploys %s only. To deploy this branch: noust push enable %s --branch %s" % (branch, config["domain"], config["branch"], config["domain"], branch))
            continue
        try:
            body = json.dumps(payload(config, ref, old, new)).encode("utf-8")
            status, answer = deliver(config, body)
        except Exception as exc:  # the push is stored whatever this does
            status, answer = None, {{"error": "%s: %s" % (type(exc).__name__, exc)}}
        report(config, status, answer)
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def render_hook(python: str) -> str:
    """
    Write the hook.

    Args:
        python: The interpreter's absolute path, for the first line.

    Returns:
        The script.
    """
    return _SCRIPT.format(python=python)


@dataclass(frozen=True)
class HookConfig:
    """
    What the hook needs to know, and nothing it could use to do more.

    Attributes:
        domain: The application.
        url: Where to tell the console: ``http://127.0.0.1:<port>/hooks/deploy/<domain>``.
        secret: The application's webhook secret, which signs what the hook sends.
        branch: The branch that is deployed.
    """

    domain: str
    url: str
    secret: str
    branch: str

    def render(self) -> str:
        """
        Returns:
            The JSON file's text.
        """
        return json.dumps(
            {"domain": self.domain, "url": self.url, "secret": self.secret, "branch": self.branch},
            indent=2,
            sort_keys=True,
        )


def read_config(text: str) -> HookConfig | None:
    """
    Read a configuration file back.

    Args:
        text: The file's text.

    Returns:
        The configuration, or None when it is not one (it is never trusted to be).
    """
    try:
        data = json.loads(text)
        return HookConfig(
            domain=str(data["domain"]),
            url=str(data["url"]),
            secret=str(data["secret"]),
            branch=str(data["branch"]),
        )
    except (ValueError, KeyError, TypeError):
        return None
