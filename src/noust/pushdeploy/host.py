"""
Preparing a server to take ``git push``: the account the pushes log in as, and sshd's rules for it.

Once per server, as root (``noust push setup``). It makes the same kind of account the fleet
makes for centrals' tunnels, with the same machinery (:mod:`noust.fleet.authorize`: the account,
the ``Match User`` block in a fragment of Noust's own, ``sshd -t`` before reload, ``sshd -T``
after, and the file put back when sshd does not apply it), and differs where a push differs:

- the shell is ``git-shell``, because sshd runs a key's forced command through the account's
  shell and ``nologin`` would refuse it; git-shell runs ``git-receive-pack`` and its siblings and
  nothing else;
- the home is the directory that holds the repositories, so the account can reach them (the
  state directory is root's alone);
- no ``ForceCommand`` in sshd, because each key forces its own: the one repository it may push
  to (:mod:`noust.pushdeploy.keys`);
- forwarding, terminals, the agent, X11 and ``~/.ssh/rc`` are off, whatever the key says, and
  only public keys are accepted.

The keys are read from a root-owned file the account cannot edit.
"""

from __future__ import annotations

import builtins
import pwd
import shutil
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from noust.core import audit, paths
from noust.core.exceptions import CommandError, ConfigError, SourceError
from noust.core.fs import FileSystem, get_fs
from noust.core.runner import CommandRunner, get_runner
from noust.fleet.authorize import (
    SSHD_CONFIG,
    SSHD_DROPIN_DIR,
    TUNNEL_KEYS_DIR,
    AccountPolicy,
    SshdPolicy,
    SshdSettings,
    apply_account_policy,
    groups_of,
    plan_account_policy,
    read_sshd_settings,
    sshd_blockers,
)

#: The account pushes log in as.
PUSH_USER = paths.PUSH_USER

#: Noust's sshd fragment for it; ``00-`` for the reason the tunnel account's is: the first value
#: sshd reads for an account wins.
PUSH_DROPIN_NAME = "00-noust-push.conf"

#: Marks the block when sshd_config includes no fragment directory.
PUSH_POLICY_BEGIN = "# BEGIN Noust push account (generated by Noust; do not edit)"
PUSH_POLICY_END = "# END Noust push account"

#: What the fragment says about itself.
PUSH_HEADER = (
    "# Generated by Noust: the account git push logs in as.\n"
    "# 'noust push setup' writes this file; changes made here are replaced.\n"
)

#: Where ``git-shell`` is on the distributions Noust installs on.
GIT_SHELL_CANDIDATES = ("/usr/bin/git-shell", "/usr/libexec/git-core/git-shell")

#: Mode of the directory the repositories are in: the account's home.
PUSH_DIR_MODE = 0o750

#: Deadline of the quick local commands this runs.
TIMEOUT = 30


def policy_block(user: str, keys_dir: Path = TUNNEL_KEYS_DIR) -> str:
    """
    Spell the ``Match User`` block that restricts the push account in sshd itself.

    Args:
        user: The push account.
        keys_dir: Where its key file is.

    Returns:
        The block, ending with a newline. There is no ``ForceCommand`` in it: each key forces
        its own command, and sshd's would win over theirs.
    """
    lines = [
        f"Match User {user}",
        f"    AuthorizedKeysFile {keys_dir}/%u.keys",
        "    PubkeyAuthentication yes",
        "    AuthenticationMethods publickey",
        "    DisableForwarding yes",
        "    AllowTcpForwarding no",
        "    AllowStreamLocalForwarding no",
        "    GatewayPorts no",
        "    PermitTunnel no",
        "    PermitTTY no",
        "    X11Forwarding no",
        "    AllowAgentForwarding no",
        "    PermitUserRC no",
    ]
    return "\n".join(lines) + "\n"


def policy_problems(settings: SshdSettings, keys_dir: Path) -> builtins.list[str]:
    """
    Compare what sshd applies to the push account with what Noust's block asks for.

    Args:
        settings: ``sshd -T -C user=<push account>``.
        keys_dir: Where the account's key file is.

    Returns:
        One sentence per setting sshd applies differently: an earlier ``Match`` block or file
        set it first.
    """
    expected: builtins.list[tuple[str, object, object]] = [
        ("AllowTcpForwarding", settings.allow_tcp_forwarding, "no"),
        ("DisableForwarding", "yes" if settings.disable_forwarding else "no", "yes"),
        ("AllowStreamLocalForwarding", settings.allow_stream_local_forwarding, "no"),
        ("PermitTTY", settings.permit_tty, "no"),
        ("X11Forwarding", settings.x11_forwarding, "no"),
        ("AllowAgentForwarding", settings.allow_agent_forwarding, "no"),
        ("ForceCommand", settings.force_command or "none", "none"),
        ("AuthorizedKeysFile", " ".join(settings.authorized_keys_files), f"{keys_dir}/%u.keys"),
    ]
    return [
        f"sshd applies '{name} {actual}' to the push account, not '{name} {wanted}': another "
        "Match block or configuration file sets it first."
        for name, actual, wanted in expected
        if actual != wanted
    ]


def account_policy(user: str = PUSH_USER, keys_dir: Path = TUNNEL_KEYS_DIR) -> AccountPolicy:
    """
    Describe the restrictions of the push account.

    Args:
        user: The push account.
        keys_dir: Where its key file is.

    Returns:
        The policy.
    """
    return AccountPolicy(
        user=user,
        block=policy_block(user, keys_dir),
        dropin_name=PUSH_DROPIN_NAME,
        begin=PUSH_POLICY_BEGIN,
        end=PUSH_POLICY_END,
        header=PUSH_HEADER,
        problems=lambda settings: policy_problems(settings, keys_dir),
        retry="run 'noust push setup' again",
    )


def git_shell() -> str | None:
    """
    Find ``git-shell``.

    Returns:
        Its absolute path; None when git is not installed with it (a few distributions package
        it apart).
    """
    for candidate in GIT_SHELL_CANDIDATES:
        if Path(candidate).is_file():
            return candidate
    return shutil.which("git-shell")


@dataclass(frozen=True)
class SetupResult:
    """
    What setting the server up did.

    Attributes:
        account: The push account.
        account_created: Whether this created it.
        home: The directory that holds the repositories.
        sshd_policy: The file the sshd block is in.
        keys_file: The file sshd reads the keys from.
        changed: Whether the sshd block changed.
        ssh_port: The port sshd listens on, for the remote's URL.
    """

    account: str
    account_created: bool
    home: str
    sshd_policy: str
    keys_file: str
    changed: bool
    ssh_port: int

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The result as plain data.
        """
        return {
            "account": self.account,
            "account_created": self.account_created,
            "home": self.home,
            "sshd_policy": self.sshd_policy,
            "keys_file": self.keys_file,
            "changed": self.changed,
            "ssh_port": self.ssh_port,
        }


@dataclass
class Status:
    """
    Whether this server takes pushes.

    Attributes:
        ready: Nothing stops it.
        problems: What does, one sentence each, with the command that fixes it.
        account: Whether the account exists.
        ssh_port: The port sshd listens on.
        home: The directory that holds the repositories.
        keys_file: The file sshd reads the keys from.
    """

    ready: bool
    problems: builtins.list[str] = field(default_factory=builtins.list)
    account: bool = False
    ssh_port: int = 22
    home: str = ""
    keys_file: str = ""

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The status as plain data.
        """
        return {
            "ready": self.ready,
            "problems": self.problems,
            "account": self.account,
            "ssh_port": self.ssh_port,
            "home": self.home,
            "keys_file": self.keys_file,
        }


class PushHost:
    """
    The push account and its place in sshd.

    Args:
        runner: Runs ``useradd``, ``sshd`` and ``systemctl``.
        fs: The filesystem seam.
        passwd: Account lookup (``pwd.getpwnam``).
        sshd_config: sshd's main configuration file.
        dropin_dir: sshd's fragment directory.
        keys_dir: Where the key files are.
        home: The directory that holds the repositories.
    """

    def __init__(
        self,
        *,
        runner: CommandRunner | None = None,
        fs: FileSystem | None = None,
        passwd: Callable[[str], pwd.struct_passwd] = pwd.getpwnam,
        sshd_config: Path = SSHD_CONFIG,
        dropin_dir: Path = SSHD_DROPIN_DIR,
        keys_dir: Path = TUNNEL_KEYS_DIR,
        home: Path | None = None,
    ) -> None:
        self.runner = runner or get_runner()
        self.fs = fs or get_fs()
        self._passwd = passwd
        self._sshd_config = sshd_config
        self._dropin_dir = dropin_dir
        self.keys_dir = keys_dir
        self.home = home or paths.push_dir()

    def account(self) -> pwd.struct_passwd | None:
        """
        Returns:
            The push account, or None when it does not exist yet.
        """
        try:
            return self._passwd(PUSH_USER)
        except KeyError:
            return None

    def ensure_account(self, *, dry_run: bool) -> bool:
        """
        Create the push account, or check the one that exists.

        A system account with its own group, the repositories' directory as its home and
        ``git-shell`` as its shell. Its password field is ``*``: nothing matches it, and unlike
        the ``!`` useradd leaves, sshd never reads it as a locked account (``UsePAM no``).

        Args:
            dry_run: Rehearse: nothing is created.

        Returns:
            Whether the account was created now.

        Raises:
            ConfigError: ``git-shell`` is missing, the account exists with a shell that can run
                anything, or it cannot be made.
        """
        shell = git_shell()
        if shell is None:
            raise ConfigError(
                "git-shell was not found on this server",
                details="It comes with git (some distributions package it apart: git-shell). "
                "Install it, then run 'noust push setup' again.",
            )
        existing = self.account()
        if existing is not None and existing.pw_shell not in (shell, *GIT_SHELL_CANDIDATES):
            raise ConfigError(
                f"The account {PUSH_USER} exists with the shell {existing.pw_shell}",
                details=f"It is meant for git-shell alone: usermod --shell {shell} "
                f"{PUSH_USER} if it is yours to change.",
            )
        created = False
        try:
            if existing is None:
                self.runner.run(
                    [
                        "useradd",
                        "--system",
                        "--user-group",
                        "--no-create-home",
                        "--home-dir",
                        str(self.home),
                        "--shell",
                        shell,
                        "--comment",
                        "Noust git push",
                        PUSH_USER,
                    ],
                    timeout=TIMEOUT,
                    check=True,
                )
                created = True
            self.runner.run(["usermod", "--password", "*", PUSH_USER], timeout=TIMEOUT, check=True)
        except CommandError as exc:
            raise ConfigError(
                f"Could not prepare the account {PUSH_USER}",
                details="useradd and usermod (shadow-utils) must be installed; run as root.",
                output=exc.details,
            ) from exc
        return created

    def ensure_home(self, *, dry_run: bool) -> None:
        """
        Make the directory that holds the repositories, the account's.

        Args:
            dry_run: Rehearse: nothing is made.

        Raises:
            SourceError: The path is a link, or the account cannot be given the directory.
        """
        if dry_run:
            return
        if self.home.is_symlink():
            raise SourceError(
                f"Refusing to use the symlink {self.home}",
                details="The push repositories' directory has to be a real directory.",
            )
        self.fs.make_dir(self.home, mode=PUSH_DIR_MODE, parents=True)
        self.fs.chmod(self.home, PUSH_DIR_MODE)
        try:
            self.runner.run(
                ["chown", f"{PUSH_USER}:{PUSH_USER}", str(self.home)], timeout=TIMEOUT, check=True
            )
        except CommandError as exc:
            raise SourceError(
                f"Could not give {self.home} to {PUSH_USER}", details=exc.details
            ) from exc

    def setup(self, *, dry_run: bool = False, actor: str | None = None) -> SetupResult:
        """
        Make this server take pushes: the account, its directory and its sshd block.

        Every check runs before anything changes, and an sshd block that does not apply is put
        back as it was.

        Args:
            dry_run: Rehearse: nothing is created, written or reloaded.
            actor: Who sets it up, for the audit trail.

        Returns:
            What was done (or would be).

        Raises:
            ConfigError: ``git-shell`` is missing or the account is unusable.
            NodeError: sshd would refuse the account or does not apply the block.
        """
        existing = self.account()
        settings = read_sshd_settings(self.runner, self._sshd_config, user=PUSH_USER)
        blockers = sshd_blockers(
            settings,
            PUSH_USER,
            groups_of(existing) if existing is not None else (PUSH_USER,),
            tunnel=True,
            again="run 'noust push setup' again",
        )
        if blockers:
            raise ConfigError(
                "sshd would refuse the account pushes log in as", details="\n".join(blockers)
            )
        created = self.ensure_account(dry_run=dry_run)
        self.ensure_home(dry_run=dry_run)
        policy = apply_account_policy(
            account_policy(PUSH_USER, self.keys_dir),
            runner=self.runner,
            fs=self.fs,
            sshd_config=self._sshd_config,
            dropin_dir=self._dropin_dir,
            dry_run=dry_run,
        )
        if not dry_run:
            audit.record(
                "push.setup",
                target=f"account:{PUSH_USER}",
                details={"created": created, "policy": str(policy.path), "by": actor},
            )
        return SetupResult(
            account=PUSH_USER,
            account_created=created,
            home=str(self.home),
            sshd_policy=str(policy.path),
            keys_file=str(self.keys_dir / f"{PUSH_USER}.keys"),
            changed=policy.changed,
            ssh_port=settings.port,
        )

    def planned_policy(self) -> SshdPolicy:
        """
        Returns:
            Where the push account's block goes and what the file becomes; nothing is written.
        """
        return plan_account_policy(
            account_policy(PUSH_USER, self.keys_dir),
            sshd_config=self._sshd_config,
            dropin_dir=self._dropin_dir,
        )

    def status(self) -> Status:
        """
        Say whether this server takes pushes.

        Read-only: ``sshd -T`` and a look at the account and the directory.

        Returns:
            The status; ``problems`` says what stops it, with the command that fixes it.
        """
        problems: builtins.list[str] = []
        account = self.account()
        settings = read_sshd_settings(self.runner, self._sshd_config, user=PUSH_USER)
        if git_shell() is None:
            problems.append("git-shell was not found: install git's shell (the package git).")
        if account is None:
            problems.append(
                f"The account {PUSH_USER} does not exist yet: run 'noust push setup' as root "
                "to create it and restrict it in sshd."
            )
        else:
            problems.extend(
                policy_problems(settings, self.keys_dir)
                + sshd_blockers(
                    settings,
                    PUSH_USER,
                    groups_of(account),
                    tunnel=True,
                    again="run 'noust push setup' again",
                )
            )
            if not self.home.is_dir():
                problems.append(
                    f"The directory {self.home} does not exist: run 'noust push setup'."
                )
        return Status(
            ready=not problems,
            problems=problems,
            account=account is not None,
            ssh_port=settings.port,
            home=str(self.home),
            keys_file=str(self.keys_dir / f"{PUSH_USER}.keys"),
        )
