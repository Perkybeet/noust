"""
What an operator may call an object of Noust: one rule, and a table of where each name travels.

A probe, an alert rule, a notification channel, a team's channel, a replica and a database
instance are all named by a person, and each had a pattern of its own. They disagreed, and the
console's help text repeated whichever pattern its author had in mind: the probe form said
"lower-case letters, digits, - and _" while the store refused the underscore, so a name the help
allowed (``admon_shoprent``) was turned down.

The rule lives here and nowhere else (rule 3). A name is lower-case words that start with a
letter, in one of three **shapes**:

- ``words``: letters, digits, ``-`` and ``_``, in any order. What an operator types for an object
  that only Noust and its API ever see.
- ``dashes``: words joined by single ``-``. A name that becomes a systemd unit, a Compose project,
  a container and a volume.
- ``underscores``: words joined by single ``_``. A name that becomes a SQL role and a replication
  slot, where a dash needs quoting.

The shape is narrower than ``words`` only where the name goes somewhere that is narrower, and the
table says where (:attr:`NameRule.why`). Before a kind is widened, check that its name does not
travel to something that cannot carry the new character: a unit, a file name, a metric label, an
identifier of a database.

The help of a field is the rule (:meth:`NameRule.help`), and the console reads the same table as
``panel/src/api/nameRules.gen.ts`` (generated by ``scripts/generate_name_rules.py``), so it can
check a name before sending it and word the help in its own language.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Literal

from noust.core.exceptions import ValidationError
from noust.core.server_text import ServerText, say

Shape = Literal["words", "dashes", "underscores"]

#: Each shape as the regular expression that accepts it, written so that Python's ``fullmatch`` and
#: a browser's ``^...$`` mean the same. The length is checked beside it, never inside it.
_SHAPE_PATTERN: dict[Shape, str] = {
    "words": r"[a-z][a-z0-9_-]*",
    "dashes": r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*",
    "underscores": r"[a-z][a-z0-9]*(?:_[a-z0-9]+)*",
}

#: The sentence that tells a person the rule of each shape.
_SHAPE_HELP: dict[Shape, str] = {
    "words": "names.rule.words",
    "dashes": "names.rule.dashes",
    "underscores": "names.rule.underscores",
}


@dataclass(frozen=True)
class NameRule:
    """
    What one kind of object may be called.

    Attributes:
        kind: The key of the table (``probe``).
        shape: ``words``, ``dashes`` or ``underscores``.
        max_length: The most characters the name may have: the limit of where it travels.
        examples: Names that are fine, for the help.
        refusal: The message of a refusal, with the name as ``{value}``.
        why: Where the name travels, when that makes its shape narrower than ``words``.
    """

    kind: str
    shape: Shape
    max_length: int
    examples: tuple[str, ...]
    refusal: str
    why: str = ""

    @property
    def pattern(self) -> re.Pattern[str]:
        """The shape as a compiled expression, for ``fullmatch``."""
        return re.compile(_SHAPE_PATTERN[self.shape])

    @property
    def javascript_pattern(self) -> str:
        """The shape as an anchored expression a browser reads the same way."""
        return f"^{_SHAPE_PATTERN[self.shape]}$"

    def help(self, max_length: int | None = None) -> ServerText:
        """
        Args:
            max_length: A smaller limit than the kind's, when the name is only part of a key.

        Returns:
            The rule as a sentence with a code, which is the help of the field.
        """
        return say(_SHAPE_HELP[self.shape], max=max_length or self.max_length)

    def accepts(self, value: object, max_length: int | None = None) -> bool:
        """
        Args:
            value: The candidate.
            max_length: A smaller limit than the kind's, when the name is only part of a key.

        Returns:
            Whether it is a name of this kind. ``fullmatch`` and not ``match`` plus ``$``, which
            lets a trailing newline through.
        """
        limit = max_length if max_length is not None else self.max_length
        return (
            isinstance(value, str)
            and 1 <= len(value) <= limit
            and self.pattern.fullmatch(value) is not None
        )

    def check(self, value: object, max_length: int | None = None) -> str:
        """
        Args:
            value: The candidate.
            max_length: A smaller limit than the kind's, when the name is only part of a key.

        Returns:
            The name, unchanged.

        Raises:
            ValidationError: When it is not a name of this kind; it carries the rule as its
                details and ``name`` as its field.
        """
        if not self.accepts(value, max_length) or not isinstance(value, str):
            raise ValidationError(
                self.refusal.format(value=value),
                details=f"{self.help(max_length).text} {_examples(self.examples)}".strip(),
                field="name",
            )
        return value

    def to_dict(self) -> dict[str, Any]:
        """
        Returns:
            The rule as the console is given it.
        """
        return {
            "shape": self.shape,
            "max_length": self.max_length,
            "pattern": self.javascript_pattern,
            "examples": list(self.examples),
            "help": self.help().to_dict(),
        }


def _examples(names: tuple[str, ...]) -> str:
    return f"For example: {', '.join(names)}." if names else ""


#: Where each kind of name travels, and so how wide it may be.
RULES: dict[str, NameRule] = {
    rule.kind: rule
    for rule in (
        NameRule(
            kind="probe",
            shape="words",
            max_length=40,
            examples=("shop-health", "admon_site"),
            refusal="Invalid probe name: {value!r}",
        ),
        NameRule(
            kind="alert_rule",
            shape="words",
            max_length=48,
            examples=("disk-high", "cpu_hot"),
            refusal="Invalid rule name: {value!r}",
        ),
        NameRule(
            kind="channel",
            shape="words",
            max_length=32,
            examples=("ops-slack", "oncall_telegram"),
            refusal="Invalid channel name: {value!r}",
        ),
        NameRule(
            kind="team_channel",
            shape="words",
            max_length=32,
            examples=("deploys", "oncall_telegram"),
            refusal="Invalid channel name: {value!r}",
        ),
        NameRule(
            kind="replica",
            shape="underscores",
            # ``noust_repl_`` and the name must stay an account name in every engine (MySQL
            # allows 32), and short enough to read in ``pg_stat_replication``.
            max_length=20,
            examples=("reports", "standby", "eu_west"),
            refusal="{value!r} cannot be the name of a replica",
            why=(
                "It becomes a role (noust_repl_<name>), a replication slot, a line of "
                "pg_hba.conf, a file name and part of a secret's name, none of which may need "
                "quoting."
            ),
        ),
        NameRule(
            kind="db_instance",
            shape="dashes",
            # ``noust-db-`` and the name must stay a short unit name.
            max_length=24,
            examples=("pg16", "analytics", "shop-cache"),
            refusal="{value!r} cannot be the name of a database instance",
            why=(
                "It becomes a systemd unit, a Compose project, a container, two volumes, a "
                "directory and the part of an engine key after the '@'."
            ),
        ),
    )
}

#: The kinds, in the order the table lists them.
KINDS = tuple(RULES)


def rule_for(kind: str) -> NameRule:
    """
    Args:
        kind: A key of :data:`RULES`.

    Returns:
        Its rule.

    Raises:
        KeyError: When there is no such kind; a bug in the caller, not an input.
    """
    return RULES[kind]


def check_name(kind: str, value: object, max_length: int | None = None) -> str:
    """
    Accept the name an operator gives an object of Noust.

    Args:
        kind: What the object is (a key of :data:`RULES`).
        value: The candidate.
        max_length: A smaller limit than the kind's, when the name is only part of a key.

    Returns:
        The name, unchanged.

    Raises:
        ValidationError: When it is not a name of that kind.
    """
    return RULES[kind].check(value, max_length)


def is_name(kind: str, value: object, max_length: int | None = None) -> bool:
    """
    Args:
        kind: What the object is (a key of :data:`RULES`).
        value: The candidate.
        max_length: A smaller limit than the kind's, when the name is only part of a key.

    Returns:
        Whether it is a name of that kind.
    """
    return RULES[kind].accepts(value, max_length)


def typescript_rules() -> str:
    """
    Returns:
        The table as the TypeScript module the console imports
        (``panel/src/api/nameRules.gen.ts``), byte for byte what the generator writes.
    """
    import json

    kinds = " | ".join(json.dumps(kind) for kind in KINDS)
    body = ",\n".join(
        f"  {kind}: {{\n"
        f"    shape: {json.dumps(rule.shape)},\n"
        f"    maxLength: {rule.max_length},\n"
        f"    pattern: {json.dumps(rule.javascript_pattern)},\n"
        f"    examples: {json.dumps(list(rule.examples))},\n"
        f"    helpCode: {json.dumps(_SHAPE_HELP[rule.shape])},\n"
        f"  }}"
        for kind, rule in RULES.items()
    )
    return (
        "// Generated by scripts/generate_name_rules.py from src/noust/validators/object_names.py.\n"
        "// Do not edit: change the rule there and run the script.\n"
        "\n"
        f"export type NameKind = {kinds};\n"
        "\n"
        'export type NameShape = "words" | "dashes" | "underscores";\n'
        "\n"
        "export interface NameRule {\n"
        "  shape: NameShape;\n"
        "  /** The most characters the name may have. */\n"
        "  maxLength: number;\n"
        "  /** An anchored regular expression: the server accepts exactly what it matches within maxLength. */\n"
        "  pattern: string;\n"
        "  examples: readonly string[];\n"
        "  /** The key of the sentence that words the rule, with `max` as its value. */\n"
        "  helpCode: string;\n"
        "}\n"
        "\n"
        f"export const NAME_RULES: Record<NameKind, NameRule> = {{\n{body},\n}};\n"
    )
