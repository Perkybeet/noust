"""
The console's authentication: who is calling, what they may do, and how often.

It was one module and is a package of the pieces it was made of; every public name it had is
imported here, so ``from noust.web.auth import TokenManager`` is what it always was. A name
that is read from here is looked up in the module that defines it: a test that replaces one
replaces it there (``noust.web.auth.tokens.BACKUP_CODE_COUNT``), not on this package, which
would change what the test reads and nothing else.

- ``constants``: the lifetimes, limits and names everything else is built on
- ``clock``: the clock the session and token logic read
- ``config``: ``SecurityConfig`` and the one manager of each kind the process shares
- ``files``: the state directory and the files private to the console
- ``ratelimit``: rate limiting, concurrent connections and the lockout after failures
- ``records``, ``sessions``: the SQLite store of sessions, API tokens and tickets
- ``tokens``: ``TokenManager``
- ``connection``: the client address, the origin and the credential a request carries
- ``payload``: the session payload every request resolves to
- ``audit``, ``fleet``, ``scopes``: the audit record, what a node admits from its central,
  and the scope a route needs
- ``credentials``: reading a credential off a connection and judging it
- ``dependencies``: the FastAPI dependencies every route resolves
"""

