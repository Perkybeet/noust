def make_stack(
    tmp_path: Path,
    store: NoustStore,
    units: Path,
    machine: Machine,
    domain: str,
    *,
    env: str = "",
    privileged: bool = False,
    compose_dir: str = "",
    unit_project: str = "",
    status: str = AppStatus.RUNNING.value,
) -> App:
    """A stack of 4.2: its tree, its row and its unit, as the old template wrote them."""
    name = domain.replace(".", "-")
    tree = tmp_path / "apps" / name
    (tree / compose_dir).mkdir(parents=True)
    (tree / compose_dir / "docker-compose.yml").write_text(
        "services:\n  web:\n    image: nginx\n    volumes:\n      - ${DATA:-./data}:/data\n"
        + ("    privileged: true\n" if privileged else "")
    )
    if env:
        (tree / ".env").write_text(env)
    project = (compose_dir.split("/")[-1] or name) if compose_dir else name
    machine.stacks[str(tree)] = {"project": project, "privileged": privileged}
    app = store.create_app(
        App(
            domain=domain,
            app_type=AppType.DOCKER_COMPOSE.value,
            source="src",
            app_path=str(tree),
            status=status,
        )
    )
    flag = f" -p {unit_project}" if unit_project else ""
    unit = UNIT_42.format(name=name, domain=domain, path=tree, project=flag)
    if compose_dir:
        unit = unit.replace(
            'Environment="MY_OWN=kept"',
            f'Environment="MY_OWN=kept"\nEnvironment="COMPOSE_FILE={compose_dir}/docker-compose.yml"',
        )
    (units / f"{name}.service").write_text(unit)
    return app


def unit_of(units: Path, domain: str) -> str:
    return (units / f"{domain.replace('.', '-')}.service").read_text()


def lines(text: str, directive: str) -> list[str]:
    return [line for line in text.splitlines() if line.startswith(f"{directive}=")]


def add_drop_in(units: Path, domain: str, name: str, text: str) -> Path:
    """Write an addition to a stack's unit, as an operator does in ``<unit>.service.d/``."""
    directory = units / f"{domain.replace('.', '-')}.service.d"
    directory.mkdir(exist_ok=True)
    path = directory / name
    path.write_text(text)
    return path
