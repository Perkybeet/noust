#: What the template of 4.2 wrote for a stack: no gate, and a project only for an adopted one.
UNIT_42 = """# Systemd service for Docker Compose: {name}
# Generated by Noust

[Unit]
Description=Docker Compose app: {domain}
Documentation=https://github.com/Perkybeet/noust
After=network.target docker.service
Requires=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
User=root
WorkingDirectory={path}

# Environment
Environment="MY_OWN=kept"

# Commands
ExecStart=/usr/bin/docker compose{project} up -d --remove-orphans
ExecStop=/usr/bin/docker compose{project} down
ExecReload=/usr/bin/docker compose{project} up -d --remove-orphans --build

# Timeouts
TimeoutStartSec=300

[Install]
WantedBy=multi-user.target
"""


class Machine(FakeRunner):
    """Docker's Compose and ``ps`` over a few stacks: each resolves its file with its ``.env``."""

    def __init__(self) -> None:
        super().__init__()
        self.stacks: dict[str, dict[str, Any]] = {}
        self.fail_config: set[str] = set()
        self.docker_down = False
        self.containers: list[dict[str, Any]] = []

    def model_of(self, path: str) -> dict[str, Any] | None:
        for tree, stack in self.stacks.items():
            if path.startswith(tree):
                env = {}
                env_file = Path(tree) / ".env"
                if env_file.is_file():
                    for line in env_file.read_text().splitlines():
                        key, _, value = line.partition("=")
                        env[key] = value
                data = env.get("DATA", f"{tree}/data")
                service: dict[str, Any] = {
                    "image": "nginx",
                    "volumes": [{"type": "bind", "source": data, "target": "/data"}],
                }
                if stack.get("privileged"):
                    service["privileged"] = True
                return {"name": stack["project"], "services": {"web": service}}
        return None

    def run(self, argv: Any, **kwargs: Any) -> CommandResult:  # type: ignore[override]
        words = [str(word) for word in argv]
        if words[:2] == ["docker", "compose"] and "config" in words:
            self.calls.append(tuple(words))
            file = words[words.index("-f") + 1] if "-f" in words else ""
            env_file = words[words.index("--env-file") + 1] if "--env-file" in words else None
            if any(file.startswith(tree) and tree in self.fail_config for tree in self.stacks):
                return CommandResult(tuple(words), 1, "", "no such service")
            model = self.model_of(file)
            if model is None:
                return CommandResult(tuple(words), 1, "", "no such file")
            if env_file:
                for line in Path(env_file).read_text().splitlines():
                    if line.startswith("DATA="):
                        model["services"]["web"]["volumes"][0]["source"] = line.partition("=")[2]
            return CommandResult(tuple(words), 0, json.dumps(model), "")
        if words[:2] == ["docker", "ps"]:
            if self.docker_down:
                return CommandResult(tuple(words), 1, "", "Cannot connect to the Docker daemon")
            self.calls.append(tuple(words))
            rows = [json.dumps(row) for row in self.containers]
            return CommandResult(tuple(words), 0, "\n".join(rows), "")
        return super().run(argv, **kwargs)


