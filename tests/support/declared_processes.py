#: The state of a copy that starts and dies, as ``systemctl show`` says it.
CRASHING = ("activating", "auto-restart", 2)


class ProcessServices(FakeServices):
    """
    ``FakeServices`` that also keeps the units of processes, as the real manager would write them.

    A copy restarted on a release whose ``worker.js`` throws does not stay up.

    Attributes:
        installed: Template name to the context it was written with, in order.
        enabled: Every copy enabled.
        copy_restarts: Every copy restarted with the release ``current`` pointed at.
        deleted: Every copy stopped and forgotten.
        templates_removed: Every template removed.
        states: Copy to ``(active, sub state, restarts)``.
    """

    def __init__(self, app_root: Path, directory: Path) -> None:
        super().__init__(app_root)
        self.SYSTEMD_DIR = directory
        self.installed: list[tuple[str, dict[str, Any]]] = []
        self.enabled: list[str] = []
        self.copy_restarts: list[tuple[str, str]] = []
        self.deleted: list[str] = []
        self.templates_removed: list[str] = []
        self.states: dict[str, tuple[str, str, int]] = {}
        #: The application's own unit, which an update may edit and the processes read.
        self.unit_text = (
            "[Unit]\nDescription=Noust\n\n[Service]\nExecStart=/usr/bin/npm run start\n"
            'WorkingDirectory=/srv/app\nEnvironment="PORT=3100"\n'
        )
        #: Raises when a template is written, for the test of a unit that cannot be.
        self.refuse_templates = False

    def get_service_config(self, name: str) -> str | None:
        return self.unit_text

    def update_config(self, name: str, text: str) -> str:
        previous, self.unit_text = self.unit_text, text
        return previous

    def install_unit(self, name: str, template: str, context: dict[str, Any]) -> Path:
        assert template == "process@"
        if self.refuse_templates:
            raise ServiceError("Refusing to write a unit Noust does not manage")
        self.installed.append((name, dict(context)))
        path = self.SYSTEMD_DIR / f"{name}.service"
        path.write_text("# Generated by Noust\n")
        return path

    def enable(self, name: str) -> bool:
        if "@" in name:
            self.enabled.append(name)
        return True

    def restart(self, name: str) -> None:
        if "@" not in name:
            super().restart(name)
            return
        link = self.app_root / "current"
        self.copy_restarts.append((name, os.readlink(link) if link.is_symlink() else ""))
        worker = link / "worker.js"
        broken = worker.is_file() and "throw" in worker.read_text()
        self.states[name] = CRASHING if broken else ("active", "running", 0)

    def delete_service(self, name: str, *, keep_record: bool = False) -> None:
        self.deleted.append(name)
        self.states.pop(name, None)

    def remove_template(self, name: str) -> bool:
        self.templates_removed.append(name)
        (self.SYSTEMD_DIR / f"{name}@.service").unlink(missing_ok=True)
        return True

    def command_of(self, template: str) -> str:
        """
        Args:
            template: A template's name, ``rel-example-com-worker@``.

        Returns:
            The command the last write of that template gave it.
        """
        return next(c["command"] for n, c in reversed(self.installed) if n == template)


class SystemdRunner(TreeRunner):
    """The runner of the machine, answering ``systemctl show`` and ``list-units`` from the units."""

    def __init__(self, services: ProcessServices) -> None:
        super().__init__()
        self.services = services

    def run(self, argv: Any, **kwargs: Any) -> Any:
        args = tuple(str(part) for part in argv)
        if args[:2] == ("systemctl", "show"):
            unit = args[2].removesuffix(".service")
            active, sub, restarts = self.services.states.get(unit, ("inactive", "dead", 0))
            return CommandResult(
                argv=args,
                exit_code=0,
                stdout=f"ActiveState={active}\nSubState={sub}\nNRestarts={restarts}\n",
            )
        if args[:2] == ("systemctl", "list-units"):
            lines = [
                f"{unit}.service loaded {active} {sub} desc"
                for unit, (active, sub, _) in sorted(self.services.states.items())
                if args[-1].startswith(unit.split("@")[0] + "@")
            ]
            return CommandResult(argv=args, exit_code=0, stdout="\n".join(lines))
        return super().run(argv, **kwargs)


class Time:
    """A clock that only moves when something sleeps, so settling a copy takes no time."""

    def __init__(self) -> None:
        self.now = 100.0

    def monotonic(self) -> float:
        return self.now

    def sleep(self, seconds: float) -> None:
        self.now += max(seconds, 0.01)


@pytest.fixture
def world(
    tmp_path: Path, root: Path, machine: SimpleNamespace, monkeypatch: pytest.MonkeyPatch
) -> ProcessServices:
    """
    The machine with systemd keeping the units of processes.

    The health gate and the blue/green engine build their own ``ProcessManager``; they are pointed at
    the same runner, and time is the test's.
    """
    directory = tmp_path / "systemd"
    directory.mkdir()
    services = ProcessServices(root, directory)
    machine.services = services
    machine.runner = SystemdRunner(services)
    monkeypatch.setattr(app_processes, "time", Time())

    original = ProcessManager

    def build(**kwargs: Any) -> ProcessManager:
        kwargs.setdefault("runner", machine.runner)
        kwargs.setdefault("log", Logger(verbose=False))
        return original(**kwargs)

    monkeypatch.setattr(app_processes, "ProcessManager", build)
    return services


def project(tmp_path: Path, name: str, files: dict[str, str], *, worker: str = "") -> Path:
    """
    A Node project with these extra files.

    Args:
        tmp_path: The test's directory.
        name: The directory's name.
        files: Relative path to content, besides the Node project.
        worker: The content of ``worker.js``, when the project has one.

    Returns:
        The directory.
    """
    tree = node_tree(tmp_path / name)
    write_tree(tree, files)
    if worker:
        write_tree(tree, {"worker.js": worker})
    return tree


def processes_of(store: NoustStore) -> dict[str, tuple[str, str, int]]:
    """
    Args:
        store: The store.

    Returns:
        Each process as ``(command, source, instances)``.
    """
    return {
        record.name: (record.command, record.source, record.instances)
        for record in processes_store.list_processes(DOMAIN, store=store)
    }


