class FakeUnits:
    """Stands in for ServiceManager: unit bodies in memory, restarts recorded."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.bodies: dict[str, str] = {}
        self.restarts: list[str] = []
        self.stops: list[bool] = []

    def stop(self, name: str) -> bool:
        # Whether the live tree was still in place when the unit stopped.
        self.stops.append((self.root / "server.js").is_file())
        return True

    def app_units(self, app: App) -> list[str]:
        return [] if app.is_static else [domain_to_app_name(app.domain)]

    def serving_units(self, app: App) -> list[str]:
        """The units serving now: every unit, outside zero-downtime mode."""
        return self.app_units(app)

    def get_service_config(self, name: str) -> str | None:
        return self.bodies.get(name)

    def update_config(self, name: str, content: str) -> str:
        previous = self.bodies[name]
        self.bodies[name] = content
        return previous

    def restart(self, name: str) -> None:
        link = self.root / "current"
        self.restarts.append(os.readlink(link) if link.is_symlink() else "in place")

    def logs(self, name: str, lines: int = 50) -> str:
        return "Error: Cannot find module 'server.js'"


class FakeSites:
    """Stands in for the web server manager: site configurations in memory."""

    def __init__(self) -> None:
        self.configs: dict[str, str] = {}
        self.reloads = 0

    def get_site_config(self, domain: str) -> str | None:
        return self.configs.get(domain)

    def replace_site_config(self, domain: str, text: str) -> Path:
        self.configs[domain] = text
        return Path("/etc/nginx/sites-available") / domain

    def reload(self) -> bool:
        self.reloads += 1
        return True


def unit_body(root: Path) -> str:
    """A unit as WASM writes one for an in-place Node application."""
    return (
        "# Generated by WASM\n[Service]\n"
        f"WorkingDirectory={root}\n"
        "ExecStart=/usr/bin/npm run start\n"
        'Environment="PORT=3100"\n'
    )


