@pytest.fixture
def machine(
    root: Path, store: NoustStore, runner: FakeRunner, monkeypatch: pytest.MonkeyPatch
) -> Any:
    """
    The application registered and running in place, with its machine faked.

    The probe answers when ``current`` has a server.js, which a correct
    migration gives it and a broken one does not.
    """
    app = store.create_app(
        App(
            domain=DOMAIN,
            app_type="nodejs",
            source=GIT_URL,
            branch="main",
            port=PORT,
            app_path=str(root),
        )
    )
    store.create_service(
        Service(
            app_id=app.id,
            name="shop-example-com",
            command="/usr/bin/npm run start",
            working_directory=str(root),
        )
    )
    store.create_site(Site(app_id=app.id, domain=DOMAIN, proxy_port=PORT))
    units = FakeUnits(root)
    units.bodies["shop-example-com"] = unit_body(root)
    sites = FakeSites()
    sites.configs[DOMAIN] = (
        f"server {{ server_name {DOMAIN}; proxy_pass http://127.0.0.1:{PORT}; }}"
    )
    probes: list[str] = []

    def probe(url: str, **kwargs: Any) -> bool:
        probes.append(url)
        answers = (root / "current" / "server.js").is_file()
        if not answers:
            kwargs["on_attempt"]("Health check attempt 1 failed: [Errno 111] Connection refused")
        return answers

    monkeypatch.setattr(migrate_module, "ServiceManager", lambda **kw: units)
    monkeypatch.setattr(lifecycle, "ServiceManager", lambda **kw: units)
    monkeypatch.setattr(migrate_module, "_webserver_for", lambda app: sites)
    monkeypatch.setattr(lifecycle, "wait_until_healthy", probe)

    prefix = ["git", "-c", f"safe.directory={root}", "--no-optional-locks"]
    runner.script([*prefix, "rev-parse"], stdout=f"{COMMIT}\n")
    runner.script(
        [*prefix, "status"],
        stdout="\0".join(
            [
                "?? uploads/",
                "!! node_modules/",
                "!! .env",
                "?? .env.local",
                "?? notes.txt",
                "?? .noust/",
                "",
            ]
        ),
    )
    return type(
        "Machine",
        (),
        {"units": units, "sites": sites, "probes": probes, "runner": runner, "app": app},
    )
