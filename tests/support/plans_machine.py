UNIT = "rel-example-com"


class Systemd(TreeRunner):
    """
    The runner of the machine: it answers what a restart asks of systemd and keeps what it was given.

    Attributes:
        changes: Every command that is not a declared probe, in order: what an operation did.
    """

    def __init__(self, unit_file: Path) -> None:
        super().__init__()
        self.changes: list[tuple[str, ...]] = []
        self.script(
            ["systemctl", "show", "-p", "FragmentPath"], stdout=f"FragmentPath={unit_file}\n"
        )
        self.script(["systemctl", "is-active"], stdout="active\n")

    def _note(self, argv: Any) -> None:
        if not is_read_only(argv):
            self.changes.append(tuple(str(part) for part in argv))

    def run(self, argv: Any, **kwargs: Any) -> CommandResult:
        self._note(argv)
        return super().run(argv, **kwargs)

    def stream(self, argv: Any, **kwargs: Any) -> CommandResult:
        self._note(argv)
        return super().stream(argv, **kwargs)


class RehearsedGit(FakeGit):
    """
    The fake repository, which does as the real one does under a rehearsal: it looks and changes nothing.

    The real :class:`~noust.managers.source_manager.SourceManager` fetches through the runner and
    writes through the filesystem, so a rehearsal never reaches the disk. This fake writes to the
    disk itself, which a plan's test must not let it do.
    """

    def sync_cache(self, source: str, cache: Path, branch: str | None = None) -> str | None:
        if is_rehearsal():
            return self.head
        return super().sync_cache(source, cache, branch)

    def export_commit(self, repository: Path, commit: str, destination: Path) -> None:
        if not is_rehearsal():
            super().export_commit(repository, commit, destination)

    def resolve_commit(self, repository: Path, commit: str) -> str:
        """The one commit an abbreviation means in the clone."""
        return next(known for known in self.commits if known.startswith(commit))

    def remote_head(self, source: str, branch: str | None, timeout: int = 20) -> SimpleNamespace:
        """The head of the branch on the remote, as ``git ls-remote`` says it."""
        return SimpleNamespace(branch=branch or "main", commit=self.head)


@pytest.fixture
def served(
    root: Path,
    store: NoustStore,
    machine: SimpleNamespace,
    two_releases: tuple[str, str],
    unit_dirs: dict[str, Path],
    monkeypatch: pytest.MonkeyPatch,
) -> SimpleNamespace:
    """
    The application with two releases, the second serving, on the real managers.

    Returns:
        ``runner`` (the process-wide one, a :class:`Systemd`), ``first`` and ``second`` (the
        releases), ``root`` and ``store``.
    """
    unit = unit_dirs["managed"] / f"{UNIT}.service"
    unit.write_text("# Generated by Noust\n[Service]\nExecStart=/usr/bin/node server.js\n")
    runner = Systemd(unit)
    set_runner(runner)
    monkeypatch.setattr(lifecycle, "ServiceManager", ServiceManager)
    # The check is asked as it always is, and answers: there is no application to ask.
    from noust.deployers.helpers import health

    monkeypatch.setattr(health, "_poll", lambda *args, **kwargs: True)
    monkeypatch.setattr(lifecycle, "wait_until_healthy", health.wait_until_healthy)
    patch_deployer(monkeypatch, "wait_until_healthy", health.wait_until_healthy)
    first, second = two_releases
    # The repository is the one fake that stays: there is no network, and the real one runs git.
    machine.git.__class__ = RehearsedGit
    monkeypatch.setattr(lifecycle, "SourceManager", lambda **kwargs: machine.git)

    def deployer(app_type: str, verbose: bool = False) -> NodeJSDeployer:
        chosen = NodeJSDeployer(verbose=False)
        chosen.source_manager = machine.git
        chosen._webserver_manager = lambda: machine.web
        chosen.cert_manager = SimpleNamespace(obtain=lambda *args, **kwargs: True)
        chosen.pre_flight_check = lambda: True
        return chosen

    monkeypatch.setattr(lifecycle, "get_deployer", deployer)
    yield SimpleNamespace(
        runner=runner,
        first=first,
        second=second,
        root=root,
        store=store,
        git=machine.git,
        machine=machine,
    )
    set_runner(None)


