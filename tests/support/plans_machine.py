"""
An application on a machine that can be both rehearsed and applied to, for the tests of plans.

The fixtures of ``tests/support/release_pipeline.py`` replace Noust's own managers with stand-ins
that record nothing a runner sees, which is right to test a pipeline and wrong to compare a plan
with an operation: a plan is the operation's own code run with a rehearsing runner, so the managers
must be the real ones over a runner that can be asked what it was given. This is that machine: the
two releases and the repository of ``release_activation``, with the real service manager, a systemd
that answers the questions a restart asks, and a health check that passes.
"""

