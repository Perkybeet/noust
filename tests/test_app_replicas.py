class Clock:
    """Monotonic time that only moves when something sleeps."""

    def __init__(self) -> None:
        self.now = 100.0
        self.slept: list[float] = []

    def __call__(self) -> float:
        return self.now

    def sleep(self, seconds: float) -> None:
        self.slept.append(seconds)
        self.now += max(seconds, 0.01)


class World(FakeRunner):
    """
    systemd, nginx and the probe, sharing one event log.

    It is the runner (``systemctl show`` answers from the states), the service manager
    and the web server manager, so a test reads one object and one order of events.
    """

    def __init__(self, directory: Path) -> None:
        super().__init__()
        self.SYSTEMD_DIR = directory
        self.events: list[tuple[Any, ...]] = []
        self.states: dict[str, tuple[str, str, int]] = {}
        self.installed: dict[str, dict[str, Any]] = {}
        self.deleted: list[str] = []
        self.templates_removed: list[str] = []
        self.control: list[tuple[str, str]] = []
        self.upstream: list[int] | None = None
        self.silent: set[int] = set()
        self.refuses_site = False
        self.main_unit = '[Service]\nEnvironment="PORT=3100"\nEnvironment="NODE_ENV=production"\n'

    # -- the runner -------------------------------------------------------------

    def run(self, argv: Sequence[str], **kwargs: Any) -> CommandResult:  # type: ignore[override]
        args = tuple(str(part) for part in argv)
        if args[:2] == ("systemctl", "show"):
            unit = args[2].removesuffix(".service")
            active, sub, restarts = self.states.get(unit, ("inactive", "dead", 0))
            return CommandResult(
                argv=args,
                exit_code=0,
                stdout=f"ActiveState={active}\nSubState={sub}\nNRestarts={restarts}\n",
            )
        if args[0] == "journalctl":
            return CommandResult(argv=args, exit_code=0, stdout="journal\n")
        return super().run(argv, **kwargs)

    # -- the service manager ------------------------------------------------------

    def get_service_config(self, name: str) -> str | None:
        return self.main_unit

    def install_unit(self, name: str, template: str, context: dict[str, Any]) -> Path:
        assert template == "replica@"
        self.events.append(("template", name))
        self.installed[name] = dict(context)
        path = self.SYSTEMD_DIR / f"{name}.service"
        path.write_text("# Generated by Noust\n")
        return path

    def restore_template(self, name: str, previous: str | None) -> None:
        self.events.append(("restore_template", name))
        (self.SYSTEMD_DIR / f"{name}@.service").write_text(previous or "")

    def remove_template(self, name: str) -> bool:
        self.events.append(("remove_template", name))
        self.templates_removed.append(name)
        (self.SYSTEMD_DIR / f"{name}@.service").unlink(missing_ok=True)
        self.installed.pop(f"{name}@", None)
        return True

    def enable(self, name: str) -> bool:
        self.events.append(("enable", name))
        return True

    def restart(self, name: str) -> None:
        self.events.append(("restart", name))
        self.states[name] = ("active", "running", 0)

    def start(self, name: str) -> None:
        self.control.append(("start", name))

    def stop(self, name: str) -> bool:
        self.control.append(("stop", name))
        return True

    def delete_service(self, name: str, *, keep_record: bool = False) -> None:
        self.events.append(("delete", name))
        self.deleted.append(name)
        self.states.pop(name, None)

    def logs(self, name: str, lines: int = 50) -> str:
        return f"{name}: Error: address already in use"

    # -- the web server manager -------------------------------------------------------

    def write_upstream(self, domain: str, port: Any) -> str | None:
        ports = [port] if isinstance(port, int) else list(port)
        self.events.append(("upstream", tuple(ports)))
        previous = None if self.upstream is None else repr(self.upstream)
        self.upstream = ports
        return previous

    def restore_upstream(self, domain: str, previous: str | None) -> None:
        self.events.append(("restore_upstream", previous))
        self.upstream = None if previous is None else eval(previous)  # noqa: S307 - own repr

    def remove_upstream(self, domain: str) -> bool:
        self.events.append(("remove_upstream",))
        self.upstream = None
        return True

    # -- the rest -------------------------------------------------------------------------

    def refresh_site(self, app: App) -> None:
        record = replica_store.get_record(app.domain)
        mode = "upstream" if record is not None and record.running else "direct"
        self.events.append(("site", mode))
        if self.refuses_site and mode == "upstream":
            raise ValidationError("nginx rejected the new configuration", details="emerg: boom")

    def probe(self, url: str, **kwargs: Any) -> bool:
        port = int(url.rsplit(":", 1)[1].split("/")[0])
        self.events.append(("probe", port))
        return port not in self.silent

    def names(self) -> list[str]:
        return [event[0] for event in self.events]


