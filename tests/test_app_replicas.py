"""
An application runs as several copies of its web process on one server (checklist B-68).

Pinned here:

- a copy is a unit of a template of its own, from the same release, account, environment and
  sandbox as the application's unit, on a port it takes from its instance name;
- copies are started and asked the application's health check on their own port before
  nginx is told about them, and one that does not answer leaves everything as it was;
- nginx shares the traffic through the one upstream file: several servers balanced by
  connections, the site proxying to it only while copies run, and plain again at one;
- the ports are Noust's to pick and keep: nobody else is handed one, scaling down and up
  brings the same ones back;
- the health gate restarts the copies with the unit and judges them on their ports, and
  what cannot run twice is refused with the reason.
"""

