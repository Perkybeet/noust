def test_scaling_out_starts_each_copy_and_asks_it_before_nginx_is_told(
    manager: ReplicaManager, world: World, store: NoustStore, app: App
) -> None:
    change = manager.set_copies(DOMAIN, 3, actor="ana")

    first, second = f"{REPLICA}@3101", f"{REPLICA}@3102"
    assert change.copies == 3 and change.before == 1
    assert change.ports == (3101, 3102) and change.started == (first, second)
    assert world.events == [
        ("template", f"{REPLICA}@"),
        ("enable", first),
        ("restart", first),
        ("probe", 3101),
        ("enable", second),
        ("restart", second),
        ("probe", 3102),
        ("upstream", (PORT, 3101, 3102)),
        ("site", "upstream"),
    ]
    record = replica_store.get_record(DOMAIN, store=store)
    assert record is not None and record.copies == 3 and record.ports == (3101, 3102)


