def test_the_site_proxies_to_the_upstream_only_while_copies_run(
    nginx: Any, store: NoustStore, app: App
) -> None:
    nginx.write_upstream(DOMAIN, [PORT, 3101])
    nginx.create_site(DOMAIN, template="proxy", context={"port": PORT})
    alone = nginx.get_site_config(DOMAIN) or ""
    assert f"proxy_pass http://127.0.0.1:{PORT};" in alone, "no copy runs yet"

    replica_store.set_record(DOMAIN, (3101,), 1, changed_by="ana", store=store)
    nginx.update_site(DOMAIN, template="proxy", context={"port": PORT})
    scaled_site = nginx.get_site_config(DOMAIN) or ""

    assert "proxy_pass http://noust_bg_bg_example_com;" in scaled_site
