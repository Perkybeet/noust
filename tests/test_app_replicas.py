    assert "no single web process" in (eligibility_problem(compose, store=store) or "")
    assert "apache" in (eligibility_problem(apache, store=store) or "")
    assert "no port" in (eligibility_problem(portless, store=store) or "")
    assert "zero-downtime" in (eligibility_problem(blue_green, store=store) or "")


