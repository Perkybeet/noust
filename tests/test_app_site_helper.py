"""
:mod:`noust.deployers.helpers.site`: one guard over every write of an application's site.

A site without Noust's marker is the operator's. 3.1.17 made ``BaseDeployer``
keep it; Docker Compose and monorepo still replaced it, and Compose deleted it
to put TLS in. The guard is now one function every deployer writes through,
and these tests pin it on the real nginx manager over a temporary tree.
"""

