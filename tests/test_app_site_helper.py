def monorepo_deployed(store: NoustStore, tmp_path: Path) -> None:
    """A monorepo as a deploy leaves it: its row, a unit and a site per workspace."""
    from noust.core.store import Service, Site

    app = store.create_app(
        App(domain=DOMAIN, app_type="monorepo", app_path=str(tmp_path), port=3000)
    )
    for name, sub, port in (("web", "www", 3000), ("api", "api", 3001)):
        store.create_service(
            Service(app_id=app.id, name=f"shop-example-com-{name}", port=port, command="x")
        )
        store.create_site(
            Site(app_id=app.id, domain=f"{sub}.{DOMAIN}", proxy_port=port, webserver="nginx")
        )


def test_a_monorepo_answers_on_its_aliases_and_redirects(
    web: NginxManager, store: NoustStore, tmp_path: Path, runner: FakeRunner
) -> None:
    monorepo_deployed(store, tmp_path)
    store.add_domain(DOMAIN, "tienda.example.com", "alias")
    store.add_domain(DOMAIN, "www.tienda.example.com", "redirect")
    deployer = MonorepoDeployer(runner=runner)
    deployer.configure(DOMAIN, str(tmp_path), app_path=tmp_path)
    deployer._webserver_manager = lambda: web  # type: ignore[method-assign]

    deployer.refresh_site(with_ssl=True)

    text = web.get_site_config(DOMAIN) or ""
    assert f"server_name {DOMAIN} tienda.example.com;" in text
    assert f"www.{DOMAIN}" in text and f"api.{DOMAIN}" in text
    assert "server_name www.tienda.example.com;" in text
    assert "return 301 https://www.shop.example.com$request_uri;" in text


def test_a_monorepo_keeps_the_operator_site(
    web: NginxManager, store: NoustStore, tmp_path: Path, runner: FakeRunner
) -> None:
    monorepo_deployed(store, tmp_path)
    operator_site(web)
    deployer = MonorepoDeployer(runner=runner)
    deployer.configure(DOMAIN, str(tmp_path), app_path=tmp_path)
    deployer._webserver_manager = lambda: web  # type: ignore[method-assign]

    deployer.refresh_site(with_ssl=False)

    assert web.get_site_config(DOMAIN) == OPERATOR_SITE


def test_a_monorepo_certificate_covers_its_subdomains_and_aliases(
    store: NoustStore, tmp_path: Path, runner: FakeRunner
) -> None:
    from types import SimpleNamespace

    from noust.managers.cert_manager import CertManager

    monorepo_deployed(store, tmp_path)
    store.add_domain(DOMAIN, "tienda.example.com", "alias")
    certs = CertManager()
    certs.LETSENCRYPT_DIR = tmp_path / "letsencrypt"
    certs.LIVE_DIR = certs.LETSENCRYPT_DIR / "live"
    certs.config = SimpleNamespace(ssl_email="")  # type: ignore[assignment]
    deployer = MonorepoDeployer(runner=runner)
    deployer.configure(DOMAIN, str(tmp_path), app_path=tmp_path)
    deployer.cert_manager = certs

    deployer.obtain_certificate()

    certbot = next(call for call in runner.calls if call[:2] == ("certbot", "certonly"))
    names = {certbot[i + 1] for i, arg in enumerate(certbot) if arg == "-d"}
    assert {DOMAIN, f"www.{DOMAIN}", f"api.{DOMAIN}", "tienda.example.com"} <= names


def test_a_failed_monorepo_deploy_keeps_the_operator_site(
    web: NginxManager, store: NoustStore, tmp_path: Path, runner: FakeRunner
) -> None:
    from types import SimpleNamespace

    operator_site(web)
    deployer = MonorepoDeployer(runner=runner)
    deployer.configure(DOMAIN, str(tmp_path), app_path=tmp_path)
    deployer._webserver_manager = lambda: web  # type: ignore[method-assign]
    deployer.deploy_target = SimpleNamespace(undo_fetch=lambda fs, log: None)  # type: ignore[assignment]

    deployer._rollback()

    assert web.get_site_config(DOMAIN) == OPERATOR_SITE
