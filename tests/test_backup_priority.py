"""
A backup runs behind the applications (audit gap: priority and CPU of the copies).

At 02:00 a dump with gzip competes for CPU and disk with the applications of a small server. Every
unit a backup runs in is written with a priority: a nice value, an I/O scheduling class and, if the
operator asks, a CPU ceiling. What is pinned: the settings are validated before they reach a root
owned unit, the block is written in one place and replaced, never doubled, units written by an
earlier version are brought along by ``apply_priority``, and a unit that is not Noust's is never
touched.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from noust.core.exceptions import ValidationError
from noust.core.runner import FakeRunner
from noust.managers.backup_priority import (
    BackupPriority,
    priority_from_config,
    with_priority,
)
from noust.managers.backup_scheduler import BackupScheduler

SERVICE = """\
# Noust scheduled database backup for postgresql/shop
# Generated by Noust

[Unit]
Description=Noust scheduled database backup for postgresql/shop

[Service]
Type=oneshot
ExecStart=/usr/bin/noust db backup-run shop --engine postgresql
"""


class Settings:
    """A configuration that answers from a dict."""

    def __init__(self, values: dict[str, object]) -> None:
        self.values = values

    def get(self, key: str, default: object = None) -> object:
        return self.values.get(key, default)


class TestTheSettings:
    def test_a_server_that_says_nothing_gets_the_gentle_default(self) -> None:
        priority = priority_from_config(Settings({}))

        assert priority == BackupPriority(nice=10, io_class="best-effort", io_priority=7)
        assert priority.cpu_quota is None

    def test_what_the_operator_set_is_what_is_used(self) -> None:
        priority = priority_from_config(
            Settings(
                {
                    "backup.nice": 15,
                    "backup.io_class": "idle",
                    "backup.cpu_quota": 50,
                }
            )
        )

        assert (priority.nice, priority.io_class, priority.cpu_quota) == (15, "idle", 50)

    @pytest.mark.parametrize(
        ("key", "value"),
        [
            ("backup.nice", 20),
            ("backup.nice", -1),
            ("backup.nice", "high"),
            ("backup.io_class", "realtime"),
            ("backup.io_priority", 8),
            ("backup.cpu_quota", 0),
            ("backup.cpu_quota", 100000),
            ("backup.cpu_quota", "half"),
        ],
    )
    def test_a_value_that_could_be_a_directive_or_nonsense_is_refused(
        self, key: str, value: object
    ) -> None:
        with pytest.raises(ValidationError) as caught:
            priority_from_config(Settings({key: value}))

        assert key in str(caught.value)

    def test_a_quota_of_none_or_off_means_no_ceiling(self) -> None:
        assert priority_from_config(Settings({"backup.cpu_quota": "none"})).cpu_quota is None
        assert priority_from_config(Settings({"backup.cpu_quota": None})).cpu_quota is None


class TestTheBlock:
    def test_it_goes_right_after_the_service_header(self) -> None:
        text = with_priority(SERVICE, BackupPriority(10, "best-effort", 7, None))

        service = text.split("[Service]\n", 1)[1]
        assert service.startswith(
            "# noust-priority\nNice=10\nIOSchedulingClass=best-effort\n"
            "IOSchedulingPriority=7\n# /noust-priority\nType=oneshot\n"
        )

    def test_idle_has_no_priority_inside_the_class_and_a_quota_is_in_percent(self) -> None:
        text = with_priority(SERVICE, BackupPriority(19, "idle", 7, 40))

        assert "IOSchedulingClass=idle\n" in text
        assert "IOSchedulingPriority" not in text
        assert "CPUQuota=40%\n" in text

    def test_a_second_pass_replaces_the_block_it_never_doubles_it(self) -> None:
        once = with_priority(SERVICE, BackupPriority(10, "best-effort", 7, None))
        twice = with_priority(once, BackupPriority(5, "idle", 7, 25))

        assert twice.count("Nice=") == 1 and "Nice=5\n" in twice
        assert twice.count("# noust-priority") == 1
        assert with_priority(twice, BackupPriority(5, "idle", 7, 25)) == twice

    def test_a_unit_with_no_service_section_is_left_as_it_is(self) -> None:
        timer = "[Unit]\nDescription=x\n\n[Timer]\nOnCalendar=daily\n"

        assert with_priority(timer, BackupPriority(10, "best-effort", 7, None)) == timer


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(BackupScheduler, "SYSTEMD_DIR", path)
    return path


@pytest.fixture
def scheduler(runner: FakeRunner, systemd_dir: Path) -> BackupScheduler:
    return BackupScheduler(verbose=False, runner=runner)


class TestEveryUnitABackupRunsIn:
    def test_a_database_policys_service_carries_it(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        scheduler.install_database_timer("postgresql", "shop", "daily")

        service = (systemd_dir / "noust-backup-db-postgresql-shop.service").read_text()
        assert "Nice=10\n" in service and "IOSchedulingClass=best-effort\n" in service

    def test_the_timer_is_not_given_one(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        scheduler.install_database_timer("postgresql", "shop", "daily")

        assert "Nice=" not in (systemd_dir / "noust-backup-db-postgresql-shop.timer").read_text()

    def test_a_volume_a_self_backup_and_an_application_schedule_carry_it_too(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        scheduler.install_volume_timer("shop.example.com", "daily")
        scheduler.install_self_backup_timer("daily")

        for name in ("noust-backup-vol-shop-example-com", "noust-backup-self"):
            assert "Nice=10\n" in (systemd_dir / f"{name}.service").read_text()

    def test_a_ceiling_the_operator_set_reaches_the_new_units(
        self,
        scheduler: BackupScheduler,
        systemd_dir: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        monkeypatch.setattr(
            "noust.managers.backup_scheduler.current_priority",
            lambda: BackupPriority(19, "idle", 7, 30),
        )

        scheduler.install_database_timer("postgresql", "shop", "daily")

        service = (systemd_dir / "noust-backup-db-postgresql-shop.service").read_text()
        assert "Nice=19\n" in service and "CPUQuota=30%\n" in service


class TestUnitsFromAnEarlierVersion:
    def test_apply_brings_them_along_and_reloads_systemd_once(
        self,
        scheduler: BackupScheduler,
        runner: FakeRunner,
        systemd_dir: Path,
    ) -> None:
        for name in ("noust-backup-db-postgresql-shop", "noust-backup-shop-example-com"):
            (systemd_dir / f"{name}.service").write_text(SERVICE)
            (systemd_dir / f"{name}.timer").write_text("[Timer]\nOnCalendar=daily\n")

        changed = scheduler.apply_priority()

        assert sorted(changed) == [
            "noust-backup-db-postgresql-shop.service",
            "noust-backup-shop-example-com.service",
        ]
        assert "Nice=10\n" in (systemd_dir / "noust-backup-shop-example-com.service").read_text()
        assert "Nice=" not in (systemd_dir / "noust-backup-shop-example-com.timer").read_text()
        assert [c for c in runner.calls if c == ("systemctl", "daemon-reload")] == [
            ("systemctl", "daemon-reload")
        ]

    def test_a_unit_that_already_has_the_settings_is_not_rewritten_and_nothing_reloads(
        self, scheduler: BackupScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        scheduler.install_database_timer("postgresql", "shop", "daily")
        runner.calls.clear()

        assert scheduler.apply_priority() == []
        assert runner.calls == []

    def test_a_unit_that_is_not_noust_s_is_never_touched(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        theirs = "[Unit]\nDescription=their own\n\n[Service]\nExecStart=/bin/true\n"
        (systemd_dir / "noust-backup-handmade.service").write_text(theirs)

        assert scheduler.apply_priority() == []
        assert (systemd_dir / "noust-backup-handmade.service").read_text() == theirs

    def test_a_link_is_never_followed(self, scheduler: BackupScheduler, systemd_dir: Path) -> None:
        elsewhere = systemd_dir.parent / "elsewhere.service"
        elsewhere.write_text(SERVICE)
        (systemd_dir / "noust-backup-linked.service").symlink_to(elsewhere)

        assert scheduler.apply_priority() == []
        assert elsewhere.read_text() == SERVICE
