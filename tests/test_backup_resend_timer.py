# ruff: noqa: F811

NOW = datetime(2026, 11, 17, 2, 0, tzinfo=timezone.utc)


@pytest.fixture
def store(tmp_path: Path) -> Iterator[NoustStore]:
    NoustStore.reset_instance()
    instance = NoustStore(tmp_path / "noust.db")
    NoustStore._instance = instance
    yield instance
    NoustStore.reset_instance()


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(BackupScheduler, "SYSTEMD_DIR", path)
    return path


def owe(store: NoustStore) -> None:
    PendingSends(store).defer(
        "app",
        "shop-example-com_a",
        "nas",
        owner="shop.example.com",
        copy_created_at=NOW,
        reason="i/o timeout",
        permanent=False,
        failure_id=None,
        now=NOW,
        next_attempt_at=NOW + timedelta(minutes=15),
    )


class TestTheTimer:
    def test_it_runs_every_five_minutes(self) -> None:
        assert RESEND_CALENDAR == "*-*-* *:0/5:00"
        assert RESEND_UNIT == "noust-backup-resend"

    def test_it_is_made_with_a_service_that_runs_the_command(
        self, systemd_dir: Path, store: NoustStore
    ) -> None:
        runner = FakeRunner()

        BackupScheduler(runner=runner).ensure_resend_timer()

        timer = (systemd_dir / "noust-backup-resend.timer").read_text()
        service = (systemd_dir / "noust-backup-resend.service").read_text()
        assert "OnCalendar=*-*-* *:0/5:00" in timer
        assert "Persistent=true" in timer
        assert "Description=Noust backup resend timer for the copies that were not sent" in timer
        assert "backup resend --reason" in service
        assert "Generated by Noust" in service and "Generated by Noust" in timer
        assert ("systemctl", "enable", "--now", "noust-backup-resend.timer") in runner.calls

    def test_it_is_made_once(self, systemd_dir: Path, store: NoustStore) -> None:
        runner = FakeRunner()
        scheduler_ = BackupScheduler(runner=runner)

        scheduler_.ensure_resend_timer()
        scheduler_.ensure_resend_timer()

        enables = [c for c in runner.calls if c[:2] == ("systemctl", "enable")]
        assert len(enables) == 1

    def test_it_is_never_made_over_a_timer_that_is_not_noust_s(
        self, systemd_dir: Path, store: NoustStore
    ) -> None:
        (systemd_dir / "noust-backup-resend.timer").write_text("[Timer]\nOnCalendar=hourly\n")

        with pytest.raises(BackupError, match="not a timer Noust wrote"):
            BackupScheduler(runner=FakeRunner()).ensure_resend_timer()

        assert (systemd_dir / "noust-backup-resend.timer").read_text() == (
            "[Timer]\nOnCalendar=hourly\n"
        )

    def test_it_is_not_taken_for_an_application_s_schedule(
        self, systemd_dir: Path, store: NoustStore
    ) -> None:
        runner = FakeRunner()
        BackupScheduler(runner=runner).ensure_resend_timer()
        runner.script(
            ("systemctl", "list-timers"),
            stdout="Tue 2026-11-17 02:05:00 UTC 3min left n/a n/a "
            "noust-backup-resend.timer noust-backup-resend.service\n",
        )
        runner.script(
            ("systemctl", "show", "noust-backup-resend.timer"),
            stdout="Description=Noust backup resend timer for the copies that were not sent\n",
        )

        assert BackupScheduler(runner=runner).list_schedules() == []


class TestBringingItAlong:
    def test_the_first_copy_that_is_owed_makes_the_timer(
        self, store: NoustStore, monkeypatch: pytest.MonkeyPatch, config: object
    ) -> None:
        made: list[int] = []
        monkeypatch.setattr(backup_sending, "install_resend_timer", lambda: made.append(1))
        sender = Sender(pending=PendingSends(store), notify=lambda note: None)

        def refused() -> dict[str, object]:
            raise BackupError("Failed to upload", details="i/o timeout")

        sender.send("app", "a", "shop.example.com", "nas", copy_created_at=NOW, push=refused)
        sender.send("app", "b", "shop.example.com", "nas", copy_created_at=NOW, push=refused)

        # The second copy finds it made already: it is asked for once per copy and the timer is idempotent,
        # but a copy that is only failing again (a retry) never asks.
        row = PendingSends(store).all()[0]
        sender.retry(row, refused)
        assert len(made) == 2

    def test_a_timer_that_cannot_be_made_costs_nothing_but_a_line_in_the_log(
        self, store: NoustStore, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        def broken(self: BackupScheduler) -> None:
            raise BackupError("cannot write the unit")

        monkeypatch.setattr(BackupScheduler, "ensure_resend_timer", broken)

        # The real function, which every other test replaces with one that makes nothing.
        real_install_resend_timer()


class TestWithoutSystemd:
    def test_the_central_runs_the_command_while_anything_is_owed(self, store: NoustStore) -> None:
        owe(store)

        tasks = {task.key: task for source in scheduler.SOURCES.values() for task in source(store)}

        task = tasks["resend"]
        assert task.argv[:2] == ("backup", "resend")
        assert task.calendar == RESEND_CALENDAR
        assert task.unit == RESEND_UNIT

    def test_it_is_not_a_task_while_nothing_is_owed(self, store: NoustStore) -> None:
        tasks = {task.key for source in scheduler.SOURCES.values() for task in source(store)}

        assert "resend" not in tasks
