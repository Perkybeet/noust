"""
What runs the pass that sends again the copies that were not sent (item 201).

On a server it is a timer (``noust-backup-resend``, every five minutes) that the first copy that is owed
brings along, once, and never over a timer that is not Noust's; where there is no systemd the central's own
scheduler runs the same command while anything is owed. The pass itself is held by
``tests/test_backup_resend.py``.
"""

