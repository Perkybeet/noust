"""
The timers of an application's data and of Noust's own state (3.4, H-23 and H-27).

The same scheduler as an application's schedule and a database's, two more
units: ``noust-backup-vol-<application>`` and ``noust-backup-self``. What is
held here is what holds for the others: the escaped templates, the calendar
validation, a timer that is not ours never overwritten or removed, a timer
that is not an application's never listed or adopted as one, and a command
that carries its reason so the timer keeps running under the ENS profile.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import pytest

from noust.core.exceptions import BackupError
from noust.core.runner import FakeRunner
from noust.core.store import NoustStore, get_store
from noust.managers.backup_scheduler import SELF_BACKUP_UNIT, BackupScheduler

UNIT = "noust-backup-vol-shop-example-com"


@pytest.fixture(autouse=True)
def _reset_store() -> Iterator[None]:
    NoustStore.reset_instance()
    yield
    NoustStore.reset_instance()


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(BackupScheduler, "SYSTEMD_DIR", path)
    return path


@pytest.fixture
def scheduler(runner: FakeRunner, systemd_dir: Path) -> BackupScheduler:
    return BackupScheduler(verbose=False, runner=runner)


class TestVolumeTimer:
    def test_it_writes_a_timer_and_a_service_and_enables_the_timer(
        self, scheduler: BackupScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        unit = scheduler.install_volume_timer("shop.example.com", "daily")

        assert unit == UNIT
        timer = (systemd_dir / f"{UNIT}.timer").read_text()
        assert "Description=Noust volume backup timer for shop.example.com" in timer
        assert "OnCalendar=*-*-* 02:00:00" in timer
        service = (systemd_dir / f"{UNIT}.service").read_text()
        assert "backup volumes run shop.example.com" in service
        assert '--reason "Scheduled volume backup policy"' in service
        assert "Generated by Noust" in service
        assert runner.ran("systemctl", "daemon-reload")
        assert runner.ran("systemctl", "enable", "--now", f"{UNIT}.timer")

    def test_the_unit_is_one_of_noust_own(self) -> None:
        from noust.core import paths

        assert paths.is_own_unit_name(UNIT)
        assert paths.is_own_unit_name(SELF_BACKUP_UNIT)

    def test_a_calendar_that_could_become_a_directive_is_refused_before_anything_is_written(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        with pytest.raises(BackupError):
            scheduler.install_volume_timer("shop.example.com", "daily\nExecStart=/bin/evil")

        assert list(systemd_dir.iterdir()) == []

    def test_a_domain_that_cannot_be_one_is_refused(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        with pytest.raises(BackupError, match="Cannot schedule"):
            scheduler.install_volume_timer("shop.example.com\nExecStart=/bin/evil", "daily")

        assert list(systemd_dir.iterdir()) == []

    def test_a_timer_that_is_not_a_volume_timer_is_not_overwritten(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        # The application vol.shop.example.com has this very unit name for its own schedule.
        theirs = systemd_dir / f"{UNIT}.timer"
        theirs.write_text("[Unit]\nDescription=Noust backup timer for vol.shop.example.com\n")

        with pytest.raises(BackupError, match="is not a timer Noust wrote"):
            scheduler.install_volume_timer("shop.example.com", "daily")

        assert "vol.shop.example.com" in theirs.read_text()
        assert not (systemd_dir / f"{UNIT}.service").exists()

    def test_a_dollar_and_a_percent_are_doubled_in_the_command(
        self, scheduler: BackupScheduler
    ) -> None:
        text = scheduler._render(
            "volume-backup-service.j2", target="a$b", domain="a$b%c", noust="/usr/bin/noust"
        )

        assert "backup volumes run a$$b%%c" in text

    def test_removing_it_removes_only_its_own_units(
        self, scheduler: BackupScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        scheduler.install_volume_timer("shop.example.com", "daily")

        assert scheduler.remove_volume_timer("shop.example.com") is True

        assert [p.name for p in systemd_dir.iterdir() if "sweep" not in p.name] == []
        assert runner.ran("systemctl", "disable", f"{UNIT}.timer")

    def test_a_timer_that_is_not_ours_is_left_alone_and_nothing_is_not_removed(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        theirs = systemd_dir / f"{UNIT}.timer"
        theirs.write_text("[Unit]\nDescription=Noust backup timer for vol.shop.example.com\n")

        assert scheduler.remove_volume_timer("shop.example.com") is False
        assert theirs.exists()
        assert scheduler.remove_volume_timer("other.example.com") is False

    def test_it_reads_when_the_timer_fires_next(
        self, scheduler: BackupScheduler, runner: FakeRunner
    ) -> None:
        runner.script(
            ("systemctl", "show", f"{UNIT}.timer"),
            stdout="LoadState=loaded\nNextElapseUSecRealtime=Tue 2026-09-30 02:03:11 UTC\n"
            "LastTriggerUSec=n/a\n",
        )

        assert scheduler.volume_timer_state("shop.example.com") == {
            "installed": True,
            "next_run": "Tue 2026-09-30 02:03:11 UTC",
            "last_run": None,
            # What the timer was given besides the policy (checklist H-01): none here.
            "max_runtime_seconds": None,
            "timezone": None,
        }


class TestSelfBackupTimer:
    def test_it_writes_a_timer_and_a_service_that_carries_its_reason(
        self, scheduler: BackupScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        unit = scheduler.install_self_backup_timer("weekly")

        assert unit == SELF_BACKUP_UNIT == "noust-backup-self"
        timer = (systemd_dir / "noust-backup-self.timer").read_text()
        assert "Description=Noust self-backup timer for this server" in timer
        assert "OnCalendar=Mon *-*-* 02:00:00" in timer
        service = (systemd_dir / "noust-backup-self.service").read_text()
        assert "self-backup run" in service and "--reason" in service
        assert runner.ran("systemctl", "enable", "--now", "noust-backup-self.timer")

    def test_a_timer_by_that_name_that_is_not_ours_is_not_overwritten_or_removed(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        theirs = systemd_dir / "noust-backup-self.timer"
        theirs.write_text("[Unit]\nDescription=something else\n")

        with pytest.raises(BackupError, match="is not a timer Noust wrote"):
            scheduler.install_self_backup_timer("daily")
        assert scheduler.remove_self_backup_timer() is False

        assert theirs.read_text().endswith("something else\n")

    def test_it_can_be_removed_and_asked_about(
        self, scheduler: BackupScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        scheduler.install_self_backup_timer("daily")
        runner.script(("systemctl", "show", "noust-backup-self.timer"), stdout="LoadState=loaded\n")

        assert scheduler.self_backup_timer_state()["installed"] is True
        assert scheduler.remove_self_backup_timer() is True
        assert [p.name for p in systemd_dir.iterdir() if "sweep" not in p.name] == []


class TestApplicationListing:
    """The applications' listing is neither the data's nor Noust's own."""

    @pytest.mark.parametrize(
        ("unit", "description"),
        [
            (UNIT, "Noust volume backup timer for shop.example.com"),
            ("noust-backup-self", "Noust self-backup timer for this server"),
        ],
    )
    def test_such_a_timer_is_not_listed_and_not_adopted_as_an_application(
        self, scheduler: BackupScheduler, runner: FakeRunner, unit: str, description: str
    ) -> None:
        runner.script(
            ("systemctl", "list-timers"),
            stdout=f"Tue 2026-09-30 02:00:00 UTC 5h left n/a n/a {unit}.timer {unit}.service\n",
        )
        runner.script(
            ("systemctl", "show", f"{unit}.timer"),
            stdout=f"Description={description}\n"
            "TimersCalendar={ OnCalendar=*-*-* 02:00:00 ; next_elapse=x }\n",
        )

        assert scheduler.list_schedules() == []
        assert get_store().get_backup_schedule(unit.removeprefix("noust-backup-")) is None
