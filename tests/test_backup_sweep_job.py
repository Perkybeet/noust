"""
The retention sweep as a job of its own: its report, its daily timer and its command (checklist H-04).

What is pinned: one kind failing does not stop the others and makes the sweep not ok, every policy
that is made brings the sweep's timer along (once, and never over a timer that is not Noust's), the
timer is not mistaken for an application's schedule, and ``noust backup sweep`` prints what it
deleted and exits 1 when something could not be swept.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from click.testing import CliRunner

from noust.cli import app as cli_app
from noust.core import audit
from noust.core.exceptions import BackupError
from noust.core.runner import FakeRunner
from noust.managers.backup_scheduler import SWEEP_UNIT, BackupScheduler
from noust.managers.backup_sweep import BackupSweep


@pytest.fixture
def audited(monkeypatch: pytest.MonkeyPatch) -> list[dict[str, Any]]:
    events: list[dict[str, Any]] = []
    monkeypatch.setattr(
        audit, "record", lambda event, **kwargs: events.append({"event": event, **kwargs})
    )
    return events


class TestTheReport:
    def test_it_adds_up_what_every_kind_deleted(self) -> None:
        report = BackupSweep(
            databases=lambda: {"postgresql/shop": ["a.dump", "b.dump"]},
            volumes=lambda: {"shop.example.com": ["x"]},
            applications=lambda: {"shop.example.com": 3},
        ).run()

        assert report.ok and report.deleted == 6

    def test_a_kind_that_fails_does_not_stop_the_others(self) -> None:
        def broken() -> dict[str, list[str]]:
            raise BackupError("the store is locked")

        report = BackupSweep(
            databases=broken, volumes=lambda: {"a.example.com": ["x"]}, applications=lambda: {}
        ).run()

        assert not report.ok
        assert report.errors == {"databases": "the store is locked"}
        assert report.volumes == {"a.example.com": ["x"]}

    def test_it_is_audited_with_the_counts_and_never_the_names(
        self, audited: list[dict[str, Any]]
    ) -> None:
        BackupSweep(
            databases=lambda: {"postgresql/shop": ["secret-name.dump"]},
            volumes=dict,
            applications=dict,
        ).run()

        [event] = [e for e in audited if e["event"] == "backups.sweep"]
        assert event["details"]["deleted"] == 1 and event["outcome"] == "ok"
        assert "secret-name" not in json.dumps(event["details"])


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(BackupScheduler, "SYSTEMD_DIR", path)
    return path


@pytest.fixture
def scheduler(runner: FakeRunner, systemd_dir: Path) -> BackupScheduler:
    return BackupScheduler(verbose=False, runner=runner)


class TestTheTimer:
    def test_a_database_policy_brings_the_sweeps_timer_along(
        self, scheduler: BackupScheduler, systemd_dir: Path, runner: FakeRunner
    ) -> None:
        scheduler.install_database_timer("postgresql", "shop", "daily")

        timer = (systemd_dir / f"{SWEEP_UNIT}.timer").read_text()
        service = (systemd_dir / f"{SWEEP_UNIT}.service").read_text()
        assert "Description=Noust backup sweep timer for every backup policy" in timer
        assert "OnCalendar=*-*-* 04:30:00" in timer
        assert "backup sweep --reason" in service and "Generated by Noust" in service
        assert runner.ran("systemctl", "enable", "--now", f"{SWEEP_UNIT}.timer")

    def test_a_volume_policy_and_an_application_schedule_bring_it_too(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        scheduler.install_volume_timer("shop.example.com", "daily")

        assert (systemd_dir / f"{SWEEP_UNIT}.timer").is_file()

    def test_it_is_made_once(
        self, scheduler: BackupScheduler, systemd_dir: Path, runner: FakeRunner
    ) -> None:
        scheduler.install_database_timer("postgresql", "shop", "daily")
        runner.calls.clear()

        scheduler.install_database_timer("postgresql", "blog", "daily")

        assert not [c for c in runner.calls if SWEEP_UNIT in " ".join(c)]

    def test_a_timer_by_that_name_that_is_not_noust_s_is_left_alone_and_the_schedule_still_works(
        self, scheduler: BackupScheduler, systemd_dir: Path
    ) -> None:
        theirs = systemd_dir / f"{SWEEP_UNIT}.timer"
        theirs.write_text("[Unit]\nDescription=somebody else's\n")

        unit = scheduler.install_database_timer("postgresql", "shop", "daily")

        assert unit == "noust-backup-db-postgresql-shop"
        assert theirs.read_text() == "[Unit]\nDescription=somebody else's\n"

    def test_it_is_not_taken_for_an_applications_schedule(
        self, scheduler: BackupScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        scheduler.install_database_timer("postgresql", "shop", "daily")
        runner.script(
            ["systemctl", "list-timers"],
            stdout=f"Sat 2026-10-17 04:30:00 UTC 2h {SWEEP_UNIT}.timer x\n",
        )
        runner.script(
            ["systemctl", "show", f"{SWEEP_UNIT}.timer"],
            stdout="Description=Noust backup sweep timer for every backup policy\n",
        )

        assert scheduler.list_schedules() == []


def invoke(*args: str) -> Any:
    return CliRunner().invoke(cli_app.cli, ["backup", "sweep", *args])


class TestTheCommand:
    def fake(self, monkeypatch: pytest.MonkeyPatch, **parts: Any) -> None:
        monkeypatch.setattr(
            "noust.cli.commands.backup_sweep.BackupSweep",
            lambda: BackupSweep(
                databases=parts.get("databases", dict),
                volumes=parts.get("volumes", dict),
                applications=parts.get("applications", dict),
            ),
        )

    def test_it_says_what_it_deleted(self, monkeypatch: pytest.MonkeyPatch) -> None:
        self.fake(
            monkeypatch,
            databases=lambda: {"postgresql/shop": ["a", "b"]},
            applications=lambda: {"shop.example.com": 1},
        )

        result = invoke()

        assert result.exit_code == 0, result.output
        assert "postgresql/shop: deleted 2 dump(s)" in result.output
        assert "shop.example.com: deleted 1 backup(s)" in result.output
        assert "3 copy(ies) beyond retention deleted" in result.output

    def test_nothing_to_do_is_said(self, monkeypatch: pytest.MonkeyPatch) -> None:
        self.fake(monkeypatch)

        assert "Nothing is beyond its retention" in invoke().output

    def test_a_kind_that_could_not_be_swept_exits_1(self, monkeypatch: pytest.MonkeyPatch) -> None:
        def broken() -> dict[str, list[str]]:
            raise BackupError("locked")

        self.fake(monkeypatch, volumes=broken)

        result = invoke()

        assert result.exit_code == 1 and "The volumes could not be swept: locked" in result.output

    def test_json_is_the_report(self, monkeypatch: pytest.MonkeyPatch) -> None:
        self.fake(monkeypatch, databases=lambda: {"mysql/wiki": ["x"]})

        data = json.loads(invoke("--json").output)

        assert data["deleted"] == 1 and data["databases"] == {"mysql/wiki": ["x"]}
