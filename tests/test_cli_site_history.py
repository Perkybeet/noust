"""
``noust site history``, ``diff`` and ``restore``.

What is kept is pinned in ``tests/test_site_history.py``; here the commands read it and put a
version back through the same write as the editor.
"""

from __future__ import annotations

import json
from typing import Any

import pytest
from click.testing import CliRunner

from noust.cli.app import cli as root_cli
from noust.cli.app import main
from noust.cli.commands import site_history
from noust.core.logger import Logger
from noust.core.runner import FakeRunner
from noust.managers.nginx_manager import NginxManager
from tests.test_domains import (  # noqa: F401 - fixtures of the domains harness
    Machine,
    certs,
    machine,
    store,
    web,
)

EDIT = "# Generated by Noust\nserver {\n    listen 80;\n    server_name example.com;\n    return 204;\n}\n"


@pytest.fixture
def log(monkeypatch: pytest.MonkeyPatch) -> list[str]:
    lines: list[str] = []
    monkeypatch.setattr(Logger, "_write", lambda self, message, newline=True: lines.append(message))
    return lines


@pytest.fixture
def served(machine: Machine, web: NginxManager, monkeypatch: pytest.MonkeyPatch) -> NginxManager:
    machine.deploy(app_type="nodejs")
    monkeypatch.setattr(site_history, "NginxManager", lambda: web)
    monkeypatch.setattr(site_history, "ApacheManager", lambda: web)
    return web


def invoke(*args: str) -> Any:
    return CliRunner().invoke(root_cli, ["site", *args])


def test_history_lists_the_versions_and_marks_the_current_one(served: NginxManager) -> None:
    served.replace_site_config("example.com", EDIT)

    result = invoke("history", "example.com", "--json")

    assert result.exit_code == 0, result.output
    body = json.loads(result.output)
    assert body["site"] == "example.com" and body["webserver"] == "nginx"
    assert body["versions"][0]["source"] == "edit" and body["versions"][0]["current"] is True
    assert sum(item["current"] for item in body["versions"]) == 1


def test_history_warns_of_a_file_changed_outside_noust(
    served: NginxManager, log: list[str], runner: FakeRunner
) -> None:
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="")
    path = served.config_path("example.com")
    path.write_text(path.read_text() + "# by hand\n")

    result = invoke("history", "example.com")

    assert result.exit_code == 0, result.output
    assert any("changed outside Noust" in line for line in log)


def test_diff_shows_what_changed_since_a_version(served: NginxManager) -> None:
    first = served.history.versions("example.com")[-1].version
    served.replace_site_config("example.com", EDIT)

    result = invoke("diff", "example.com", str(first))

    assert result.exit_code == 0, result.output
    assert f"--- version {first}" in result.output and "+    return 204;" in result.output
    newest = served.history.versions("example.com")[0].version
    assert "No difference" in invoke("diff", "example.com", str(newest)).output


def test_diff_between_two_versions(served: NginxManager) -> None:
    first = served.history.versions("example.com")[-1].version
    served.replace_site_config("example.com", EDIT)
    second = served.history.versions("example.com")[0].version

    result = invoke("diff", "example.com", str(first), "--against", str(second))

    assert f"+++ version {second}" in result.output


def test_restore_puts_a_version_back_through_the_editors_save(
    served: NginxManager, machine: Machine, log: list[str]
) -> None:
    first = served.history.versions("example.com")[-1]
    original = served.history.version("example.com", first.version).text  # type: ignore[union-attr]
    served.replace_site_config("example.com", EDIT)

    result = invoke("restore", "example.com", str(first.version))

    assert result.exit_code == 0, result.output
    assert machine.config() == original
    assert served.history.versions("example.com")[0].source == "restore"
    assert any("Reload nginx to apply it" in line for line in log)


def test_restore_can_reload(served: NginxManager, machine: Machine) -> None:
    first = served.history.versions("example.com")[-1].version

    result = invoke("restore", "example.com", str(first), "--reload")

    assert result.exit_code == 0, result.output
    assert machine.reloaded()


def test_a_version_that_is_not_kept_is_exit_one_with_the_way_to_see_what_is(
    served: NginxManager, log: list[str]
) -> None:
    assert main(["site", "restore", "example.com", "999"]) == 1
    assert main(["site", "diff", "example.com", "999"]) == 1
    assert any("noust site history example.com" in line for line in log)


def test_an_unknown_site_is_said(served: NginxManager, log: list[str]) -> None:
    assert main(["site", "history", "ghost.example.com"]) == 1
    assert any("Site not found" in line for line in log)


def test_a_rehearsal_restores_nothing(served: NginxManager, machine: Machine) -> None:
    first = served.history.versions("example.com")[-1].version
    served.replace_site_config("example.com", EDIT)

    result = CliRunner().invoke(
        root_cli, ["--dry-run", "site", "restore", "example.com", str(first)]
    )

    assert result.exit_code == 0, result.output
    assert machine.config() == EDIT
