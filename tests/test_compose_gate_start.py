"""
What Noust says of a stack is what systemd starts, also when the start is not the one Noust wrote.

``noust health`` already says when the check of a stack's start is not in front of it because the unit is the
operator's, or because an addition empties ``ExecStartPre=``. Two things it kept quiet:

- a unit that carries the ``# Generated by Noust`` line but whose ``ExecStart`` is not the one Noust writes
  (somebody edited it and left the line): the pass said "unchanged";
- an addition that reassigns ``ExecStart=``: the check is still in front of the start, but what starts is no
  longer what Noust wrote and judged.

Both are said, with the way to mend them, and neither unit nor addition is touched.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from noust.core import compose_acceptance
from noust.core.store import NoustStore
from noust.deployers import compose_gate, compose_upgrade
from noust.deployers.docker_compose import stack_deployer
from tests.support.compose_gate_rig import (  # noqa: F401
    Machine,
    add_drop_in,
    lines,
    machine,
    make_stack,
    store,
    unit_of,
    units,
)

# ruff: noqa: F811

SHOP = "shop.example.com"
TEMPLATE_START = "ExecStart=/usr/bin/docker compose up -d --remove-orphans"
EDITED_START = "ExecStart=/usr/bin/docker compose -f other.yml up -d"


def bring(store: NoustStore, machine: Machine) -> list[compose_upgrade.Outcome]:
    return compose_upgrade.bring_up_to_date(store=store, runner=machine)


def says(store: NoustStore, machine: Machine) -> list[str]:
    return [
        line
        for line in compose_upgrade.attention(store=store, runner=machine)
        if line.startswith(f"{SHOP}: ")
    ]


#: What the start is once the pass has put the project of the stack in every command.
WITH_PROJECT = TEMPLATE_START.replace("docker compose", "docker compose -p shop-example-com")


def edit_the_start(units: Path, new: str = EDITED_START, old: str = TEMPLATE_START) -> None:
    """Change the start of the unit and leave the marker, as somebody who edited it by hand would."""
    path = units / "shop-example-com.service"
    assert old in path.read_text()
    path.write_text(path.read_text().replace(old, new))


class TestAUnitWithTheMarkerAndAnotherStart:
    def test_the_pass_says_so_and_does_not_call_it_unchanged(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)
        before = unit_of(units, SHOP)

        [outcome] = bring(store, machine)

        assert outcome.state == "edited"
        assert EDITED_START.removeprefix("ExecStart=") in outcome.detail
        assert unit_of(units, SHOP) == before, "Noust never rewrites a start it did not write"
        # What it could do is still done: the stack is recorded, so what Noust itself starts is judged.
        assert outcome.recorded and compose_acceptance.get(SHOP, store=store) is not None

    def test_a_second_pass_says_it_again(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)
        bring(store, machine)

        [again] = bring(store, machine)

        assert again.state == "edited"

    def test_health_says_what_is_wrong_and_the_ways_to_mend_it(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)
        bring(store, machine)

        [said] = says(store, machine)

        assert "this stack does not start as Noust wrote it" in said
        assert "'# Generated by Noust'" in said
        assert EDITED_START.removeprefix("ExecStart=") in said
        assert "Deploy the stack again" in said and "deleting its first line" in said
        assert f"noust setup compose-gate --app {SHOP}" in said

    def test_a_unit_that_has_the_check_and_then_had_its_start_edited_is_said_too(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        [first] = bring(store, machine)
        assert first.state == "done"
        edit_the_start(
            units,
            EDITED_START.replace("docker compose", "docker compose -p shop-example-com"),
            WITH_PROJECT,
        )

        [again] = bring(store, machine)

        assert again.state == "edited"
        assert len(says(store, machine)) == 1

    def test_a_start_with_the_projects_name_in_it_is_the_template_s_and_is_not_said(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP, unit_project="shop-example-com")

        [outcome] = bring(store, machine)

        assert outcome.state == "done"
        assert says(store, machine) == []

    def test_a_unit_that_is_the_operators_is_theirs_and_not_edited(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)
        path = units / "shop-example-com.service"
        path.write_text(path.read_text().replace("# Generated by Noust\n", ""))

        [outcome] = bring(store, machine)

        assert outcome.state == "own"
        [said] = says(store, machine)
        assert "its unit is yours" in said

    def test_the_command_says_it_and_is_not_a_failure(
        self,
        tmp_path: Path,
        store: NoustStore,
        units: Path,
        machine: Machine,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        from noust.cli.app import main

        make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)

        code = main(["setup", "compose-gate"])

        out = capsys.readouterr().out
        assert code == 0
        assert (
            f"{SHOP}: its unit has the '# Generated by Noust' line but its start is not the one Noust"
            in out
        )
        assert "1 stack(s) start without the check" in out

    def test_what_noust_starts_itself_is_still_judged(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        app = make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)
        bring(store, machine)
        (Path(app.app_path) / ".env").write_text("DATA=/\n")

        assert not compose_gate.judge_app(app, store=store).allowed


class TestAnAdditionThatReassignsTheStart:
    REASSIGN = "[Service]\nExecStart=\nExecStart=/usr/bin/docker compose -f evil.yml up -d\n"

    def stack(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine, text: str
    ) -> Path:
        make_stack(tmp_path, store, units, machine, SHOP)
        return add_drop_in(units, SHOP, "20-start.conf", text)

    def test_it_is_named_with_its_path_as_overridden_and_is_not_left_waiting(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        path = self.stack(tmp_path, store, units, machine, self.REASSIGN)

        [outcome] = bring(store, machine)

        assert outcome.state == "overridden"
        assert str(path) in outcome.detail
        assert outcome.directives == ("ExecStart=",)
        assert path.read_text() == self.REASSIGN, "Noust never changes an addition of yours"
        assert lines(unit_of(units, SHOP), "ExecStartPre"), "the check is in the file"
        assert compose_acceptance.note_of(SHOP, store=store) is None

    def test_health_says_the_start_is_not_what_noust_judged_and_not_that_the_check_is_missing(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        path = self.stack(tmp_path, store, units, machine, self.REASSIGN)
        bring(store, machine)

        [said] = says(store, machine)

        assert "what this stack starts is not what Noust wrote and judged" in said
        assert f"an addition to its unit ({path})" in said
        assert "ExecStart=" in said
        assert "starts without the check of its start" not in said
        assert "systemctl daemon-reload" in said
        assert f"noust setup compose-gate --app {SHOP}" in said

    def test_an_addition_that_adds_a_second_start_is_the_same_thing(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        self.stack(
            tmp_path, store, units, machine, "[Service]\nExecStart=/usr/bin/docker compose run x\n"
        )

        [outcome] = bring(store, machine)

        assert outcome.state == "overridden" and outcome.directives == ("ExecStart=",)

    def test_an_addition_that_also_empties_the_check_says_both_and_keeps_the_old_sentence(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        self.stack(
            tmp_path, store, units, machine, "[Service]\nExecStartPre=\n" + self.REASSIGN[10:]
        )
        bring(store, machine)

        [said] = says(store, machine)

        assert "starts without the check of its start" in said
        assert "(ExecStartPre=, ExecStart=)" in said

    def test_an_addition_that_leaves_the_start_alone_is_not_said(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        self.stack(tmp_path, store, units, machine, '[Service]\nEnvironment="X=1"\n')

        [outcome] = bring(store, machine)

        assert outcome.state == "done"
        assert says(store, machine) == []

    def test_the_operator_mends_it_and_the_next_pass_sees_it_in_place(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        path = self.stack(tmp_path, store, units, machine, self.REASSIGN)
        bring(store, machine)
        path.unlink()

        [again] = bring(store, machine)

        assert again.state == "unchanged"
        assert says(store, machine) == []

    def test_a_unit_that_was_not_reloaded_is_not_blamed_on_an_addition(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        bring(store, machine)
        # systemd has the unit as it was when it loaded it, with another start, and no addition explains it.
        machine.loaded["shop-example-com.service"] = unit_of(units, SHOP).replace(
            WITH_PROJECT, EDITED_START
        )

        [again] = bring(store, machine)

        assert again.state == "unverified"
        assert "daemon-reload" in again.detail

    def test_what_noust_starts_itself_is_still_judged(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        make_stack(tmp_path, store, units, machine, SHOP)
        add_drop_in(units, SHOP, "20-start.conf", self.REASSIGN)
        bring(store, machine)
        app = store.get_app(SHOP)
        assert app is not None
        (Path(app.app_path) / ".env").write_text("DATA=/\n")

        assert not compose_gate.judge_app(app, store=store).allowed

    def test_the_command_says_which_directive_and_is_not_a_failure(
        self,
        tmp_path: Path,
        store: NoustStore,
        units: Path,
        machine: Machine,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        from noust.cli.app import main

        path = self.stack(tmp_path, store, units, machine, self.REASSIGN)

        code = main(["setup", "compose-gate"])

        out = capsys.readouterr().out
        assert code == 0
        assert f"an addition of the unit ({path}) replaces what it starts" in out
        assert "1 stack(s) start without the check" in out


class TestTheEffectOfAUnit:
    def test_the_function_that_asks_systemd_names_the_directive(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        app = make_stack(tmp_path, store, units, machine, SHOP)
        bring(store, machine)
        path = add_drop_in(
            units, SHOP, "20-start.conf", TestAnAdditionThatReassignsTheStart.REASSIGN
        )

        effect = compose_upgrade.gate_effect(stack_deployer(app, runner=machine))

        assert effect is not None
        assert effect.state == compose_upgrade.OVERRIDDEN
        assert effect.directives == ("ExecStart=",)
        assert effect.paths == (str(path),)

    def test_a_unit_of_the_template_is_in_place(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        app = make_stack(tmp_path, store, units, machine, SHOP, unit_project="shop-example-com")
        bring(store, machine)

        effect = compose_upgrade.gate_effect(stack_deployer(app, runner=machine))

        assert effect is not None and effect.state == compose_upgrade.IN_PLACE

    def test_a_marked_unit_with_another_start_is_edited_and_systemd_is_not_asked(
        self, tmp_path: Path, store: NoustStore, units: Path, machine: Machine
    ) -> None:
        app = make_stack(tmp_path, store, units, machine, SHOP)
        edit_the_start(units)

        effect = compose_upgrade.gate_effect(stack_deployer(app, runner=machine))

        assert effect is not None and effect.state == compose_upgrade.EDITED
        assert effect.start == (EDITED_START.removeprefix("ExecStart="),)
        assert not [call for call in machine.calls if "ExecStartPre" in call]


class TestWhatTheConsoleSaysInItsLog:
    def test_a_unit_whose_start_is_not_noust_s_is_a_line_of_the_log_and_an_overridden_one_is_not(
        self, caplog: pytest.LogCaptureFixture
    ) -> None:
        import logging

        from noust.web.compose_gate_worker import ComposeGateWorker

        worker = ComposeGateWorker(
            lambda: [
                compose_upgrade.Outcome(SHOP, "edited", EDITED_START.removeprefix("ExecStart=")),
                compose_upgrade.Outcome("b.example.com", "overridden", "/etc/x.d/20.conf"),
            ],
            first_after=0.0,
            every=3600.0,
        )

        with caplog.at_level(logging.INFO):
            worker.tick()

        assert f"{SHOP} starts as its unit says, not as Noust wrote it" in caplog.text
        assert "b.example.com" not in caplog.text
