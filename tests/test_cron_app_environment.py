"""
A scheduled task of an application runs as the application does (item 150).

A task tied to an application ran in its folder and nothing else of it: no ``.env``, so a
``manage.py migrate`` failed for want of ``DATABASE_URL``, and no virtual environment or pinned
runtime, so ``python`` was the system's. There is one answer to "with what environment does
something of this application run": its unit's, and a task's unit now carries it.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import pytest

from noust.core.runner import FakeRunner
from noust.core.store import App, NoustStore
from noust.deployers.helpers import app_run_environment
from noust.managers.cron_manager import CronJob, CronManager

DOMAIN = "shop.example.com"

#: What the application's own unit says: the port and mode Noust decides, the pinned runtime on
#: the PATH, and a secret that a unit from before 2.0 still held inline.
APP_UNIT = (
    "# Generated by Noust\n[Service]\n"
    'Environment="PORT=8000"\n'
    'Environment="WEB_CONCURRENCY=4"\n'
    'Environment="PATH=/opt/noust/runtimes/python/3.12/bin:/usr/local/bin:/usr/bin"\n'
    'Environment="DATABASE_URL=postgres://shop:hunter2@db.example.com/shop"\n'
    "ExecStart=/var/www/apps/shop/current/venv/bin/python -m gunicorn app:app\n"
)


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """The directory the manager writes units into, inside the sandbox."""
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(CronManager, "SYSTEMD_DIR", path)
    return path


@pytest.fixture
def root(tmp_path: Path) -> Path:
    """An application on the releases layout, with a virtual environment in its running code."""
    base = tmp_path / "apps" / "shop-example-com"
    python = base / "current" / "venv" / "bin" / "python"
    python.parent.mkdir(parents=True)
    python.write_text("#!/bin/sh\n")
    python.chmod(0o755)
    (base / "shared").mkdir()
    return base


@pytest.fixture
def store(tmp_path: Path, root: Path) -> Iterator[NoustStore]:
    """A store holding that application, and a static site that has no process."""
    NoustStore.reset_instance()
    instance = NoustStore(tmp_path / "noust.db")
    instance.create_app(
        App(
            domain=DOMAIN,
            app_type="python",
            app_path=str(root),
            layout="releases",
            port=8000,
        )
    )
    instance.create_app(
        App(
            domain="old.example.com",
            app_type="python",
            app_path=str(tmp_path / "apps" / "old"),
            port=8001,
        )
    )
    yield instance
    instance.close()
    NoustStore.reset_instance()


@pytest.fixture
def unit(monkeypatch: pytest.MonkeyPatch) -> None:
    """The application's own unit is the one above."""
    monkeypatch.setattr(
        "noust.managers.service_manager.ServiceManager.get_service_config",
        lambda self, name: APP_UNIT,
    )


def job(**overrides: object) -> CronJob:
    fields: dict = {
        "name": "cleanup",
        "command": "python manage.py migrate --noinput",
        "schedule": "daily",
        "app_domain": DOMAIN,
    }
    fields.update(overrides)
    return CronJob(**fields)


def service_text(systemd_dir: Path) -> str:
    return (systemd_dir / "noust-cron-cleanup.service").read_text()


class TestTheTaskLoadsWhatTheApplicationLoads:
    def test_its_env_file_and_the_releases_variables_come_in_that_order(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None, root: Path
    ) -> None:
        CronManager().create_job(job())

        text = service_text(systemd_dir)

        env_line = f"EnvironmentFile=-{root}/shared/.env"
        release_line = f"EnvironmentFile=-{root}/current/.noust-env"
        assert env_line in text and release_line in text
        # The same order as the application's unit: what Noust says of the release wins.
        assert text.index(env_line) < text.index(release_line)

    def test_an_application_in_place_has_its_env_beside_its_code(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None, tmp_path: Path
    ) -> None:
        CronManager().create_job(job(app_domain="old.example.com"))

        text = service_text(systemd_dir)

        assert f"EnvironmentFile=-{tmp_path}/apps/old/.env" in text
        assert f"EnvironmentFile=-{tmp_path}/apps/old/.noust-env" in text

    def test_the_variables_its_unit_sets_inline_come_too(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None
    ) -> None:
        CronManager().create_job(job())

        text = service_text(systemd_dir)

        assert 'Environment="PORT=8000"' in text
        assert 'Environment="WEB_CONCURRENCY=4"' in text

    def test_a_secret_an_old_unit_still_held_inline_is_not_copied_into_another_unit(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None
    ) -> None:
        # Units are world-readable: what Noust keeps inline is what is not secret.
        CronManager().create_job(job())

        text = service_text(systemd_dir)

        assert "DATABASE_URL" not in text and "hunter2" not in text

    def test_the_virtual_environment_and_the_pinned_runtime_are_first_on_the_path(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None, root: Path
    ) -> None:
        CronManager().create_job(job())

        text = service_text(systemd_dir)

        assert (
            f'Environment="PATH={root}/current/venv/bin:'
            '/opt/noust/runtimes/python/3.12/bin:/usr/local/bin:/usr/bin"'
        ) in text


class TestThePythonItRuns:
    def test_python_is_the_virtual_environments_not_the_systems(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None, root: Path
    ) -> None:
        CronManager().create_job(job())

        text = service_text(systemd_dir)

        assert f"ExecStart={root}/current/venv/bin/python manage.py migrate --noinput" in text
        # What the operator typed is what an edit hands back.
        assert '# Command: "python manage.py migrate --noinput"' in text

    def test_a_program_that_is_not_among_its_tools_is_found_where_it_always_was(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None
    ) -> None:
        CronManager().create_job(job(command="env"))

        assert "ExecStart=/usr/bin/env" in service_text(systemd_dir)

    def test_a_program_nothing_has_is_refused_with_nothing_written(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None
    ) -> None:
        from noust.core.exceptions import ServiceError

        with pytest.raises(ServiceError, match="Command not found"):
            CronManager().create_job(job(command="no-such-tool-anywhere"))

        assert list(systemd_dir.iterdir()) == []

    def test_an_application_with_no_unit_still_gets_its_files_and_tools(
        self,
        runner: FakeRunner,
        systemd_dir: Path,
        store: NoustStore,
        monkeypatch: pytest.MonkeyPatch,
        root: Path,
    ) -> None:
        monkeypatch.setattr(
            "noust.managers.service_manager.ServiceManager.get_service_config",
            lambda self, name: None,
        )

        CronManager().create_job(job())

        text = service_text(systemd_dir)
        assert f"EnvironmentFile=-{root}/shared/.env" in text
        assert (
            f'Environment="PATH={root}/current/venv/bin:'
            '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"'
        ) in text


class TestWhatDoesNotChange:
    def test_a_task_of_no_application_has_neither_files_nor_variables(
        self, runner: FakeRunner, systemd_dir: Path, store: NoustStore, unit: None
    ) -> None:
        CronManager().create_job(
            job(app_domain=None, command="/usr/bin/true", working_directory="/srv/caches")
        )

        text = service_text(systemd_dir)

        assert "EnvironmentFile" not in text and "Environment=" not in text

    def test_a_task_in_a_service_of_a_stack_runs_in_the_container_with_its_own(
        self,
        runner: FakeRunner,
        systemd_dir: Path,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        from noust.deployers.helpers import compose_exec as compose_exec_module

        NoustStore.reset_instance()
        stack = NoustStore(tmp_path / "stack.db")
        (tmp_path / "stack").mkdir()
        stack.create_app(
            App(
                domain="stack.example.com",
                app_type="docker-compose",
                app_path=str(tmp_path / "stack"),
                compose_project="stack",
            )
        )
        monkeypatch.setattr(
            compose_exec_module.shutil,
            "which",
            lambda name: f"/usr/bin/{name}" if name == "docker" else None,
        )
        monkeypatch.setattr(
            "noust.managers.service_manager.ServiceManager.get_service_config",
            lambda self, name: APP_UNIT,
        )
        try:
            CronManager().create_job(
                job(app_domain="stack.example.com", service="web", command="python manage.py x")
            )
        finally:
            stack.close()
            NoustStore.reset_instance()

        text = service_text(systemd_dir)
        assert "EnvironmentFile" not in text
        assert "PORT=8000" not in text and "DATABASE_URL" not in text
        assert "docker compose -p stack exec -T web python manage.py x" in text


class TestOneAnswerForTheToolsOfAnApplication:
    """The tool directories are the deployers' own: a layout they change is followed here."""

    def test_the_python_deployer_names_the_same_directory(self, tmp_path: Path) -> None:
        from noust.deployers.python import PythonDeployer

        (tmp_path / "venv" / "bin").mkdir(parents=True)
        deployer = PythonDeployer(runner=FakeRunner())
        deployer.configure(DOMAIN, "src", app_path=tmp_path)

        assert app_run_environment.tool_directories(tmp_path) == [
            d for d in deployer._tool_dirs() if d.is_dir()
        ]

    def test_the_node_deployer_names_the_same_directory(self, tmp_path: Path) -> None:
        from noust.deployers.nodejs import NodeJSDeployer

        (tmp_path / "node_modules" / ".bin").mkdir(parents=True)
        deployer = NodeJSDeployer(runner=FakeRunner())
        deployer.configure(DOMAIN, "src", app_path=tmp_path)

        assert app_run_environment.tool_directories(tmp_path) == [
            d for d in deployer._tool_dirs() if d.is_dir()
        ]

    def test_an_application_with_neither_has_none(self, tmp_path: Path) -> None:
        assert app_run_environment.tool_directories(tmp_path) == []
