def test_the_maximum_time_is_the_start_timeout_of_the_oneshot(
    runner: FakeRunner, systemd_dir: Path
) -> None:
    CronManager().create_job(plain_job(timeout=900))

    text = (systemd_dir / "noust-cron-cleanup.service").read_text()
    assert "TimeoutStartSec=900\n" in text
    assert "RuntimeMaxSec" not in text, "systemd ignores it on a oneshot"


def test_a_task_without_a_maximum_has_no_directive(runner: FakeRunner, systemd_dir: Path) -> None:
    CronManager().create_job(plain_job())

    assert "TimeoutStartSec" not in (systemd_dir / "noust-cron-cleanup.service").read_text()


@pytest.mark.parametrize("timeout", [0, -5, 86401, True, 1.5, "60"])
def test_a_maximum_outside_one_second_to_a_day_is_refused_and_nothing_is_written(
    runner: FakeRunner, systemd_dir: Path, timeout: Any
) -> None:
    with pytest.raises(ServiceError, match="cannot be given"):
        CronManager().create_job(plain_job(timeout=timeout))

    assert list(systemd_dir.iterdir()) == []


@pytest.mark.parametrize("timeout", [1, 60, 36000, 86400])
def test_the_ends_of_the_range_are_accepted(
    runner: FakeRunner, systemd_dir: Path, timeout: int
) -> None:
    CronManager().create_job(plain_job(timeout=timeout))

    assert (
        f"TimeoutStartSec={timeout}\n" in (systemd_dir / "noust-cron-cleanup.service").read_text()
    )


def test_the_maximum_is_read_back_into_the_listing(runner: FakeRunner, systemd_dir: Path) -> None:
    CronManager().create_job(plain_job(timeout=120))
    runner.script(
        ["systemctl", "list-unit-files"], stdout="noust-cron-cleanup.timer enabled enabled\n"
    )

    [entry] = CronManager().list_jobs()

    assert entry["timeout"] == 120
    assert entry["service"] == ""


def test_a_task_that_never_had_one_lists_none(runner: FakeRunner, systemd_dir: Path) -> None:
    CronManager().create_job(plain_job())
    runner.script(
        ["systemctl", "list-unit-files"], stdout="noust-cron-cleanup.timer enabled enabled\n"
    )

    [entry] = CronManager().list_jobs()

    assert entry["timeout"] is None


