def test_the_prefix_uses_the_project_the_stack_runs_under(store: NoustStore, docker: None) -> None:
    app = store.get_app(DOMAIN)
    assert app is not None

    described = compose_exec(app, "worker", APP_UNIT)

    assert described.prefix == ("/usr/bin/docker", "compose", "-p", "shop", "exec", "-T", "worker")
    assert described.environment == {"COMPOSE_FILE": "docker/compose.prod.yml"}


def test_a_stack_whose_unit_names_no_file_leaves_compose_to_find_it(
    store: NoustStore, docker: None
) -> None:
    app = store.get_app(DOMAIN)
    assert app is not None

    described = compose_exec(app, "worker", "# Generated by Noust\n[Service]\n")

    assert described.environment == {}


def test_a_stack_without_a_recorded_project_derives_it_from_its_directory(
    store: NoustStore, docker: None, tmp_path: Path
) -> None:
    app = App(
        domain="plain.example.com",
        app_type="docker-compose",
        app_path=str(tmp_path / "apps" / "Plain_App"),
    )

    described = compose_exec(app, "web", None)

    assert described.prefix[2:4] == ("-p", "plain_app")


def test_the_helper_refuses_what_is_not_a_stack_or_has_no_service(
    store: NoustStore, docker: None
) -> None:
    node = store.get_app("node.example.com")
    stack = store.get_app(DOMAIN)
    assert node is not None and stack is not None

    with pytest.raises(ValidationError):
        compose_exec(node, "app", None)
    with pytest.raises(ValidationError):
        compose_exec(stack, "", None)


