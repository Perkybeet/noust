"""
A task's maximum time and the service of a stack it runs in (checklist B-65).

Pinned here:

- the maximum time is ``TimeoutStartSec=``: a task's unit is a ``oneshot``, for
  which systemd ignores ``RuntimeMaxSec=``;
- a task in a service is ``docker compose exec -T <service> <argv>`` as root,
  with the stack's own project and compose file, and no shell: the program is
  the container's, so it is not looked up on this server;
- what the operator typed is what an edit hands back, not the compose prefix;
- the CLI and the API carry both settings, and each refusal says why.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
from click.testing import CliRunner

from noust.cli.app import cli as root_cli
from noust.core.exceptions import ServiceError, ValidationError
from noust.core.runner import FakeRunner
from noust.core.store import App, NoustStore
from noust.deployers.helpers import compose_exec as compose_exec_module
from noust.deployers.helpers.compose_exec import compose_exec
from noust.managers.cron_manager import CronJob, CronManager

DOMAIN = "shop.example.com"
APP_UNIT = (
    "# Generated by Noust\n[Service]\n"
    'Environment="COMPOSE_FILE=docker/compose.prod.yml"\n'
    "ExecStart=/usr/bin/docker compose up -d\n"
)


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Point the manager's unit directory into the sandbox."""
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(CronManager, "SYSTEMD_DIR", path)
    return path


@pytest.fixture
def store(tmp_path: Path) -> Iterator[NoustStore]:
    """A store of the test's own, with a Compose stack and a Node application."""
    NoustStore.reset_instance()
    instance = NoustStore(tmp_path / "noust.db")
    root = tmp_path / "apps" / "shop-example-com"
    root.mkdir(parents=True)
    instance.create_app(
        App(domain=DOMAIN, app_type="docker-compose", app_path=str(root), compose_project="shop")
    )
    instance.create_app(
        App(domain="node.example.com", app_type="nodejs", app_path=str(tmp_path / "apps" / "node"))
    )
    yield instance
    instance.close()
    NoustStore.reset_instance()


@pytest.fixture
def docker(monkeypatch: pytest.MonkeyPatch) -> None:
    """The Docker client is installed, and the stack's unit names its compose file."""
    monkeypatch.setattr(
        compose_exec_module.shutil,
        "which",
        lambda name: f"/usr/bin/{name}" if name == "docker" else None,
    )
    monkeypatch.setattr(
        "noust.managers.service_manager.ServiceManager.get_service_config",
        lambda self, name: APP_UNIT,
    )


def service_job(**overrides: object) -> CronJob:
    fields: dict[str, Any] = {
        "name": "artisan",
        "command": "php artisan schedule:run",
        "schedule": "hourly",
        "app_domain": DOMAIN,
        "service": "app",
    }
    fields.update(overrides)
    return CronJob(**fields)


def plain_job(**overrides: object) -> CronJob:
    fields: dict[str, Any] = {
        "name": "cleanup",
        "command": "/usr/bin/find /tmp/caches -delete",
        "schedule": "daily",
        "user": "www-data",
        "working_directory": "/srv/caches",
    }
    fields.update(overrides)
    return CronJob(**fields)


