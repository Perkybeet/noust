def test_the_command_creates_a_task_with_a_maximum_and_a_service(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    result = CliRunner().invoke(
        root_cli,
        [
            "cron",
            "create",
            "artisan",
            "php artisan schedule:run",
            "--schedule",
            "hourly",
            "--app",
            DOMAIN,
            "--service",
            "app",
            "--timeout",
            "300",
        ],
    )

    assert result.exit_code == 0, result.output
    text = (systemd_dir / "noust-cron-artisan.service").read_text()
    assert "TimeoutStartSec=300" in text and "exec -T app" in text


def test_the_api_carries_the_maximum_and_the_service(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    from fastapi import FastAPI
    from fastapi.testclient import TestClient

    from noust.web.api import cron as cron_api
    from noust.web.api.auth import get_current_session
    from noust.web.api.deps import install_error_handlers, require_elevated

    app = FastAPI()
    install_error_handlers(app)
    app.include_router(cron_api.router, prefix="/api/cron")
    session = {"sid": "s", "scope": "admin"}
    app.dependency_overrides[get_current_session] = lambda: session
    app.dependency_overrides[require_elevated] = lambda: session
    client = TestClient(app)

    response = client.post(
        "/api/cron",
        json={
            "name": "artisan",
            "command": "php artisan schedule:run",
            "schedule": "hourly",
            "app_domain": DOMAIN,
            "service": "app",
            "timeout": 300,
        },
    )

    assert response.status_code == 201, response.text
    assert (systemd_dir / "noust-cron-artisan.service").read_text().count(
        "TimeoutStartSec=300"
    ) == 1


