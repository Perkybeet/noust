def test_a_task_in_a_service_is_a_compose_exec_as_root(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    created = CronManager().create_job(service_job(timeout=300))

    text = (systemd_dir / "noust-cron-artisan.service").read_text()
    assert created.user == "root"
    assert "User=root\n" in text
    assert (
        "ExecStart=/usr/bin/docker compose -p shop exec -T app php artisan schedule:run\n" in text
    )
    assert 'Environment="COMPOSE_FILE=docker/compose.prod.yml"\n' in text
    assert "# Service: app\n" in text
    assert "# Application: shop.example.com\n" in text
    assert "TimeoutStartSec=300\n" in text
    assert "WorkingDirectory=" in text


def test_the_program_is_the_containers_not_this_servers(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    """php is not installed here: the container has it."""
    CronManager().create_job(service_job(command="php artisan queue:work --stop-when-empty"))

    text = (systemd_dir / "noust-cron-artisan.service").read_text()
    assert "exec -T app php artisan queue:work --stop-when-empty\n" in text
    assert "/usr/bin/php" not in text


def test_no_shell_is_put_between_the_stack_and_the_command(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    """A distroless container has no sh: the task still runs."""
    CronManager().create_job(service_job(command="/app/bin/job --once"))

    text = (systemd_dir / "noust-cron-artisan.service").read_text()
    assert " sh -c" not in text and "/bin/sh" not in text
    assert "exec -T app /app/bin/job --once\n" in text


def test_an_edit_gets_back_what_the_operator_typed(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    CronManager().create_job(service_job(command="php artisan 'schedule:run' --verbose"))
    runner.script(
        ["systemctl", "list-unit-files"], stdout="noust-cron-artisan.timer enabled enabled\n"
    )

    [entry] = CronManager().list_jobs()

    assert entry["command"] == "php artisan 'schedule:run' --verbose"
    assert entry["service"] == "app"
    assert entry["user"] == "root"


def test_a_service_needs_the_application_it_belongs_to(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    with pytest.raises(ServiceError, match="needs the application"):
        CronManager().create_job(service_job(app_domain=None))

    assert list(systemd_dir.iterdir()) == []


def test_an_application_that_is_not_a_stack_has_no_service_to_run_in(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    with pytest.raises(ServiceError, match="not a stack of services"):
        CronManager().create_job(service_job(app_domain="node.example.com"))

    assert list(systemd_dir.iterdir()) == []


def test_a_task_in_a_service_runs_as_root_and_says_so_when_asked_for_another(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    with pytest.raises(ServiceError, match="runs as root"):
        CronManager().create_job(service_job(user="www-data"))

    CronManager().create_job(service_job(user="root"))


def test_a_service_name_compose_would_not_accept_is_refused(
    runner: FakeRunner, systemd_dir: Path, store: NoustStore, docker: None
) -> None:
    with pytest.raises(ServiceError):
        CronManager().create_job(service_job(service="app; rm -rf /"))

    assert list(systemd_dir.iterdir()) == []


def test_without_docker_a_task_in_a_service_is_refused_with_the_reason(
    runner: FakeRunner,
    systemd_dir: Path,
    store: NoustStore,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(compose_exec_module.shutil, "which", lambda name: None)
