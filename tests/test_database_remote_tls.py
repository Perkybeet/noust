"""
Requiring TLS of the account made for a public database (checklist C-22).

PostgreSQL refuses it without TLS through one marked line above every other in
``pg_hba.conf``; MySQL and MariaDB through ``REQUIRE SSL`` on the account;
Redis and MongoDB cannot do it for one account and say so. What matters: the
file is checked by PostgreSQL before it is reloaded and put back when it
refuses it, nothing but that one block is ever touched, the file keeps its
owner, and an engine that lets anyone in without a password is refused.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

from noust.core.exceptions import DatabaseUserError
from noust.core.runner import CommandResult, FakeRunner, set_runner
from noust.core.store import NoustStore
from noust.managers.database import pg_hba
from noust.managers.database.base import BaseDatabaseManager
from noust.managers.database.mongodb import MongoDBManager
from noust.managers.database.mysql import MySQLManager
from noust.managers.database.postgres import PostgresManager
from noust.managers.database.redis import RedisManager

HBA = """# PostgreSQL Client Authentication Configuration File
# ===================================================

# TYPE  DATABASE        USER            ADDRESS                 METHOD

# "local" is for Unix domain socket connections only
local   all             postgres                                peer
local   all             all                                     peer
host    all             all             127.0.0.1/32            scram-sha-256
host    all             all             ::1/128                 scram-sha-256
"""


class TestTheHbaBlock:
    """One marked block, above every connection line, and exactly removable."""

    def test_the_block_refuses_the_account_without_tls_on_any_address(self) -> None:
        assert pg_hba.block("shop", "shop_remote") == (
            "# BEGIN noust remote access: shop_remote\n"
            "# Generated by Noust: this account is for a database reachable from the network "
            "and must use TLS.\n"
            "hostnossl shop shop_remote all reject\n"
            "# END noust remote access: shop_remote\n"
        )

    def test_it_goes_after_the_leading_comments_and_before_the_first_rule(self) -> None:
        text = pg_hba.with_block(HBA, "shop", "shop_remote")
        lines = text.splitlines()
        first_rule = next(i for i, line in enumerate(lines) if line.startswith("local"))
        block_at = lines.index("# BEGIN noust remote access: shop_remote")
        assert block_at < first_rule
        assert lines[block_at + 2] == "hostnossl shop shop_remote all reject"
        # The "local" comment that sits above the first rule stays above it.
        assert text.replace(pg_hba.block("shop", "shop_remote"), "") == HBA

    def test_taking_it_out_gives_back_the_file_byte_for_byte(self) -> None:
        added = pg_hba.with_block(HBA, "shop", "shop_remote")
        assert pg_hba.has_block(added, "shop_remote")
        assert pg_hba.without_block(added, "shop_remote") == HBA

    def test_putting_it_twice_does_not_repeat_it(self) -> None:
        once = pg_hba.with_block(HBA, "shop", "shop_remote")
        assert pg_hba.with_block(once, "shop", "shop_remote") == once

    def test_another_account_s_block_is_not_touched(self) -> None:
        both = pg_hba.with_block(pg_hba.with_block(HBA, "a", "a_remote"), "b", "b_remote")
        assert pg_hba.without_block(both, "a_remote") == pg_hba.with_block(HBA, "b", "b_remote")

    def test_a_block_that_was_never_closed_is_left_alone(self) -> None:
        broken = (
            HBA
            + "# BEGIN noust remote access: shop_remote\nhostnossl shop shop_remote all reject\n"
        )
        assert pg_hba.without_block(broken, "shop_remote") == broken

    def test_a_file_without_a_block_is_unchanged(self) -> None:
        assert pg_hba.without_block(HBA, "shop_remote") == HBA
        assert not pg_hba.has_block(HBA, "shop_remote")

    def test_a_file_that_is_only_comments_gets_the_block_at_the_end(self) -> None:
        assert pg_hba.with_block("# nothing\n", "shop", "a").startswith("# nothing\n# BEGIN")

    @pytest.mark.parametrize("name", ["", "a b", "a;b", 'a"b', "1abc", "a" * 64, "a\nb"])
    def test_a_name_that_needs_quoting_is_refused(self, name: str) -> None:
        with pytest.raises(ValueError, match="unquoted"):
            pg_hba.block("shop", name)
        with pytest.raises(ValueError, match="unquoted"):
            pg_hba.block(name, "shop_remote")


class SqlRunner(FakeRunner):
    """A runner that answers the statements the manager sends on stdin."""

    def __init__(self, hba: Path | None, *, ssl: str = "on", errors: str = "0") -> None:
        super().__init__()
        self.hba = hba
        self.ssl = ssl
        self.errors = errors
        self.statements: list[str] = []

    def run(self, argv: Sequence[str], **kwargs: Any) -> CommandResult:  # type: ignore[override]
        result = super().run(argv, **kwargs)
        sql = (kwargs.get("input") or "").strip()
        if not sql:
            return result
        self.statements.append(sql)
        answers = {
            "SHOW ssl;": self.ssl,
            "SHOW hba_file;": str(self.hba) if self.hba else "",
            "SELECT count(*) FROM pg_hba_file_rules WHERE error IS NOT NULL;": self.errors,
            "SELECT pg_reload_conf();": "t",
        }
        if sql in answers:
            return CommandResult(argv=result.argv, exit_code=0, stdout=answers[sql] + "\n")
        return result


@pytest.fixture
def hba(tmp_path: Path) -> Path:
    """A pg_hba.conf."""
    path = tmp_path / "pg_hba.conf"
    path.write_text(HBA)
    os.chmod(path, 0o640)
    return path


@pytest.fixture
def postgres(hba: Path, tmp_path: Path) -> PostgresManager:
    """A PostgreSQL manager talking to a runner that knows its hba file."""
    NoustStore.reset_instance()
    runner = SqlRunner(hba)
    set_runner(runner)
    manager = PostgresManager()
    try:
        yield manager  # type: ignore[misc]
    finally:
        set_runner(None)
        NoustStore.reset_instance()


def runner_of(manager: BaseDatabaseManager) -> SqlRunner:
    """The runner a manager runs through."""
    runner = manager.runner
    assert isinstance(runner, SqlRunner)
    return runner


class TestPostgreSql:
    """The block is written, checked by the server, then loaded."""

    def test_it_can_require_tls_when_ssl_is_on(self, postgres: PostgresManager) -> None:
        assert postgres.remote_tls_blocker() is None

    def test_it_cannot_when_ssl_is_off_and_says_what_to_do(self, postgres: PostgresManager) -> None:
        runner_of(postgres).ssl = "off"
        blocker = postgres.remote_tls_blocker()
        assert blocker is not None and "ssl = off" in blocker and "postgresql.conf" in blocker

    def test_requiring_it_writes_the_block_checks_it_and_reloads(
        self, postgres: PostgresManager, hba: Path
    ) -> None:
        postgres.set_remote_tls("shop_remote", "shop", True)

        assert pg_hba.has_block(hba.read_text(), "shop_remote")
        statements = runner_of(postgres).statements
        check = statements.index("SELECT count(*) FROM pg_hba_file_rules WHERE error IS NOT NULL;")
        reload = statements.index("SELECT pg_reload_conf();")
        assert check < reload, "the server reads the file before it is loaded"

    def test_lifting_it_gives_back_the_file(self, postgres: PostgresManager, hba: Path) -> None:
        postgres.set_remote_tls("shop_remote", "shop", True)
        postgres.set_remote_tls("shop_remote", "shop", False)
        assert hba.read_text() == HBA

    def test_the_file_keeps_its_mode(self, postgres: PostgresManager, hba: Path) -> None:
        postgres.set_remote_tls("shop_remote", "shop", True)
        assert hba.stat().st_mode & 0o777 == 0o640

    def test_a_file_the_server_does_not_accept_is_put_back_and_not_loaded(
        self, postgres: PostgresManager, hba: Path
    ) -> None:
        runner_of(postgres).errors = "1"
        with pytest.raises(DatabaseUserError, match="did not accept") as caught:
            postgres.set_remote_tls("shop_remote", "shop", True)
        assert "put back" in caught.value.message
        assert hba.read_text() == HBA
        assert "SELECT pg_reload_conf();" not in runner_of(postgres).statements

    def test_nothing_is_written_when_there_is_nothing_to_change(
        self, postgres: PostgresManager, hba: Path
    ) -> None:
        postgres.set_remote_tls("shop_remote", "shop", False)
        assert hba.read_text() == HBA
        assert "SELECT pg_reload_conf();" not in runner_of(postgres).statements

    def test_a_server_that_does_not_say_where_its_file_is_is_refused(
        self, postgres: PostgresManager, hba: Path
    ) -> None:
        runner_of(postgres).hba = None
        with pytest.raises(DatabaseUserError, match="did not say where"):
            postgres.set_remote_tls("shop_remote", "shop", True)

    def test_a_missing_file_is_refused(self, postgres: PostgresManager, hba: Path) -> None:
        hba.unlink()
        with pytest.raises(DatabaseUserError, match="does not exist"):
            postgres.set_remote_tls("shop_remote", "shop", True)

    def test_a_file_that_is_a_symbolic_link_is_not_written_through(
        self, postgres: PostgresManager, hba: Path, tmp_path: Path
    ) -> None:
        target = tmp_path / "elsewhere.conf"
        target.write_text(HBA)
        hba.unlink()
        hba.symlink_to(target)
        with pytest.raises(DatabaseUserError, match="symbolic link"):
            postgres.set_remote_tls("shop_remote", "shop", True)
        assert target.read_text() == HBA

    def test_a_dry_run_writes_nothing(
        self, postgres: PostgresManager, hba: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setattr("noust.managers.database.postgres.is_rehearsal", lambda: True)
        postgres.set_remote_tls("shop_remote", "shop", True)
        assert hba.read_text() == HBA


class TestMySql:
    """The account's own ``REQUIRE SSL``."""

    @pytest.fixture
    def mysql(self, runner: FakeRunner) -> MySQLManager:
        runner.only_knows("mysql", "mysqldump")
        manager = MySQLManager()
        manager.config = SimpleNamespace(  # type: ignore[assignment]
            get=lambda key, default=None: {} if key == "databases" else default
        )
        return manager

    def test_a_server_with_tls_can_require_it(
        self, mysql: MySQLManager, runner: FakeRunner
    ) -> None:
        runner.script(["mysql"], stdout="have_ssl\tYES\n")
        assert mysql.remote_tls_blocker() is None

    def test_a_server_without_the_variable_is_one_that_always_has_tls(
        self, mysql: MySQLManager, runner: FakeRunner
    ) -> None:
        runner.script(["mysql"], stdout="")
        assert mysql.remote_tls_blocker() is None

    def test_a_server_with_tls_off_says_so(self, mysql: MySQLManager, runner: FakeRunner) -> None:
        runner.script(["mysql"], stdout="have_ssl\tDISABLED\n")
        blocker = mysql.remote_tls_blocker()
        assert blocker is not None and "have_ssl = DISABLED" in blocker
        assert "could never connect" in blocker

    def test_requiring_it_alters_that_account_only(
        self, mysql: MySQLManager, runner: FakeRunner
    ) -> None:
        runner.script(["mysql"], stdout="shop_remote\n")
        mysql.set_remote_tls("shop_remote", "shop", True)
        sent = [text for text in runner.inputs if text]
        assert any("ALTER USER 'shop_remote'@'localhost' REQUIRE SSL;" in text for text in sent)
        assert not any("REQUIRE NONE" in text for text in sent)

    def test_lifting_it(self, mysql: MySQLManager, runner: FakeRunner) -> None:
        runner.script(["mysql"], stdout="shop_remote\n")
        mysql.set_remote_tls("shop_remote", "shop", False)
        assert any("REQUIRE NONE;" in text for text in runner.inputs if text)

    def test_an_account_that_is_not_there_is_refused(
        self, mysql: MySQLManager, runner: FakeRunner
    ) -> None:
        runner.script(["mysql"], stdout="")
        with pytest.raises(DatabaseUserError, match="does not exist"):
            mysql.set_remote_tls("ghost", "shop", True)

    def test_a_refusal_by_the_server_is_reported(
        self, mysql: MySQLManager, runner: FakeRunner
    ) -> None:
        runner.script(["mysql"], stdout="shop_remote\n")
        outcomes = iter([True, False])

        original = runner.run

        def run(argv: Sequence[str], **kwargs: Any) -> CommandResult:
            result = original(argv, **kwargs)
            if "ALTER USER" in (kwargs.get("input") or ""):
                return CommandResult(argv=result.argv, exit_code=1, stderr="ERROR 1064")
            next(outcomes, None)
            return result

        runner.run = run  # type: ignore[method-assign]
        with pytest.raises(DatabaseUserError, match="Failed to change the TLS requirement"):
            mysql.set_remote_tls("shop_remote", "shop", True)


class TestTheEnginesThatCannot:
    """Redis and MongoDB cannot do it for one account, and say so."""

    @pytest.mark.parametrize("manager", [RedisManager, MongoDBManager])
    def test_they_say_why_and_refuse(self, manager: type[BaseDatabaseManager], runner: Any) -> None:
        engine = manager()
        assert engine.remote_tls_blocker() is not None
        with pytest.raises(DatabaseUserError, match="TLS"):
            engine.set_remote_tls("u", "d", True)


class TestAnEngineWithoutAPassword:
    """It is refused before a port is opened in front of it."""

    def test_redis_without_a_password_is_a_blocker(
        self, runner: Any, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        redis = RedisManager()
        monkeypatch.setattr(RedisManager, "_known_password", lambda self: False)
        runner.script(["redis-cli"], stdout="default\n")
        blockers = redis.remote_access_blockers()
        assert blockers and "without a password" in blockers[0]

    def test_redis_with_a_password_is_not(
        self, runner: Any, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        redis = RedisManager()
        monkeypatch.setattr(RedisManager, "_known_password", lambda self: True)
        assert redis.remote_access_blockers() == []

    def test_mongodb_without_authorization_is_a_blocker(
        self, runner: Any, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        mongo = MongoDBManager()
        monkeypatch.setattr(MongoDBManager, "_authorization_enabled", lambda self: False)
        blockers = mongo.remote_access_blockers()
        assert blockers and "without authorization" in blockers[0]

    def test_mongodb_with_authorization_is_not(
        self, runner: Any, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        mongo = MongoDBManager()
        monkeypatch.setattr(MongoDBManager, "_authorization_enabled", lambda self: True)
        assert mongo.remote_access_blockers() == []

    def test_postgresql_has_none_of_it(self, runner: Any) -> None:
        assert PostgresManager().remote_access_blockers() == []
