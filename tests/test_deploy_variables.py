#: A lockfile that differs from the first, so an update installs instead of reusing.
NEW_LOCK = '{"name": "app", "lockfileVersion": 3, "packages": {"x": {}}}\n'

UNIT = """# Generated by Noust
[Unit]
Description=x

[Service]
User=app
WorkingDirectory=/var/www/apps/x/current
Environment="PORT=3000"
EnvironmentFile=-/var/www/apps/x/shared/.env
ExecStart=/usr/bin/node server.js
"""


class TestTheUnitLine:
    def test_the_line_goes_after_the_other_environment_files(self) -> None:
        line = release_env_line("/var/www/apps/x/current")

        edited = with_release_env(UNIT, line)

        lines = edited.split("\n")
        assert lines.index(line) == lines.index("EnvironmentFile=-/var/www/apps/x/shared/.env") + 1
        assert with_release_env(edited, line) == edited

    def test_a_template_keeps_the_instances_port_file_last(self) -> None:
        template = UNIT + "EnvironmentFile=/var/www/apps/x/colors/%i.env\n"
        line = release_env_line("/var/www/apps/x/colors", instance=True)

        edited = with_release_env(template, line).split("\n")

        assert line == "EnvironmentFile=-/var/www/apps/x/colors/%i/.noust-env"
        assert edited.index(line) < edited.index("EnvironmentFile=/var/www/apps/x/colors/%i.env")

    def test_a_unit_without_a_file_gets_it_after_its_environment(self) -> None:
        bare = UNIT.replace("EnvironmentFile=-/var/www/apps/x/shared/.env\n", "")

        edited = with_release_env(bare, "EnvironmentFile=-/x/.noust-env").split("\n")

        assert (
            edited.index("EnvironmentFile=-/x/.noust-env")
            == edited.index('Environment="PORT=3000"') + 1
        )

    def test_a_percent_in_a_path_is_not_a_specifier(self) -> None:
        assert release_env_line("/srv/100%/x") == "EnvironmentFile=-/srv/100%%/x/.noust-env"


def read_env(path: Path) -> dict[str, str]:
    return EnvManager().read_env_file(path)


class TestWhatNoustSaysAboutADeployment:
    def test_every_release_carries_its_own_facts(
        self, tmp_path: Path, root: Path, store: NoustStore, machine: SimpleNamespace
    ) -> None:
        commit = machine.git.publish(node_tree(tmp_path / "v1"))

        deploy_new(root, machine)

        release = Path(os.readlink(root / "current")).name
        facts = read_env(root / "releases" / release / ".noust-env")
        assert facts["NOUST_URL"] == "http://rel.example.com"
        assert facts["NOUST_DOMAIN"] == "rel.example.com"
        assert facts["NOUST_COMMIT"] == commit[:7]
        assert facts["NOUST_RELEASE"] == release
        assert facts["NOUST_BRANCH"] == "main"

    def test_the_unit_loads_the_file_of_whatever_current_points_at(
        self, tmp_path: Path, root: Path, store: NoustStore, machine: SimpleNamespace
    ) -> None:
        machine.git.publish(node_tree(tmp_path / "v1"))

        deploy_new(root, machine)

        unit = machine.services.units["rel-example-com"]
        assert unit["runtime_environment_file"] == str(root / "current" / ".noust-env")

    def test_the_next_release_has_its_own_commit(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        first = machine.git.publish(node_tree(tmp_path / "v1"))
        deploy_new(root, machine)
        old = Path(os.readlink(root / "current")).name
        second = machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))

        update(machine, monkeypatch)

        new = Path(os.readlink(root / "current")).name
        assert new != old
        assert read_env(root / "releases" / new / ".noust-env")["NOUST_COMMIT"] == second[:7]
        assert read_env(root / "releases" / old / ".noust-env")["NOUST_COMMIT"] == first[:7]

    def test_a_static_site_gets_no_file_it_would_serve(
        self, tmp_path: Path, root: Path, store: NoustStore, machine: SimpleNamespace
    ) -> None:
        machine.git.publish(write_tree(tmp_path / "site", {"index.html": "<h1>x</h1>"}))

        deploy_new(root, machine, deployer_class=StaticDeployer)

        assert not list(root.rglob(".noust-env"))

    def test_the_build_is_given_the_url_and_not_the_commit(
        self, tmp_path: Path, root: Path, store: NoustStore, machine: SimpleNamespace
    ) -> None:
        machine.git.publish(node_tree(tmp_path / "v1"))

        deploy_new(root, machine)

        index = machine.runner.calls.index(("npm", "ci"))
        env = machine.runner.envs[index] or {}
        assert env["NOUST_URL"] == "http://rel.example.com"
        assert env["NOUST_BRANCH"] == "main"
        assert "NOUST_COMMIT" not in env and "NOUST_RELEASE" not in env

    def test_a_unit_from_before_gets_the_line_on_its_next_update_and_only_then(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        machine.git.publish(node_tree(tmp_path / "v1"))
        deploy_new(root, machine)
        written: list[str] = []
        text = UNIT.replace("/var/www/apps/x", str(root))
        services = machine.services
        services.read_unit = lambda name: text if not written else written[-1]
        services.update_config = lambda name, body: written.append(body) or text
        machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))

        update(machine, monkeypatch)

        assert len(written) == 1
        assert f"EnvironmentFile=-{root}/current/.noust-env" in written[0]
        machine.git.publish(node_tree(tmp_path / "v3", server="//3\n"))
        update(machine, monkeypatch)
        assert len(written) == 1  # it has the line now


class TestAudiences:
    def deployed(self, tmp_path: Path, root: Path, machine: SimpleNamespace) -> Any:
        machine.git.publish(node_tree(tmp_path / "v1"))
        return deploy_new(root, machine)

    def test_a_build_only_variable_reaches_the_install_and_never_the_file(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        self.deployed(tmp_path, root, machine)
        app = store.get_app(DOMAIN)
        assert app is not None
        write_app_env(app, {"NPM_TOKEN": "npm_secret_value"}, audience={"NPM_TOKEN": "build"})
        machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))
        machine.runner.calls.clear()
        machine.runner.envs.clear()

        update(machine, monkeypatch)

        index = machine.runner.calls.index(("npm", "ci"))
        assert (machine.runner.envs[index] or {})["NPM_TOKEN"] == "npm_secret_value"
        assert "NPM_TOKEN" not in read_env(root / "shared" / ".env")
        assert "npm_secret_value" not in (root / "shared" / ".env").read_text()

    def test_a_runtime_only_variable_is_taken_out_of_what_the_build_sees(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        self.deployed(tmp_path, root, machine)
        app = store.get_app(DOMAIN)
        assert app is not None
        write_app_env(
            app, {"SESSION_SECRET": "s3cr3t-value"}, audience={"SESSION_SECRET": "runtime"}
        )
        machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))
        machine.runner.calls.clear()
        machine.runner.envs.clear()

        update(machine, monkeypatch)

        index = machine.runner.calls.index(("npm", "ci"))
        assert "SESSION_SECRET" not in (machine.runner.envs[index] or {})
        assert read_env(root / "shared" / ".env")["SESSION_SECRET"] == "s3cr3t-value"


class TestReferencesAtDeployTime:
    def deployed(self, tmp_path: Path, root: Path, machine: SimpleNamespace) -> Any:
        machine.git.publish(node_tree(tmp_path / "v1"))
        return deploy_new(root, machine)

    def test_a_changed_shared_variable_reaches_the_next_release_before_it_is_built(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        variables = VariableStore(store)
        variables.set(SERVER, 0, "REGION", "eu")
        self.deployed(tmp_path, root, machine)
        app = store.get_app(DOMAIN)
        assert app is not None
        write_app_env(app, {"REGION": "{{server.REGION}}"})
        variables.set(SERVER, 0, "REGION", "us")
        machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))
        machine.runner.calls.clear()
        machine.runner.envs.clear()

        update(machine, monkeypatch)

        assert read_env(root / "shared" / ".env")["REGION"] == "us"
        index = machine.runner.calls.index(("npm", "ci"))
        assert (machine.runner.envs[index] or {})["REGION"] == "us"

    def test_the_commit_a_variable_asks_for_is_the_one_being_built(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        self.deployed(tmp_path, root, machine)
        app = store.get_app(DOMAIN)
        assert app is not None
        write_app_env(app, {"PUBLIC_URL": "{{app.URL}}"})
        # A reference to the commit cannot be resolved while editing; the deploy knows it.
        store_rows = VariableStore(store)
        assert app.id is not None
        from noust.core.variables.store import AppVariable

        rows = list(store_rows.app_variables(app.id).values())
        rows.append(AppVariable("BUILD_COMMIT", expression="{{app.COMMIT}}"))
        store_rows.set_app_variables(app.id, rows)
        (root / "shared" / ".env").write_text(
            (root / "shared" / ".env").read_text() + "BUILD_COMMIT=old\n"
        )
        second = machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))

        update(machine, monkeypatch)

        assert read_env(root / "shared" / ".env")["BUILD_COMMIT"] == second[:7]

    def test_a_reference_that_no_longer_resolves_stops_the_update_before_it_builds(
        self,
        tmp_path: Path,
        root: Path,
        store: NoustStore,
        machine: SimpleNamespace,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        variables = VariableStore(store)
        variables.set(SERVER, 0, "REGION", "eu")
        self.deployed(tmp_path, root, machine)
        app = store.get_app(DOMAIN)
        assert app is not None
        write_app_env(app, {"REGION": "{{server.REGION}}"})
        variables.delete(SERVER, 0, "REGION")
        before = os.readlink(root / "current")
        machine.git.publish(node_tree(tmp_path / "v2", server="//2\n", lockfile=NEW_LOCK))
        machine.runner.calls.clear()

        with pytest.raises(UnresolvedReferenceError, match="no variable REGION"):
            update(machine, monkeypatch)

        assert ("npm", "ci") not in machine.runner.calls
        assert os.readlink(root / "current") == before
        assert read_env(root / "shared" / ".env")["REGION"] == "eu"
