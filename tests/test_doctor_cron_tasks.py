"""
``noust setup doctor`` names the tasks written before a task loaded its application's environment.

A task tied to an application now loads the application's ``.env`` and tools (item 150), but the
ones that exist change only when they are written again: nothing rewrites a unit an operator
may have edited. The doctor says which are still as they were and gives the command that writes
each one again, which is run here as it is.
"""

from __future__ import annotations

import shlex
from collections.abc import Iterator
from pathlib import Path

import pytest
from click.testing import CliRunner

from noust.cli.app import cli as root_cli
from noust.core.runner import FakeRunner
from noust.core.store import App, NoustStore
from noust.managers import setup_doctor
from noust.managers.cron_manager import CronJob, CronManager

DOMAIN = "shop.example.com"

#: A task as 4.2 wrote it: the application's folder and account, and nothing of its environment.
OLD_SERVICE = """# Noust cron job nightly
# Generated by Noust
# Command: "/usr/bin/env migrate --noinput"
# Application: shop.example.com

[Unit]
Description=Noust cron job nightly

[Service]
Type=oneshot
User=noust-app-shop
WorkingDirectory={root}/current
ExecStart=/usr/bin/env migrate --noinput
TimeoutStartSec=600

StandardOutput=journal
StandardError=journal
SyslogIdentifier=noust-cron-nightly
"""
OLD_TIMER = """# Generated by Noust
[Unit]
Description=Noust cron job nightly

[Timer]
OnCalendar=*-*-* 03:30:00
Persistent=true

[Install]
WantedBy=timers.target
"""


@pytest.fixture
def systemd_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    path = tmp_path / "systemd"
    path.mkdir()
    monkeypatch.setattr(CronManager, "SYSTEMD_DIR", path)
    return path


@pytest.fixture
def store(tmp_path: Path) -> Iterator[NoustStore]:
    NoustStore.reset_instance()
    instance = NoustStore(tmp_path / "noust.db")
    root = tmp_path / "apps" / "shop-example-com"
    (root / "current").mkdir(parents=True)
    instance.create_app(
        App(domain=DOMAIN, app_type="python", app_path=str(root), layout="releases", port=8000)
    )
    yield instance
    instance.close()
    NoustStore.reset_instance()


@pytest.fixture(autouse=True)
def no_unit(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(
        "noust.managers.service_manager.ServiceManager.get_service_config",
        lambda self, name: None,
    )


@pytest.fixture
def old_task(systemd_dir: Path, store: NoustStore, tmp_path: Path) -> Path:
    root = tmp_path / "apps" / "shop-example-com"
    service = systemd_dir / "noust-cron-nightly.service"
    service.write_text(OLD_SERVICE.replace("{root}", str(root)))
    (systemd_dir / "noust-cron-nightly.timer").write_text(OLD_TIMER)
    return service


class TestWhichTasksAreStillAsTheyWere:
    def test_a_task_of_an_application_without_its_env_file_is_named(
        self, old_task: Path, tmp_path: Path
    ) -> None:
        (named,) = CronManager().tasks_without_their_environment()

        assert named["name"] == "nightly"
        assert named["app_domain"] == DOMAIN
        assert named["command"] == "/usr/bin/env migrate --noinput"
        assert named["on_calendar"] == "*-*-* 03:30:00"
        assert named["user"] == "noust-app-shop"
        assert named["timeout"] == 600

    def test_a_task_written_again_is_no_longer_named(
        self, runner: FakeRunner, old_task: Path
    ) -> None:
        CronManager().create_job(
            CronJob(
                name="nightly",
                command="/usr/bin/env migrate --noinput",
                schedule="*-*-* 03:30:00",
                app_domain=DOMAIN,
                user="noust-app-shop",
            )
        )

        assert CronManager().tasks_without_their_environment() == []

    def test_a_task_of_no_application_or_of_a_service_of_a_stack_is_not_named(
        self, systemd_dir: Path, store: NoustStore
    ) -> None:
        plain = OLD_SERVICE.replace("# Application: shop.example.com\n", "")
        stack = OLD_SERVICE.replace(
            "# Application: shop.example.com\n", "# Application: shop.example.com\n# Service: web\n"
        )
        for name, text in (("plain", plain), ("stack", stack)):
            (systemd_dir / f"noust-cron-{name}.service").write_text(text.replace("{root}", "/x"))
            (systemd_dir / f"noust-cron-{name}.timer").write_text(OLD_TIMER)

        assert CronManager().tasks_without_their_environment() == []

    def test_a_task_nobody_owns_is_not_named(self, systemd_dir: Path, store: NoustStore) -> None:
        (systemd_dir / "noust-cron-theirs.service").write_text(
            "[Service]\n# Application: shop.example.com\nExecStart=/bin/true\n"
        )
        (systemd_dir / "noust-cron-theirs.timer").write_text("[Timer]\nOnCalendar=daily\n")

        assert CronManager().tasks_without_their_environment() == []

    def test_a_task_of_an_application_that_is_gone_is_not_named(
        self, old_task: Path, store: NoustStore
    ) -> None:
        store.delete_app(DOMAIN)

        assert CronManager().tasks_without_their_environment() == []


class TestWhatTheDoctorSays:
    def test_it_names_each_task_with_the_command_that_writes_it_again(self, old_task: Path) -> None:
        section = setup_doctor.cron_section()

        assert section is not None
        assert (section.title, section.key) == ("Scheduled tasks", "cron")
        (found,) = section.items
        assert found.status == "warn"
        assert found.coded is not None and found.coded.code == "doctor.cron.without_environment"
        assert found.coded.params == {"name": "nightly", "domain": DOMAIN}
        assert found.fix is not None and found.fix.startswith("noust cron create nightly ")

    def test_nothing_to_say_is_no_section(self, systemd_dir: Path, store: NoustStore) -> None:
        assert setup_doctor.cron_section() is None

    def test_the_command_it_gives_works_as_it_is(
        self, runner: FakeRunner, old_task: Path, tmp_path: Path
    ) -> None:
        section = setup_doctor.cron_section()
        assert section is not None
        fix = section.items[0].fix
        assert fix is not None

        argv = shlex.split(fix)
        result = CliRunner().invoke(root_cli, argv[1:])

        assert result.exit_code == 0, result.output
        root = tmp_path / "apps" / "shop-example-com"
        assert f"EnvironmentFile=-{root}/shared/.env" in old_task.read_text()
        # And what the operator had set is what the command wrote again.
        text = old_task.read_text()
        assert "User=noust-app-shop" in text and "TimeoutStartSec=600" in text
        assert (
            "OnCalendar=*-*-* 03:30:00"
            in (old_task.parent / "noust-cron-nightly.timer").read_text()
        )
        assert setup_doctor.cron_section() is None

    def test_a_command_with_a_quote_in_it_is_still_one_command(
        self, systemd_dir: Path, store: NoustStore, tmp_path: Path
    ) -> None:
        root = tmp_path / "apps" / "shop-example-com"
        text = OLD_SERVICE.replace("{root}", str(root))
        text = text.replace(
            '# Command: "/usr/bin/env migrate --noinput"',
            '# Command: "/usr/bin/env sh -c \\"echo it\'s done\\""',
        ).replace(
            "ExecStart=/usr/bin/env migrate --noinput",
            'ExecStart=/usr/bin/env sh -c "echo it\'s done"',
        )
        (systemd_dir / "noust-cron-nightly.service").write_text(text)
        (systemd_dir / "noust-cron-nightly.timer").write_text(OLD_TIMER)

        section = setup_doctor.cron_section()

        assert section is not None
        fix = section.items[0].fix
        assert fix is not None
        assert shlex.split(fix)[4] == '/usr/bin/env sh -c "echo it\'s done"'

    def test_it_is_part_of_the_report_the_command_and_the_console_both_read(
        self, runner: FakeRunner, old_task: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from noust.deployers import compose_relay
        from noust.managers.server.requirements import DiskFree, Resources
        from noust.validators import ssh as ssh_module

        monkeypatch.setattr(compose_relay, "leftover_relays", lambda: [])
        monkeypatch.setattr(ssh_module, "ssh_key_exists", lambda: (True, "/root/.ssh/id_ed25519"))
        env = setup_doctor.DoctorEnvironment(
            command_exists=lambda program: True,
            run=lambda argv: type("R", (), {"stdout": "x 1.0\n"})(),
            include_ssh=False,
            apps_dir=tmp_path,
            log_dir=tmp_path,
            config_path=tmp_path / "config.yaml",
            resources=lambda: Resources(4096, 0, 2, (DiskFree(str(tmp_path), 51200, 102400),)),
            listeners=lambda: [(80, ("nginx",)), (443, ("nginx",))],
            app_types=lambda: {"python"},
        )

        report = setup_doctor.collect(env)

        tasks = next(section for section in report.sections if section.key == "cron")
        assert [item.status for item in tasks.items] == ["warn"]
        assert report.to_dict()["sections"][-1]["items"][0]["coded"]["code"] == (
            "doctor.cron.without_environment"
        )
