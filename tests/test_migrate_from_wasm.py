"""
The move of a WASM 2.x server onto Noust's names.

Every test builds a whole 2.x machine under ``tmp_path`` - /etc/wasm with its
config.yaml, /var/lib/wasm with a store in write-ahead-log mode, backups, the
nginx upstreams directory and the sites that include it, PHP-FPM pools, and
WASM's own units - and runs the real migration against it through a
FakeRunner. The properties asserted are the ones whose absence would lose an
operator's data or take their sites down: nothing is copied, the store is
never left behind an empty one, every failure is undone, and a run stopped
halfway is finished by the next.
"""

from __future__ import annotations

import errno
import json
import os
import sqlite3
from pathlib import Path

import pytest

import noust.core.migrate_from_wasm as migration
from noust.core import paths
from noust.core.fs import RealFileSystem
from noust.core.migrate_from_wasm import Layout, Migrator, needs_migration
from noust.core.runner import FakeRunner

APPS = ("shop-example-com", "blog-example-com")


def make_layout(root: Path) -> Layout:
    """
    Build a layout whose every path lives under ``root``.

    Args:
        root: The fake filesystem root.

    Returns:
        The layout.
    """
    return Layout(
        config_dir=root / "etc/noust",
        legacy_config_dir=root / "etc/wasm",
        state_dir=root / "var/lib/noust",
        legacy_state_dir=root / "var/lib/wasm",
        backup_dir=root / "var/backups/noust",
        legacy_backup_dir=root / "var/backups/wasm",
        user_data_dir=root / "root/.local/share/noust",
        legacy_user_data_dir=root / "root/.local/share/wasm",
        upstreams_dir=root / "etc/nginx/noust-upstreams",
        legacy_upstreams_dir=root / "etc/nginx/wasm-upstreams",
        nginx_site_dirs=(root / "etc/nginx/sites-available", root / "etc/nginx/sites-enabled"),
        systemd_dir=root / "etc/systemd/system",
        php_root=root,
        lock_file=root / "run/noust-migrate.lock",
    )


def make_store(path: Path, apps: tuple[str, ...] = APPS) -> None:
    """
    Create a store in write-ahead-log mode with a few applications in it.

    Args:
        path: The database file.
        apps: Application names to insert.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    connection.execute("PRAGMA journal_mode=WAL")
    connection.execute("CREATE TABLE apps (name TEXT)")
    connection.executemany("INSERT INTO apps VALUES (?)", [(a,) for a in apps])
    connection.commit()
    connection.close()


def app_names(path: Path) -> list[str]:
    """
    Read the applications a store holds.

    Args:
        path: The database file.

    Returns:
        Their names, sorted.
    """
    connection = sqlite3.connect(path)
    try:
        return sorted(row[0] for row in connection.execute("SELECT name FROM apps"))
    finally:
        connection.close()


