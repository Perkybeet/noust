def migrator(layout: Layout, runner: FakeRunner, lines: list[str] | None = None) -> Migrator:
    """
    Build a migrator over a fake machine.

    Args:
        layout: The machine.
        runner: Answers systemctl, nginx and php-fpm.
        lines: Collects the announced steps.

    Returns:
        The migrator.
    """
    return Migrator(
        layout,
        runner=runner,
        fs=RealFileSystem(),
        announce=(lines.append if lines is not None else None),
        noust_executable="/usr/bin/noust",
    )


def inactive(runner: FakeRunner, *units: str) -> FakeRunner:
    """
    Make systemd report units as neither enabled nor running.

    Args:
        runner: The runner to script.
        units: Unit file names.

    Returns:
        The runner.
    """
    for unit in units:
        runner.script(["systemctl", "is-active", "--quiet", unit], exit_code=3)
        runner.script(["systemctl", "is-enabled", "--quiet", unit], exit_code=1)
    return runner


def quiet_runner() -> FakeRunner:
    """
    A machine where every unit is enabled and running but the cron job's
    service, which only its timer starts and which is not running now.

    Returns:
        The runner.
    """
    return inactive(FakeRunner(), "wasm-cron-nightly.service")


class TestFullMigration:
    """A 2.x server, migrated in one run."""

    def test_every_directory_moves_and_leaves_a_link(self, machine: Layout) -> None:
        report = migrator(machine, quiet_runner()).run()

        assert report.complete, report.as_dict()
        for legacy, new in (
            (machine.legacy_config_dir, machine.config_dir),
            (machine.legacy_state_dir, machine.state_dir),
            (machine.legacy_backup_dir, machine.backup_dir),
            (machine.legacy_upstreams_dir, machine.upstreams_dir),
        ):
            assert new.is_dir() and not new.is_symlink()
            assert legacy.is_symlink()
            assert legacy.resolve() == new.resolve()
        assert (machine.config_dir / "web-secret").read_text() == "signing key"
        assert (machine.state_dir / "secrets" / "shop").read_text() == "s3cret"
        # A backup path recorded as /var/backups/wasm/... still opens.
        recorded = machine.legacy_backup_dir / "shop-example-com-20260901.tar.gz"
        assert recorded.read_text() == "archive"

    def test_the_store_is_renamed_with_every_row(self, machine: Layout) -> None:
        migrator(machine, quiet_runner()).run()

        store = machine.state_dir / paths.STORE_NAME
        assert app_names(store) == sorted(APPS)
        assert not (machine.state_dir / paths.LEGACY_STORE_NAME).exists()
        assert not Path(f"{machine.state_dir / paths.LEGACY_STORE_NAME}-wal").exists()

    def test_config_defaults_are_rewritten_and_the_rest_kept(self, machine: Layout) -> None:
        migrator(machine, quiet_runner()).run()

        text = (machine.config_dir / "config.yaml").read_text()
        assert "# Operator's comment, kept" in text
        assert "directory: /var/backups/noust\n" in text
        assert "file: /var/log/noust/noust.log\n" in text
        assert "log_file: '/var/log/noust/monitor.log'\n" in text
        assert "max_per_app: 10" in text
        assert (machine.config_dir / "config.yaml").stat().st_mode & 0o777 == 0o600

    def test_sites_are_repointed_and_nginx_tested_then_reloaded(self, machine: Layout) -> None:
        runner = quiet_runner()
        migrator(machine, runner).run()

        site = machine.nginx_site_dirs[0] / "shop.example.com"
        assert f"include {machine.upstreams_dir}/shop-example-com.conf;" in site.read_text()
        # The enabling symlink was not replaced by a copy.
        assert (machine.nginx_site_dirs[1] / "shop.example.com").is_symlink()
        test = runner.calls.index(("nginx", "-t"))
        reload = runner.calls.index(("systemctl", "reload", "nginx"))
        assert test < reload

    def test_units_are_replaced_in_the_same_state(self, machine: Layout) -> None:
        runner = quiet_runner()
        migrator(machine, runner).run()

        units = machine.systemd_dir
        for old in ("wasm-web.service", "wasm-monitor.service", "wasm-cron-nightly.timer"):
            assert not (units / old).exists()
        web = (units / "noust-web.service").read_text()
        assert "# Generated by Noust." in web
        assert "Generated by WASM" not in web
        assert "ExecStart=/usr/bin/noust web start --under-systemd" in web
        assert "--tls-cert /etc/noust/panel-tls/panel.crt" in web
        assert "SyslogIdentifier=noust-web" in web
        assert "Description=Noust console" in web
        monitor = (units / "noust-monitor.service").read_text()
        assert "StateDirectory=noust\nLogsDirectory=noust\n" in monitor
        assert "ExecStart=/usr/bin/noust monitor run" in monitor
        timer = (units / "noust-cron-nightly.timer").read_text()
        assert "Unit=noust-cron-nightly.service" in timer
        service = (units / "noust-cron-nightly.service").read_text()
        assert "ExecStart=/usr/bin/php /var/www/apps/shop-example-com/artisan" in service

        # Enabled and started as the old ones were (all reported active here,
        # but the cron job's service, which only a timer starts).
        assert ("systemctl", "enable", "noust-web.service") in runner.calls
        assert ("systemctl", "start", "noust-web.service") in runner.calls
        assert ("systemctl", "enable", "noust-cron-nightly.timer") in runner.calls
        assert ("systemctl", "start", "noust-cron-nightly.timer") in runner.calls
        assert ("systemctl", "start", "noust-cron-nightly.service") not in runner.calls
        assert ("systemctl", "disable", "wasm-web.service") in runner.calls

    def test_the_old_console_stops_before_the_new_one_starts(self, machine: Layout) -> None:
        runner = quiet_runner()
        migrator(machine, runner).run()

        stops = [
            i for i, c in enumerate(runner.calls) if c == ("systemctl", "stop", "wasm-web.service")
        ]
        start = runner.calls.index(("systemctl", "start", "noust-web.service"))
        assert stops and min(stops) < start
        # It was not started again under its old name: the new one replaced it.
        assert ("systemctl", "start", "wasm-web.service") not in runner.calls

    def test_application_and_foreign_units_keep_their_names(self, machine: Layout) -> None:
        migrator(machine, quiet_runner()).run()

        assert (machine.systemd_dir / "wasm-shop-example-com.service").read_text() == APP_UNIT
        assert (machine.systemd_dir / "wasm-backup-handmade.service").exists()
        assert not (machine.systemd_dir / "noust-backup-handmade.service").exists()

    def test_a_record_is_left_for_the_console(self, machine: Layout) -> None:
        migrator(machine, quiet_runner()).run()

        history = json.loads(machine.record.read_text())
        assert history[-1]["complete"] is True
        assert any(step["kind"] == "store" for step in history[-1]["steps"])

    def test_one_line_per_step_is_announced(self, machine: Layout) -> None:
        lines: list[str] = []
        migrator(machine, quiet_runner(), lines).run()

        assert any("renamed" in line and "etc/wasm" in line for line in lines)
        assert any("wasm-web" in line and "noust-web" in line for line in lines)

    def test_running_again_does_nothing(self, machine: Layout) -> None:
        migrator(machine, quiet_runner()).run()
        assert not needs_migration(machine)

        runner = quiet_runner()
        report = migrator(machine, runner).run()
        assert report.steps == []
        assert runner.calls == []


class TestDryRun:
    """A plan changes nothing."""

    def test_plan_lists_every_step_and_touches_nothing(self, machine: Layout) -> None:
        runner = quiet_runner()
        before = sorted(str(p) for p in machine.legacy_config_dir.parent.parent.rglob("*"))

        report = migrator(machine, runner).plan()

        after = sorted(str(p) for p in machine.legacy_config_dir.parent.parent.rglob("*"))
        assert before == after
        assert runner.calls == []
        kinds = [step.kind for step in report.steps]
        assert kinds.count("directory") == 3
        assert {"store", "config", "nginx", "unit"} <= set(kinds)
        assert all(step.status == "pending" for step in report.steps)


class TestRefusals:
    """What is not safe to do is not done, and is explained."""

    def test_a_different_filesystem_is_refused_and_nothing_copied(
        self, machine: Layout, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        state = machine.legacy_state_dir

        def same(first: Path, second: Path) -> bool:
            return first != state

        monkeypatch.setattr(migration, "same_filesystem", same)
        report = migrator(machine, quiet_runner()).run()

        refused = [s for s in report.steps if s.status == "refused"]
        assert any("different filesystems" in s.detail for s in refused)
        assert state.is_dir() and not state.is_symlink()
        assert not machine.state_dir.exists()
        # The store was renamed in place, where the resolution still finds it.
        assert app_names(state / paths.STORE_NAME) == sorted(APPS)
        # The units expect the new state directory, so they were left alone.
        assert (machine.systemd_dir / "wasm-monitor.service").exists()
        assert not (machine.systemd_dir / "noust-monitor.service").exists()
        assert not report.complete

    def test_a_cross_device_rename_is_undone(
        self, machine: Layout, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        class CrossDevice(RealFileSystem):
            def rename(self, source: Path, destination: Path) -> None:
                if source == machine.legacy_backup_dir:
                    raise OSError(errno.EXDEV, "Invalid cross-device link")
                super().rename(source, destination)

        report = Migrator(
            machine, runner=quiet_runner(), fs=CrossDevice(), noust_executable="/usr/bin/noust"
        ).run()

        failed = [s for s in report.steps if s.status == "failed"]
        assert failed and "different filesystems" in failed[0].detail
        assert machine.legacy_backup_dir.is_dir() and not machine.legacy_backup_dir.is_symlink()
        assert not os.path.lexists(migration._pending_link(machine.legacy_backup_dir))
        # backup.directory still names the backups where they are.
        text = (machine.config_dir / "config.yaml").read_text()
        assert "directory: /var/backups/wasm\n" in text

    def test_a_store_held_open_is_not_moved(self, machine: Layout) -> None:
        holder = sqlite3.connect(machine.legacy_state_dir / "wasm.db")
        holder.execute("INSERT INTO apps VALUES ('late')")
        holder.commit()
        try:
            report = migrator(machine, quiet_runner()).run()
        finally:
            holder.close()

        store = next(s for s in report.steps if s.kind == "store")
        assert store.status == "refused"
        assert "open" in store.detail
        assert (machine.legacy_state_dir / "wasm.db").exists()
        assert app_names(machine.legacy_state_dir / "wasm.db") == sorted((*APPS, "late"))

    def test_a_noust_directory_a_package_created_is_made_way_for(self, machine: Layout) -> None:
        machine.config_dir.mkdir(parents=True)
        (machine.config_dir / "config.yaml").write_text("# packaged default\n")
        machine.state_dir.mkdir(parents=True)

        report = migrator(machine, quiet_runner()).run()

        assert report.complete
        assert "Operator's comment" in (machine.config_dir / "config.yaml").read_text()
        aside = list(machine.config_dir.parent.glob("noust.before-migration-*"))
        assert len(aside) == 1
        assert (aside[0] / "config.yaml").read_text() == "# packaged default\n"
        assert app_names(machine.state_dir / paths.STORE_NAME) == sorted(APPS)

    def test_a_timer_job_running_right_now_is_left_for_later(self, machine: Layout) -> None:
        runner = FakeRunner()  # every unit reports active, the job's service included
        report = migrator(machine, runner).run()

        cron = next(s for s in report.steps if "wasm-cron-nightly" in s.description)
        assert cron.status == "refused"
        assert (machine.systemd_dir / "wasm-cron-nightly.timer").exists()


class TestUndo:
    """Every failure puts back what was there."""

    def test_a_unit_that_cannot_be_enabled_is_put_back(self, machine: Layout) -> None:
        runner = quiet_runner()
        runner.script(
            ["systemctl", "enable", "noust-cron-nightly.timer"],
            exit_code=1,
            stderr="Failed to enable unit: Unit file noust-cron-nightly.timer is masked.",
        )

        report = migrator(machine, runner).run()

        step = next(s for s in report.steps if "wasm-cron-nightly" in s.description)
        assert step.status == "failed"
        assert "masked" in step.detail
        assert (machine.systemd_dir / "wasm-cron-nightly.timer").read_text() == CRON_TIMER
        assert not (machine.systemd_dir / "noust-cron-nightly.timer").exists()
        assert not (machine.systemd_dir / "noust-cron-nightly.service").exists()
        # Restored in the state it had: enabled and running again.
        last_enable = max(
            i
            for i, c in enumerate(runner.calls)
            if c == ("systemctl", "enable", "wasm-cron-nightly.timer")
        )
        failed_enable = runner.calls.index(("systemctl", "enable", "noust-cron-nightly.timer"))
        assert last_enable > failed_enable
        assert ("systemctl", "start", "wasm-cron-nightly.timer") in runner.calls
        # The other units were still migrated.
        assert (machine.systemd_dir / "noust-web.service").exists()

    def test_a_console_that_does_not_come_up_is_put_back_and_restarted(
        self, machine: Layout
    ) -> None:
        runner = quiet_runner()
        runner.script(["systemctl", "is-active", "--quiet", "noust-web.service"], exit_code=3)
        runner.script(
            ["journalctl", "-u", "noust-web.service"], stdout="bind: address already in use"
        )

        report = migrator(machine, runner).run()

        step = next(s for s in report.steps if "wasm-web" in s.description)
        assert step.status == "failed"
        assert "address already in use" in step.detail
        assert (machine.systemd_dir / "wasm-web.service").exists()
        assert not (machine.systemd_dir / "noust-web.service").exists()
        assert runner.calls[-1] != ("systemctl", "stop", "wasm-web.service")
        assert ("systemctl", "start", "wasm-web.service") in runner.calls

    def test_nginx_rejecting_the_includes_restores_every_site(self, machine: Layout) -> None:
        site = machine.nginx_site_dirs[0] / "shop.example.com"
        original = site.read_text()
        runner = quiet_runner()
        runner.script(["nginx", "-t"], exit_code=1, stderr="nginx: [emerg] unexpected end of file")

        report = migrator(machine, runner).run()

        step = next(s for s in report.steps if s.kind == "nginx")
        assert step.status == "failed"
        assert "[emerg] unexpected end of file" in step.detail
        assert site.read_text() == original
        assert ("systemctl", "reload", "nginx") not in runner.calls
        # The includes keep loading through the link.
        assert (machine.legacy_upstreams_dir / "shop-example-com.conf").is_file()


class TestInterrupted:
    """A run stopped between two steps is finished by the next."""

    def test_a_directory_renamed_before_its_link_was_placed(self, machine: Layout) -> None:
        # What a run stopped right after renaming /etc/wasm leaves behind.
        pending = migration._pending_link(machine.legacy_config_dir)
        pending.symlink_to(machine.config_dir)
        machine.legacy_config_dir.rename(machine.config_dir)
        assert needs_migration(machine)

        report = migrator(machine, quiet_runner()).run()

        assert report.complete
        assert machine.legacy_config_dir.is_symlink()
        assert not os.path.lexists(pending)

    def test_a_store_renamed_before_its_directory_moved(self, machine: Layout) -> None:
        (machine.legacy_state_dir / "wasm.db").rename(machine.legacy_state_dir / "noust.db")

        report = migrator(machine, quiet_runner()).run()

        assert report.complete
        assert app_names(machine.state_dir / paths.STORE_NAME) == sorted(APPS)

    def test_a_run_that_crashed_mid_way_is_completed(
        self, machine: Layout, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        class Crash(Exception):
            pass

        class Crashing(RealFileSystem):
            def rename(self, source: Path, destination: Path) -> None:
                super().rename(source, destination)
                if destination == machine.state_dir:
                    raise Crash

        with pytest.raises(Crash):
            Migrator(
                machine, runner=quiet_runner(), fs=Crashing(), noust_executable="/usr/bin/noust"
            ).run()
        assert machine.state_dir.is_dir()
        assert not machine.legacy_state_dir.exists()

        report = migrator(machine, quiet_runner()).run()

        assert report.complete
        assert machine.legacy_state_dir.is_symlink()
        assert app_names(machine.state_dir / paths.STORE_NAME) == sorted(APPS)
        assert (machine.systemd_dir / "noust-web.service").exists()


