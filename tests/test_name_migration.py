"""
Finishing the renaming of 4.0: ``noust setup rename`` and what ``noust health`` and the doctor say.

Every step is idempotent, nothing here restarts anything, and a step that fails leaves the
others to run. The marker rewrite is the one that also runs by itself, once, on the first
privileged command after the update.
"""

from __future__ import annotations

import json
import os
from dataclasses import replace
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

from noust.core import legacy_names, paths
from noust.core.fs import DryRunFileSystem, get_fs
from noust.core.runner import FakeRunner
from noust.core.store import App
from noust.managers import name_migration
from noust.managers.name_migration import NameMigration
from noust.managers.nginx_manager import NginxManager
from noust.managers.webserver import NGINX_BACKEND

OLD_MARKER = legacy_names.GENERATED_MARKER


class Apps:
    """The part of the store the migration reads: the applications."""

    def __init__(self, *apps: App) -> None:
        self.apps = list(apps)

    def list_apps(self, **_: object) -> list[App]:
        return list(self.apps)

    def list_backup_destinations(self) -> list[Any]:
        return []


def application(root: Path, name: str = "shop-example-com", layout: str = "releases") -> App:
    return App(
        domain="shop.example.com",
        app_type="nodejs",
        app_path=str(root / name),
        layout=layout,
        port=3000,
    )


def tree_with_old_names(root: Path) -> Path:
    app = root / "shop-example-com"
    (app / legacy_names.TREE_ENV_DIR).mkdir(parents=True, mode=0o700)
    (app / legacy_names.TREE_ENV_DIR / "env-config.json").write_text("{}")
    modules = app / "releases" / "20260101-000000" / "node_modules"
    modules.mkdir(parents=True)
    (modules / legacy_names.TREE_RUNTIME_STAMP).write_text("{}")
    return app


class TestMarkers:
    def roots(self, tmp_path: Path) -> list[tuple[Path, tuple[str, ...]]]:
        sites = tmp_path / "nginx" / "sites-available"
        units = tmp_path / "systemd"
        sites.mkdir(parents=True)
        units.mkdir()
        return [(sites, ()), (units, (".service", ".timer"))]

    def write(self, directory: Path, name: str, text: str, mode: int = 0o644) -> Path:
        path = directory / name
        path.write_text(text)
        path.chmod(mode)
        return path

    def test_only_the_marker_changes_and_a_copy_is_kept(self, tmp_path: Path) -> None:
        roots = self.roots(tmp_path)
        site = self.write(
            roots[0][0],
            "shop.example.com",
            f"# Nginx reverse proxy for shop.example.com\n# {OLD_MARKER}\nserver {{ listen 80; }}\n",
            mode=0o640,
        )
        backups = tmp_path / "copies"

        done = name_migration.rewrite_markers(fs=get_fs(), roots=roots, backup_to=backups)

        assert done == [site]
        assert site.read_text() == (
            "# Nginx reverse proxy for shop.example.com\n# Generated by Noust\n"
            "server { listen 80; }\n"
        )
        assert site.stat().st_mode & 0o777 == 0o640
        copy = backups / str(site).lstrip("/")
        assert OLD_MARKER in copy.read_text()
        assert copy.stat().st_mode & 0o777 == 0o600

    def test_files_that_were_not_noust_s_and_links_are_left_alone(self, tmp_path: Path) -> None:
        roots = self.roots(tmp_path)
        foreign = self.write(roots[0][0], "default", "server { listen 80; }\n")
        target = tmp_path / "elsewhere"
        target.write_text(f"# {OLD_MARKER}\n")
        (roots[0][0] / "linked").symlink_to(target)
        wrong_suffix = self.write(roots[1][0], "notes.txt", f"# {OLD_MARKER}\n")

        done = name_migration.rewrite_markers(
            fs=get_fs(), roots=roots, backup_to=tmp_path / "copies"
        )

        assert done == []
        assert foreign.read_text() == "server { listen 80; }\n"
        assert target.read_text() == f"# {OLD_MARKER}\n"
        assert wrong_suffix.read_text() == f"# {OLD_MARKER}\n"

    def test_a_marker_far_down_a_file_is_a_mention_not_a_signature(self, tmp_path: Path) -> None:
        roots = self.roots(tmp_path)
        text = "x\n" * 2000 + f"# {OLD_MARKER}\n"
        site = self.write(roots[0][0], "long", text)

        assert name_migration.rewrite_markers(fs=get_fs(), roots=roots) == []
        assert site.read_text() == text

    def test_a_second_run_finds_nothing(self, tmp_path: Path) -> None:
        roots = self.roots(tmp_path)
        self.write(roots[1][0], "app.service", f"# {OLD_MARKER}\n[Unit]\n")
        name_migration.rewrite_markers(fs=get_fs(), roots=roots, backup_to=tmp_path / "copies")

        assert name_migration.rewrite_markers(fs=get_fs(), roots=roots) == []

    def test_a_rehearsal_changes_nothing(self, tmp_path: Path) -> None:
        roots = self.roots(tmp_path)
        unit = self.write(roots[1][0], "app.service", f"# {OLD_MARKER}\n[Unit]\n")

        name_migration.rewrite_markers(
            fs=DryRunFileSystem(), roots=roots, backup_to=tmp_path / "copies"
        )

        assert OLD_MARKER in unit.read_text()
        assert not (tmp_path / "copies").exists()


class TestAutomaticRun:
    @pytest.fixture
    def state(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
        monkeypatch.setattr(paths, "state_dir", lambda: tmp_path / "state")
        monkeypatch.setattr(paths, "backup_dir", lambda: tmp_path / "backups")
        monkeypatch.setattr(os, "geteuid", lambda: 0)
        monkeypatch.delenv("INVOCATION_ID", raising=False)
        monkeypatch.delenv("_NOUST_COMPLETE", raising=False)
        monkeypatch.delenv("_WASM_COMPLETE", raising=False)
        monkeypatch.setattr(name_migration, "_MARKED_PLACES", ())
        return tmp_path / "state" / "name-migration.json"

    def test_it_looks_once_and_remembers(self, state: Path) -> None:
        lines: list[str] = []

        assert name_migration.run_automatically(["list"], lines.append) == []
        assert json.loads(state.read_text())["markers"]
        assert name_migration.run_automatically(["list"], lines.append) is None

    def test_it_says_what_it_rewrote(
        self, state: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        sites = tmp_path / "sites"
        sites.mkdir()
        (sites / "a").write_text(f"# {OLD_MARKER}\n")
        monkeypatch.setattr(name_migration, "_MARKED_PLACES", ((str(sites), ()),))
        lines: list[str] = []

        done = name_migration.run_automatically(["list"], lines.append)

        assert done == [sites / "a"]
        assert "1 file(s)" in lines[0] and str(tmp_path / "backups") in lines[0]

    @pytest.mark.parametrize(
        ("argv", "environment"),
        [
            (["list", "--dry-run"], {}),
            (["list"], {"INVOCATION_ID": "abc"}),
            (["list"], {"_NOUST_COMPLETE": "bash_complete"}),
        ],
        ids=["a rehearsal", "a unit of systemd", "completion"],
    )
    def test_it_does_not_run_where_it_should_not(
        self,
        state: Path,
        monkeypatch: pytest.MonkeyPatch,
        argv: list[str],
        environment: dict[str, str],
    ) -> None:
        for key, value in environment.items():
            monkeypatch.setenv(key, value)

        assert name_migration.run_automatically(argv, lambda line: None) is None
        assert not state.exists()

    def test_it_does_not_run_for_somebody_who_is_not_root(
        self, state: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setattr(os, "geteuid", lambda: 1000)

        assert name_migration.run_automatically(["list"], lambda line: None) is None


class TestSteps:
    def test_trees_are_renamed_for_every_application(self, tmp_path: Path) -> None:
        app = tree_with_old_names(tmp_path)
        migration = NameMigration(store=Apps(application(tmp_path)), fs=get_fs())  # type: ignore[arg-type]

        outcome = migration.trees()

        assert len(outcome.changed) == 2
        assert list(app.rglob(".wasm*")) == []
        assert migration.trees().changed == []

    def test_a_step_that_cannot_read_the_store_does_not_stop_the_others(
        self, tmp_path: Path
    ) -> None:
        class Broken:
            def list_apps(self, **_: object) -> list[App]:
                from noust.core.store import StoreError

                raise StoreError("the store is locked")

        migration = NameMigration(store=Broken(), fs=get_fs(), marker_roots=[], web=object())  # type: ignore[arg-type]

        outcomes = migration.run(["trees", "markers"])

        assert [outcome.step for outcome in outcomes] == ["trees", "markers"]
        assert outcomes[0].changed == []

    def test_image_tags_are_moved_to_the_current_name(self, tmp_path: Path) -> None:
        runner = FakeRunner().only_knows("docker")
        old, new = legacy_names.PREVIOUS_IMAGE_TAG, "noust_previous"
        runner.script(
            ("docker", "image", "ls", "--filter", f"reference=*:{old}"),
            stdout="stack-web\tsha256:aaa\nstack-db\tsha256:bbb\n",
        )
        runner.script(
            ("docker", "image", "ls", "--filter", f"reference=stack-db:{new}"),
            stdout="sha256:bbb\n",
        )
        migration = NameMigration(store=Apps(), fs=get_fs(), runner=runner)  # type: ignore[arg-type]

        outcome = migration.images()

        assert outcome.changed == [
            f"stack-web:{old} -> stack-web:{new}",
            f"stack-db:{old} -> stack-db:{new}",
        ]
        assert ("docker", "image", "tag", "sha256:aaa", f"stack-web:{new}") in runner.calls
        assert not [c for c in runner.calls if c[:4] == ("docker", "image", "tag", "sha256:bbb")], (
            "a stack that already has the new tag is not tagged again"
        )
        assert ("docker", "image", "rm", f"stack-web:{old}") in runner.calls
        assert ("docker", "image", "rm", f"stack-db:{old}") in runner.calls

    def test_a_machine_without_docker_has_no_images_to_move(self) -> None:
        runner = FakeRunner().only_knows()

        outcome = NameMigration(store=Apps(), fs=get_fs(), runner=runner).images()  # type: ignore[arg-type]

        assert outcome.changed == [] and outcome.failed == []
        assert runner.calls == []

    def test_a_tag_docker_refuses_to_remove_is_a_failure_not_a_stop(self) -> None:
        runner = FakeRunner().only_knows("docker")
        old = legacy_names.PREVIOUS_IMAGE_TAG
        runner.script(
            ("docker", "image", "ls", "--filter", f"reference=*:{old}"),
            stdout="stack-web\tsha256:aaa\n",
        )
        runner.script(("docker", "image", "rm"), stderr="image is being used", exit_code=1)

        outcome = NameMigration(store=Apps(), fs=get_fs(), runner=runner).images()  # type: ignore[arg-type]

        assert outcome.changed == []
        assert "image is being used" in outcome.failed[0]

    def test_accounts_are_dropped_in_every_engine_that_runs(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        dropped: list[str] = []

        def manager(name: str, *, running: bool, databases: list[str]) -> SimpleNamespace:
            return SimpleNamespace(
                ENGINE_NAME=name,
                is_installed=lambda: True,
                is_running=lambda: running,
                list_databases=lambda: [SimpleNamespace(name=db) for db in databases],
                drop_legacy_read_only_account=lambda db: dropped.append(f"{name}/{db}") or True,
            )

        engines = [
            manager("postgresql", running=True, databases=["shop", "blog"]),
            manager("mysql", running=False, databases=["old"]),
        ]
        monkeypatch.setattr(
            "noust.managers.database.service.DatabaseService",
            lambda: SimpleNamespace(all_managers=lambda: engines),
        )

        outcome = NameMigration(store=Apps(), fs=get_fs()).accounts()  # type: ignore[arg-type]

        assert dropped == ["postgresql/shop", "postgresql/blog"]
        assert outcome.changed == dropped


class TestFindings:
    def migration(self, tmp_path: Path, apps: list[App] | None = None) -> NameMigration:
        units = tmp_path / "systemd"
        units.mkdir(exist_ok=True)
        nginx = tmp_path / "nginx"
        for name in ("sites-available", "sites-enabled", "noust-upstreams"):
            (nginx / name).mkdir(parents=True, exist_ok=True)
        web = NginxManager(
            backend=replace(
                NGINX_BACKEND,
                sites_available=nginx / "sites-available",
                sites_enabled=nginx / "sites-enabled",
                upstreams_dir=nginx / "noust-upstreams",
            )
        )
        return NameMigration(
            store=Apps(*(apps or [])),  # type: ignore[arg-type]
            fs=get_fs(),
            web=web,
            unit_dir=units,
            marker_roots=[(units, (".service",))],
        )

    def kinds(self, found: list[name_migration.Finding]) -> list[str]:
        return [finding.kind for finding in found]

    def test_a_server_with_nothing_left_has_nothing_to_say(
        self, tmp_path: Path, runner: FakeRunner
    ) -> None:
        assert self.migration(tmp_path).findings() == []

    def test_a_unit_waits_for_its_applications_next_update(
        self, tmp_path: Path, runner: FakeRunner
    ) -> None:
        migration = self.migration(tmp_path, [application(tmp_path)])
        (migration.unit_dir / "wasm-shop-example-com.service").write_text("[Unit]\n")

        (finding,) = migration.findings()

        assert finding.kind == "unit" and not finding.waits_for_operator
        assert "next update" in (finding.fix or "")
        assert "noust update shop.example.com" in (finding.fix or "")

    def test_a_tree_with_old_names_is_listed_with_the_command_that_finishes_it(
        self, tmp_path: Path, runner: FakeRunner
    ) -> None:
        tree_with_old_names(tmp_path)

        (finding,) = self.migration(tmp_path, [application(tmp_path)]).findings()

        assert finding.kind == "tree" and finding.fix == "Run: noust setup rename"
        assert "2 file(s)" in finding.text

    def test_a_repository_with_the_old_overrides_file_is_an_operator_s_to_rename(
        self, tmp_path: Path, runner: FakeRunner
    ) -> None:
        app = application(tmp_path, layout="inplace")
        (tmp_path / "shop-example-com").mkdir()
        (tmp_path / "shop-example-com" / legacy_names.NGINX_OVERRIDE_FILES[0]).write_text(
            "routes: []"
        )

        (finding,) = self.migration(tmp_path, [app]).findings()

        assert finding.kind == "repository file" and finding.waits_for_operator
        assert "git mv" in (finding.fix or "")

    def test_an_operator_s_site_that_names_the_old_upstream_is_said_with_its_line(
        self, tmp_path: Path, runner: FakeRunner
    ) -> None:
        migration = self.migration(tmp_path)
        nginx = tmp_path / "nginx"
        (nginx / "noust-upstreams" / "shop.conf").write_text(
            "# Generated by Noust\nupstream wasm_bg_shop {\n    server 127.0.0.1:3001;\n}\n"
        )
        edge = nginx / "sites-available" / "edge"
        edge.write_text(
            "server {\n    location / {\n        proxy_pass http://wasm_bg_shop;\n    }\n}\n"
        )

        found = migration.findings()

        assert self.kinds(found) == ["upstream"]
        assert found[0].waits_for_operator
        assert f"{edge.resolve()}:3" in found[0].notes[0]
        assert "noust_bg_shop" in found[0].notes[0]
        assert "noust setup rename" in (found[0].fix or "")

    def test_what_waits_for_the_operator_comes_first(
        self, tmp_path: Path, runner: FakeRunner
    ) -> None:
        migration = self.migration(tmp_path)
        (migration.unit_dir / "wasm-shop-example-com.service").write_text("[Unit]\n")
        nginx = tmp_path / "nginx"
        (nginx / "noust-upstreams" / "shop.conf").write_text(
            "# Generated by Noust\nupstream wasm_bg_shop {\n    server 127.0.0.1:3001;\n}\n"
        )
        (nginx / "sites-available" / "edge").write_text("proxy_pass http://wasm_bg_shop;\n")

        found = migration.findings()

        assert [f.waits_for_operator for f in found] == [True, False]

    def test_the_lines_of_a_report(self) -> None:
        lines = name_migration.finding_lines(
            [name_migration.Finding("unit", "x", "A unit  has it", fix="do this")]
        )

        assert lines == ["A unit has it (do this)"]
