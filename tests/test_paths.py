"""
noust.core.paths: the one place that knows where Noust keeps things.

The directories are the system ones, or the ones under ``NOUST_DATA_DIR``; a directory under
another name is never preferred to them, because that is how creating one directory once moved a
populated store to an empty one (2026-08-13). A server whose data was never moved is refused
before it gets here (``noust.core.retired_names``).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from noust.core import paths


class TestDirectories:
    def test_the_system_directories_are_noust_s(self) -> None:
        if paths.DATA_DIR is not None:  # pragma: no cover - a suite run under a data directory
            pytest.skip("a data directory was named")
        assert paths.config_dir() == Path("/etc/noust")
        assert paths.state_dir() == Path("/var/lib/noust")
        assert paths.backup_dir() == Path("/var/backups/noust")
        assert paths.log_dir() == Path("/var/log/noust")
        assert paths.nginx_upstreams_dir() == Path("/etc/nginx/noust-upstreams")

    def test_a_directory_under_another_name_is_never_preferred(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        (tmp_path / "old").mkdir()
        monkeypatch.setattr(paths, "CONFIG_DIR", tmp_path / "new")

        assert paths.config_dir() == tmp_path / "new"


class TestEnvironment:
    def test_the_noust_spelling_is_read(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setenv("NOUST_WEB_STATE_DIR", "/new")
        assert paths.getenv("WEB_STATE_DIR") == "/new"

    def test_the_spelling_before_3_0_is_not(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.delenv("NOUST_WEB_STATE_DIR", raising=False)
        monkeypatch.setenv("WASM_WEB_STATE_DIR", "/old")
        assert paths.getenv("WEB_STATE_DIR") is None
        assert paths.getenv("WEB_STATE_DIR", "fallback") == "fallback"

    def test_an_empty_value_is_a_value(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setenv("NOUST_WEB_STATE_DIR", "")
        assert paths.getenv("WEB_STATE_DIR", "fallback") == ""


class TestUnits:
    @pytest.mark.parametrize(
        "name",
        [
            "noust-web",
            "wasm-web",
            "noust-monitor",
            "wasm-monitor",
            "noust-previews",
            "wasm-previews",
            "noust-cron-nightly",
            "wasm-cron-nightly",
            "noust-backup-shop-example-com",
            "wasm-backup-shop-example-com",
        ],
    )
    def test_own_units_under_either_name(self, name: str) -> None:
        assert paths.is_own_unit_name(name)

    @pytest.mark.parametrize("name", ["shop-example-com", "wasm-shop-example-com", "nginx"])
    def test_application_and_system_units_are_not_own(self, name: str) -> None:
        assert not paths.is_own_unit_name(name)

    def test_either_marker_is_recognised(self) -> None:
        assert paths.carries_unit_marker("# Generated by Noust\n[Unit]\n")
        assert paths.carries_unit_marker("# Generated by WASM\n[Unit]\n")
        assert not paths.carries_unit_marker("[Unit]\nDescription=hand made\n")


def test_repository_overrides_prefer_the_new_name(tmp_path: Path) -> None:
    from noust.deployers.helpers.nginx_config import NginxConfigBuilder

    builder = NginxConfigBuilder()
    (tmp_path / "wasm.nginx.yaml").write_text("routes: []\n")
    assert builder.detect(tmp_path) == tmp_path / "wasm.nginx.yaml"
    (tmp_path / "noust.nginx.yaml").write_text("routes: []\n")
    assert builder.detect(tmp_path) == tmp_path / "noust.nginx.yaml"
