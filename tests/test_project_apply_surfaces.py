"""
``noust app export --as-yaml``, ``noust app apply`` and their API (checklist A-51).

The surfaces only parse, show and confirm: what they do is :mod:`noust.deployers.project_apply`.
What is pinned here is what a person or a script meets: a plan before anything changes, a
question (or ``--yes``) before anything that runs commands, no way to write secrets, and a route
that is root-equivalent, needs sudo mode and refuses to run commands nobody confirmed.
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest

from noust.core.store import App, NoustStore
from noust.deployers import app_export, project_apply
from tests.test_project_apply import DOMAIN, FakeCron, Recorder

DECLARATION = (
    "app:\n  limits: {memory_max_mb: 256}\nenv:\n  LOG_LEVEL: debug\n"
    "tasks:\n  - {name: nightly, schedule: daily, command: ./bin/cleanup}\n"
)


