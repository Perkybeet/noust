def invoke(*args: str) -> Any:
    from click.testing import CliRunner

    from noust.cli.app import cli

    return CliRunner().invoke(cli, list(args))


def declaration_file(tmp_path: Path, text: str = DECLARATION) -> str:
    path = tmp_path / "noust.yaml"
    path.write_text(text)
    return str(path)


class TestTheCommands:
    def test_export_as_yaml(self, store: NoustStore, cron: FakeCron, tmp_path: Path) -> None:
        store.set_app_health(DOMAIN, path="/up", expect=None, timeout=None)

        printed = invoke("app", "export", DOMAIN, "--as-yaml")
        target = tmp_path / "out.yaml"
        written = invoke("app", "export", DOMAIN, "--as-yaml", "-o", str(target))

        assert printed.exit_code == 0, printed.output
        assert "health:\n    path: /up" in printed.output
        assert printed.output.startswith("# Generated by: noust app export --as-yaml")
        assert written.exit_code == 0
        assert target.read_text() == printed.output

    def test_secrets_cannot_be_asked_for_in_a_declaration(self, store: NoustStore) -> None:
        refused = invoke("app", "export", DOMAIN, "--as-yaml", "--with-secrets")

        assert refused.exit_code != 0
        assert "never writes secrets" in refused.output

    def test_check_shows_the_plan_and_changes_nothing(
        self, store: NoustStore, cron: FakeCron, recorder: Recorder, tmp_path: Path
    ) -> None:
        shown = invoke("app", "apply", DOMAIN, declaration_file(tmp_path), "--check")

        assert shown.exit_code == 0, shown.output
        assert "tasks: create nightly (daily)  [runs commands]" in shown.output
        assert "Rehearsal: nothing was changed" in shown.output
        assert recorder.names() == [] and cron.jobs == {}

    def test_check_in_json_is_the_plan_alone(
        self, store: NoustStore, cron: FakeCron, recorder: Recorder, tmp_path: Path
    ) -> None:
        shown = invoke("app", "apply", DOMAIN, declaration_file(tmp_path), "--check", "--json")

        assert shown.exit_code == 0, shown.output
        body = json.loads(shown.output)
        assert body["rehearsed"] is True
        assert body["plan"]["confirm"] == ["tasks: create nightly (daily)"]
        assert recorder.names() == []

    def test_what_runs_commands_needs_a_yes_and_a_script_cannot_answer(
        self, store: NoustStore, cron: FakeCron, recorder: Recorder, tmp_path: Path
    ) -> None:
        refused = invoke("app", "apply", DOMAIN, declaration_file(tmp_path))

        assert refused.exit_code != 0
        assert "needs confirming" in str(refused.exception)
        assert "--yes" in (getattr(refused.exception, "details", "") or "")
        assert "set_resource_limits" not in recorder.names()
        assert cron.jobs == {}

    def test_yes_applies_it(
        self, store: NoustStore, cron: FakeCron, recorder: Recorder, tmp_path: Path
    ) -> None:
        done = invoke("app", "apply", DOMAIN, declaration_file(tmp_path), "--yes", "--json")

        assert done.exit_code == 0, done.output
        body = json.loads(done.output)
        assert all(step["applied"] for step in body["result"]["steps"])
        assert cron.jobs["nightly"]["command"] == "./bin/cleanup"
        assert recorder.args("set_resource_limits")[1].memory_max_mb == 256

    def test_what_does_not_run_commands_needs_no_question(
        self, store: NoustStore, cron: FakeCron, recorder: Recorder, tmp_path: Path
    ) -> None:
        done = invoke(
            "app",
            "apply",
            DOMAIN,
            declaration_file(tmp_path, "app: {limits: {memory_max_mb: 256}}\n"),
        )

        assert done.exit_code == 0, done.output
        assert "Applied the declaration" in done.output

    def test_a_declaration_that_is_wrong_is_refused_before_anything(
        self, store: NoustStore, cron: FakeCron, recorder: Recorder, tmp_path: Path
    ) -> None:
        refused = invoke(
            "app", "apply", DOMAIN, declaration_file(tmp_path, "env: {STRIPE_SECRET_KEY: x}\n")
        )

        assert refused.exit_code != 0
        assert refused.exception.field == "env.STRIPE_SECRET_KEY"
        assert recorder.names() == []


class TestTheApi:
    @pytest.fixture
    def client(self, store: NoustStore) -> Any:
        from fastapi import FastAPI
        from fastapi.testclient import TestClient

        from noust.web.api import app_apply
        from noust.web.api.auth import get_current_session
        from noust.web.api.deps import install_error_handlers, require_elevated

        server = FastAPI()
        install_error_handlers(server)
        server.include_router(app_apply.router, prefix="/api/apps")
        session = {"type": "session", "session_id": "s", "scope": "admin", "name": "alice"}
        server.dependency_overrides[get_current_session] = lambda: session
        server.dependency_overrides[require_elevated] = lambda: session
        return TestClient(server)

    def test_the_permissions(self) -> None:
        from noust.web.permissions import Permission
        from noust.web.permissions.routes_app_apply import ROUTES

        assert ROUTES[("GET", "/api/apps/{domain}/declaration")] == Permission.SECRETS_REVEAL
        assert ROUTES[("POST", "/api/apps/{domain}/apply")] == Permission.ROOT_EQUIVALENT

    def test_the_declaration_of_an_application(
        self, client: Any, store: NoustStore, cron: FakeCron
    ) -> None:
        got = client.get(f"/api/apps/{DOMAIN}/declaration")

        assert got.status_code == 200, got.text
        assert got.json()["declaration"].startswith("# Generated by: noust app export --as-yaml")
        assert client.get("/api/apps/nope.example.com/declaration").status_code == 404

    def test_check_says_what_would_change(
        self, client: Any, cron: FakeCron, recorder: Recorder
    ) -> None:
        got = client.post(
            f"/api/apps/{DOMAIN}/apply", json={"declaration": DECLARATION, "check": True}
        )

        assert got.status_code == 200, got.text
        body = got.json()
        assert body["applied"] is False and body["steps"] == []
        assert {change["section"] for change in body["plan"]["changes"]} == {
            "limits",
            "env",
            "tasks",
        }
        assert recorder.names() == []

    def test_commands_that_nobody_confirmed_are_not_run(
        self, client: Any, cron: FakeCron, recorder: Recorder
    ) -> None:
        got = client.post(f"/api/apps/{DOMAIN}/apply", json={"declaration": DECLARATION})

        assert got.status_code == 400
        assert "confirm" in got.text
        assert cron.jobs == {}

    def test_confirmed_it_is_applied(self, client: Any, cron: FakeCron, recorder: Recorder) -> None:
        got = client.post(
            f"/api/apps/{DOMAIN}/apply", json={"declaration": DECLARATION, "confirm": True}
        )

        assert got.status_code == 200, got.text
        assert got.json()["applied"] is True
        assert all(step["applied"] for step in got.json()["steps"])
        assert "nightly" in cron.jobs

    def test_a_declaration_that_is_wrong_is_a_400_naming_the_field(
        self, client: Any, cron: FakeCron
    ) -> None:
        got = client.post(
            f"/api/apps/{DOMAIN}/apply", json={"declaration": "env: {API_TOKEN: x}\n"}
        )

        assert got.status_code == 400
        assert got.json()["fields"] is not None or "API_TOKEN" in got.text

    def test_an_unknown_application(self, client: Any) -> None:
        got = client.post("/api/apps/nope.example.com/apply", json={"declaration": ""})
        assert got.status_code == 404
