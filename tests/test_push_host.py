"""
Preparing a server to take ``git push`` (checklist A-23): the account and sshd's rules for it.

What is pinned: that the account is a system account with git-shell for a shell and the
repositories' directory for a home (nologin would refuse a forced command); that its sshd block
takes forwarding, terminals, the agent and passwords away and has no ForceCommand (each key forces
its own, and sshd's would win); that the block is checked with ``sshd -t`` and ``sshd -T`` and put
back when sshd does not apply it; and that setting up twice changes nothing.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest

from noust.core import audit
from noust.core.exceptions import ConfigError, NodeError
from noust.pushdeploy.host import (
    PUSH_POLICY_BEGIN,
    PUSH_USER,
    git_shell,
    policy_block,
    policy_problems,
)
from tests.push_support import GIT_SHELL, PushRig, PushWorld, build_rig


@pytest.fixture
def rig(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[PushRig]:
    yield from build_rig(tmp_path, monkeypatch)


@pytest.fixture
def events(monkeypatch: pytest.MonkeyPatch) -> list[tuple[str, dict[str, Any]]]:
    recorded: list[tuple[str, dict[str, Any]]] = []
    monkeypatch.setattr(audit, "record", lambda event, **kwargs: recorded.append((event, kwargs)))
    return recorded


class TestTheBlock:
    def test_it_takes_away_everything_but_git_over_a_key(self) -> None:
        block = policy_block(PUSH_USER, Path("/etc/ssh/noust"))

        assert block.startswith(f"Match User {PUSH_USER}\n")
        for line in (
            "AuthorizedKeysFile /etc/ssh/noust/%u.keys",
            "AuthenticationMethods publickey",
            "DisableForwarding yes",
            "AllowTcpForwarding no",
            "AllowStreamLocalForwarding no",
            "PermitTTY no",
            "X11Forwarding no",
            "AllowAgentForwarding no",
            "PermitUserRC no",
            "PermitTunnel no",
        ):
            assert f"    {line}\n" in block

    def test_it_forces_no_command_because_each_key_forces_its_own(self) -> None:
        assert "ForceCommand" not in policy_block(PUSH_USER)

    def test_a_setting_another_block_applied_first_is_a_problem(self, rig: PushRig) -> None:
        rig.world.add_account(PUSH_USER, login_shell=GIT_SHELL, home=str(rig.world.home))
        rig.world.home.mkdir()
        rig.world.runner.ignore_policy = True
        rig.world.runner.config += "forcecommand /bin/true\n"
        settings = rig.world.host().status()
        assert not settings.ready
        text = "\n".join(settings.problems)
        assert "ForceCommand /bin/true" in text
        assert "AllowTcpForwarding yes" in text

    def test_nothing_to_say_when_sshd_applies_it(self, rig: PushRig) -> None:
        rig.set_up()
        from noust.fleet.authorize import read_sshd_settings

        settings = read_sshd_settings(rig.runner, rig.world.sshd_config, user=PUSH_USER)
        assert policy_problems(settings, rig.world.keys_dir) == []


class TestSettingUp:
    def test_it_makes_the_account_the_directory_and_the_block(
        self, rig: PushRig, events: list[tuple[str, dict[str, Any]]]
    ) -> None:
        result = rig.world.host().setup(actor="alice")

        assert result.account == PUSH_USER and result.account_created is True
        assert result.changed is True
        assert result.ssh_port == 22
        assert result.keys_file == str(rig.world.keys_file)
        useradd = next(call for call in rig.runner.calls if call[0] == "useradd")
        assert useradd[useradd.index("--shell") + 1] == GIT_SHELL
        assert useradd[useradd.index("--home-dir") + 1] == str(rig.world.home)
        assert "--no-create-home" in useradd and "--system" in useradd
        # No password anything matches, and the directory is the account's.
        assert ("usermod", "--password", "*", PUSH_USER) in rig.runner.calls
        assert ("chown", f"{PUSH_USER}:{PUSH_USER}", str(rig.world.home)) in rig.runner.calls
        assert rig.world.home.is_dir() and (rig.world.home.stat().st_mode & 0o777) == 0o750
        assert rig.world.dropin.read_text().startswith("# Generated by Noust")
        assert ("sshd", "-t") in rig.runner.calls
        assert ("push.setup" in [name for name, _ in events]) is True

    def test_setting_up_twice_changes_nothing(self, rig: PushRig) -> None:
        rig.world.host().setup()
        before = rig.world.dropin.read_text()
        calls = len(rig.runner.calls)

        second = rig.world.host().setup()

        assert second.account_created is False and second.changed is False
        assert rig.world.dropin.read_text() == before
        assert not any(call[0] == "useradd" for call in rig.runner.calls[calls:])

    def test_a_rehearsal_writes_nothing(self, rig: PushRig) -> None:
        result = rig.world.host().setup(dry_run=True)
        assert result.account == PUSH_USER
        assert not rig.world.dropin.exists()
        assert not rig.world.home.exists()
        assert not any(
            call[0] in ("sshd", "systemctl") and call[1] == "reload" for call in rig.runner.calls
        )

    def test_a_server_without_git_shell_is_told_to_install_it(
        self, rig: PushRig, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setattr("noust.pushdeploy.host.git_shell", lambda: None)
        with pytest.raises(ConfigError) as caught:
            rig.world.host().setup()
        assert "git-shell" in str(caught.value)
        assert not rig.world.dropin.exists()

    def test_an_existing_account_that_can_run_anything_is_refused(self, rig: PushRig) -> None:
        rig.world.add_account(PUSH_USER, login_shell="/bin/bash", home=str(rig.world.home))
        with pytest.raises(ConfigError) as caught:
            rig.world.host().setup()
        assert "/bin/bash" in str(caught.value)
        assert f"usermod --shell {GIT_SHELL} {PUSH_USER}" in caught.value.details
        assert not rig.world.dropin.exists()

    def test_sshd_that_would_shut_the_account_out_is_said_before_anything_is_changed(
        self, rig: PushRig
    ) -> None:
        rig.world.runner.config += "allowusers ana bob\n"
        with pytest.raises(ConfigError) as caught:
            rig.world.host().setup()
        assert "AllowUsers ana bob" in caught.value.details
        assert not any(call[0] == "useradd" for call in rig.runner.calls)

    def test_a_block_sshd_does_not_apply_is_put_back_as_it_was(self, rig: PushRig) -> None:
        rig.runner.ignore_policy = True
        with pytest.raises(NodeError) as caught:
            rig.world.host().setup()
        assert "does not apply Noust's restrictions" in str(caught.value)
        assert "noust push setup" in caught.value.details
        assert not rig.world.dropin.exists()

    def test_a_config_without_a_fragment_directory_gets_the_block_at_its_end(
        self, rig: PushRig
    ) -> None:
        rig.world.sshd_config.write_text("Port 22\n")
        rig.world.host().setup()
        text = rig.world.sshd_config.read_text()
        assert PUSH_POLICY_BEGIN in text and text.index("Port 22") < text.index("Match User")


class TestStatus:
    def test_a_server_that_is_not_set_up_says_what_to_run(self, rig: PushRig) -> None:
        status = rig.world.host().status()
        assert status.ready is False and status.account is False
        assert any("noust push setup" in problem for problem in status.problems)
        assert status.to_dict()["ready"] is False

    def test_a_server_that_is_set_up_is_ready(self, rig: PushRig) -> None:
        rig.set_up()
        status = rig.world.host().status()
        assert status.ready is True and status.problems == []
        assert status.account is True and status.home == str(rig.world.home)
        assert status.keys_file == str(rig.world.keys_file)

    def test_a_missing_directory_is_a_problem(self, rig: PushRig) -> None:
        rig.set_up()
        rig.world.home.rmdir()
        assert any(str(rig.world.home) in problem for problem in rig.world.host().status().problems)


def test_git_shell_is_found_where_the_distributions_put_it(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    present = tmp_path / "git-shell"
    present.write_text("")
    monkeypatch.setattr("noust.pushdeploy.host.GIT_SHELL_CANDIDATES", (str(present),))
    assert git_shell() == str(present)
    monkeypatch.setattr("noust.pushdeploy.host.GIT_SHELL_CANDIDATES", (str(tmp_path / "none"),))
    monkeypatch.setattr("shutil.which", lambda name: None)
    assert git_shell() is None


def test_the_world_of_the_tests_is_a_directory_of_their_own(tmp_path: Path) -> None:
    world = PushWorld(tmp_path / "w")
    assert world.dropin_dir.is_dir() and world.home == tmp_path / "w" / "git"
