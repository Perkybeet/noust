"""
``/api/server/storage/schedule`` and ``/history``: the cleanup policy over HTTP.

The policy, its timer and the history are tested on their own (``test_storage_policy.py``);
what is pinned here is what the HTTP layer owes: a policy that is checked before anything is
written, a timer written only for a valid one, sudo mode for changing it, a job for running
it now, and the history served newest first.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from noust.managers.backup_scheduler import BackupScheduler
from noust.managers.server.storage_policy import CleanupRun
from noust.web.jobs import JobType
from noust.web.permissions.registry import route_map
from tests.server_support import no_package_manager_running  # noqa: F401 - registers itself
from tests.test_server_api import api, store  # noqa: F401 - the fixtures the server API tests share

pytestmark = pytest.mark.usefixtures("no_package_manager_running")


@pytest.fixture(autouse=True)
def units_directory(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Write the timer's units under the test's own directory, not /etc/systemd/system."""
    directory = tmp_path / "systemd"
    directory.mkdir()
    monkeypatch.setattr(BackupScheduler, "SYSTEMD_DIR", directory)
    return directory


def test_before_any_policy_it_is_off_and_says_what_a_policy_may_run(api) -> None:  # noqa: F811
    body = api.client.get("/api/server/storage/schedule").json()

    assert body["policy"]["enabled"] is False
    assert body["policy"]["threshold_percent"] == 80
    assert "docker-image" not in body["schedulable"]
    assert body["docker_actions"] == ["docker-build-cache", "docker-dangling-images"]
    assert body["timer"]["installed"] is False


def test_setting_a_policy_keeps_it_and_writes_the_timer(api, units_directory: Path) -> None:  # noqa: F811
    response = api.client.put(
        "/api/server/storage/schedule",
        json={"enabled": True, "schedule": "weekly", "threshold_percent": 70},
    )

    assert response.status_code == 200, response.text
    assert response.json()["policy"]["schedule"] == "weekly"
    assert (
        api.client.get("/api/server/storage/schedule").json()["policy"]["threshold_percent"] == 70
    )
    assert any(
        call[:2] == ("systemctl", "enable") and call[-1] == "noust-storage-clean.timer"
        for call in api.machine.runner.calls
    )
    assert (units_directory / "noust-storage-clean.timer").is_file()
    service = (units_directory / "noust-storage-clean.service").read_text()
    assert 'server cleanup-schedule run --scheduled --reason "Scheduled storage cleanup"' in service
    assert "Generated by Noust" in service
    assert api.audit.records[-1]["event"] == "server.storage"
    assert api.audit.records[-1]["details"]["action"] == "schedule"


@pytest.mark.parametrize(
    "body",
    [
        {"threshold_percent": 150},
        {"actions": ["docker-image"]},
        {"actions": ["journal", "docker-build-cache"]},
        {"schedule": "daily\nExecStart=/bin/sh"},
    ],
)
def test_a_policy_that_is_not_valid_is_a_400_and_changes_nothing(api, body) -> None:  # noqa: F811
    response = api.client.put("/api/server/storage/schedule", json={"enabled": True, **body})

    assert response.status_code == 400
    assert api.client.get("/api/server/storage/schedule").json()["policy"]["enabled"] is False
    assert not any(call[:2] == ("systemctl", "enable") for call in api.machine.runner.calls)


def test_running_the_policy_now_is_a_job(api) -> None:  # noqa: F811
    response = api.client.post("/api/server/storage/schedule/run")

    assert response.status_code == 202
    queued = api.jobs.queued[0]
    assert queued["job_type"] is JobType.CLEANUP
    assert queued["metadata"] == {"action": "policy"}
    assert api.audit.records[0]["details"]["action"] == "run-policy"


def test_the_history_lists_what_ran_newest_first(api) -> None:  # noqa: F811
    history = api.machine.ctx.storage_schedule.history
    history.record(CleanupRun(trigger="manual", reason="first"))
    history.record(CleanupRun(trigger="schedule", reason="second"))

    body = api.client.get("/api/server/storage/history?limit=1").json()

    assert [run["reason"] for run in body] == ["second"]
    assert api.client.get("/api/server/storage/history?limit=0").status_code == 422


def test_reading_is_the_viewers_and_changing_is_the_operators_with_sudo_mode() -> None:
    permissions = route_map()

    assert permissions[("GET", "/api/server/storage/schedule")] == "server.read"
    assert permissions[("GET", "/api/server/storage/history")] == "server.read"
    assert permissions[("PUT", "/api/server/storage/schedule")] == "server.manage"
    assert permissions[("POST", "/api/server/storage/schedule/run")] == "server.manage"
