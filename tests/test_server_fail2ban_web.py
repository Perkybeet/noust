"""
fail2ban watching nginx: a password refused, a scanner, a client over a rate limit.

fail2ban ships the filters; what Noust adds is the jail file, and the part of it that matters is who
it must never ban. A ban is made from the address nginx logs, which behind a CDN is the CDN's, and
banning a CDN's edge takes every site behind it down. So besides who is connected over SSH and the
console's client, the ranges Cloudflare publishes and every proxy a site declares are ignored. A
file fail2ban refuses is put back, and stopping removes it.
"""

