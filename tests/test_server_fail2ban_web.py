def test_the_console_asks_for_it_through_a_job_and_its_client_is_never_banned(
    client: Any, machine: Any
) -> None:
    machine.runner.only_knows("apt-get", "ufw", "systemctl", "sshd", "fail2ban-client", "nginx")
    for filter_file in WEB_FILTERS:
        machine.host.write(filter_file, "[Definition]\n")

    response = client.post(f"{PREFIX}/fail2ban/web", json={"enable": True})

    assert response.status_code == 202, response.text
    job = machine.jobs.jobs[0]
    assert job.status.value == "completed" and job.result["jails"] == list(WEB_JAILS)
    assert job.metadata["operation"] == "fail2ban.web" and job.metadata["access_change"] is False
    assert "ignoreip" in (machine.host.read(FAIL2BAN_WEB_JAIL) or "")


def test_a_server_without_nginx_is_told_before_anything_is_queued(
    client: Any, machine: Any
) -> None:
    response = client.post(f"{PREFIX}/fail2ban/web", json={"enable": True})

    assert response.status_code in (400, 409, 500)
    assert "nginx is not installed" in response.text
    assert machine.jobs.jobs == []


def test_stopping_is_a_job_too(client: Any, machine: Any) -> None:
    machine.host.write(FAIL2BAN_WEB_JAIL, "# Generated by Noust.\n")

    response = client.post(f"{PREFIX}/fail2ban/web", json={"enable": False})

    assert response.status_code == 202, response.text
    assert machine.host.read(FAIL2BAN_WEB_JAIL) is None


def test_the_state_the_console_reads_carries_whether_nginx_is_watched(
    client: Any, machine: Any
) -> None:
    body = client.get(f"{PREFIX}/fail2ban").json()

    assert "web_available" in body and body["web_jails"] is False
