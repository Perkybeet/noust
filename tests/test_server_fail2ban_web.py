def test_a_cdn_and_a_declared_proxy_are_never_banned_nor_who_is_connected(
    runner: FakeSshd, host: FakeHost
) -> None:
    runner.script(
        ["ss", "-Htnp"],
        stdout='0 0 10.0.0.5:22 198.51.100.77:51234 users:(("sshd",pid=1,fd=4))\n',
    )

    result = fail2ban(runner, host).enable_web(ignore=["203.0.113.50", "127.0.0.1"])

    text = host.read(FAIL2BAN_WEB_JAIL) or ""
    assert result["jails"] == list(WEB_JAILS)
    assert result["ignored"] == [
        "198.51.100.77",
        "203.0.113.50",
        "173.245.48.0/20",
        "103.21.244.0/22",
        "198.51.100.0/24",
    ]
    assert (
        "ignoreip = 127.0.0.1/8 ::1 198.51.100.77 203.0.113.50 173.245.48.0/20 "
        "103.21.244.0/22 198.51.100.0/24" in text
    )
    steps = [call for call in runner.calls if call[0] == "fail2ban-client"]
    assert steps[-3:] == [
        ("fail2ban-client", "-t"),
        ("fail2ban-client", "reload"),
        ("fail2ban-client", "status", "nginx-limit-req"),
    ]


def test_it_is_refused_while_fail2ban_is_not_running(runner: FakeSshd, host: FakeHost) -> None:
    runner.script(["fail2ban-client", "ping"], stderr="Failed to access socket", exit_code=255)

    with pytest.raises(SecurityError) as raised:
        fail2ban(runner, host).enable_web()

    assert "not running" in raised.value.message and "fail2ban install" in raised.value.details
    assert host.read(FAIL2BAN_WEB_JAIL) is None


def test_it_is_refused_when_there_is_no_nginx_to_watch(runner: FakeSshd, host: FakeHost) -> None:
    runner.only_knows("apt-get", "fail2ban-client", "systemctl", "sshd")

    with pytest.raises(SecurityError) as raised:
        fail2ban(runner, host).enable_web()

    assert "nginx is not installed" in raised.value.message


def test_a_fail2ban_without_the_filters_says_which_are_missing(
    runner: FakeSshd, host: FakeHost
) -> None:
    (host.paths.at(WEB_FILTERS[2])).unlink()

    with pytest.raises(SecurityError) as raised:
        fail2ban(runner, host).enable_web()

    assert "nginx-limit-req.conf" in raised.value.details and host.read(FAIL2BAN_WEB_JAIL) is None


def test_a_file_fail2ban_refuses_is_taken_away_again(runner: FakeSshd, host: FakeHost) -> None:
    runner.script(
        ["fail2ban-client", "-t"], stderr="ERROR  Found no accessible config files", exit_code=255
    )

    with pytest.raises(SecurityError) as raised:
        fail2ban(runner, host).enable_web()

    assert "Found no accessible config files" in (raised.value.output or "")
    assert host.read(FAIL2BAN_WEB_JAIL) is None


def test_a_file_that_was_there_comes_back_when_the_new_one_is_refused(
    runner: FakeSshd, host: FakeHost
) -> None:
    host.write(FAIL2BAN_WEB_JAIL, "# Generated by Noust. old\n")
    runner.script(["fail2ban-client", "reload"], stderr="ERROR  reload failed", exit_code=255)

    with pytest.raises(SecurityError):
        fail2ban(runner, host).enable_web()

    assert host.read(FAIL2BAN_WEB_JAIL) == "# Generated by Noust. old\n"


# -- what is running, and turning it off --------------------------------------------------


def test_the_state_says_when_all_three_jails_run(runner: FakeSshd, host: FakeHost) -> None:
    runner.script(["fail2ban-client", "status"], stdout=F2B_WITH_WEB)
    for jail in WEB_JAILS:
        runner.script(["fail2ban-client", "status", jail], stdout="Status\n")

    state = fail2ban(runner, host).state()

    assert state.web_available and state.web_jails
    assert state.to_dict()["web_jails"] is True


def test_the_state_says_when_they_do_not(runner: FakeSshd, host: FakeHost) -> None:
    state = fail2ban(runner, host).state()

    assert state.web_available and not state.web_jails


def test_stopping_removes_the_file_and_reads_the_jails_again(
    runner: FakeSshd, host: FakeHost
) -> None:
    host.write(FAIL2BAN_WEB_JAIL, "# Generated by Noust.\n")

    result = fail2ban(runner, host).disable_web()

    assert result == {"jail_file": FAIL2BAN_WEB_JAIL}
    assert host.read(FAIL2BAN_WEB_JAIL) is None
    assert ("fail2ban-client", "reload") in runner.calls


def test_stopping_what_was_never_started_changes_nothing(runner: FakeSshd, host: FakeHost) -> None:
    result = fail2ban(runner, host).disable_web()

    assert result == {"jail_file": None}
    assert ("fail2ban-client", "reload") not in runner.calls


