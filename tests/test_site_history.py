"""
What a site's file said before, and whether it still says what the web server runs.

Every write of the file goes through the web server manager, so that is where the versions are
kept: a deployer's rendering, an edit, a restore. What is pinned is what makes the history worth
having: a hand edit that a deploy is about to overwrite is kept first, a version is a text and
never a duplicate of the one before, a restore is tested like any edit, and drift is told from the
file and the process table without any daemon.
"""

from __future__ import annotations

import os
import time
from pathlib import Path
from typing import Any

import pytest

from noust.core.exceptions import ValidationError
from noust.core.fs import DryRunFileSystem
from noust.core.runner import FakeRunner
from noust.core.site_history_store import KEEP, SiteHistoryStore, sha256_of
from noust.core.store import NoustStore
from noust.deployers import domains
from noust.managers.nginx_manager import NginxManager
from noust.managers.site_history import GRACE_SECONDS, SiteHistory, unified_diff
from tests.test_domains import (  # noqa: F401 - fixtures of the domains harness
    Machine,
    certs,
    machine,
    store,
    web,
)

EDIT = "# Generated by Noust\nserver {\n    listen 80;\n    server_name example.com;\n    return 204;\n}\n"


def versions(web: NginxManager, domain: str = "example.com") -> list[Any]:
    return web.history.versions(domain)


# -- the versions ----------------------------------------------------------------


def sources(web: NginxManager) -> list[tuple[int, str]]:
    return [(v.version, v.source) for v in versions(web)]


def test_what_a_deployer_renders_is_kept_as_a_version(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")

    newest = versions(web)[0]

    assert newest.source == "generated"
    stored = web.history.version("example.com", newest.version)
    assert stored is not None and stored.text == machine.config()
    assert stored.sha256 == sha256_of(machine.config())
    assert {version.source for version in versions(web)} == {"generated"}


def test_rendering_the_same_text_again_adds_nothing(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    before = sources(web)

    domains.refresh_site(machine.store.get_app("example.com"))
    domains.refresh_site(machine.store.get_app("example.com"))

    assert sources(web) == before


def test_a_new_alias_is_a_new_version(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    number = versions(web)[0].version

    domains.add_domain("example.com", "shop.example.com", "alias")

    newest = versions(web)[0]
    assert (newest.version, newest.source) == (number + 1, "generated")
    assert "shop.example.com" in web.history.version("example.com", newest.version).text  # type: ignore[union-attr]


def test_an_edit_is_kept_with_its_text(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    number = versions(web)[0].version

    web.replace_site_config("example.com", EDIT)

    newest = versions(web)[0]
    assert (newest.version, newest.source) == (number + 1, "edit")
    assert web.history.version("example.com", newest.version).text == EDIT  # type: ignore[union-attr]


def test_a_hand_edit_a_deploy_overwrites_is_kept_first(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    number = versions(web)[0].version
    by_hand = machine.config().replace("proxy_connect_timeout 60s", "proxy_connect_timeout 5s")
    web.config_path("example.com").write_text(by_hand)

    domains.refresh_site(machine.store.get_app("example.com"))

    assert sources(web)[:2] == [(number + 2, "generated"), (number + 1, "found")]
    assert web.history.version("example.com", number + 1).text == by_hand  # type: ignore[union-attr]
    assert "proxy_connect_timeout 60s" in machine.config()


def test_a_restore_is_an_edit_the_web_server_tests_and_a_version_of_its_own(
    machine: Machine, web: NginxManager, runner: FakeRunner
) -> None:
    machine.deploy(app_type="nodejs")
    first = versions(web)[0]
    text = web.history.version("example.com", first.version).text  # type: ignore[union-attr]
    web.replace_site_config("example.com", EDIT)

    web.replace_site_config("example.com", text, source="restore")

    assert machine.config() == text
    assert sources(web)[:2] == [(first.version + 2, "restore"), (first.version + 1, "edit")]
    count = len(versions(web))
    runner.script(("nginx", "-t"), stderr="nginx: [emerg] no\n", exit_code=1)
    with pytest.raises(ValidationError):
        web.replace_site_config("example.com", EDIT, source="restore")
    assert machine.config() == text
    assert len(versions(web)) == count


def test_a_site_keeps_its_latest_versions_only(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    number = versions(web)[0].version

    for index in range(KEEP + 5):
        web.replace_site_config("example.com", EDIT.replace("204", str(200 + index)))

    kept = versions(web)
    assert len(kept) == KEEP
    assert kept[0].version == number + KEEP + 5
    assert web.history.version("example.com", 1) is None


def test_deleting_a_site_forgets_its_history(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    assert versions(web)

    web.delete_site("example.com")

    assert versions(web) == []


def test_a_rehearsal_keeps_nothing(machine: Machine, web: NginxManager) -> None:
    machine.deploy(app_type="nodejs")
    before = versions(web)
    rehearsal = NginxManager(backend=web.backend, fs=DryRunFileSystem())

    rehearsal.replace_site_config("example.com", EDIT)

    assert versions(web) == before
    assert machine.config() != EDIT


def test_the_versions_of_two_web_servers_do_not_mix(store: NoustStore) -> None:
    records = SiteHistoryStore(store)

    records.add("example.com", "nginx", "a", source="generated", actor=None)
    records.add("example.com", "apache", "b", source="generated", actor=None)

    assert records.latest("example.com", "nginx").text == "a"  # type: ignore[union-attr]
    assert records.latest("example.com", "apache").text == "b"  # type: ignore[union-attr]


def test_a_diff_shows_what_changed_and_nothing_for_the_same_text() -> None:
    assert unified_diff("a\nb\n", "a\nb\n", older_label="x", newer_label="y") == ""
    changed = unified_diff("a\nb\n", "a\nc\n", older_label="version 1", newer_label="now")
    assert "--- version 1" in changed and "-b" in changed and "+c" in changed


# -- drift -----------------------------------------------------------------------


def file_aged(path: Path, seconds_ago: float) -> None:
    moment = time.time() - seconds_ago
    os.utime(path, (moment, moment))


def test_a_file_written_after_the_workers_started_is_pending(
    machine: Machine, web: NginxManager, runner: FakeRunner
) -> None:
    machine.deploy(app_type="nodejs")
    path = web.config_path("example.com")
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="  3600\n  3600\n  1800\n")
    history = web.history

    file_aged(path, 3000)  # older than every worker: they loaded it
    assert history.drift({"example.com": path}, runner) == {}

    file_aged(path, 10)
    # The newest worker started 1800 s ago: a file written 10 s ago has not been loaded.
    pending = history.drift({"example.com": path}, runner)["example.com"]
    assert pending.pending_reload and not pending.edited_outside


def test_a_file_written_by_the_reload_itself_is_not_pending(
    machine: Machine, web: NginxManager, runner: FakeRunner
) -> None:
    machine.deploy(app_type="nodejs")
    path = web.config_path("example.com")
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="2\n")
    file_aged(path, 2 + GRACE_SECONDS - 1)

    assert web.history.drift({"example.com": path}, runner) == {}


def test_nothing_is_said_when_the_web_server_is_not_running(
    machine: Machine, web: NginxManager, runner: FakeRunner
) -> None:
    machine.deploy(app_type="nodejs")
    path = web.config_path("example.com")
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="", exit_code=1)

    assert web.history.drift({"example.com": path}, runner) == {}


def test_a_file_that_is_not_what_noust_last_wrote_is_edited_outside(
    machine: Machine, web: NginxManager, runner: FakeRunner
) -> None:
    machine.deploy(app_type="nodejs")
    path = web.config_path("example.com")
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="")
    assert web.history.drift({"example.com": path}, runner) == {}

    path.write_text(path.read_text() + "# by hand\n")

    edited = web.history.drift({"example.com": path}, runner)["example.com"]
    assert edited.edited_outside and not edited.pending_reload


def test_a_site_noust_never_wrote_is_never_said_to_have_drifted(
    web: NginxManager, runner: FakeRunner
) -> None:
    path = web.backend.sites_available / "proggest"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("server { listen 80; }\n")
    web.history.about_to_overwrite("proggest.es", path.read_text())
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="")
    path.write_text("server { listen 81; }\n")

    assert web.history.drift({"proggest.es": path}, runner) == {}


def test_history_is_per_web_server_and_a_missing_database_is_not_a_crash(
    web: NginxManager, runner: FakeRunner
) -> None:
    history = SiteHistory("nginx", store=web.store, runner=runner)

    assert history.versions("never.example.com") == []
    assert history.version("never.example.com", 1) is None
