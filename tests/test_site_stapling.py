"""
Noust stops asking nginx to staple OCSP responses (item 172).

Let's Encrypt turned its OCSP service off in August 2025, and its certificates carry no OCSP
address since: nginx with ``ssl_stapling on`` logs a warning at every reload, for every site. A site
Noust generated changes the next time Noust writes it; a site the operator wrote is never touched,
and ``noust setup doctor`` names the generated ones that still carry the lines.
"""

from __future__ import annotations

from pathlib import Path

import noust
from noust.managers import setup_doctor, site_stapling

TEMPLATES = Path(noust.__file__).parent / "templates"

MARKER = "# Generated by Noust. Changes made here are replaced the next time the site is written.\n"

STAPLING_SITE = (
    MARKER
    + """server {
    listen 443 ssl;
    server_name shop.example.com;
    ssl_certificate /etc/letsencrypt/live/shop.example.com/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/shop.example.com/privkey.pem;
    ssl_session_cache shared:SSL:50m;
    ssl_stapling on;
    ssl_stapling_verify on;
}
"""
)


def test_no_template_writes_the_stapling_directives_any_more() -> None:
    offenders = [
        str(path.relative_to(TEMPLATES))
        for path in sorted(TEMPLATES.rglob("*.j2"))
        if "ssl_stapling" in path.read_text(encoding="utf-8")
        or "sslusestapling" in path.read_text(encoding="utf-8").lower()
    ]

    assert offenders == []


class TestWhatDoctorNames:
    def test_a_generated_site_that_still_staples_is_named(self, tmp_path: Path) -> None:
        (tmp_path / "shop.example.com").write_text(STAPLING_SITE)

        assert site_stapling.generated_sites_with_stapling(tmp_path) == ["shop.example.com"]

    def test_a_site_the_operator_wrote_is_never_named(self, tmp_path: Path) -> None:
        (tmp_path / "mine.example.com").write_text(STAPLING_SITE.replace(MARKER, "# my own edge\n"))

        assert site_stapling.generated_sites_with_stapling(tmp_path) == []

    def test_a_generated_site_that_does_not_staple_is_not_named(self, tmp_path: Path) -> None:
        clean = STAPLING_SITE.replace("    ssl_stapling on;\n    ssl_stapling_verify on;\n", "")
        (tmp_path / "shop.example.com").write_text(clean)

        assert site_stapling.generated_sites_with_stapling(tmp_path) == []

    def test_a_comment_that_talks_about_it_is_not_a_directive(self, tmp_path: Path) -> None:
        text = STAPLING_SITE.replace(
            "    ssl_stapling on;\n    ssl_stapling_verify on;\n", "    # ssl_stapling on;\n"
        )
        (tmp_path / "shop.example.com").write_text(text)

        assert site_stapling.generated_sites_with_stapling(tmp_path) == []

    def test_stapling_switched_off_is_not_the_warning(self, tmp_path: Path) -> None:
        text = STAPLING_SITE.replace("ssl_stapling on;", "ssl_stapling off;").replace(
            "ssl_stapling_verify on;", "ssl_stapling_verify off;"
        )
        (tmp_path / "shop.example.com").write_text(text)

        assert site_stapling.generated_sites_with_stapling(tmp_path) == []

    def test_several_sites_are_named_in_order(self, tmp_path: Path) -> None:
        for name in ("b.example.com", "a.example.com"):
            (tmp_path / name).write_text(STAPLING_SITE)

        assert site_stapling.generated_sites_with_stapling(tmp_path) == [
            "a.example.com",
            "b.example.com",
        ]

    def test_a_directory_that_is_not_there_names_nothing(self, tmp_path: Path) -> None:
        assert site_stapling.generated_sites_with_stapling(tmp_path / "missing") == []

    def test_a_file_that_is_not_text_is_left_alone(self, tmp_path: Path) -> None:
        (tmp_path / "blob").write_bytes(b"\xff\xfe\x00 not text")

        assert site_stapling.generated_sites_with_stapling(tmp_path) == []


class TestTheDoctorSection:
    def test_it_names_each_site_and_says_when_it_goes(self, tmp_path: Path) -> None:
        (tmp_path / "shop.example.com").write_text(STAPLING_SITE)

        section = setup_doctor.stapling_section(tmp_path)

        assert section is not None
        assert section.key == "stapling"
        [item] = section.items
        assert item.status == "info"
        assert "shop.example.com" in item.text
        assert "OCSP" in item.text

    def test_there_is_no_section_when_nothing_staples(self, tmp_path: Path) -> None:
        assert setup_doctor.stapling_section(tmp_path) is None
