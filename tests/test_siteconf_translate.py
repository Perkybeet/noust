"""
Translating a site from nginx to Apache and back (backlog item 105, wave 4).

The input is what Noust's own templates write, for the three kinds of application (a proxied one, a
static one and PHP), because that is what an operator's server holds. The checks are of two kinds:

- **What the new site says.** The lines that carry the meaning (the names, the certificate, where
  the proxy goes, the redirect to HTTPS, the refusals), and that the result is a file its web
  server reads (it parses, and says it is Noust's).
- **What it does not say.** A line the other server has nothing for is a finding, never a dropped
  line; a protection that is lost is told apart from a setting that changes no answer.
"""

from __future__ import annotations

import pytest

from noust.managers.apache_manager import ApacheManager
from noust.managers.nginx_manager import NginxManager
from noust.managers.siteconf import parse, structure
from noust.managers.siteconf.translate import translate
from tests.support.webserver_managers import apache, nginx, store, validation_tmp  # noqa: F401

# A fixture imported from the support module is found by pytest in this module's namespace, and a
# test that asks for it by name looks like a redefinition of an import that is never used.
# ruff: noqa: F811

DOMAIN = "shop.example.com"

CONTEXT = {
    "port": 3000,
    "static_dir": "/var/www/apps/shop/current",
    "document_root": "/var/www/apps/shop/current/public",
    "fastcgi_socket": "/run/php/php8.3-fpm.sock",
    "max_upload": "64m",
    "max_upload_bytes": 67108864,
    "deny_paths": ["xmlrpc.php"],
    "deny_patterns": ["xmlrpc.php"],
    "server_names": f"{DOMAIN} www.{DOMAIN}",
}

TEMPLATES = ["proxy", "static", "fastcgi"]


def rendered(manager: NginxManager | ApacheManager, template: str, ssl: bool) -> str:
    return manager.render_config(DOMAIN, template, {**CONTEXT, "ssl": ssl})


def to_apache(template: str, ssl: bool, nginx: NginxManager) -> tuple[str, list]:
    result = translate(
        rendered(nginx, template, ssl), source="nginx", target="apache", domain=DOMAIN
    )
    return result.text, list(result.findings)


def to_nginx(template: str, ssl: bool, apache: ApacheManager) -> tuple[str, list]:
    result = translate(
        rendered(apache, template, ssl), source="apache", target="nginx", domain=DOMAIN
    )
    return result.text, list(result.findings)


def lines_of(text: str) -> set[str]:
    return {line.strip() for line in text.splitlines()}


@pytest.mark.parametrize("ssl", [False, True])
@pytest.mark.parametrize("template", TEMPLATES)
class TestWhatNoustWrites:
    """A site as Noust's templates write it comes across whole, whichever way it goes."""

    def test_nginx_to_apache_is_a_site_apache_reads_and_noust_owns(
        self, nginx, template: str, ssl: bool
    ) -> None:
        text, findings = to_apache(template, ssl, nginx)

        parse(text, "apache")
        assert "Generated by Noust" in text.splitlines()[1]
        assert [item for item in findings if item.severity != "notes"] == []

    def test_apache_to_nginx_is_a_site_nginx_reads_and_noust_owns(
        self, apache, template: str, ssl: bool
    ) -> None:
        text, findings = to_nginx(template, ssl, apache)

        parse(text, "nginx")
        assert "Generated by Noust" in text.splitlines()[1]
        assert [item for item in findings if item.severity != "notes"] == []

    def test_the_names_the_site_answers_on_survive_both_ways(
        self, nginx, apache, template: str, ssl: bool
    ) -> None:
        for kind, manager, translated in (
            ("apache", nginx, to_apache(template, ssl, nginx)[0]),
            ("nginx", apache, to_nginx(template, ssl, apache)[0]),
        ):
            tree = structure(parse(translated, kind))  # type: ignore[arg-type]
            names = {name for server in tree.servers for name in server.names}
            assert names == {DOMAIN, f"www.{DOMAIN}"}, f"{kind} lost a name"
            del manager

    def test_what_the_proxy_reaches_and_the_certificate_survive(
        self, nginx, apache, template: str, ssl: bool
    ) -> None:
        for kind, translated in (
            ("apache", to_apache(template, ssl, nginx)[0]),
            ("nginx", to_nginx(template, ssl, apache)[0]),
        ):
            model = structure(parse(translated, kind))  # type: ignore[arg-type]
            certificates = {server.tls.certificate for server in model.servers if server.tls}
            if ssl:
                assert certificates == {f"/etc/letsencrypt/live/{DOMAIN}/fullchain.pem"}
            else:
                assert certificates == set()
            if template == "proxy":
                ports = {
                    location.target.port
                    for server in model.servers
                    for location in server.locations
                    if location.target.kind == "proxy"
                }
                assert ports == {3000}

    def test_translating_twice_is_stable(self, nginx, template: str, ssl: bool) -> None:
        """Out and back is not the same text, but the second trip changes nothing more."""
        first = translate(
            rendered(nginx, template, ssl), source="nginx", target="apache", domain=DOMAIN
        )
        back = translate(first.text, source="apache", target="nginx", domain=DOMAIN)
        again = translate(back.text, source="nginx", target="apache", domain=DOMAIN)
        assert again.text == first.text


class TestTheNginxSiteInApache:
    def test_a_proxied_site_with_tls_redirects_and_proxies(self, nginx) -> None:
        text, _ = to_apache("proxy", True, nginx)

        assert "<VirtualHost *:80>" in text and "<VirtualHost *:443>" in text
        found = lines_of(text)
        assert "ServerName shop.example.com" in found
        assert "ServerAlias www.shop.example.com" in found
        assert "SSLEngine on" in found
        assert f"SSLCertificateFile /etc/letsencrypt/live/{DOMAIN}/fullchain.pem" in found
        assert "RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]" in found
        assert "ProxyPass / http://127.0.0.1:3000/ timeout=60 connectiontimeout=60" in found
        assert "ProxyPreserveHost On" in found

    def test_the_certificate_authoritys_directory_is_not_sent_to_https(self, nginx) -> None:
        text, _ = to_apache("proxy", True, nginx)

        found = lines_of(text)
        assert (
            "Alias /.well-known/acme-challenge/ /var/www/html/.well-known/acme-challenge/" in found
        )
        assert "RewriteCond %{REQUEST_URI} !^/\\.well-known/acme-challenge/" in found

    def test_what_the_app_is_told_about_the_request_still_reaches_it(self, nginx) -> None:
        text, _ = to_apache("proxy", True, nginx)

        found = lines_of(text)
        assert 'RequestHeader set X-Forwarded-Proto "expr=%{REQUEST_SCHEME}"' in found
        assert 'RequestHeader set X-Real-IP "expr=%{REMOTE_ADDR}"' in found
        assert 'RewriteRule ^/(.*)$ "ws://127.0.0.1:3000/$1" [P,L]' in found

    def test_the_log_is_in_the_format_the_traffic_page_reads(self, nginx) -> None:
        text, _ = to_apache("proxy", False, nginx)

        found = lines_of(text)
        assert any(line.startswith("LogFormat ") and "rtus=%D" in line for line in found)
        assert f"CustomLog /var/log/apache2/{DOMAIN}.access.log noust_{DOMAIN}" in found
        assert f"ErrorLog /var/log/apache2/{DOMAIN}.error.log" in found

    def test_the_modules_it_needs_are_named(self, nginx) -> None:
        result = translate(
            rendered(nginx, "proxy", True), source="nginx", target="apache", domain=DOMAIN
        )

        assert {"ssl", "proxy", "proxy_http", "proxy_wstunnel", "rewrite", "headers"} <= set(
            result.modules
        )

    def test_a_static_site_serves_its_directory_and_falls_back_to_the_page(self, nginx) -> None:
        text, _ = to_apache("static", True, nginx)

        found = lines_of(text)
        assert "DocumentRoot /var/www/apps/shop/current" in found
        assert "FallbackResource /index.html" in found
        assert "Require all granted" in found
        assert 'Header set Cache-Control "max-age=31536000"' in found
        assert 'Header append Cache-Control "public, immutable"' in found

    def test_hidden_files_stay_refused_and_well_known_stays_reachable(self, nginx) -> None:
        text, _ = to_apache("static", True, nginx)

        assert '<LocationMatch "/\\.(?!well-known(?:/|$))">' in text

    def test_php_goes_to_its_pool_and_the_front_controller_catches_the_rest(self, nginx) -> None:
        text, _ = to_apache("fastcgi", True, nginx)

        found = lines_of(text)
        assert 'SetHandler "proxy:unix:/run/php/php8.3-fpm.sock|fcgi://localhost"' in found
        assert "FallbackResource /index.php" in found
        assert "LimitRequestBody 67108864" in found
        assert "ProxyTimeout 300" in found

    def test_every_refusal_of_the_php_site_is_kept_behind_the_well_known_shield(
        self, nginx
    ) -> None:
        text, _ = to_apache("fastcgi", True, nginx)

        assert text.count("Require all denied") == 6
        assert '<LocationMatch "^/xmlrpc\\.php$">' in text
        # The expressions that are not anchored are searched for anywhere in the path, as nginx
        # does, but never in /.well-known/, which the ^~ location kept them out of.
        assert "(?!/\\.well-known/)" in text

    def test_a_plain_http_site_is_not_sent_to_https(self, nginx) -> None:
        text, _ = to_apache("proxy", False, nginx)

        assert "<VirtualHost *:443>" not in text
        assert "https://%{HTTP_HOST}" not in text
        assert "SSLEngine" not in text


class TestTheApacheSiteInNginx:
    def test_a_proxied_site_with_tls_redirects_and_proxies(self, apache) -> None:
        text, _ = to_nginx("proxy", True, apache)

        found = lines_of(text)
        assert "server_name shop.example.com www.shop.example.com;" in found
        assert "return 301 https://$host$request_uri;" in found
        assert "proxy_pass http://127.0.0.1:3000;" in found
        assert "proxy_set_header Host $host;" in found
        assert "proxy_set_header Upgrade $http_upgrade;" in found
        assert f"ssl_certificate /etc/letsencrypt/live/{DOMAIN}/fullchain.pem;" in found

    def test_the_challenge_directory_is_kept_beside_the_redirect(self, apache) -> None:
        text, findings = to_nginx("proxy", True, apache)

        assert "location ^~ /.well-known/acme-challenge/ {" in text
        assert "root /var/www/html;" in lines_of(text)
        assert any("certificate authority" in item.sentence.text for item in findings)

    def test_the_log_format_is_the_one_the_nginx_template_writes(self, apache) -> None:
        text, _ = to_nginx("proxy", False, apache)

        assert text.count("log_format noust_shop.example.com") == 1
        assert "rt=$request_time" in text
        assert f"access_log /var/log/nginx/{DOMAIN}.access.log noust_{DOMAIN};" in lines_of(text)

    def test_a_static_site_keeps_its_fallback_cache_and_hidden_file_rules(self, apache) -> None:
        text, _ = to_nginx("static", True, apache)

        found = lines_of(text)
        assert "root /var/www/apps/shop/current;" in found
        assert "try_files $uri $uri/ /index.html;" in found
        assert "location ~ /\\. {" in found
        assert "location ^~ /.well-known/ {" in found
        assert 'add_header Cache-Control "public, immutable";' in found

    def test_php_goes_to_its_pool(self, apache) -> None:
        text, _ = to_nginx("fastcgi", True, apache)

        found = lines_of(text)
        assert "fastcgi_pass unix:/run/php/php8.3-fpm.sock;" in found
        assert "try_files $uri $uri/ /index.php?$args;" in found
        assert "client_max_body_size 64m;" in found
        assert "fastcgi_read_timeout 300;" in found
        assert text.count("deny all;") == 6


class TestWhatCannotBeCarriedOver:
    def test_a_rate_limit_is_a_protection_that_is_lost(self) -> None:
        source = (
            "limit_req_zone $binary_remote_addr zone=z:10m rate=10r/s;\n"
            "server {\n    listen 80;\n    server_name a.example.com;\n"
            "    limit_req zone=z burst=20 nodelay;\n"
            "    location / { proxy_pass http://127.0.0.1:3000; }\n}\n"
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        (lost,) = result.losses
        assert lost.protection and lost.directive == "limit_req" and lost.line == 5
        assert lost.sentence.code == "webserver_move.protection"
        assert "ProxyPass / http://127.0.0.1:3000/" in result.text

    def test_forward_auth_is_a_protection_that_is_lost(self) -> None:
        source = (
            "server {\n    listen 80;\n    server_name a.example.com;\n"
            "    auth_request /_auth;\n"
            "    location / { proxy_pass http://127.0.0.1:3000; }\n}\n"
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        assert [(item.directive, item.protection) for item in result.losses] == [
            ("auth_request", True)
        ]

    def test_a_directive_with_no_twin_is_said_with_its_line(self) -> None:
        source = (
            "server {\n    listen 80;\n    server_name a.example.com;\n"
            "    sub_filter 'a' 'b';\n"
            "    location / { proxy_pass http://127.0.0.1:3000; }\n}\n"
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        (lost,) = result.losses
        assert (lost.directive, lost.line, lost.protection) == ("sub_filter", 4, False)
        assert lost.sentence.params == {"directive": "sub_filter", "line": 4, "target": "Apache"}
        assert lost.sentence.hint

    def test_an_include_is_a_loss_that_names_the_file(self) -> None:
        source = "server {\n    listen 80;\n    include /etc/nginx/snippets/x.conf;\n}\n"

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        (lost,) = result.losses
        assert lost.reason == "included" and lost.sentence.params["path"].endswith("x.conf")

    def test_a_variable_apache_cannot_read_is_a_loss(self) -> None:
        source = (
            "server {\n    listen 80;\n    server_name a.example.com;\n"
            '    add_header X-Id "$request_id" always;\n}\n'
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        (lost,) = result.losses
        assert lost.reason == "variable" and lost.sentence.params["variable"] == "$request_id"

    def test_the_http3_listener_is_said_not_dropped(self) -> None:
        source = (
            "server {\n    listen 443 ssl;\n    listen 443 quic;\n    http3 on;\n"
            "    server_name a.example.com;\n}\n"
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        assert {item.directive for item in result.losses} == {"listen 443 quic", "http3"}

    def test_a_file_the_server_would_not_read_blocks(self) -> None:
        result = translate(
            "server {\n    listen 80\n", source="nginx", target="apache", domain="a.example.com"
        )

        assert result.blocked and result.text == ""
        (blocker,) = result.findings
        assert blocker.severity == "blocks" and blocker.sentence.code == "webserver_move.unreadable"

    def test_a_password_and_an_address_list_come_across_together(self) -> None:
        source = (
            "server {\n    listen 80;\n    server_name a.example.com;\n"
            "    satisfy any;\n    allow 10.0.0.0/8;\n    deny all;\n"
            '    auth_basic "Staff";\n    auth_basic_user_file /etc/nginx/noust-auth/a.htpasswd;\n'
            "    location / { proxy_pass http://127.0.0.1:3000; }\n}\n"
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        assert result.losses == ()
        found = lines_of(result.text)
        assert "<RequireAny>" in found
        assert "Require ip 10.0.0.0/8" in found and "Require valid-user" in found
        assert "AuthUserFile /etc/nginx/noust-auth/a.htpasswd" in found

    def test_the_other_way_a_htaccess_is_a_note_not_silence(self, apache) -> None:
        _, findings = to_nginx("static", True, apache)

        # The Apache static template turns .htaccess on (AllowOverride All): nginx never reads one.
        assert any(item.directive == "AllowOverride" for item in findings)

    def test_a_mixed_address_rule_is_a_protection_that_is_lost(self) -> None:
        source = (
            "server {\n    listen 80;\n    server_name a.example.com;\n"
            "    allow 1.1.1.1;\n    deny 2.2.2.2;\n    allow 3.3.3.3;\n    deny all;\n}\n"
        )

        result = translate(source, source="nginx", target="apache", domain="a.example.com")

        assert [(item.directive, item.protection) for item in result.losses] == [
            ("allow/deny", True)
        ]

    def test_translating_to_the_same_server_is_a_programming_error(self) -> None:
        with pytest.raises(ValueError):
            translate("", source="nginx", target="nginx", domain="a.example.com")
