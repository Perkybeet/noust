"""
The translation over the whole corpus of the site analyser (backlog item 105).

The corpus is what the lossless guarantee is proved on (``tests/test_siteconf_corpus.py``): Noust's
own templates, the Proggest sites and public configurations that use what the model does not
understand (Lua, ``map``, ``geo``, ``split_clients``, ``if``, glob includes, third-party modules).
Translating them is a different promise: **whatever a web server accepts is read without failing**,
the result is a file the other web server's parser reads, and what is left out is said.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from noust.managers.siteconf import parse
from noust.managers.siteconf.translate import translate

CORPUS = Path(__file__).parent / "fixtures" / "siteconf"


def corpus(kind: str) -> list[Path]:
    """
    Args:
        kind: ``nginx`` or ``apache``.

    Returns:
        The files of the corpus written in that dialect: the public configurations, the
        renderings of the templates and, for nginx, the Proggest sites.
    """
    folders = ("nginx", "templates", "proggest") if kind == "nginx" else ("apache", "templates")
    found: list[Path] = []
    for folder in folders:
        for path in sorted((CORPUS / folder).iterdir()):
            if folder == "templates" and not path.name.startswith(kind):
                continue
            found.append(path)
    return found


def _id(path: Path) -> str:
    return f"{path.parent.name}/{path.name}"


@pytest.mark.parametrize("path", corpus("nginx"), ids=_id)
def test_every_nginx_file_is_translated_or_blocked_never_a_crash(path: Path) -> None:
    result = translate(
        path.read_text(), source="nginx", target="apache", domain="corpus.example.com"
    )

    if result.blocked:
        assert result.text == ""
    else:
        parse(result.text, "apache")
        assert "Generated by Noust" in result.text
    for finding in result.findings:
        assert finding.sentence.text and finding.severity in ("blocks", "loses", "notes")


@pytest.mark.parametrize("path", corpus("apache"), ids=_id)
def test_every_apache_file_is_translated_or_blocked_never_a_crash(path: Path) -> None:
    result = translate(
        path.read_text(), source="apache", target="nginx", domain="corpus.example.com"
    )

    if result.blocked:
        assert result.text == ""
    else:
        parse(result.text, "nginx")
        assert "Generated by Noust" in result.text
    for finding in result.findings:
        assert finding.sentence.text and finding.severity in ("blocks", "loses", "notes")


class TestWhatTheCorpusSaysIsNotCarriedOver:
    def test_a_blue_green_site_names_the_file_it_includes(self) -> None:
        text = (CORPUS / "templates" / "nginx-proxy.bluegreen.conf").read_text()

        result = translate(text, source="nginx", target="apache", domain="shop.example.com")

        included = [item for item in result.findings if item.reason == "included"]
        assert included and included[0].sentence.params["path"].endswith(".conf")

    def test_the_advanced_site_loses_its_rate_limits_as_protections(self) -> None:
        text = (CORPUS / "templates" / "nginx-advanced.ssl.conf").read_text()

        result = translate(text, source="nginx", target="apache", domain="shop.example.com")

        assert any(item.protection for item in result.losses)

    def test_a_stream_block_is_not_a_site_and_is_said(self) -> None:
        text = (CORPUS / "templates" / "nginx-stream.udp.conf").read_text()

        result = translate(text, source="nginx", target="apache", domain="shop.example.com")

        assert result.blocked and result.text == ""
        assert {item.directive for item in result.findings if item.severity == "blocks"} >= {
            "listen 5353 udp",
            "proxy_pass",
        }

    def test_lua_is_not_carried_over(self) -> None:
        text = (CORPUS / "nginx" / "openresty-lua.conf").read_text()

        result = translate(text, source="nginx", target="apache", domain="shop.example.com")

        assert any("lua" in item.directive for item in result.losses)

    def test_the_load_balancer_becomes_a_balancer(self) -> None:
        text = (CORPUS / "nginx" / "load-balancer.conf").read_text()

        result = translate(text, source="nginx", target="apache", domain="shop.example.com")

        assert "balancer://" in result.text and "BalancerMember" in result.text
        assert {"proxy_balancer", "lbmethod_byrequests"} <= set(result.modules)
