"""
How a unit launches its application: the command text, and editing a unit that exists.

``systemd_command`` is the one place an argument vector becomes the text of an
``ExecStart=``; ``with_launch`` is how an update carries a changed start
command, directory or ``PATH`` to a unit without throwing away what an
operator edited by hand.
"""

from __future__ import annotations

import pytest

from noust.core.exceptions import ServiceError, ValidationError
from noust.deployers.helpers.unit_launch import systemd_command, with_launch

UNIT = """\
# Systemd service for rel-example-com
# Generated by Noust

[Unit]
Description=Noust: rel.example.com (nodejs)

[Service]
Type=simple
User=www-data
Group=www-data
WorkingDirectory=/var/www/apps/rel/current

# Environment
Environment="PORT=3000"
Environment="NODE_ENV=production"
EnvironmentFile=-/var/www/apps/rel/shared/.env

# Command
ExecStart=/usr/bin/npm run start

Restart=always
LimitNOFILE=65535
MemoryMax=512M

[Install]
WantedBy=multi-user.target
"""


class TestSystemdCommand:
    def test_plain_words_are_left_alone(self) -> None:
        assert systemd_command(["/usr/bin/node", "dist/server.js", "--port", "3000"]) == (
            "/usr/bin/node dist/server.js --port 3000"
        )

    def test_the_port_variable_is_kept_for_systemd_to_expand(self) -> None:
        assert systemd_command(["/x/serve", "-l", "${PORT}"]) == "/x/serve -l ${PORT}"

    def test_an_argument_with_a_space_is_one_word(self) -> None:
        assert systemd_command(["/x/serve", "--title", "my app"]) == '/x/serve --title "my app"'

    def test_quotes_and_backslashes_are_escaped_inside_the_quotes(self) -> None:
        assert systemd_command(["/x/run", 'say "hi"', "a\\b"]) == r'/x/run "say \"hi\"" "a\\b"'

    def test_a_percent_is_doubled_so_it_is_not_a_specifier(self) -> None:
        assert systemd_command(["/x/run", "--format=%s"]) == "/x/run --format=%%s"

    def test_a_semicolon_is_quoted_so_it_is_not_a_second_command(self) -> None:
        assert systemd_command(["/x/run", ";", "/bin/evil"]) == '/x/run ";" /bin/evil'

    def test_an_empty_argument_is_kept(self) -> None:
        assert systemd_command(["/x/run", ""]) == '/x/run ""'

    @pytest.mark.parametrize("bad", ["a\nExecStartPre=/bin/evil", "a\rb", "a\x00b"])
    def test_a_control_character_cannot_start_another_directive(self, bad: str) -> None:
        with pytest.raises(ValidationError):
            systemd_command(["/x/run", bad])


class TestWithLaunch:
    def test_the_command_and_the_directory_change_and_nothing_else_does(self) -> None:
        edited = with_launch(
            UNIT,
            command="/opt/noust/runtimes/node/22.11.0/bin/npm run start",
            working_directory="/var/www/apps/rel/current/apps/web",
            path=None,
        )

        assert "ExecStart=/opt/noust/runtimes/node/22.11.0/bin/npm run start\n" in edited
        assert "WorkingDirectory=/var/www/apps/rel/current/apps/web\n" in edited
        assert "ExecStart=/usr/bin/npm run start" not in edited
        for kept in (
            'Environment="PORT=3000"',
            "MemoryMax=512M",
            "EnvironmentFile=-/var/www/apps/rel/shared/.env",
            "WantedBy=multi-user.target",
            "# Generated by Noust",
        ):
            assert kept in edited
        assert edited.count("ExecStart=") == 1

    def test_a_path_is_added_after_the_other_variables(self) -> None:
        edited = with_launch(
            UNIT, command="/x/run", working_directory="/w", path="/opt/node/bin:/usr/bin"
        )

        lines = edited.splitlines()
        index = lines.index('Environment="PATH=/opt/node/bin:/usr/bin"')
        assert lines[index - 1] == 'Environment="NODE_ENV=production"'

    def test_a_path_that_was_there_is_replaced_not_repeated(self) -> None:
        once = with_launch(UNIT, command="/x/run", working_directory="/w", path="/a:/usr/bin")

        twice = with_launch(once, command="/x/run", working_directory="/w", path="/b:/usr/bin")

        assert twice.count('Environment="PATH=') == 1
        assert 'Environment="PATH=/b:/usr/bin"' in twice

    def test_without_a_path_an_old_one_is_removed(self) -> None:
        pinned = with_launch(UNIT, command="/x/run", working_directory="/w", path="/a:/usr/bin")

        unpinned = with_launch(pinned, command="/x/run", working_directory="/w", path=None)

        assert "PATH=" not in unpinned

    def test_a_percent_in_a_path_is_doubled_like_every_environment_value(self) -> None:
        edited = with_launch(
            UNIT, command="/x/run", working_directory="/w", path="/odd%dir:/usr/bin"
        )

        assert 'Environment="PATH=/odd%%dir:/usr/bin"' in edited

    def test_editing_twice_with_the_same_values_changes_nothing(self) -> None:
        once = with_launch(UNIT, command="/x/run", working_directory="/w", path="/a:/usr/bin")

        assert (
            with_launch(once, command="/x/run", working_directory="/w", path="/a:/usr/bin") == once
        )

    def test_a_unit_without_a_service_section_is_refused(self) -> None:
        with pytest.raises(ServiceError):
            with_launch("[Unit]\nDescription=x\n", command="/x", working_directory="/w", path=None)

    def test_a_unit_without_an_exec_start_is_refused(self) -> None:
        broken = UNIT.replace("ExecStart=/usr/bin/npm run start\n", "")

        with pytest.raises(ServiceError):
            with_launch(broken, command="/x", working_directory="/w", path=None)

    def test_a_directive_cannot_be_smuggled_through_a_value(self) -> None:
        with pytest.raises(ValidationError):
            with_launch(UNIT, command="/x\nUser=root", working_directory="/w", path=None)
        with pytest.raises(ValidationError):
            with_launch(UNIT, command="/x", working_directory="/w\nUser=root", path=None)
        with pytest.raises(ValidationError):
            with_launch(UNIT, command="/x", working_directory="/w", path="/a\nUser=root")

    def test_a_section_after_service_is_not_touched(self) -> None:
        text = UNIT + "\n[Other]\nExecStart=/keep/me\n"

        edited = with_launch(text, command="/x/run", working_directory="/w", path=None)

        assert "[Other]\nExecStart=/keep/me" in edited
