"""
An application deployed before 0.14.1 runs as ``wasm-<name>``; its next deployment makes it ``<name>``.

The rename belongs to the deployment because a deployment restarts the unit anyway: nothing
else that Noust does may stop an application to give its unit another name. It happens at the
chokepoint every unit passes (``ServiceManager``), only for a unit Noust owns, never over a unit
that already has the new name, and it can be put back exactly when the release does not pass its
health check.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from noust.core import legacy_names
from noust.core.fs import DryRunFileSystem
from noust.core.runner import FakeRunner
from noust.core.store import Service
from noust.managers.service_manager import ServiceManager
from tests.test_service_manager import FakeStore, manager, store, unit_dirs  # noqa: F401 - fixtures

OLD_MARKER = legacy_names.GENERATED_MARKER

LEGACY_UNIT = f"""\
# {OLD_MARKER}
[Unit]
Description=Noust managed service: wasm-shop-example-com
After=network.target

[Service]
Type=simple
User=www-data
WorkingDirectory=/var/www/apps/shop-example-com
ExecStart=/usr/bin/node server.js
SyslogIdentifier=wasm-shop-example-com
Restart=always

[Install]
WantedBy=multi-user.target
"""


def install(unit_dirs: dict[str, Path], text: str = LEGACY_UNIT) -> Path:  # noqa: F811
    path = unit_dirs["managed"] / "wasm-shop-example-com.service"
    path.write_text(text)
    return path


def script_enabled(runner: FakeRunner, *, enabled: bool) -> None:
    runner.script(
        ["systemctl", "is-enabled", "wasm-shop-example-com.service"],
        stdout="enabled\n" if enabled else "disabled\n",
        exit_code=0 if enabled else 1,
    )


def systemctl(runner: FakeRunner) -> list[tuple[str, ...]]:
    return [call for call in runner.calls if call[:1] == ("systemctl",)]


def test_the_unit_gets_its_new_name_and_everything_that_named_the_old_one(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    old = install(unit_dirs)
    script_enabled(runner, enabled=True)

    renamed = manager.rename_legacy_unit("shop-example-com")

    assert renamed is not None
    assert (renamed.old, renamed.new) == ("wasm-shop-example-com", "shop-example-com")
    new = unit_dirs["managed"] / "shop-example-com.service"
    assert not old.exists()
    text = new.read_text()
    assert "wasm-" not in text
    assert "Description=Noust managed service: shop-example-com" in text
    assert "SyslogIdentifier=shop-example-com" in text
    assert text.startswith("# Generated by Noust\n")
    assert "ExecStart=/usr/bin/node server.js" in text


def test_the_old_unit_is_stopped_and_disabled_and_the_new_one_enabled_but_not_started(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    """Starting it is the deployment's restart, behind its health gate."""
    install(unit_dirs)
    script_enabled(runner, enabled=True)

    manager.rename_legacy_unit("shop-example-com")

    calls = systemctl(runner)
    stop = calls.index(("systemctl", "stop", "wasm-shop-example-com.service"))
    disable = calls.index(("systemctl", "disable", "wasm-shop-example-com.service"))
    enable = calls.index(("systemctl", "enable", "shop-example-com.service"))
    assert stop < enable and disable < enable
    assert ("systemctl", "start", "shop-example-com.service") not in calls
    assert ("systemctl", "restart", "shop-example-com.service") not in calls


def test_a_unit_that_was_not_enabled_is_not_enabled_by_the_rename(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    install(unit_dirs)
    script_enabled(runner, enabled=False)

    manager.rename_legacy_unit("shop-example-com")

    assert ("systemctl", "enable", "shop-example-com.service") not in systemctl(runner)


def test_the_stored_service_follows_the_unit(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    store: FakeStore,  # noqa: F811
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    install(unit_dirs)
    script_enabled(runner, enabled=True)
    store.create_service(
        Service(
            name="wasm-shop-example-com",
            unit_file=str(unit_dirs["managed"] / "wasm-shop-example-com.service"),
            command="/usr/bin/node server.js",
            working_directory="/var/www/apps/shop-example-com",
            user="www-data",
            group="www-data",
            environment={},
            status="active",
            enabled=True,
        )
    )

    manager.rename_legacy_unit("shop-example-com")

    assert "wasm-shop-example-com" not in store.services
    row = store.services["shop-example-com"]
    assert row.unit_file == str(unit_dirs["managed"] / "shop-example-com.service")
    assert row.command == "/usr/bin/node server.js"


def test_putting_it_back_restores_the_old_unit_exactly(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    old = install(unit_dirs)
    script_enabled(runner, enabled=True)
    renamed = manager.rename_legacy_unit("shop-example-com")
    assert renamed is not None

    manager.restore_legacy_unit(renamed)

    assert old.read_text() == LEGACY_UNIT
    assert not (unit_dirs["managed"] / "shop-example-com.service").exists()
    calls = systemctl(runner)
    assert ("systemctl", "enable", "wasm-shop-example-com.service") in calls
    assert ("systemctl", "disable", "shop-example-com.service") in calls


def test_a_unit_that_already_has_the_new_name_is_not_overwritten(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    old = install(unit_dirs)
    other = unit_dirs["managed"] / "shop-example-com.service"
    other.write_text("# Generated by Noust\n[Unit]\nDescription=other\n")

    assert manager.rename_legacy_unit("shop-example-com") is None

    assert old.read_text() == LEGACY_UNIT
    assert "other" in other.read_text()
    assert not [c for c in systemctl(runner) if c[1] in {"stop", "disable", "enable"}]


def test_an_application_without_a_unit_of_before_has_nothing_to_rename(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
) -> None:
    assert manager.rename_legacy_unit("shop-example-com") is None
    assert not [c for c in systemctl(runner) if c[1] in {"stop", "disable", "enable"}]


@pytest.mark.parametrize("name", ["noust-web", "noust-monitor", "noust-previews"])
def test_a_unit_of_noust_s_own_is_never_an_application_s_to_rename(
    manager: ServiceManager,  # noqa: F811
    unit_dirs: dict[str, Path],  # noqa: F811
    name: str,
) -> None:
    path = unit_dirs["managed"] / f"wasm-{name}.service"
    path.write_text(f"# {OLD_MARKER}\n[Unit]\nDescription=x\n")

    assert manager.rename_legacy_unit(name) is None
    assert path.exists()


def test_a_unit_a_distribution_ships_under_the_new_name_is_not_shadowed(
    manager: ServiceManager,  # noqa: F811
    runner: FakeRunner,
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    install(unit_dirs)
    (unit_dirs["distro"] / "shop-example-com.service").write_text(
        "[Service]\nExecStart=/bin/true\n"
    )

    assert manager.rename_legacy_unit("shop-example-com") is None
    assert (unit_dirs["managed"] / "wasm-shop-example-com.service").exists()


def test_a_link_where_the_unit_should_be_is_not_followed(
    manager: ServiceManager,  # noqa: F811
    unit_dirs: dict[str, Path],  # noqa: F811
    tmp_path: Path,
) -> None:
    target = tmp_path / "elsewhere.service"
    target.write_text(LEGACY_UNIT)
    (unit_dirs["managed"] / "wasm-shop-example-com.service").symlink_to(target)

    assert manager.rename_legacy_unit("shop-example-com") is None
    assert target.read_text() == LEGACY_UNIT


def test_a_rehearsal_changes_nothing(
    runner: FakeRunner,
    store: FakeStore,  # noqa: F811
    unit_dirs: dict[str, Path],  # noqa: F811
) -> None:
    old = install(unit_dirs)
    rehearsing = ServiceManager(fs=DryRunFileSystem())

    renamed = rehearsing.rename_legacy_unit("shop-example-com")

    assert renamed is None
    assert old.read_text() == LEGACY_UNIT
    assert not (unit_dirs["managed"] / "shop-example-com.service").exists()
