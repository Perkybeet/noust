class TestTheTimer:
    def test_a_timer_and_a_service_are_written_and_enabled(
        self, store: NoustStore, scheduler: UpdateScheduler, runner: FakeRunner, systemd_dir: Path
    ) -> None:
        saved = scheduler.set(DOMAIN, "weekly", by="ana")

        assert saved.calendar == "Sun *-*-* 03:00:00" and saved.created_by == "ana"
        timer = (systemd_dir / f"{UNIT}.timer").read_text()
        assert "Description=Noust update timer for shop.example.com" in timer
        assert "OnCalendar=Sun *-*-* 03:00:00" in timer
        service = (systemd_dir / f"{UNIT}.service").read_text()
        assert "deploy schedule run shop.example.com" in service
        assert "Generated by Noust" in service
        assert runner.ran("systemctl", "enable", "--now", f"{UNIT}.timer")

    def test_the_unit_is_one_of_noust_own(self) -> None:
        from noust.core import paths

        assert paths.is_own_unit_name(UNIT)

    def test_an_expression_is_checked_before_anything_is_written(
        self, store: NoustStore, scheduler: UpdateScheduler, systemd_dir: Path
    ) -> None:
        for bad in ("daily\nExecStart=/bin/evil", "", "x" * 300):
            with pytest.raises(ValidationError) as caught:
                scheduler.set(DOMAIN, bad)
            assert caught.value.field == "calendar"

        assert list(systemd_dir.iterdir()) == []
        assert update_schedule_store.get(DOMAIN) is None

    def test_a_preview_is_not_scheduled(
        self, store: NoustStore, scheduler: UpdateScheduler, systemd_dir: Path
    ) -> None:
        store.create_app(
            App(
                domain="pr-1-shop.previews.example.com",
                app_type="nodejs",
                port=3010,
                app_path="/tmp/p",
                preview_parent=DOMAIN,
            )
        )

        with pytest.raises(ValidationError, match="is a preview"):
            scheduler.set("pr-1-shop.previews.example.com", "daily")

    def test_an_unknown_application_is_refused(
        self, store: NoustStore, scheduler: UpdateScheduler
    ) -> None:
        with pytest.raises(NoustError, match="not found"):
            scheduler.set("gone.example.com", "daily")

    def test_off_keeps_the_schedule_and_removes_the_timer(
        self, store: NoustStore, scheduler: UpdateScheduler, systemd_dir: Path
    ) -> None:
        scheduler.set(DOMAIN, "daily")

        scheduler.set(DOMAIN, "daily", enabled=False)

        saved = update_schedule_store.get(DOMAIN)
        assert saved is not None and saved.enabled is False
        assert not (systemd_dir / f"{UNIT}.timer").exists()

    def test_removing_takes_the_timer_and_the_row(
        self, store: NoustStore, scheduler: UpdateScheduler, systemd_dir: Path
    ) -> None:
        scheduler.set(DOMAIN, "daily")

        assert scheduler.remove(DOMAIN) is True
        assert scheduler.remove(DOMAIN) is False
        assert list(systemd_dir.iterdir()) == []
        assert update_schedule_store.get(DOMAIN) is None

    def test_a_timer_that_is_not_ours_is_not_overwritten(
        self, store: NoustStore, scheduler: UpdateScheduler, systemd_dir: Path
    ) -> None:
        (systemd_dir / f"{UNIT}.timer").write_text("[Timer]\nOnCalendar=hourly\n")

        with pytest.raises(BackupError, match="not a timer Noust wrote"):
            scheduler.set(DOMAIN, "daily")

        assert "hourly" in (systemd_dir / f"{UNIT}.timer").read_text()

    def test_deleting_the_application_takes_its_timer(
        self, store: NoustStore, scheduler: UpdateScheduler, systemd_dir: Path
    ) -> None:
        scheduler.set(DOMAIN, "daily")
        failures: list[str] = []

        lifecycle._forget_update_schedule(
            store, DOMAIN, lambda message, exc: failures.append(message)
        )

        assert failures == []
        assert not (systemd_dir / f"{UNIT}.timer").exists()


class Calls:
    """What a run asked of the update and of the remote."""

    def __init__(self) -> None:
        self.updates: list[dict[str, Any]] = []
        self.events: list[Any] = []
        self.new = True
        self.fail: Exception | None = None


@pytest.fixture
def calls(store: NoustStore, monkeypatch: pytest.MonkeyPatch) -> Calls:
    seen = Calls()

    def fake_update(domain: str, **kwargs: Any) -> Any:
        seen.updates.append({"domain": domain, **kwargs})
        if seen.fail is not None:
            raise seen.fail
        return SimpleNamespace(deployment_id=41, restarted=("shop-example-com",))

    monkeypatch.setattr(lifecycle, "update_app", fake_update)
    monkeypatch.setattr(
        lifecycle,
        "check_upstream",
        lambda domain, **_k: SimpleNamespace(has_new_commits=seen.new, summary="abc is ahead"),
    )
    monkeypatch.setattr(deploy_events, "publish", lambda event: seen.events.append(event))
    update_schedule_store.save(DOMAIN, "*-*-* 03:00:00", by="ana", store=store)
    return seen


class TestARun:
    def test_it_updates_with_its_backup_required_and_records_the_deployment(
        self, store: NoustStore, calls: Calls
    ) -> None:
        outcome = run_scheduled(DOMAIN)

        assert outcome.outcome == "updated" and outcome.deployment_id == 41
        assert calls.updates[0]["automatic"] is True
        assert calls.updates[0]["backup_required"] is True
        saved = update_schedule_store.get(DOMAIN)
        assert saved is not None
        assert (saved.last_outcome, saved.last_deployment_id) == ("updated", 41)
        assert saved.last_run_at

    def test_without_the_backup_it_is_a_choice(self, store: NoustStore, calls: Calls) -> None:
        update_schedule_store.save(DOMAIN, "daily", backup_first=False, store=store)

        run_scheduled(DOMAIN)

        assert calls.updates[0]["backup_required"] is False

    def test_nothing_new_is_nothing_done(self, store: NoustStore, calls: Calls) -> None:
        calls.new = False

        outcome = run_scheduled(DOMAIN)

        assert outcome.outcome == "nothing_new" and "abc is ahead" in outcome.detail
        assert calls.updates == []

    def test_always_updates_even_with_nothing_new(self, store: NoustStore, calls: Calls) -> None:
        calls.new = False
        update_schedule_store.save(DOMAIN, "daily", only_if_new=False, store=store)

        assert run_scheduled(DOMAIN).outcome == "updated"

    def test_an_application_that_follows_tags_compares_the_newest_tag(
        self, store: NoustStore, calls: Calls, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        store.set_app_follow_tags(DOMAIN, "v*")
        monkeypatch.setattr(
            update_scheduler.SourceManager,
            "remote_tags",
            lambda self, source: ["v1.0.0", "v1.1.0"],
        )
        monkeypatch.setattr(lifecycle, "deployed_tag", lambda app, **k: "v1.1.0")
        assert run_scheduled(DOMAIN).outcome == "nothing_new"

        monkeypatch.setattr(lifecycle, "deployed_tag", lambda app, **k: "v1.0.0")
        assert run_scheduled(DOMAIN).outcome == "updated"

    def test_a_pause_holds_it(self, store: NoustStore, calls: Calls) -> None:
        app_rollout_store.pause(DOMAIN, reason="rolled back", by="rollback")

        outcome = run_scheduled(DOMAIN)

        assert outcome.outcome == "held" and "rolled back" in outcome.detail
        assert calls.updates == []

    def test_a_freeze_holds_it(self, store: NoustStore, calls: Calls) -> None:
        deploy_freeze.create("incident 412")

        outcome = run_scheduled(DOMAIN)

        assert outcome.outcome == "held" and "incident 412" in outcome.detail

    def test_a_backup_that_does_not_happen_refuses_the_update_and_is_announced(
        self, store: NoustStore, calls: Calls
    ) -> None:
        calls.fail = BackupError("the disk is full", details="Nothing was changed.")

        outcome = run_scheduled(DOMAIN)

        assert outcome.outcome == "backup_failed"
        [event] = calls.events
        assert event.kind.value == "failed" and event.domain == DOMAIN
        assert event.operation == "update" and event.trigger == "schedule"
        assert "the disk is full" in (event.error or "")

    def test_a_failed_update_is_recorded_without_a_second_announcement(
        self, store: NoustStore, calls: Calls
    ) -> None:
        calls.fail = DeploymentError("did not pass its health check")

        outcome = run_scheduled(DOMAIN)

        assert outcome.outcome == "failed"
        assert calls.events == []  # the recorder of the update announced it

    def test_an_application_with_no_schedule_or_one_that_is_off_has_nothing_to_run(
        self, store: NoustStore, calls: Calls
    ) -> None:
        update_schedule_store.save(DOMAIN, "daily", enabled=False, store=store)

        with pytest.raises(NoustError, match="no scheduled update that is on"):
            run_scheduled(DOMAIN)
        update_schedule_store.delete(DOMAIN, store=store)
        with pytest.raises(NoustError, match="no scheduled update"):
            run_scheduled(DOMAIN)


class TestCommandLine:
    def invoke(self, *args: str) -> Any:
        return CliRunner().invoke(root_cli, list(args))

    def test_set_show_list_and_remove(
        self,
        store: NoustStore,
        scheduler: UpdateScheduler,
        systemd_dir: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        monkeypatch.setattr(update_scheduler, "UpdateScheduler", lambda: scheduler)
        monkeypatch.setattr("noust.managers.update_scheduler.UpdateScheduler", lambda: scheduler)

        made = self.invoke("deploy", "schedule", "set", DOMAIN, "--at", "daily", "--no-backup")
        assert made.exit_code == 0, made.output
        assert "will update itself" in made.output

        shown = json.loads(self.invoke("deploy", "schedule", "show", DOMAIN, "--json").output)
        assert shown["schedule"]["backup_first"] is False
        assert shown["schedule"]["calendar"] == "*-*-* 03:00:00"

        listed = self.invoke("deploy", "schedule", "list")
        assert DOMAIN in listed.output

        gone = self.invoke("deploy", "schedule", "remove", DOMAIN)
        assert gone.exit_code == 0 and "no longer updates itself" in gone.output
        assert "No application updates itself" in self.invoke("deploy", "schedule", "list").output

    def test_a_bad_expression_is_refused(self, store: NoustStore) -> None:
        result = self.invoke("deploy", "schedule", "set", DOMAIN, "--at", "daily\nx")

        assert result.exit_code != 0
        assert update_schedule_store.get(DOMAIN) is None

    def test_run_exits_1_when_the_update_failed_or_was_refused(
        self, store: NoustStore, calls: Calls
    ) -> None:
        ok = self.invoke("deploy", "schedule", "run", DOMAIN)
        calls.fail = BackupError("no space")
        refused = self.invoke("deploy", "schedule", "run", DOMAIN)

        assert ok.exit_code == 0 and refused.exit_code == 1

    def test_a_dry_run_changes_nothing(self, store: NoustStore) -> None:
        result = self.invoke("--dry-run", "deploy", "schedule", "set", DOMAIN, "--at", "daily")

        assert result.exit_code == 0
        assert update_schedule_store.get(DOMAIN) is None


class TestApi:
    @pytest.fixture
    def client(
        self, store: NoustStore, scheduler: UpdateScheduler, monkeypatch: pytest.MonkeyPatch
    ) -> TestClient:
        monkeypatch.setattr(app_schedule, "UpdateScheduler", lambda: scheduler)
        server = FastAPI()
        install_error_handlers(server)
        server.include_router(app_schedule.router, prefix="/api/apps")
        server.dependency_overrides[get_current_session] = lambda: {
            "sid": "abcdef012345",
            "username": "ana",
            "account_id": 1,
        }
        return TestClient(server)

    def test_an_application_that_does_not_update_itself_says_so(self, client: TestClient) -> None:
        body = client.get(f"/api/apps/{DOMAIN}/update-schedule").json()

        assert body["scheduled"] is False and body["calendar"] is None
        assert body["aliases"]["weekly"] == "Sun *-*-* 03:00:00"

    def test_putting_and_removing(self, client: TestClient, systemd_dir: Path) -> None:
        put = client.put(
            f"/api/apps/{DOMAIN}/update-schedule",
            json={"calendar": "weekly", "backup_first": True, "only_if_new": False},
        )

        assert put.status_code == 200, put.text
        body = put.json()
        assert body["scheduled"] and body["calendar"] == "Sun *-*-* 03:00:00"
        assert body["only_if_new"] is False
        assert (systemd_dir / f"{UNIT}.timer").exists()

        gone = client.delete(f"/api/apps/{DOMAIN}/update-schedule")
        assert gone.json()["scheduled"] is False
        assert not (systemd_dir / f"{UNIT}.timer").exists()

    def test_what_is_not_a_calendar_is_a_400(self, client: TestClient) -> None:
        response = client.put(
            f"/api/apps/{DOMAIN}/update-schedule", json={"calendar": "daily\nExecStart=/bin/x"}
        )

        assert response.status_code == 400
        assert "calendar" in str(response.json())

    def test_an_unknown_application_is_a_404(self, client: TestClient) -> None:
        assert client.get("/api/apps/gone.example.com/update-schedule").status_code == 404
