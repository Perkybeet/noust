"""
The upstream Noust generates is named ``noust_bg_<app>`` from 4.0 and ``wasm_bg_<app>`` before.

What Noust wrote it renames, together and behind nginx's own test. A site somebody else wrote
that names the old upstream is never rewritten, so the old name stays for as long as it does.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import pytest

from noust.core import legacy_names
from noust.core.runner import FakeRunner
from noust.managers import upstream_names
from noust.managers.nginx_manager import NginxManager
from noust.managers.webserver import NGINX_BACKEND

OLD = "wasm_bg_shop_example_com"
NEW = "noust_bg_shop_example_com"

UPSTREAM_FILE = """\
# Upstream of shop.example.com: the blue/green instance that serves
# Generated by Noust; rewritten on every activation.
upstream wasm_bg_shop_example_com {
    server 127.0.0.1:3001;
}
"""

GENERATED_SITE = """\
# Nginx reverse proxy configuration for shop.example.com
# Generated by Noust

include /etc/nginx/noust-upstreams/shop-example-com.conf;

server {
    listen 80;
    server_name shop.example.com;
    location / {
        proxy_pass http://wasm_bg_shop_example_com;
    }
}
"""

OPERATOR_EDGE = """\
# Written by hand, long before the application behind it was deployed by Noust.
server {
    listen 80;
    server_name edge.example.com;
    location / {
        proxy_pass http://wasm_bg_shop_example_com;
        proxy_set_header Host $host;
    }
}
"""


@pytest.fixture
def nginx(tmp_path: Path, runner: FakeRunner) -> NginxManager:
    """
    Args:
        tmp_path: Per-test temporary directory.
        runner: The fake command runner.

    Returns:
        An nginx manager over a temporary configuration tree, nginx answering well.
    """
    root = tmp_path / "nginx"
    for name in ("sites-available", "sites-enabled", "noust-upstreams", "conf.d"):
        (root / name).mkdir(parents=True)
    (root / "nginx.conf").write_text(
        "events {}\nhttp {\n    include /etc/nginx/sites-enabled/*;\n}\n"
    )
    return NginxManager(
        backend=replace(
            NGINX_BACKEND,
            sites_available=root / "sites-available",
            sites_enabled=root / "sites-enabled",
            upstreams_dir=root / "noust-upstreams",
        )
    )


def put(manager: NginxManager, name: str, text: str, *, upstream: bool = False) -> Path:
    """
    Write a file where nginx would find it.

    Args:
        manager: The manager whose tree it goes in.
        name: The file's name.
        text: Its content.
        upstream: Put it in the upstream directory, not the sites.

    Returns:
        The file.
    """
    if upstream:
        path = manager.backend.upstreams_dir / name  # type: ignore[operator]
        path.write_text(text)
        return path
    path = manager.sites_available / name
    path.write_text(text)
    (manager.sites_enabled / name).symlink_to(path)
    return path


class TestReading:
    def test_a_directive_that_names_the_upstream_is_a_reference(self) -> None:
        found = upstream_names.references_in(OPERATOR_EDGE, OLD)

        assert found == [(6, "proxy_pass http://wasm_bg_shop_example_com;")]

    def test_a_comment_is_not(self) -> None:
        text = f"# this used to be {OLD}\nserver {{ listen 80; }}\n"

        assert upstream_names.references_in(text, OLD) == []

    def test_a_block_that_defines_the_name_is_not_a_reference_to_it(self) -> None:
        """Somebody giving their own block the old convention needs nothing from Noust."""
        text = f"upstream {OLD} {{\n    include /etc/nginx/noust-upstreams/shop/web.servers;\n}}\n"

        assert upstream_names.references_in(text, OLD) == []

    def test_another_name_that_starts_the_same_is_not_it(self) -> None:
        text = f"server {{ location / {{ proxy_pass http://{OLD}_admin; }} }}\n"

        assert upstream_names.references_in(text, OLD) == []

    def test_a_file_the_parser_refuses_is_searched_by_line_so_nothing_is_missed(self) -> None:
        text = f"server {{\n  proxy_pass http://{OLD}\n  # {OLD}\n"

        assert upstream_names.references_in(text, OLD) == [(2, f"proxy_pass http://{OLD}")]

    def test_the_names_a_file_defines(self) -> None:
        assert upstream_names.defined_names(UPSTREAM_FILE) == [OLD]
        assert upstream_names.defined_names("server { listen 80; }\n") == []

    def test_a_whole_word_only_is_replaced(self) -> None:
        text = f"{OLD} {OLD}_admin x{OLD}"

        assert upstream_names.renamed_text(text, OLD, NEW) == f"{NEW} {OLD}_admin x{OLD}"


class TestScanning:
    def test_a_generated_pair_nobody_else_names_is_free_to_be_renamed(
        self, nginx: NginxManager
    ) -> None:
        upstream = put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        site = put(nginx, "shop.example.com", GENERATED_SITE)

        verdicts = upstream_names.scan(nginx)

        assert [v.name for v in verdicts] == [OLD]
        assert verdicts[0].new_name == NEW
        assert verdicts[0].free
        assert sorted(verdicts[0].files) == sorted([upstream.resolve(), site.resolve()])

    def test_an_operators_site_that_names_it_keeps_it(self, nginx: NginxManager) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        put(nginx, "shop.example.com", GENERATED_SITE)
        edge = put(nginx, "edge", OPERATOR_EDGE)

        verdict = upstream_names.scan(nginx)[0]

        assert not verdict.free
        assert [(r.path, r.line) for r in verdict.references] == [(edge.resolve(), 6)]

    def test_nothing_to_say_when_nothing_carries_the_old_prefix(self, nginx: NginxManager) -> None:
        put(nginx, "plain", "# Generated by Noust\nserver { listen 80; }\n")

        assert upstream_names.scan(nginx) == []

    def test_a_site_somebody_wrote_that_defines_the_old_name_is_not_ours_to_rename(
        self, nginx: NginxManager
    ) -> None:
        put(nginx, "proggest", f"upstream {OLD} {{\n    include /x/web.servers;\n}}\n")

        assert upstream_names.scan(nginx) == []

    def test_the_name_to_write_is_the_old_one_only_while_somebody_names_it(
        self, nginx: NginxManager
    ) -> None:
        assert upstream_names.name_for(nginx, "shop_example_com") == NEW

        edge = put(nginx, "edge", OPERATOR_EDGE)
        assert upstream_names.name_for(nginx, "shop_example_com") == OLD

        edge.write_text(OPERATOR_EDGE.replace(OLD, NEW))
        assert upstream_names.name_for(nginx, "shop_example_com") == NEW


class TestRenaming:
    def test_the_generated_files_change_together_and_nginx_is_loaded(
        self, nginx: NginxManager, runner: FakeRunner
    ) -> None:
        upstream = put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        site = put(nginx, "shop.example.com", GENERATED_SITE)

        outcomes = upstream_names.rename(nginx)

        assert [(o.name, o.status) for o in outcomes] == [(OLD, "renamed")]
        assert OLD not in upstream.read_text() and NEW in upstream.read_text()
        assert OLD not in site.read_text() and f"proxy_pass http://{NEW};" in site.read_text()
        calls = [call[:2] for call in runner.calls]
        assert ("nginx", "-t") in calls
        assert any(call[:2] == ("systemctl", "reload") or "reload" in call for call in runner.calls)

    def test_the_site_an_operator_wrote_is_never_touched(self, nginx: NginxManager) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        put(nginx, "shop.example.com", GENERATED_SITE)
        edge = put(nginx, "edge", OPERATOR_EDGE)

        outcomes = upstream_names.rename(nginx)

        assert [(o.name, o.status) for o in outcomes] == [(OLD, "kept")]
        assert edge.read_text() == OPERATOR_EDGE
        assert OLD in (nginx.backend.upstreams_dir / "shop-example-com.conf").read_text()  # type: ignore[operator]

    def test_the_rename_completes_once_the_operator_has_changed_their_line(
        self, nginx: NginxManager
    ) -> None:
        upstream = put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        put(nginx, "shop.example.com", GENERATED_SITE)
        edge = put(nginx, "edge", OPERATOR_EDGE)
        assert upstream_names.rename(nginx)[0].status == "kept"

        edge.write_text(OPERATOR_EDGE.replace(OLD, NEW))
        outcomes = upstream_names.rename(nginx)

        assert [o.status for o in outcomes] == ["renamed"]
        assert OLD not in upstream.read_text()
        assert edge.read_text() == OPERATOR_EDGE.replace(OLD, NEW)

    def test_a_refusal_by_nginx_puts_every_file_back(
        self, nginx: NginxManager, runner: FakeRunner
    ) -> None:
        upstream = put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        site = put(nginx, "shop.example.com", GENERATED_SITE)
        runner.script(
            ["nginx", "-t"],
            exit_code=1,
            stderr='nginx: [emerg] host not found in upstream "x" in /etc/nginx/sites/a:9\n',
        )

        outcomes = upstream_names.rename(nginx)

        assert [o.status for o in outcomes] == ["failed"]
        assert "host not found in upstream" in outcomes[0].detail
        assert upstream.read_text() == UPSTREAM_FILE
        assert site.read_text() == GENERATED_SITE

    def test_nothing_is_written_in_a_rehearsal(self, nginx: NginxManager) -> None:
        from noust.core.fs import DryRunFileSystem

        upstream = put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        rehearsing = NginxManager(backend=nginx.backend, fs=DryRunFileSystem())

        outcomes = upstream_names.rename(rehearsing)

        assert [o.status for o in outcomes] == ["rehearsed"]
        assert upstream.read_text() == UPSTREAM_FILE

    def test_running_it_again_has_nothing_left_to_do(self, nginx: NginxManager) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        put(nginx, "shop.example.com", GENERATED_SITE)
        upstream_names.rename(nginx)

        assert upstream_names.rename(nginx) == []


def test_the_prefixes_are_the_two_spellings() -> None:
    assert upstream_names.NEW_PREFIX == "noust_bg_"
    assert upstream_names.OLD_PREFIX == legacy_names.UPSTREAM_PREFIX


class TestWriting:
    """A write of the upstream file renames the application's own site along with it."""

    def test_a_new_file_gets_the_new_name(self, nginx: NginxManager) -> None:
        assert nginx.upstream_name("shop.example.com") == NEW
        assert nginx.write_upstream("shop.example.com", 3001) is None

        text = nginx.read_upstream("shop.example.com") or ""
        assert f"upstream {NEW} {{" in text
        assert "127.0.0.1:3001" in text

    def test_the_old_file_and_the_site_are_renamed_in_one_write(self, nginx: NginxManager) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        site = put(nginx, "shop.example.com", GENERATED_SITE)

        previous = nginx.write_upstream("shop.example.com", 3002)

        assert previous == UPSTREAM_FILE
        assert f"upstream {NEW} {{" in (nginx.read_upstream("shop.example.com") or "")
        assert f"proxy_pass http://{NEW};" in site.read_text()
        assert OLD not in site.read_text()

    def test_putting_the_previous_file_back_puts_the_site_back(self, nginx: NginxManager) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        site = put(nginx, "shop.example.com", GENERATED_SITE)
        previous = nginx.write_upstream("shop.example.com", 3002)

        nginx.restore_upstream("shop.example.com", previous)

        assert nginx.read_upstream("shop.example.com") == UPSTREAM_FILE
        assert site.read_text() == GENERATED_SITE

    def test_an_operators_site_that_names_the_old_one_keeps_both_files_as_they_are(
        self, nginx: NginxManager
    ) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        site = put(nginx, "shop.example.com", GENERATED_SITE)
        edge = put(nginx, "edge", OPERATOR_EDGE)

        nginx.write_upstream("shop.example.com", 3002)

        assert f"upstream {OLD} {{" in (nginx.read_upstream("shop.example.com") or "")
        assert site.read_text() == GENERATED_SITE
        assert edge.read_text() == OPERATOR_EDGE

    def test_a_site_the_operator_wrote_for_the_application_is_not_renamed(
        self, nginx: NginxManager
    ) -> None:
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)
        own = GENERATED_SITE.replace("# Generated by Noust", "# Mine")
        site = put(nginx, "shop.example.com", own)

        nginx.write_upstream("shop.example.com", 3002)

        assert site.read_text() == own

    def test_a_site_rendered_before_the_file_changes_says_what_the_file_says(
        self, nginx: NginxManager
    ) -> None:
        """Rendering the site must not name an upstream the file on disk does not define."""
        put(nginx, "shop-example-com.conf", UPSTREAM_FILE, upstream=True)

        assert nginx._upstream_name_in_force("shop.example.com") == OLD
        assert nginx.upstream_name("shop.example.com") == NEW
