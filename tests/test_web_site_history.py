"""
``/api/sites/{domain}/config/versions`` and the drift flags of ``/api/sites``.

What is kept, and when, is pinned in ``tests/test_site_history.py``. Here: the shapes the console
reads, that reading a version is reading the site and putting one back asks for sudo mode, the
diff against the file now, and that the list of sites says which of them have drifted.
"""

from __future__ import annotations

import os
import time
from typing import Any

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from noust.core.runner import FakeRunner
from noust.managers.nginx_manager import NginxManager
from noust.web.api import site_history as history_api
from noust.web.api import sites as sites_api
from noust.web.api.deps import install_error_handlers
from noust.web.auth import require_auth
from tests.test_domains import (  # noqa: F401 - fixtures of the domains harness
    Machine,
    certs,
    machine,
    store,
    web,
)

BEARER = {"sid": "token", "scope": "admin", "source": "bearer", "type": "api_token"}
COOKIE = {"sid": "s1", "scope": "admin", "source": "cookie", "type": "session"}
EDIT = "# Generated by Noust\nserver {\n    listen 80;\n    server_name example.com;\n    return 204;\n}\n"


def build(web: NginxManager, session: dict[str, Any]) -> TestClient:
    sites_api._manager_for = lambda webserver=None: ("nginx", web)  # type: ignore[assignment]
    history_api._manager_for = sites_api._manager_for  # type: ignore[assignment]
    app = FastAPI()
    install_error_handlers(app)
    app.include_router(sites_api.router, prefix="/api/sites")
    app.include_router(history_api.router, prefix="/api/sites")
    app.dependency_overrides[require_auth] = lambda: session
    return TestClient(app)


@pytest.fixture(autouse=True)
def restore_lookup() -> Any:
    original = sites_api._manager_for
    yield
    sites_api._manager_for = original
    history_api._manager_for = original


@pytest.fixture
def client(machine: Machine, web: NginxManager) -> TestClient:
    machine.deploy(app_type="nodejs")
    return build(web, BEARER)


def test_the_versions_are_listed_newest_first_with_the_current_one_marked(
    client: TestClient, web: NginxManager
) -> None:
    web.replace_site_config("example.com", EDIT)

    response = client.get("/api/sites/example.com/config/versions")

    assert response.status_code == 200, response.text
    body = response.json()
    assert body["site"] == "example.com" and body["webserver"] == "nginx"
    numbers = [item["version"] for item in body["versions"]]
    assert numbers == sorted(numbers, reverse=True)
    assert body["versions"][0]["current"] is True
    assert body["versions"][0]["source"] == "edit"
    assert all("config" not in item for item in body["versions"])


def test_one_version_comes_with_its_text_and_a_diff_to_the_file_now(
    client: TestClient, web: NginxManager, machine: Machine
) -> None:
    first = web.history.versions("example.com")[-1]
    original = web.history.version("example.com", first.version).text  # type: ignore[union-attr]
    web.replace_site_config("example.com", EDIT)

    response = client.get(f"/api/sites/example.com/config/versions/{first.version}")

    assert response.status_code == 200, response.text
    body = response.json()
    assert body["config"] == original
    assert body["current"] is False
    assert f"--- version {first.version}" in body["diff"] and "+++ now" in body["diff"]
    assert "+    return 204;" in body["diff"]
    newest = web.history.versions("example.com")[0].version
    assert client.get(f"/api/sites/example.com/config/versions/{newest}").json()["diff"] == ""


def test_an_unknown_site_or_version_is_a_404(client: TestClient) -> None:
    assert client.get("/api/sites/ghost.example.com/config/versions").status_code == 404
    assert client.get("/api/sites/example.com/config/versions/999").status_code == 404
    assert client.post("/api/sites/example.com/config/versions/999/restore").status_code == 404


def test_putting_a_version_back_is_tested_installed_and_recorded(
    client: TestClient, web: NginxManager, machine: Machine
) -> None:
    first = web.history.versions("example.com")[-1]
    original = web.history.version("example.com", first.version).text  # type: ignore[union-attr]
    web.replace_site_config("example.com", EDIT)

    response = client.post(f"/api/sites/example.com/config/versions/{first.version}/restore")

    assert response.status_code == 200, response.text
    assert machine.config() == original
    assert web.history.versions("example.com")[0].source == "restore"


def test_a_version_the_web_server_refuses_is_a_400_with_its_words_and_changes_nothing(
    client: TestClient, web: NginxManager, machine: Machine, runner: FakeRunner
) -> None:
    first = web.history.versions("example.com")[-1]
    web.replace_site_config("example.com", EDIT)
    runner.script(("nginx", "-t"), stderr="nginx: [emerg] unknown directive\n", exit_code=1)

    response = client.post(f"/api/sites/example.com/config/versions/{first.version}/restore")

    assert response.status_code == 400
    assert "unknown directive" in response.text
    assert machine.config() == EDIT


def test_putting_a_version_back_asks_for_sudo_mode_and_reading_does_not(
    web: NginxManager, machine: Machine
) -> None:
    machine.deploy(app_type="nodejs")
    client = build(web, COOKIE)
    version = web.history.versions("example.com")[0].version

    assert client.get("/api/sites/example.com/config/versions").status_code == 200
    assert (
        client.post(f"/api/sites/example.com/config/versions/{version}/restore").status_code == 403
    )


def test_the_list_of_sites_says_which_have_drifted(
    client: TestClient, web: NginxManager, machine: Machine, runner: FakeRunner
) -> None:
    runner.script(("ps", "-C", "nginx", "-o", "etimes="), stdout="3600\n")
    path = web.config_path("example.com")
    os.utime(path, (time.time() - 7200, time.time() - 7200))

    quiet = client.get("/api/sites").json()["sites"][0]
    assert (quiet["pending_reload"], quiet["edited_outside"]) == (False, False)

    path.write_text(path.read_text() + "# by hand\n")

    drifted = client.get("/api/sites").json()["sites"][0]
    assert drifted["pending_reload"] is True and drifted["edited_outside"] is True
    detail = client.get("/api/sites/example.com").json()
    assert detail["pending_reload"] is True and detail["edited_outside"] is True
