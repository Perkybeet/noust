class TestReadServers:
    """Reading is the inverse of writing, and tolerant of a hand-edited file."""

    def test_a_missing_file_has_no_servers(self, upstreams: Path) -> None:
        assert webserver.read_servers("proggest-es", "backend") == []

    def test_returns_the_ports_in_file_order(self, upstreams: Path) -> None:
        webserver.write_servers("proggest-es", "backend", [3002, 3001])

        assert webserver.read_servers("proggest-es", "backend") == [3002, 3001]

    def test_ignores_comments_and_blank_lines(self, upstreams: Path) -> None:
        path = webserver.servers_file("proggest-es", "backend")
        path.parent.mkdir(parents=True)
        path.write_text(
            "# the relay\n\nserver 127.0.0.1:3001;  # holder\n  server 127.0.0.1:3002;\n"
        )

        assert webserver.read_servers("proggest-es", "backend") == [3001, 3002]

    def test_does_not_read_through_a_symlink(self, upstreams: Path, tmp_path: Path) -> None:
        secret = tmp_path / "secret"
        secret.write_text("server 127.0.0.1:9999;\n")
        path = webserver.servers_file("proggest-es", "backend")
        path.parent.mkdir(parents=True)
        path.symlink_to(secret)

        assert webserver.read_servers("proggest-es", "backend") == []


