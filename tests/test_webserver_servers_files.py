"""
Tests for what the web server layer gained in 3.2 to serve Docker Compose.

Three things are pinned, each one the chokepoint a later flow leans on:

- **Servers files.** ``/etc/nginx/noust-upstreams/<app>/<service>.servers``
  holds only ``server 127.0.0.1:<port>;`` lines, so one file can be included
  from an upstream block Noust wrote or from one the operator wrote. The
  relay of a Compose service moves traffic by rewriting it, so a write is
  atomic, goes through the filesystem seam (a dry run writes nothing) and
  never lands through a symlink, since Noust writes it as root.
- **Site names.** A site the operator named ``proggest`` serves
  ``proggest.es``; ``config_path`` is the only place a domain becomes a file
  name, so it is the one that has to know.
- **The list.** The sites list is the union of the store and what is in
  ``sites-available``: a hand-written site must not vanish from it the moment
  Noust has written one of its own.
"""

