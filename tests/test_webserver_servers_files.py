class TestServersFile:
    """The path of a servers file is one app directory and one service file."""

    def test_is_one_directory_per_app_under_the_upstreams_directory(self, upstreams: Path) -> None:
        assert webserver.servers_file("proggest-es", "backend") == (
            upstreams / "proggest-es" / "backend.servers"
        )

    @pytest.mark.parametrize(
        "app_name",
        ["..", "../etc", "a/b", "/etc", "", "evil\nname", "evil name", "evil\x00"],
    )
    def test_refuses_an_app_name_that_is_not_one_inert_component(
        self, upstreams: Path, app_name: str
    ) -> None:
        with pytest.raises(ValidationError):
            webserver.servers_file(app_name, "backend")

    @pytest.mark.parametrize(
        "service",
        ["..", "../backend", "a/b", "/etc/passwd", "", "back end", "evil\nname", ".hidden"],
    )
    def test_refuses_a_service_name_that_is_not_one_inert_component(
        self, upstreams: Path, service: str
    ) -> None:
        with pytest.raises(ValidationError):
            webserver.servers_file("proggest-es", service)

    def test_accepts_the_names_compose_gives_services(self, upstreams: Path) -> None:
        path = webserver.servers_file("proggest-es", "web_api-2.v1")

        assert path.name == "web_api-2.v1.servers"

    def test_refuses_an_app_directory_that_is_a_link_out_of_the_tree(
        self, upstreams: Path, tmp_path: Path
    ) -> None:
        outside = tmp_path / "elsewhere"
        outside.mkdir()
        upstreams.mkdir(parents=True)
        (upstreams / "proggest-es").symlink_to(outside)

        with pytest.raises(SecurityError):
            webserver.servers_file("proggest-es", "backend")


