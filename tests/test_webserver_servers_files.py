class TestWriteServers:
    """A servers file holds exactly the loopback servers it was given."""

    def test_writes_only_server_lines(self, upstreams: Path) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])

        path = upstreams / "proggest-es" / "backend.servers"
        assert path.read_text() == "server 127.0.0.1:3001;\n"

    def test_writes_every_port_in_the_order_given(self, upstreams: Path) -> None:
        webserver.write_servers("proggest-es", "backend", [3002, 3001])

        path = upstreams / "proggest-es" / "backend.servers"
        assert path.read_text() == "server 127.0.0.1:3002;\nserver 127.0.0.1:3001;\n"

    def test_replaces_what_was_there(self, upstreams: Path) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])
        webserver.write_servers("proggest-es", "backend", [3002])

        assert webserver.read_servers("proggest-es", "backend") == [3002]

    def test_is_world_readable_like_the_rest_of_the_web_server_configuration(
        self, upstreams: Path
    ) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])

        mode = stat.S_IMODE((upstreams / "proggest-es" / "backend.servers").stat().st_mode)
        assert mode == 0o644

    def test_goes_through_the_filesystem_seam(self, upstreams: Path) -> None:
        recording = RecordingFileSystem()
        set_fs(recording)

        webserver.write_servers("proggest-es", "backend", [3001])

        written = [path for kind, path in recording.changes if kind == "write"]
        assert written == [upstreams / "proggest-es" / "backend.servers"]

    def test_a_dry_run_writes_nothing(self, upstreams: Path) -> None:
        set_fs(DryRunFileSystem())

        webserver.write_servers("proggest-es", "backend", [3001])

        assert not upstreams.exists()

    def test_a_write_that_fails_leaves_the_previous_file_and_no_temporary_one(
        self, upstreams: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])

        def refuse(source: Any, destination: Any) -> None:
            raise OSError("disk full")

        # A context, so only this patch is undone: the fixture's redirection of
        # the upstreams directory must outlive it for the reads below.
        with monkeypatch.context() as patch:
            patch.setattr(os, "replace", refuse)
            with pytest.raises(NginxError, match="disk full"):
                webserver.write_servers("proggest-es", "backend", [3002])

        directory = upstreams / "proggest-es"
        assert [entry.name for entry in directory.iterdir()] == ["backend.servers"]
        assert webserver.read_servers("proggest-es", "backend") == [3001]

    def test_refuses_to_write_through_a_symlinked_file(
        self, upstreams: Path, tmp_path: Path
    ) -> None:
        victim = tmp_path / "victim"
        victim.write_text("keep me\n")
        directory = upstreams / "proggest-es"
        directory.mkdir(parents=True)
        (directory / "backend.servers").symlink_to(victim)

        with pytest.raises(NginxError, match="symlink"):
            webserver.write_servers("proggest-es", "backend", [3001])

        assert victim.read_text() == "keep me\n"
        assert (directory / "backend.servers").is_symlink()

    def test_refuses_to_write_through_a_symlinked_app_directory(
        self, upstreams: Path, tmp_path: Path
    ) -> None:
        elsewhere = tmp_path / "elsewhere"
        elsewhere.mkdir()
        upstreams.mkdir(parents=True)
        (upstreams / "proggest-es").symlink_to(elsewhere)

        with pytest.raises(NoustError):
            webserver.write_servers("proggest-es", "backend", [3001])

        assert list(elsewhere.iterdir()) == []

    @pytest.mark.parametrize("port", [0, -1, 65536, 99999])
    def test_refuses_a_port_out_of_range_and_writes_nothing(
        self, upstreams: Path, port: int
    ) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])

        with pytest.raises(ValidationError):
            webserver.write_servers("proggest-es", "backend", [3002, port])

        assert webserver.read_servers("proggest-es", "backend") == [3001]

    @pytest.mark.parametrize("port", ["3001", 3001.0, None, True])
    def test_refuses_a_port_that_is_not_an_integer(self, upstreams: Path, port: Any) -> None:
        with pytest.raises(ValidationError):
            webserver.write_servers("proggest-es", "backend", [port])

    def test_refuses_an_empty_list_because_nginx_refuses_an_upstream_with_no_servers(
        self, upstreams: Path
    ) -> None:
        with pytest.raises(ValidationError, match="at least one"):
            webserver.write_servers("proggest-es", "backend", [])

    def test_a_hub_does_not_write_sites_infrastructure(self, upstreams: Path, hub: None) -> None:
        with pytest.raises(RoleError):
            webserver.write_servers("proggest-es", "backend", [3001])

        assert not upstreams.exists()


