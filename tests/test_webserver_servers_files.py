SERVERS = Path("/etc/nginx/noust-upstreams/proggest-es/backend.servers")


def site_with(include: str) -> str:
    """An operator's site that includes a servers file the way it was given."""
    return (
        "upstream nestjs_upstream {\n"
        f"    {include}\n"
        "    keepalive 64;\n"
        "}\n"
        "server {\n    listen 80;\n    server_name proggest.es;\n"
        "    location / { proxy_pass http://nestjs_upstream; }\n}\n"
    )


class TestSiteIncludesServers:
    """The check behind "activating the relay needs this line in your site"."""

    @pytest.mark.parametrize(
        "include",
        [
            f"include {SERVERS};",
            f'include "{SERVERS}";',
            f"include '{SERVERS}';",
            f"include   {SERVERS}  ;",
            f"include {SERVERS}; # the relay moves this one",
        ],
        ids=["bare", "double-quoted", "single-quoted", "spaced", "trailing-comment"],
    )
    def test_finds_the_include_inside_an_upstream(self, include: str) -> None:
        assert webserver.site_includes_servers(site_with(include), SERVERS) is True

    def test_finds_an_include_written_on_the_same_line_as_the_block(self) -> None:
        site = f"upstream backend {{ include {SERVERS}; keepalive 64; }}\n"

        assert webserver.site_includes_servers(site, SERVERS) is True

    def test_finds_an_include_outside_an_upstream_block(self) -> None:
        assert webserver.site_includes_servers(f"include {SERVERS};\n", SERVERS) is True

    def test_does_not_count_a_commented_out_include(self) -> None:
        site = site_with(f"# include {SERVERS};")

        assert webserver.site_includes_servers(site, SERVERS) is False

    def test_does_not_count_another_file(self) -> None:
        other = "/etc/nginx/noust-upstreams/proggest-es/frontend.servers"

        assert webserver.site_includes_servers(site_with(f"include {other};"), SERVERS) is False

    def test_does_not_count_a_file_that_only_starts_with_the_same_path(self) -> None:
        site = site_with(f"include {SERVERS}.bak;")

        assert webserver.site_includes_servers(site, SERVERS) is False

    def test_does_not_count_the_path_appearing_as_something_else(self) -> None:
        site = (
            site_with("server 127.0.0.1:3001;")
            + f"# see {SERVERS}\nadd_header X-Servers {SERVERS};\n"
        )

        assert webserver.site_includes_servers(site, SERVERS) is False

    def test_a_relative_include_is_relative_to_the_nginx_prefix(self) -> None:
        site = site_with("include noust-upstreams/proggest-es/backend.servers;")

        assert webserver.site_includes_servers(site, SERVERS) is True

    def test_a_glob_that_nginx_would_expand_to_the_file_counts(self) -> None:
        site = site_with("include /etc/nginx/noust-upstreams/proggest-es/*.servers;")

        assert webserver.site_includes_servers(site, SERVERS) is True

    def test_a_glob_does_not_cross_directories(self) -> None:
        site = site_with("include /etc/nginx/noust-upstreams/*.servers;")

        assert webserver.site_includes_servers(site, SERVERS) is False

    def test_an_empty_site_includes_nothing(self) -> None:
        assert webserver.site_includes_servers("", SERVERS) is False


