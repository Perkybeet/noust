class TestRemoveServers:
    """Removal leaves nothing of an app behind, and never follows a link."""

    def test_removes_one_service_file(self, upstreams: Path) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])
        webserver.write_servers("proggest-es", "frontend", [3000])

        assert webserver.remove_servers("proggest-es", "backend") is True

        assert webserver.read_servers("proggest-es", "backend") == []
        assert webserver.read_servers("proggest-es", "frontend") == [3000]

    def test_removes_the_whole_app_directory_when_no_service_is_named(
        self, upstreams: Path
    ) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])
        webserver.write_servers("proggest-es", "frontend", [3000])

        assert webserver.remove_servers("proggest-es") is True

        assert not (upstreams / "proggest-es").exists()

    def test_says_when_there_was_nothing_to_remove(self, upstreams: Path) -> None:
        assert webserver.remove_servers("proggest-es") is False
        assert webserver.remove_servers("proggest-es", "backend") is False

    def test_a_dry_run_removes_nothing(self, upstreams: Path) -> None:
        webserver.write_servers("proggest-es", "backend", [3001])
        set_fs(DryRunFileSystem())

        webserver.remove_servers("proggest-es")

        assert webserver.read_servers("proggest-es", "backend") == [3001]

    def test_does_not_follow_a_symlinked_app_directory(
        self, upstreams: Path, tmp_path: Path
    ) -> None:
        elsewhere = tmp_path / "elsewhere"
        elsewhere.mkdir()
        (elsewhere / "keep.txt").write_text("keep\n")
        upstreams.mkdir(parents=True)
        link = upstreams / "proggest-es"
        link.symlink_to(elsewhere)

        with pytest.raises(NoustError):
            webserver.remove_servers("proggest-es")

        assert (elsewhere / "keep.txt").read_text() == "keep\n"


