def make_app(store: NoustStore, domain: str, *, site_name: str | None = None) -> App:
    """Record an application, with the site file name the adoption would store."""
    store.create_app(App(domain=domain, app_type="nodejs", port=3000, app_path=f"/srv/{domain}"))
    if site_name is not None:
        assert store.set_app_site_name(domain, site_name)
    found = store.get_app(domain)
    assert found is not None
    return found


