class TestConfigPathResolvesTheSiteName:
    """``config_path`` is the one place a domain becomes a file name (rule 4)."""

    def test_a_domain_with_a_site_name_resolves_to_that_file(
        self, nginx: NginxManager, store: NoustStore
    ) -> None:
        make_app(store, "proggest.es", site_name="proggest")

        path = nginx.config_path("proggest.es")

        assert path == nginx.sites_available.resolve() / "proggest"

    def test_a_domain_without_one_resolves_to_itself_as_before(
        self, nginx: NginxManager, store: NoustStore
    ) -> None:
        make_app(store, "shop.example.com")

        assert nginx.config_path("shop.example.com").name == "shop.example.com"
        assert nginx.config_path("unknown.example.com").name == "unknown.example.com"

    def test_the_apache_suffix_is_added_to_the_site_name(
        self, apache: ApacheManager, store: NoustStore
    ) -> None:
        make_app(store, "proggest.es", site_name="proggest")

        assert apache.config_path("proggest.es").name == "proggest.conf"

    def test_the_enabled_link_follows_the_same_name(
        self, nginx: NginxManager, store: NoustStore
    ) -> None:
        make_app(store, "proggest.es", site_name="proggest")
        nginx.sites_available.mkdir(parents=True)
        nginx.sites_enabled.mkdir(parents=True)
        (nginx.sites_available / "proggest").write_text(NOUST_SITE)

        assert nginx.site_exists("proggest.es")
        assert nginx.site_enabled("proggest.es") is False
        nginx.enable_site("proggest.es")

        assert (nginx.sites_enabled / "proggest").is_symlink()
        assert nginx.site_enabled("proggest.es") is True

    def test_reading_and_replacing_the_configuration_use_the_named_file(
        self, nginx: NginxManager, store: NoustStore
    ) -> None:
        make_app(store, "proggest.es", site_name="proggest")
        nginx.sites_available.mkdir(parents=True)
        (nginx.sites_available / "proggest").write_text("server { listen 80; }\n")

        assert nginx.get_site_config("proggest.es") == "server { listen 80; }\n"
        nginx.replace_site_config("proggest.es", "server { listen 8080; }\n", validate=False)

        assert (nginx.sites_available / "proggest").read_text() == "server { listen 8080; }\n"
        assert not (nginx.sites_available / "proggest.es").exists()

    def test_served_names_and_the_operator_marker_read_the_named_file(
        self, nginx: NginxManager, store: NoustStore
    ) -> None:
        make_app(store, "proggest.es", site_name="proggest")
        nginx.sites_available.mkdir(parents=True)
        (nginx.sites_available / "proggest").write_text(
            "server {\n    server_name proggest.es www.proggest.es;\n}\n"
        )

        assert nginx.served_names("proggest.es") == ["proggest.es", "www.proggest.es"]
        assert nginx.site_is_noust("proggest.es") is False

    def test_a_site_name_that_is_not_a_file_name_is_refused_not_resolved(
        self, nginx: NginxManager
    ) -> None:
        class TamperedStore:
            def get_app(self, domain: str) -> App:
                return App(domain=domain, site_name="../../etc/shadow")

        nginx.__dict__["store"] = TamperedStore()

        with pytest.raises(ValidationError, match="site name"):
            nginx.config_path("proggest.es")

    def test_the_domain_is_still_validated_first(
        self, nginx: NginxManager, store: NoustStore
    ) -> None:
        with pytest.raises(DomainError):
            nginx.config_path("evil/../domain")

    def test_an_unreadable_store_leaves_a_site_where_it_always_was(
        self, nginx: NginxManager
    ) -> None:
        class BrokenStore:
            def get_app(self, domain: str) -> None:
                raise StoreError("database is locked")

        nginx.__dict__["store"] = BrokenStore()

        assert nginx.config_path("shop.example.com").name == "shop.example.com"


class TestDeletingASiteLeavesNoServersFiles:
    """The servers files belong to the app's site, as its blue/green upstream does."""

    def test_delete_site_removes_the_servers_directory_of_the_app(
        self, nginx: NginxManager, store: NoustStore, upstreams: Path
    ) -> None:
        domain = "shop.example.com"
        nginx.sites_available.mkdir(parents=True)
        (nginx.sites_available / domain).write_text(NOUST_SITE)
        webserver.write_servers(domain_to_app_name(domain), "backend", [3001])

        nginx.delete_site(domain)

        assert not (upstreams / domain_to_app_name(domain)).exists()

    def test_a_servers_directory_that_cannot_be_removed_does_not_fail_the_deletion(
        self, nginx: NginxManager, store: NoustStore, upstreams: Path, tmp_path: Path
    ) -> None:
        domain = "shop.example.com"
        nginx.sites_available.mkdir(parents=True)
        site = nginx.sites_available / domain
